async function mockQuantityApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.slice('/api/'.length);
      const rows =
        kind === 'drift' ? DRIFT_ROWS : kind === 'excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (/^\/api\/(drift|excess|stockout)\/decisions$/.test(path)) {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

// The inputs of the selected row as [label, value] pairs.
const inputPairs = (page) =>
  page.locator('.q-input').evaluateAll((els) =>
    els.map((el) => [
      el.querySelector('dt').textContent.trim(),
      el.querySelector('dd').textContent.trim(),
    ]),
  );

test('271_ac_3_data_source', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  await mockQuantityApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // --- drift inputs: whole units, two-decimal k, whole-dollar money --
  await expect(page.locator('.q-detail-title')).toHaveText('D3');
  expect(await inputPairs(page)).toEqual([
    ['Average lead-time demand', '1,235'],
    ['Lead-time demand variability (std dev)', '46'],
    ['Service level the ERP point gives (k)', '1.20'],
    ['Recommended safety stock', '251'],
    ['Money at stake', '$17,585'],
  ]);
  // The uniform two-decimal rendering of the same data is gone from the
  // input list (the quoted arithmetic string is server-provided text).
  const driftInputsText = await page.locator('.q-inputs').textContent();
  expect(driftInputsText).not.toContain('1234.56');
  expect(driftInputsText).not.toContain('45.67');
  expect(driftInputsText).not.toContain('250.9');

  // --- excess inputs: whole units, one-decimal months of cover -------
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-detail-title')).toHaveText('X3');
  expect(await inputPairs(page)).toEqual([
    ['On hand', '12,000'],
    ['Justified units', '1,539'],
    ['Months of cover', '18.3'],
    ['Money tied up', '$26,152'],
  ]);
  const excessInputsText = await page.locator('.q-inputs').textContent();
  expect(excessInputsText).not.toContain('18.34');
  expect(excessInputsText).not.toContain('12000.3');
  expect(excessInputsText).not.toContain('1539.4');

  // --- stockout inputs: one-decimal days, whole units ---------------
  await page.click('.q-tab[data-kind="stockout"]');
  await expect(page.locator('.q-detail-title')).toHaveText('Y3');
  expect(await inputPairs(page)).toEqual([
    ['Lead time', '12.9 days'],
    ['Days of cover', '0.8'],
    ['Expected units short', '35'],
    ['Money at risk', '$350'],
  ]);
  const stockoutInputsText = await page.locator('.q-inputs').textContent();
  expect(stockoutInputsText).not.toContain('12.94');
  expect(stockoutInputsText).not.toContain('0.76');
});
