async function mockGapApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.slice('/api/'.length);
      const rows = kind === 'drift' ? DRIFT_ROWS : [];
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (/^\/api\/(drift|excess|stockout)\/decisions$/.test(path)) {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

test('271_ac_4_data_source', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  await mockGapApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  await page.goto('/#/overview');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // The attention list: U1 ($17,585), then O1 ($906); N1 has no money
  // and comes last.
  const attention = page.locator('#ov-attention-body .attn-row');
  await expect(attention).toHaveCount(3);
  const items = await attention.evaluateAll((rows) =>
    rows.map((row) => row.querySelector('.attn-item').textContent.trim()),
  );
  expect(items).toEqual(['U1 · S1', 'O1 · S1', 'N1 · S2']);

  // The -1465.42 under-protected row: unsigned magnitude, whole number
  // with a separator, next to the direction word — never a signed
  // decimal next to "below".
  await expect(attention.nth(0).locator('.attn-why')).toHaveText(
    'ERP point 1,465 units below the recommended point',
  );

  // The 90.6 over-protected row: the same shape for "above".
  await expect(attention.nth(1).locator('.attn-why')).toHaveText(
    'ERP point 91 units above the recommended point',
  );

  // The null-gap row keeps its direction word and shows an em dash.
  await expect(attention.nth(2).locator('.attn-why')).toHaveText(
    'ERP point — units below the recommended point',
  );

  // No attention line carries a signed numeric gap: no minus sign in
  // front of a digit anywhere in the list, and no raw wire decimal.
  const attentionText = await page.locator('#ov-attention-body').textContent();
  expect(attentionText).not.toMatch(/-\s?\d/);
  expect(attentionText).not.toContain('-1,465');
  expect(attentionText).not.toContain('-1465.42');
  expect(attentionText).not.toContain('1465.42');
});
