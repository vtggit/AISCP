async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.slice('/api/'.length);
      const rows =
        kind === 'drift' ? DRIFT_ROWS : kind === 'excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (/^\/api\/(drift|excess|stockout)\/decisions$/.test(path)) {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

// The selected row's inputs as [label, value] pairs, in list order.
const inputPairs = (page) =>
  page.locator('.q-input').evaluateAll((els) =>
    els.map((el) => [
      el.querySelector('dt').textContent.trim(),
      el.querySelector('dd').textContent.trim(),
    ]),
  );

// The key/value geometry of the selected row's inputs list: the list's
// box and grid tracks, and per row whether the label/value elements
// clip, end in an ellipsis or drift off their row's left/right edges.
const inputLayout = (page) =>
  page.evaluate(() => {
    const dl = document.querySelector('.q-inputs');
    const dlRect = dl.getBoundingClientRect();
    return {
      dlLeft: dlRect.left,
      dlRight: dlRect.right,
      dlWidth: dlRect.width,
      tracks: getComputedStyle(dl).gridTemplateColumns.split(/\s+/).filter(Boolean),
      rows: Array.from(dl.querySelectorAll('.q-input')).map((el) => {
        const dt = el.querySelector('dt');
        const dd = el.querySelector('dd');
        const dtRect = dt.getBoundingClientRect();
        const ddRect = dd.getBoundingClientRect();
        return {
          label: dt.textContent.trim(),
          value: dd.textContent.trim(),
          rowWidth: el.getBoundingClientRect().width,
          dtClipped: dt.scrollWidth > dt.clientWidth,
          ddClipped: dd.scrollWidth > dd.clientWidth,
          dtTextOverflow: getComputedStyle(dt).textOverflow,
          ddTextOverflow: getComputedStyle(dd).textOverflow,
          dtWraps: getComputedStyle(dt).whiteSpace !== 'nowrap',
          labelLeft: dtRect.left,
          valueRight: ddRect.right,
        };
      }),
    };
  });

// AC-3's contract for the selected tab: one column, every row full
// width, labels and values fully visible — nothing clipped, no ellipsis,
// labels on the left (and able to wrap), values on the right.
async function expectSingleColumnKeyValueList(page) {
  const layout = await inputLayout(page);
  expect(
    layout.tracks,
    'the inputs list must be a single column',
  ).toHaveLength(1);
  expect(Math.abs(parseFloat(layout.tracks[0]) - layout.dlWidth)).toBeLessThanOrEqual(1);
  for (const row of layout.rows) {
    expect(
      Math.abs(row.rowWidth - layout.dlWidth),
      `the input row "${row.label}" must span the full width of the inputs list`,
    ).toBeLessThanOrEqual(1);
    expect(row.dtClipped, `the label "${row.label}" is clipped`).toBe(false);
    expect(row.ddClipped, `the value "${row.value}" is clipped`).toBe(false);
    expect(row.dtTextOverflow, `the label "${row.label}" ends in an ellipsis`).not.toBe(
      'ellipsis',
    );
    expect(row.ddTextOverflow, `the value "${row.value}" ends in an ellipsis`).not.toBe(
      'ellipsis',
    );
    expect(row.dtWraps, `a long label must be able to wrap, not clip`).toBe(true);
    expect(
      Math.abs(row.labelLeft - layout.dlLeft),
      `the label "${row.label}" must sit on the left of its row`,
    ).toBeLessThanOrEqual(1);
    expect(
      Math.abs(row.valueRight - layout.dlRight),
      `the value "${row.value}" must sit on the right of its row`,
    ).toBeLessThanOrEqual(1);
  }
}

test('272_ac_3_data_source', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  await mockQueueApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // The detail pane is the 440px one the criterion names.
  await expect(page.locator('.q-detail-title')).toHaveText('K1');
  await expect(page.locator('.q-detail')).toHaveCSS('width', '440px');

  // --- drift: the single-column key/value list, all five in order ----
  expect(await inputPairs(page)).toEqual([
    ['Average lead-time demand', '126'],
    ['Lead-time demand variability (std dev)', '100'],
    ['Service level the ERP point gives (k)', '-0.62'],
    ['Recommended safety stock', '164'],
    ['Money at stake', '$23,823'],
  ]);
  await expectSingleColumnKeyValueList(page);

  // --- AC-4: the -0.62 case ------------------------------------------
  // The k input is labeled as the service level the ERP point gives,
  // not "service factor", and shows the -0.62 value.
  const kInput = page.locator('.q-input').nth(2);
  await expect(kInput.locator('dt')).toHaveText('Service level the ERP point gives (k)');
  await expect(kInput.locator('dd')).toHaveText('-0.62');
  // And it is visually distinguishable from the z = 1.644854 formula in
  // the monospace block: the two numbers live in two different
  // elements, and neither element carries the other's number.
  expect(K_ARITHMETIC).toContain('1.644854');
  expect(K_ARITHMETIC).not.toContain('-0.62');
  await expect(page.locator('.q-arithmetic')).toHaveText(K_ARITHMETIC);
  expect(await kInput.textContent()).not.toContain('1.644854');
  expect(await page.locator('.q-arithmetic').textContent()).not.toContain(
    'Service level the ERP point gives',
  );

  // --- the other tabs keep their labels; the same contract holds -----
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-detail-title')).toHaveText('X3');
  expect(await inputPairs(page)).toEqual([
    ['On hand', '12,000'],
    ['Justified units', '1,539'],
    ['Months of cover', '18.3'],
    ['Money tied up', '$26,152'],
  ]);
  await expectSingleColumnKeyValueList(page);

  await page.click('.q-tab[data-kind="stockout"]');
  await expect(page.locator('.q-detail-title')).toHaveText('Y3');
  expect(await inputPairs(page)).toEqual([
    ['Lead time', '12.9 days'],
    ['Days of cover', '0.8'],
    ['Expected units short', '35'],
    ['Money at risk', '$350'],
  ]);
  await expectSingleColumnKeyValueList(page);
});
