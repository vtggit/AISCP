// Proving spec for AIERP issue #1003 — the ERP source tags and the
// ERP filter of the Work queue (#/queue).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route — the queue's three lists, its settings,
// /api/auth/me and GET /api/erp-sources. Proves, signed in through
// the development token card as an admin at 1440x900:
//   * the view sends GET /api/erp-sources once with the load of the
//     three lists — the lists render without waiting for the answer
//     (the answer is held in flight, then released) — and only the
//     newest answer renders (a request-sequence guard);
//   * the tags — with two or more sources in the answer, each row
//     whose item-site the answer lists shows a tag in the list
//     pane's item and site cell and, beside the site, in the detail
//     pane: "Acumatica" for acumatica (ITEM-A), "Odoo" for odoo
//     (ITEM-B), and no tag for ITEM-C, whose item-site is not in the
//     answer;
//   * the filter — the tab bar gains a select with "All ERPs" first
//     and one option per source, starting on "All ERPs"; choosing
//     "Odoo" lists only ITEM-B, selects it, and the Reorder points
//     tab count reads 1 (the tab counts follow it); choosing "All
//     ERPs" lists all three; the Decided chip composes with it (only
//     the decided Odoo row lists); a row without a source shows only
//     under "All ERPs";
//   * one request — opening the view sends one /api/erp-sources
//     request, and choosing a filter sends none;
//   * the choice lives in module state — it survives re-renders (a
//     tab switch) and is cleared on sign-out (the select reads "All
//     ERPs" again after signing in);
//   * one ERP — an answer with a single source shows no tag (in
//     the list pane or beside the site in the detail pane) and no
//     select, and the row cells read as they do with no answer;
//   * failed — a 503 from /api/erp-sources shows no tag, no select
//     and no error, and the rows still list;
//   * hostile text — a source_system of <img src=x
//     onerror=window.__pwned=1> renders as text in the tag and the
//     select's option, with window.__pwned undefined and no <img>
//     on the page;
//   * at 390x844, with the tags and the select shown, the page does
//     not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1003 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

