  ctrl.holdSources = true;
  await page.reload();
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('.q-row')).toHaveCount(3);
  await expect(erpFilter).toHaveCount(0);
  await expect(erpTags).toHaveCount(0);
