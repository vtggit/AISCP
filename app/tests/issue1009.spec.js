// Mock every /api/* call the app makes. The single handler reads ctrl
// on every request, so the test can steer the sign-in (ctrl.config /
// ctrl.me), the suggestions answer (ctrl.suggestionsAnswer, or a
// one-shot ctrl.suggestionsNext such as the 503) and the confirm
// (a one-shot ctrl.putFailNext, or holding the next PUT until the
// test answers it). Every read is counted; every PUT body is kept.
async function mockApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    store: freshStore(),
    nextId: 100,
    suggestionsAnswer: SUGGESTIONS.map((s) => ({ ...s })),
    suggestionsNext: null,
    suggestionsGets: 0,
    mappingsGets: 0,
    mappingPuts: [],
    meRequests: [],
    putFailNext: null,
    putHoldNext: false,
    heldPut: null,
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      ctrl.mappingsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.store });
    }
    if (path === '/api/erp-mappings/suggestions' && request.method() === 'GET') {
      ctrl.suggestionsGets += 1;
      if (ctrl.suggestionsNext) {
        const next = ctrl.suggestionsNext;
        ctrl.suggestionsNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: ctrl.suggestionsAnswer });
    }
    if (path === '/api/erp-mappings' && request.method() === 'PUT') {
      const body = request.postDataJSON();
      ctrl.mappingPuts.push(body);
      if (ctrl.putFailNext) {
        const fail = ctrl.putFailNext;
        ctrl.putFailNext = null;
        return route.fulfill(fail);
      }
      // The API's upsert: an existing (kind, source_code) updates its
      // target code instead of creating a duplicate.
      const existing = ctrl.store.find(
        (row) => row.kind === body.kind && String(row.source_code) === String(body.source_code),
      );
      const row = existing
        ? { ...existing, target_code: body.target_code, updated_at: '2026-11-05T10:00:00+00:00' }
        : {
            id: ctrl.nextId++,
            kind: body.kind,
            target_system: body.target_system,
            source_code: body.source_code,
            target_code: body.target_code,
            created_at: '2026-11-05T10:00:00+00:00',
            updated_at: '2026-11-05T10:00:00+00:00',
          };
      const index = existing ? ctrl.store.indexOf(existing) : -1;
      if (index === -1) {
        ctrl.store.push(row);
      } else {
        ctrl.store[index] = row;
      }
      // A stored mapping is "already mapped": the API leaves its pair
      // out of the suggestions, along with any pair sharing its codes.
      ctrl.suggestionsAnswer = ctrl.suggestionsAnswer.filter(
        (s) =>
          String(s.source_code) !== String(body.source_code) &&
          String(s.target_code) !== String(body.target_code),
      );
      if (ctrl.putHoldNext) {
        // Held: the test answers the route itself.
        ctrl.putHoldNext = false;
        ctrl.heldPut = { route, row };
        return;
      }
      return route.fulfill({ status: 200, json: row });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

