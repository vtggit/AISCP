// Proving spec for AIERP issue #1009 — the "Suggested matches" section
// of the Settings view's "ERP code mappings" card
// ([data-testid="erp-mappings"]).
//
// The section ([data-testid="erp-suggestions"]) sits below the stored
// mappings, is headed "Suggested matches", and is fetched with the
// card — GET /api/erp-mappings/suggestions through app/js/api.js, once
// when the card loads and again after each successful confirm, under a
// request-sequence guard; the card's own requests are unchanged. It
// holds one row per suggestion ([data-testid="erp-suggestion-row",
// with data-source-code and data-target-code]) — the AIERP code, the
// Odoo code, both descriptions (an em dash when null) and why it
// matched, "Same code" or "Same description" — a suggestion the API
// flags as ambiguous also reads "More than one possible match". With
// no suggestions the section reads "No suggested matches."; a failed
// fetch reads "Suggested matches could not be loaded." and the rest of
// the card works as before.
//
// For an admin the section first reads "Confirming tells AIERP these
// are the same item. Draft purchase orders use this match too, so
// check it first." and each row carries a "Confirm match" button
// ([data-testid="erp-suggestion-confirm"], no code attributes of its
// own, so a locator by code finds exactly one element, the row).
// Nothing is sent until a person presses it; the button stays disabled
// while the request is out, so a double click sends one request. A
// press PUTs /api/erp-mappings with {kind: "item", target_system:
// "odoo", source_code, target_code} — the same body the add form
// sends — and a success re-loads the stored mappings and the
// suggestions; a failure shows the response's detail inline and leaves
// the row in place. For a non-admin the section shows the list, with
// no buttons and no warning. Every API value is escaped or set as
// text; at 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route — the same mocks and sign-in as
// app/tests/issue475.spec.js (the card's own spec), plus a mock for
// /api/erp-mappings/suggestions that counts its reads and the stored
// mappings' store, which a successful confirm upserts and which drops
// the confirmed pair from the suggestions, as the API does.
//
// The pass runs as an ADMIN (roles ["admin"]) through the development
// token card at 1440x900, and it ends as a NON-ADMIN (role 'user')
// after a full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, and the section shows the list — no buttons, no warning
// — while the page still renders.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1009 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

