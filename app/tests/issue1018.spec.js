// The as-of the answer carries (the screen does not read it, but the
// answer is complete the way the API's is).
const AS_OF = '2026-11-05';

// Mock every /api/* call the app makes. The single handler reads ctrl
// on every request, so the test can steer the sign-in (ctrl.me), the
// comparison answer (ctrl.rows / ctrl.status) and hold the next
// comparison request in flight (ctrl.holdNext; release through
// ctrl.heldRoute.fulfill(...)). Every comparison read is counted;
// every non-GET method is kept for the read-only check.
async function mockApi(page) {
  const ctrl = {
    me: ADMIN_ME,
    rows: freshRows(ROWS),
    status: 200,
    holdNext: false,
    heldRoute: null,
    gets: 0,
    nonGets: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/cross-erp/items') {
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.gets += 1;
      if (ctrl.holdNext) {
        ctrl.holdNext = false;
        ctrl.heldRoute = route;
        return; // held: the test answers it
      }
      if (ctrl.status !== 200) {
        return route.fulfill({ status: ctrl.status, json: { detail: 'upstream unavailable' } });
      }
      return route.fulfill({ status: 200, json: { as_of: AS_OF, rows: ctrl.rows } });
    }
    if (request.method() !== 'GET') {
      ctrl.nonGets.push(request.method() + ' ' + path);
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

