// Proving spec for AIERP issue #1018 — the Across ERPs view (#/across).
//
// The view, titled "Across ERPs" with the subtitle "The same item in
// each ERP, side by side, and where one is short while the other holds
// too much.", sits directly after the S&OP button in the nav (the
// shared list in app/tests/nav_order.js carries "across" and "Across
// ERPs" directly after S&OP) and is wired into app/js/app.js the same
// way as the sop view, including its activate and sign-out reset.
//
// Opening the view sends GET /api/cross-erp/items once through
// app/js/api.js, under a request-sequence guard so only the newest
// answer renders; the Refresh button
// ([data-testid="across-refresh"]) sends it again.
//
// The opportunities come first: rows with opportunity true lead the
// list, then the others, keeping the answer's order within each group.
// The count above the list ([data-testid="across-count"]) reads "N
// items short in one ERP with excess in the other", with N
// thousands-separated, or "No item is short in one ERP with excess in
// the other." when N is 0. Below it, the screen always reads "AIERP
// does not convert currencies. Values assume both ERPs report in the
// same currency." and "AIERP shows the opportunity. It does not create
// a move between ERPs."
//
// One card per row ([data-testid="across-item"]) is headed by the
// description, or the codes when there is none. An opportunity row
// carries [data-testid="across-opportunity"] reading "<short ERP>
// short, <excess ERP> has excess", the ERP names read from short_side
// and excess_side. Each card shows the two sides of the row's sides
// side by side, each headed by the ERP's name ("Acumatica", "Odoo", or
// otherwise the code as text) and its item code, with the side's total
// on hand and one row per site: site, on hand, daily demand, days of
// cover, reorder point, suggested order and the state — "Stockout
// likely", "Stockout at risk" or "Excess <n> units" when those apply,
// else an em dash; a null figure reads an em dash. A side with no
// sites reads "No stock record in this ERP."
//
// With no rows the screen reads "No items are matched across ERPs
// yet." with a link to #/settings. A failed fetch shows "The
// comparison could not be loaded." with a "Try again" button that
// sends another request, and the rest of the app works as before.
//
// The screen is read-only: it has no button that writes, and the whole
// pass sends no POST, PUT or DELETE. Every API value is escaped or set
// as text (a description of <img src=x onerror=window.__pwned=1>
// renders as text, with window.__pwned undefined). The site table
// scrolls inside its own region, and at 390x844 the two sides stack
// and the page does not scroll sideways. Sign-out clears the answer,
// and an answer arriving after sign-out is discarded.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route — /api/auth/config, /api/auth/me and
// GET /api/cross-erp/items (which counts its reads and can hold the
// next answer in flight). The mock answers two rows out of order:
// HEALTHY-1 with opportunity false, then SHORT-1 with opportunity
// true, short_side 1 and excess_side 0, whose Acumatica side carries
// excess_units 500 at site 154 and whose Odoo side carries
// stockout_category "likely" at WH.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1018 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

