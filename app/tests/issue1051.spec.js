// Proving spec for AIERP issue #1051 — the "Supplier risk" section of
// the Suppliers screen (#/suppliers): one read of GET
// /api/supplier-risk per load of the screen (the view's activation),
// beside the existing reads, under its own request-sequence guard — a
// late answer from an older load or from before sign-out is dropped,
// and sign-out clears it. A window change re-fetches only the
// performance answer and leaves the section's state alone.
//
// The section ([data-testid="suppliers-risk"], label "Supplier risk")
// sits below the performance table and above the supplier terms. Its
// table ([data-testid="suppliers-risk-table"]) carries one row per
// supplier in the answer's order
// ([data-testid="suppliers-risk-row"] with data-supplier-code):
// Supplier (supplier_name, else the supplier_code), Risk (a badge
// [data-testid="suppliers-risk-level"] reading High, Medium or Low,
// with the class is-high, is-medium or is-low), Why (the true signs
// joined by a comma and a space — Late deliveries, Variable lead
// times, Only supplier of <N> item(s), the word item when N is 1 — or
// an em dash with no sign), On time (the rate as a whole percent, or
// an em dash when null) and Lead-time variation (lead_time_cv to 2
// places, or an em dash when null). While the read is out a short
// skeleton shows (never the word "Loading"); a failed or malformed
// answer shows "Supplier risk could not be loaded." in
// [data-testid="suppliers-risk-error"], an empty list "No supplier has
// receipts to rate yet." in [data-testid="suppliers-risk-empty"] — a
// failure here leaves the performance table and the terms exactly as
// they are. Every API value is escaped. The screen sends no POST, PUT
// or DELETE.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue605.spec.js does it. The mocked risk answer has
// three suppliers in the answer's order — 4834 high (late, variable
// and the only supplier of 1 item), 4861 medium (the only supplier of
// 3 items) and 4883 low (no sign, no name, no rate, no variation) —
// with hostile variants that carry the sole-source counts as strings
// and the supplier codes as numbers, which the section must read the
// same way. While the first load's reads are held in flight, the
// risk section must already render beside the performance skeleton.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1051 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

