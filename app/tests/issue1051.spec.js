// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route. The handler reads
// ctrl on every request, so the test can steer the risk answers
// (ctrl.riskAnswer, the one-shot ctrl.riskNext), hold the next risk
// request until it is answered (ctrl.holdRiskNext / ctrl.heldRisk)
// or the next performance request (ctrl.holdPerfNext / ctrl.heldPerf)
// for the in-flight state, and steer the sign-in (ctrl.config /
// ctrl.me). Every performance request is counted in ctrl.perfGets
// and every risk request in ctrl.riskGets, and each request's method
// and path land in ctrl.requests for the read-only check.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    riskAnswer: null,
    riskNext: null,
    holdRiskNext: false,
    heldRisk: [],
    holdPerfNext: false,
    heldPerf: [],
    perfGets: 0,
    riskGets: 0,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.perfGets += 1;
      if (ctrl.holdPerfNext) {
        ctrl.holdPerfNext = false;
        ctrl.heldPerf.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      return route.fulfill({ status: 200, json: PERFORMANCE });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      if (ctrl.holdRiskNext) {
        ctrl.holdRiskNext = false;
        ctrl.heldRisk.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      if (ctrl.riskNext) {
        const next = ctrl.riskNext;
        ctrl.riskNext = null;
        return route.fulfill(next);
      }
      const answer =
        typeof ctrl.riskAnswer === 'function' ? ctrl.riskAnswer() : ctrl.riskAnswer;
      if (answer !== null && answer !== undefined) {
        return route.fulfill(answer);
      }
      return route.fulfill({ status: 200, json: RISK_PAYLOAD });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

