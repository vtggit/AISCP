// Proving spec for AIERP issue #1060 — the "Order plan" screen
// (#/orders): the supplier risk badge in each supplier block's head.
//
// Whenever the screen fetches GET /api/supply-plan it sends one GET
// /api/supplier-risk beside it, under its own request-sequence guard
// — a late answer from an older fetch or from before sign-out is
// dropped, and sign-out clears it. The supply-plan read, its order
// and its count are unchanged.
//
// In a supplier block's head (.op-supplier-head), after the title and
// the vendor code, a span ([data-testid="orders-supplier-risk"], class
// op-supplier-risk) shows when the risk answer rates that block's
// supplier_code "high" or "medium": it reads "High risk" with the
// class is-high or "Medium risk" with is-medium, and its title lists
// the true signs — Late deliveries, Variable lead times, Only
// supplier of <N> item(s), the word item when N is 1 — joined by a
// comma and a space. A supplier rated "low", one missing from the
// answer, the block without supplier terms, a failed or malformed
// risk answer, and the time before the answer arrives all show no
// badge; the block's title, vendor code, totals and lines are exactly
// as before. Every API value is escaped, and the screen sends no
// POST, PUT or DELETE (the release flow is untouched).
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered with page.route, the way
// app/tests/issue841.spec.js does it. The mocked supply-plan answer
// has three groups — supplier S-HIGH, supplier S-LOW and the group
// without supplier terms — and the mocked risk answer rates S-HIGH
// high (late, and the only supplier of 2 items) and S-LOW low.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1060 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


