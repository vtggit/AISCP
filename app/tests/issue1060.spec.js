// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route. The handler reads
// ctrl on every request, so the test can steer the risk answer
// (ctrl.riskAnswer, either a payload or a { status, json } failure),
// hold the next risk request until it is answered (ctrl.holdRiskNext
// / ctrl.heldRisk) and steer the sign-in (ctrl.config / ctrl.me).
// Every supply-plan request is counted in ctrl.supplyGets and every
// risk request in ctrl.riskGets, and each request's method and path
// land in ctrl.requests for the read-only check.
async function mockOrdersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    riskAnswer: null,
    holdRiskNext: false,
    heldRisk: [],
    supplyGets: 0,
    riskGets: 0,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/supply-plan') {
      ctrl.supplyGets += 1;
      return route.fulfill({ status: 200, json: supplyAnswer() });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      if (ctrl.holdRiskNext) {
        ctrl.holdRiskNext = false;
        ctrl.heldRisk.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      if (ctrl.riskAnswer !== null) {
        return route.fulfill(ctrl.riskAnswer);
      }
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

test('issue1060 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in --------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockOrdersApi(page);

  const summary = page.locator('[data-testid="orders-summary"]');
  const groups = page.locator('[data-testid="orders-supplier"]');
  const refresh = page.locator('[data-testid="orders-refresh"]');
  const badges = page.locator('[data-testid="orders-supplier-risk"]');

  await page.goto('/');

  // No plan or risk read before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.supplyGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // The default view is the Overview (it loads on its own), and the
  // Order plan has not asked for its data yet.
  expect(ctrl.supplyGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);
  expect(pageErrors).toEqual([]);

  // --- activation: one plan read and one risk read ----------------------
  // The first risk request is held until the test answers it, so the
  // plan can settle while the risk answer is still out the door.
  ctrl.holdRiskNext = true;
  await page.click('.nav-btn[data-view="orders"]');
  await expect(page).toHaveURL(/#\/orders$/);
  await expect(page.locator('#view-orders')).toBeVisible();

  // The load of the screen sends exactly one supply-plan read and,
  // beside it, exactly one risk read.
  await expect.poll(() => ctrl.supplyGets).toBe(1);
  await expect.poll(() => ctrl.riskGets).toBe(1);

  // The plan answer settles: the summary and the three blocks read
  // exactly as the supply-plan answer names them — and no badge yet,
  // while the risk answer is still out the door.
  await expect(summary).toHaveText('3 lines \u00b7 $140 across 2 suppliers');
  await expect(groups).toHaveCount(3);
  await expect(groups.nth(0).locator('h2')).toHaveText('Highland Fasteners');
  await expect(groups.nth(0).locator('.op-supplier-vendor')).toHaveText('V-900');
  await expect(groups.nth(1).locator('h2')).toHaveText('Lowland Metals');
  await expect(groups.nth(1).locator('.op-supplier-vendor')).toHaveText('V-901');
  await expect(groups.nth(2).locator('h2')).toHaveText('No supplier terms');
  await expect(badges).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- the badge: S-HIGH reads high --------------------------------------
  // Answering the held risk read settles it: the S-HIGH block's head
  // gains the badge, after the title and the vendor code.
  ctrl.heldRisk[0].fulfill({ status: 200, json: RISK_ANSWER });
  ctrl.heldRisk.length = 0; // later holds start at index 0 again
  const highBadge = groups
    .nth(0)
    .locator('.op-supplier-head [data-testid="orders-supplier-risk"]');
  await expect(highBadge).toHaveCount(1);
  await expect(highBadge).toHaveText('High risk');
  await expect(highBadge).toHaveClass(/is-high/);
  await expect(highBadge).toHaveAttribute(
    'title',
    'Late deliveries, Only supplier of 2 items',
  );
  expect(pageErrors).toEqual([]);

  // --- no badge: S-LOW is low, the no-terms block has no supplier --------
  await expect(groups.nth(1).locator('[data-testid="orders-supplier-risk"]')).toHaveCount(0);
  await expect(groups.nth(2).locator('[data-testid="orders-supplier-risk"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- unchanged: the blocks read as before ------------------------------
  // The badge joins the head only; the title, vendor code, totals and
  // lines of every block are exactly as before.
  await expect(groups.nth(0).locator('h2')).toHaveText('Highland Fasteners');
  await expect(groups.nth(0).locator('.op-supplier-vendor')).toHaveText('V-900');
  await expect(groups.nth(0).locator('[data-testid="orders-supplier-totals"]')).toHaveText(
    '1 line \u00b7 $100',
  );
  await expect(groups.nth(1).locator('h2')).toHaveText('Lowland Metals');
  await expect(groups.nth(1).locator('.op-supplier-vendor')).toHaveText('V-901');
  await expect(groups.nth(1).locator('[data-testid="orders-supplier-totals"]')).toHaveText(
    '1 line \u00b7 $40',
  );
  await expect(groups.nth(2).locator('h2')).toHaveText('No supplier terms');
  await expect(groups.nth(2).locator('[data-testid="orders-supplier-totals"]')).toHaveText(
    '1 line \u00b7 $0',
  );
  await expect(groups.nth(0).locator('[data-testid="orders-lines"] tbody tr')).toHaveCount(1);
  await expect(groups.nth(1).locator('[data-testid="orders-lines"] tbody tr')).toHaveCount(1);
  await expect(groups.nth(2).locator('[data-testid="orders-lines"] tbody tr')).toHaveCount(1);
  expect(pageErrors).toEqual([]);

  // --- failure: a 500 risk answer shows no badge, all blocks remain ------
  ctrl.riskAnswer = { status: 500, json: { detail: 'risk boom' } };
  await refresh.click();
  // The Refresh re-reads the plan and the risk alike: one plan read
  // and one risk read per load, the plan read first.
  await expect.poll(() => ctrl.supplyGets).toBe(2);
  await expect.poll(() => ctrl.riskGets).toBe(2);
  // No block has a badge, and all three blocks still show, as before.
  await expect(summary).toHaveText('3 lines \u00b7 $140 across 2 suppliers');
  await expect(groups).toHaveCount(3);
  await expect(badges).toHaveCount(0);
  await expect(groups.nth(0).locator('h2')).toHaveText('Highland Fasteners');
  await expect(groups.nth(1).locator('h2')).toHaveText('Lowland Metals');
  await expect(groups.nth(2).locator('h2')).toHaveText('No supplier terms');
  expect(pageErrors).toEqual([]);

  // --- read-only: no request other than a GET was sent ---------------------
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(true);
});
