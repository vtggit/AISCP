  await expect(dupToggleTwo).toHaveCount(1);
  await expect(dupToggleOne).toHaveText('Show items');
  await expect(dupToggleTwo).toHaveText('Show items');
  await expect(dupToggleOne).toHaveAttribute('aria-expanded', 'false');
  await expect(dupToggleTwo).toHaveAttribute('aria-expanded', 'false');
