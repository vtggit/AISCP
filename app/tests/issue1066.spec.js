// Proving spec for AIERP issue #1066 — the "Supplier risk" section of
// the Suppliers screen (#/suppliers): the expandable sole-source item
// list. A risk row whose supplier carries a non-empty
// sole_source_item_codes list (a list of strings) gains a "Show items"
// button in its Why cell, after the text
// ([data-testid="suppliers-risk-items-toggle"], aria-expanded "false").
// Pressing it inserts, directly below that row, one row
// ([data-testid="suppliers-risk-items"]) whose single cell spans the
// table and lists the codes in the answer's order, joined by a comma
// and a space, and the button then reads "Hide items" with
// aria-expanded "true"; pressing it again removes that row and
// restores the button. Each row on its own: opening one row's items
// leaves every other row as it is — the open state is the
// row's, not the supplier code's, so two rows carrying the same
// supplier code toggle independently. The open rows live in the risk
// section's state — a performance re-fetch (a window change) keeps
// them — and a new risk answer, a view re-activation, a reload and
// sign-out close every open list. A supplier whose list is empty,
// missing or not a list of strings shows no button, and its row is
// exactly as before. The rest of the risk section, the performance
// table and the terms are unchanged, every value is escaped, and the
// toggle sends no new request: the screen sends no request other than
// a GET.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1051.spec.js does it. The mocked /api/supplier-risk
// answer rates S-HIGH high (late, variable, the only supplier of 2
// items, sole_source_item_codes ["ITEM-A", "ITEM-B"]) and S-LOW low
// (no sign, an empty sole_source_item_codes list); a second answer
// carries two rows with the SAME supplier code (S-DUP), one item
// list each, for the per-row toggle proof.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1066 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

