// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route, the way
// app/tests/issue608.spec.js does it. The handler reads ctrl on
// every request, so the test can steer the risk answer
// (ctrl.riskAnswer, either a payload or a { status, json } failure),
// hold the next risk request until it is answered (ctrl.holdRiskNext
// / ctrl.heldRisk) and steer the sign-in (ctrl.config / ctrl.me).
// Every expedite request is counted in ctrl.expediteGets and every
// risk request in ctrl.riskGets, and each request's method and path
// land in ctrl.requests for the read-only check.
async function mockExpediteApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    riskAnswer: null,
    holdRiskNext: false,
    heldRisk: [],
    expediteGets: 0,
    riskGets: 0,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/expedite') {
      ctrl.expediteGets += 1;
      return route.fulfill({ status: 200, json: expediteAnswer() });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      if (ctrl.holdRiskNext) {
        ctrl.holdRiskNext = false;
        ctrl.heldRisk.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      if (ctrl.riskAnswer !== null) {
        return route.fulfill(ctrl.riskAnswer);
      }
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

test('issue1071 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in -------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockExpediteApi(page);

  const table = page.locator('[data-testid="expedite-table"]');
  const rows = page.locator('tr.ex-row');
  const refresh = page.locator('[data-testid="expedite-refresh"]');
  const badges = page.locator('[data-testid="expedite-supplier-risk"]');

  await page.goto('/');

  // No expedite or risk read before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.expediteGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // The default view is the Overview (it loads on its own), and the
  // Expedite screen has not asked for its data yet.
  expect(ctrl.expediteGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);
  expect(pageErrors).toEqual([]);

  // --- activation: one expedite read and one risk read -----------------
  // The first risk request is held until the test answers it, so the
  // expedite answer can settle while the risk answer is still out
  // the door.
  ctrl.holdRiskNext = true;
  await page.click('.nav-btn[data-view="expedite"]');
  await expect(page).toHaveURL(/#\/expedite$/);
  await expect(page.locator('#view-expedite')).toBeVisible();

  // Every load of the screen sends exactly one expedite read and,
  // beside it, exactly one risk read.
  await expect.poll(() => ctrl.expediteGets).toBe(1);
  await expect.poll(() => ctrl.riskGets).toBe(1);

  // The expedite answer settles: the two rows read in the answer's
  // order — and no badge yet, while the risk answer is still out the
  // door.
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(rows.locator('.ex-cell-order')).toHaveText(['PO004101 / 1', 'PO004102 / 2']);
  await expect(badges).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- the badge: S-HIGH reads high --------------------------------------
  // Answering the held risk read settles it: the S-HIGH row's
  // supplier cell gains the badge, after the name, the vendor code
  // and the on-time rate.
  ctrl.heldRisk[0].fulfill({ status: 200, json: RISK_ANSWER });
  ctrl.heldRisk.length = 0; // later holds start at index 0 again
  const highBadge = rows
    .nth(0)
    .locator('.ex-cell-supplier [data-testid="expedite-supplier-risk"]');
  await expect(highBadge).toHaveCount(1);
  await expect(highBadge).toHaveText('High risk');
  await expect(highBadge).toHaveClass(/is-high/);
  await expect(highBadge).toHaveAttribute(
    'title',
    'Variable lead times, Only supplier of 3 items',
  );
  expect(pageErrors).toEqual([]);

  // --- no badge: S-LOW is rated low --------------------------------------
  await expect(rows.nth(1).locator('[data-testid="expedite-supplier-risk"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- unchanged: the supplier cell reads as before -----------------------
  // The badge joins the cell only, after the existing elements: each
  // row's .ex-supplier-name reads as the expedite answer names it,
  // and the vendor code and the on-time rate stay where they were.
  await expect(rows.nth(0).locator('.ex-supplier-name')).toHaveText('Highland Fasteners');
  await expect(rows.nth(1).locator('.ex-supplier-name')).toHaveText('Lowland Metals');
  await expect(rows.nth(0).locator('.ex-supplier-code')).toHaveText('V-900');
  await expect(rows.nth(1).locator('.ex-supplier-code')).toHaveText('V-901');
  await expect(rows.nth(0).locator('.ex-supplier-rate')).toHaveText('\u00b7 72% on time');
  await expect(rows.nth(0).locator('.ex-supplier-rate')).toHaveClass(/ex-supplier-rate--risk/);
  await expect(rows.nth(1).locator('.ex-supplier-rate')).toHaveText('\u00b7 97% on time');
  await expect(rows.nth(1).locator('.ex-supplier-rate')).not.toHaveClass(/ex-supplier-rate--risk/);
  // The cell's textContent: the name's own line is CSS only (the
  // block span) — textContent carries no newline, so the parts
  // concatenate plainly, and the badge joins last, on the S-HIGH
  // row only.
  expect(await rows.nth(0).locator('.ex-cell-supplier').allTextContents()).toEqual([
    'Highland FastenersV-900\u00b7 72% on timeHigh risk',
  ]);
  expect(await rows.nth(1).locator('.ex-cell-supplier').allTextContents()).toEqual([
    'Lowland MetalsV-901\u00b7 97% on time',
  ]);
  // The line break after the name must stay CSS-only: a text-node
  // newline in the markup would break the plain concatenation above.
  expect(
    (await rows.nth(0).locator('.ex-cell-supplier').allTextContents())[0].includes('\n'),
  ).toBe(false);
  expect(pageErrors).toEqual([]);

  // --- failure: a 500 risk answer shows no badge, both rows remain --------
  ctrl.riskAnswer = { status: 500, json: { detail: 'risk boom' } };
  await refresh.click();
  // The Refresh re-reads the expedite list and the risk alike: one
  // of each per load.
  await expect.poll(() => ctrl.expediteGets).toBe(2);
  await expect.poll(() => ctrl.riskGets).toBe(2);
  // No row has a badge, and both rows still show, as before.
  await expect(badges).toHaveCount(0);
  await expect(rows).toHaveCount(2);
  await expect(rows.locator('.ex-cell-order')).toHaveText(['PO004101 / 1', 'PO004102 / 2']);
  await expect(rows.nth(0).locator('.ex-supplier-name')).toHaveText('Highland Fasteners');
  await expect(rows.nth(1).locator('.ex-supplier-name')).toHaveText('Lowland Metals');
  expect(pageErrors).toEqual([]);

  // --- read-only: no request other than a GET was sent ---------------------
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(true);
});
