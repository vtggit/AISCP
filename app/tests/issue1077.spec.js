// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route, the way
// app/tests/issue841.spec.js does it. The handler reads ctrl on
// every request, so the test can steer the sign-in (ctrl.config /
// ctrl.me). Every supply-plan request is counted in ctrl.supplyGets
// with its horizon_days query recorded in ctrl.supplyQueries, every
// risk request in ctrl.riskGets, and each request's method and path
// land in ctrl.requests for the read-only check.
async function mockOrdersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    supplyGets: 0,
    supplyQueries: [],
    riskGets: 0,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/supply-plan') {
      ctrl.supplyGets += 1;
      ctrl.supplyQueries.push(url.searchParams.get('horizon_days'));
      return route.fulfill({ status: 200, json: supplyAnswer() });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

test('issue1077 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // Every request the page sends, whatever its target: the
  // read-only check spans the whole test.
  const requests = [];
  page.on('request', (request) => {
    requests.push({ method: request.method(), url: request.url() });
  });

  // --- planner pass: development sign-in -------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = await mockOrdersApi(page);

  const summary = page.locator('[data-testid="orders-summary"]');
  const groups = page.locator('[data-testid="orders-supplier"]');
  const rows = page.locator('[data-testid="orders-lines"] tbody tr');

  await page.goto('/');

  // No plan or risk read before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.supplyGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // The default view is the Overview (it loads on its own), and the
  // Order plan has not asked for its data yet.
  expect(ctrl.supplyGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);
  expect(pageErrors).toEqual([]);

  // --- activation: one plan read and one risk read -------------------
  await page.click('.nav-btn[data-view="orders"]');
  await expect(page).toHaveURL(/#\/orders$/);
  await expect(page.locator('#view-orders')).toBeVisible();
  await expect.poll(() => ctrl.supplyGets).toBe(1);
  expect(ctrl.supplyQueries[0]).toBe('7');
  await expect.poll(() => ctrl.riskGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // --- the block, the summary and the two lines ------------------------
  await expect(summary).toHaveText('2 lines \u00b7 $340 across 1 suppliers');
  await expect(groups).toHaveCount(1);
  await expect(groups.locator('h2')).toHaveText('Chosen Toys Ltd.');
  await expect(groups.locator('.op-supplier-vendor')).toHaveText('V-500');
  await expect(groups.locator('[data-testid="orders-supplier-totals"]')).toHaveText(
    '2 lines \u00b7 $340',
  );
  // The risk answer rates the block's supplier low: no badge in the
  // block's head, as before the reason joined the lines.
  await expect(page.locator('[data-testid="orders-supplier-risk"]')).toHaveCount(0);
  await expect(rows).toHaveCount(2);

  // --- Shown: line 1's Why cell carries the supplier reason -------------
  // The arithmetic text stays, and after it one element with the test
  // id and the class holds the reason.
  const line1Reason = rows.nth(0).locator('[data-testid="orders-line-supplier-reason"]');
  await expect(line1Reason).toHaveCount(1);
  await expect(line1Reason).toHaveClass('op-supplier-reason');
  await expect(line1Reason).toHaveText(REASON);
  // The cell's text: the arithmetic, then the reason, in that order.
  expect(await rows.nth(0).locator('td.op-cell-why').allTextContents()).toEqual([
    ARITHMETIC_1 + REASON,
  ]);

  // Line 1's other cells read as before the reason joined the screen.
  await expect(rows.nth(0).locator('td.op-cell-pair')).toHaveText('TOY-01 / MAIN');
  await expect(rows.nth(0).locator('td.op-cell-due')).toHaveText('Now');
  await expect(rows.nth(0).locator('td.op-cell-date').nth(0)).toHaveText('2026-11-09');
  await expect(rows.nth(0).locator('td.op-cell-date').nth(1)).toHaveText('2026-11-23');
  await expect(rows.nth(0).locator('.op-cell-qty-num')).toHaveText('12');
  await expect(rows.nth(0).locator('.op-note')).toHaveText(['raised to minimum']);
  await expect(rows.nth(0).locator('td.op-cell-money')).toHaveText('$180');

  // --- Not shown: line 2's supplier_reason is null ----------------------
  // No reason element at all, and the Why cell reads exactly its
  // arithmetic.
  await expect(rows.nth(1).locator('[data-testid="orders-line-supplier-reason"]')).toHaveCount(
    0,
  );
  await expect(rows.nth(1).locator('td.op-cell-why')).toHaveText(ARITHMETIC_2);
  await expect(rows.nth(1).locator('td.op-cell-pair')).toHaveText('TOY-02 / WHOLESALE');
  await expect(rows.nth(1).locator('td.op-cell-due')).toHaveText('in 3 days');
  await expect(rows.nth(1).locator('.op-cell-qty-num')).toHaveText('16');
  await expect(rows.nth(1).locator('td.op-cell-money')).toHaveText('$160');
  expect(pageErrors).toEqual([]);

  // --- release state: a reserved supplier_code never aliases -------------
  // Object.prototype. The per-supplier release table is module state
  // keyed by supplier_code: with a plain object a reserved code
  // ("__proto__") would read the table's own prototype (truthy)
  // and the block's panel state would be written onto the global
  // Object.prototype. The table is null-prototype where it is
  // created (the module state) and re-created (the sign-out reset),
  // and the page's Object.prototype carries none of the release
  // state's keys as its own properties.
  // The source is read as the page itself loads it, so the check runs
  // wherever the app is served, not only next to a checkout.
  const ordersSource = (
    await page.evaluate(async () => (await fetch('js/orders.js')).text())
  ).replace(/\s+/g, ' ');
  expect(ordersSource.includes('release: Object.create(null)')).toBe(true);
  expect(ordersSource.includes('state.release = Object.create(null)')).toBe(true);
  expect(ordersSource.includes('release: {}')).toBe(false);
  expect(ordersSource.includes('state.release = {}')).toBe(false);
  const pollutedProtoKeys = await page.evaluate(
    (keys) => keys.filter((key) => Object.prototype.hasOwnProperty.call(Object.prototype, key)),
    RELEASE_STATE_KEYS,
  );
  expect(pollutedProtoKeys).toEqual([]);
  expect(pageErrors).toEqual([]);

  // --- read-only: no request other than a GET was sent --------------------
  // The handler's log covers every /api/* request ...
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(true);
  // ... and the page's own log covers everything the page sent.
  expect(requests.length).toBeGreaterThan(0);
  expect(requests.every((request) => request.method === 'GET')).toBe(true);
  expect(pageErrors).toEqual([]);
});
