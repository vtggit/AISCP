// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route. The handler reads
// ctrl on every request, so the test can steer the sign-in
// (ctrl.config / ctrl.me) and the second-sources answer
// (ctrl.secondAnswer / ctrl.secondStatus). Every performance request
// is counted in ctrl.perfGets, every risk request in ctrl.riskGets,
// every second-sources request in ctrl.secondGets, and each request's
// method and path land in ctrl.requests for the read-only check.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    perfGets: 0,
    riskGets: 0,
    secondGets: 0,
    secondAnswer: SECOND_ANSWER,
    secondStatus: 200,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.perfGets += 1;
      return route.fulfill({ status: 200, json: PERFORMANCE });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/second-sources') {
      ctrl.secondGets += 1;
      if (ctrl.secondStatus !== 200) {
        return route.fulfill({
          status: ctrl.secondStatus,
          json: { detail: 'Internal Server Error' },
        });
      }
      return route.fulfill({ status: 200, json: ctrl.secondAnswer });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

test('issue1087 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockSuppliersApi(page);

  const perfTable = page.locator('[data-testid="suppliers-table"]');
  const riskSection = page.locator('[data-testid="suppliers-risk"]');
  const riskRows = page.locator('[data-testid="suppliers-risk-row"]');
  const termsSection = page.locator('[data-testid="suppliers-terms"]');
  const secondSection = page.locator('[data-testid="suppliers-second"]');
  const secondRows = page.locator('[data-testid="suppliers-second-row"]');
  const secondError = secondSection.locator(
    '[data-testid="suppliers-second-error"]',
  );

  // --- planner pass: development sign-in ------------------------------
  await page.goto('/');

  // No suppliers read before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.perfGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);
  expect(ctrl.secondGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(pageErrors).toEqual([]);

  // --- the load: one second-sources read beside the risk read --------
  await page.click('.nav-btn[data-view="suppliers"]');
  await expect(page).toHaveURL(/#\/suppliers$/);
  await expect.poll(() => ctrl.perfGets).toBe(1);
  await expect.poll(() => ctrl.riskGets).toBe(1);
  await expect.poll(() => ctrl.secondGets).toBe(1);

  // The section sits directly after the risk section and before the
  // terms section in the DOM, and renders whenever the risk section
  // does.
  await expect(riskSection).toBeVisible();
  await expect(secondSection).toBeVisible();
  await expect(secondSection.locator('.sp-second-heading')).toHaveText(
    'Second sources',
  );
  const sectionPlace = await page.evaluate(() => {
    const risk = document.querySelector('[data-testid="suppliers-risk"]');
    const second = document.querySelector('[data-testid="suppliers-second"]');
    const terms = document.querySelector('[data-testid="suppliers-terms"]');
    return {
      afterRisk: !!(risk && second && risk.nextElementSibling === second),
      beforeTerms: !!(second && terms && second.nextElementSibling === terms),
    };
  });
  expect(sectionPlace).toEqual({ afterRisk: true, beforeTerms: true });
  // the settled section shows its table, never the word "Loading"
  await expect(secondSection).toContainText('Second sources');
  await expect(secondSection).not.toContainText('Loading');
  expect(pageErrors).toEqual([]);

  // --- rows: two, ITEM-A then ITEM-B -----------------------------------
  await expect(secondRows).toHaveCount(2);
  const rowTexts = await secondRows.evaluateAll((rows) =>
    rows.map((row) => row.textContent),
  );
  expect(rowTexts[0].includes('ITEM-A')).toBe(true);
  expect(rowTexts[0].includes('ITEM-B')).toBe(false);
  expect(rowTexts[1].includes('ITEM-B')).toBe(true);
  expect(rowTexts[1].includes('ITEM-A')).toBe(false);

  // The ITEM-A row includes the description, the only supplier's
  // name and its level.
  const itemARow = secondRows.nth(0);
  await expect(itemARow).toContainText('Bose headset');
  await expect(itemARow).toContainText('Only Co');
  await expect(itemARow).toContainText('High risk');
  expect(pageErrors).toEqual([]);

  // --- candidates: the three, in the answer's order --------------------
  const itemACandidates = itemARow.locator(
    '[data-testid="suppliers-second-candidate"]',
  );
  await expect(itemACandidates).toHaveCount(3);
  await expect(itemACandidates.nth(0)).toHaveText(
    'Low Co (Low risk, terms, 5 days)',
  );
  await expect(itemACandidates.nth(1)).toHaveText(
    'S-ZERO (Medium risk, terms)',
  );
  await expect(itemACandidates.nth(2)).toHaveText(
    'Sim Co (Unrated, 3 similar items)',
  );
  // no "no other supplier" note on a row that has candidates
  await expect(
    itemARow.locator('[data-testid="suppliers-second-none"]'),
  ).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- none: ITEM-B has no candidates, its hold is an em dash ----------
  const itemBRow = secondRows.nth(1);
  const itemBNone = itemBRow.locator('[data-testid="suppliers-second-none"]');
  await expect(itemBNone).toHaveCount(1);
  await expect(itemBNone).toHaveText('No other supplier found');
  await expect(itemBRow.locator('[data-testid="suppliers-second-candidate"]')).toHaveCount(0);
  await expect(itemBRow.locator('[data-testid="suppliers-second-hold"]')).toHaveText(
    '\u2014',
  );
  expect(pageErrors).toEqual([]);

  // --- hold: ITEM-A's bridge stock, the arithmetic as title ------------
  const itemAHold = itemARow.locator('[data-testid="suppliers-second-hold"]');
  await expect(itemAHold).toHaveCount(1);
  await expect(itemAHold).toHaveText('Hold 56, short 26');
  await expect(itemAHold).toHaveAttribute(
    'title',
    '4.0 a day x 14 days = 56 units; on hand 30, short 26',
  );
  expect(pageErrors).toEqual([]);

  // The performance table, the risk section and the terms stand
  // exactly as they were: the risk rows with their Show items
  // toggles, the performance rows, the terms section.
  await expect(perfTable).toBeVisible();
  await expect(perfTable.locator('tr.sp-row')).toHaveCount(2);
  await expect(riskRows).toHaveCount(2);
  await expect(
    page.locator('[data-testid="suppliers-risk-items-toggle"]'),
  ).toHaveCount(1);
  await expect(termsSection).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- failure: a 500 answers the error note, no rows ------------------
  // Re-activating the view re-loads the screen; the new
  // second-sources read answers 500.
  ctrl.secondStatus = 500;
  await page.click('.nav-btn[data-view="overview"]');
  await page.click('.nav-btn[data-view="suppliers"]');
  await expect.poll(() => ctrl.secondGets).toBe(2);
  await expect(secondError).toBeVisible();
  await expect(secondRows).toHaveCount(0);
  await expect(secondSection.locator('[data-testid="suppliers-second-empty"]')).toHaveCount(0);
  // the rest of the screen is as before: the risk section still shows
  // its rows, and so does the performance table
  await expect(riskSection).toBeVisible();
  await expect(riskRows).toHaveCount(2);
  await expect(perfTable).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- read-only: no request other than a GET in the whole test --------
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(
    true,
  );
});
