// Proving spec for AIERP issue #1087 — the "Second sources" section
// of the Suppliers screen (#/suppliers): the other suppliers of the
// sole-source items. Each load of the screen sends one
// GET /api/second-sources in the same load call that sends the
// existing risk read, under its own request-sequence guard, so a
// late answer from an older load or from before sign-out is dropped;
// sign-out clears it, and the existing reads keep their order and
// their count. The section ([data-testid="suppliers-second"],
// heading "Second sources") sits directly after the risk section
// ([data-testid="suppliers-risk"]) and before the terms section, and
// renders whenever the risk section does: one row
// ([data-testid="suppliers-second-row"]) per entry in the answer's
// items array, in the answer's order — the item (the item_code, the
// description when present), the only supplier (the supplier_name,
// else the supplier_code, then the level as High risk, Medium risk
// or Low risk, Unrated when the level is null), the candidates and
// the stock to hold. Each candidate is one element
// ([data-testid="suppliers-second-candidate"]) in the answer's
// order, reading "<name> (<risk>, <basis>)": the name the
// supplier_name else the supplier_code, the risk Low risk, Medium
// risk or High risk, Unrated when null, the basis "terms, <N> days"
// for a terms candidate whose lead_time_days is a number above 0,
// "terms" for any other terms candidate, "<N> similar items" (the
// word item when it is 1) for a similar candidate. An entry with an
// empty candidates list shows one element
// ([data-testid="suppliers-second-none"]) reading "No other supplier
// found". The hold cell ([data-testid="suppliers-second-hold"])
// reads "Hold <bridge_units>, short <bridge_short_units>" with a
// title of the bridge_arithmetic when bridge_units is a number, an
// em dash otherwise. While the read is out a short skeleton shows
// (never the word "Loading"); a failed or malformed answer shows
// [data-testid="suppliers-second-error"] with no rows, an empty
// items array [data-testid="suppliers-second-empty"] reading "No
// item relies on a single supplier." — in both cases the rest of
// the screen is as before. The screen does not coerce numeric
// strings: lead_time_days and bridge_units count as numbers only
// when they are JSON numbers. The performance table, the risk
// section and its Show items toggles and the terms are unchanged,
// every value is escaped, and the screen sends no request other
// than a GET.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1066.spec.js does it. The mocked performance and
// risk answers are that spec's: S-HIGH high (late, variable, the
// only supplier of 2 items, sole_source_item_codes ["ITEM-A",
// "ITEM-B"]) and S-LOW low (no sign, an empty sole_source_item_codes
// list). The mocked /api/second-sources answer carries two entries:
// ITEM-A, described "Bose headset", only from S-ONLY named "Only Co"
// rated high, with candidates S-LOW named "Low Co" rated low on
// terms with lead time 5, S-ZERO with no name rated medium on terms
// with lead time 0, and S-SIM named "Sim Co" unrated on similar with
// 3 similar items — bridge_units 56, bridge_short_units 26 and
// bridge_arithmetic "4.0 a day x 14 days = 56 units; on hand 30,
// short 26"; and ITEM-B, only from S-ONLY, with no candidates and a
// null bridge_units.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1087 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

