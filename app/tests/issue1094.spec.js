// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route. The handler reads
// ctrl on every request, so the test can steer the sign-in
// (ctrl.config / ctrl.me) and the second-sources answer
// (ctrl.secondAnswer). Every performance request is counted in
// ctrl.perfGets, every second-sources request in ctrl.secondGets,
// and each request's method and path land in ctrl.requests for the
// read-only check.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    perfGets: 0,
    secondGets: 0,
    secondAnswer: SECOND_ANSWER,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.perfGets += 1;
      return route.fulfill({ status: 200, json: PERFORMANCE });
    }
    if (path === '/api/supplier-risk') {
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/second-sources') {
      ctrl.secondGets += 1;
      return route.fulfill({ status: 200, json: ctrl.secondAnswer });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

test('issue1094 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockSuppliersApi(page);

  const perfTable = page.locator('[data-testid="suppliers-table"]');
  const secondSection = page.locator('[data-testid="suppliers-second"]');
  const secondTable = page.locator('[data-testid="suppliers-second-table"]');
  const secondRows = page.locator('[data-testid="suppliers-second-row"]');
  const summary = page.locator('[data-testid="suppliers-second-summary"]');
  const shortOnly = page.locator('[data-testid="suppliers-second-short-only"]');
  const noneShort = secondSection.locator(
    '[data-testid="suppliers-second-none-short"]',
  );

  // --- planner pass: development sign-in ------------------------------
  await page.goto('/');

  // No second-sources read before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.perfGets).toBe(0);
  expect(ctrl.secondGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(pageErrors).toEqual([]);

  // --- the load: one second-sources read, the table shows -------------
  await page.click('.nav-btn[data-view="suppliers"]');
  await expect(page).toHaveURL(/#\/suppliers$/);
  await expect.poll(() => ctrl.perfGets).toBe(1);
  await expect.poll(() => ctrl.secondGets).toBe(1);
  await expect(secondSection).toBeVisible();

  // --- summary: the line stands directly above the table --------------
  await expect(summary).toBeVisible();
  await expect(summary).toHaveText(
    '3 items rely on one supplier; 1 is short of stock.',
  );
  const summaryPlace = await page.evaluate(() => {
    const line = document.querySelector(
      '[data-testid="suppliers-second-summary"]',
    );
    const bar = line ? line.closest('.sp-second-summary-bar') : null;
    const table = document.querySelector('[data-testid="suppliers-second-table"]');
    const region = table ? table.closest('.sp-second-region') : null;
    return {
      lineAboveTable: !!(bar && region && bar.nextElementSibling === region),
      filterBesideSummary: !!(
        bar &&
        bar.querySelector('[data-testid="suppliers-second-short-only"]')
      ),
    };
  });
  expect(summaryPlace).toEqual({
    lineAboveTable: true,
    filterBesideSummary: true,
  });
  expect(pageErrors).toEqual([]);

  // --- filter: unchecked by default, labelled, all three rows ---------
  await expect(shortOnly).toBeVisible();
  await expect(shortOnly).not.toBeChecked();
  await expect(page.locator('label[for="sp-second-short-only"]'))
    .toHaveText('Only items short of stock');
  await expect(secondRows).toHaveCount(3);
  const rowCodes = await secondRows.evaluateAll((rowElements) =>
    rowElements.map((row) =>
      row.querySelector('.sp-second-item-code').textContent,
    ),
  );
  expect(rowCodes).toEqual(['ITEM-A', 'ITEM-B', 'ITEM-C']);

  // The rows and their cells are unchanged by the new summary line:
  // ITEM-A's hold with its arithmetic title, ITEM-B's zero short,
  // ITEM-C's em dash.
  await expect(secondRows.nth(0).locator('[data-testid="suppliers-second-hold"]'))
    .toHaveText('Hold 56, short 26');
  await expect(secondRows.nth(0).locator('[data-testid="suppliers-second-hold"]'))
    .toHaveAttribute('title', '4.0 a day x 14 days = 56 units; on hand 30, short 26');
  await expect(secondRows.nth(1).locator('[data-testid="suppliers-second-hold"]'))
    .toHaveText('Hold 12, short 0');
  await expect(secondRows.nth(2).locator('[data-testid="suppliers-second-hold"]'))
    .toHaveText('\u2014');
  // the rest of the screen is as before
  await expect(perfTable).toBeVisible();
  await expect(perfTable.locator('tr.sp-row')).toHaveCount(2);
  await expect(page.locator('[data-testid="suppliers-risk-row"]')).toHaveCount(2);
  expect(pageErrors).toEqual([]);

  // --- checking: only the short row, in the answer's order, and no
  //     request goes out ------------------------------------------------
  let requestsBefore = ctrl.requests.length;
  await shortOnly.check();
  await expect(shortOnly).toBeChecked();
  await expect(secondRows).toHaveCount(1);
  await expect(secondRows.nth(0).locator('.sp-second-item-code'))
    .toHaveText('ITEM-A');
  // the summary stays, with its figures unchanged
  await expect(summary).toHaveText(
    '3 items rely on one supplier; 1 is short of stock.',
  );
  expect(ctrl.requests.length).toBe(requestsBefore);
  expect(pageErrors).toEqual([]);

  // --- unchecking: all three rows again, and no request ---------------
  requestsBefore = ctrl.requests.length;
  await shortOnly.uncheck();
  await expect(shortOnly).not.toBeChecked();
  await expect(secondRows).toHaveCount(3);
  const rowCodesAgain = await secondRows.evaluateAll((rowElements) =>
    rowElements.map((row) =>
      row.querySelector('.sp-second-item-code').textContent,
    ),
  );
  expect(rowCodesAgain).toEqual(['ITEM-A', 'ITEM-B', 'ITEM-C']);
  expect(ctrl.requests.length).toBe(requestsBefore);
  expect(pageErrors).toEqual([]);

  // --- a window change re-renders the section with the filter exactly
  //     as left — it does not silently revert ----------------------------
  await shortOnly.check();
  await expect(secondRows).toHaveCount(1);
  const perfGetsBefore = ctrl.perfGets;
  const secondGetsBefore = ctrl.secondGets;
  await page.selectOption('[data-testid="suppliers-window"]', '90');
  await expect.poll(() => ctrl.perfGets).toBe(perfGetsBefore + 1);
  expect(ctrl.secondGets).toBe(secondGetsBefore);
  await expect(shortOnly).toBeChecked();
  await expect(secondRows).toHaveCount(1);
  await expect(secondRows.nth(0).locator('.sp-second-item-code'))
    .toHaveText('ITEM-A');
  // the summary still counts the whole answer, not the filtered rows
  await expect(summary).toHaveText(
    '3 items rely on one supplier; 1 is short of stock.',
  );
  expect(pageErrors).toEqual([]);
  await shortOnly.uncheck();
  await expect(secondRows).toHaveCount(3);

  // --- a new second-sources answer unchecks the filter -----------------
  await shortOnly.check();
  await expect(secondRows).toHaveCount(1);
  await page.click('.nav-btn[data-view="overview"]');
  await page.click('.nav-btn[data-view="suppliers"]');
  await expect.poll(() => ctrl.secondGets).toBe(secondGetsBefore + 1);
  await expect(shortOnly).not.toBeChecked();
  await expect(secondRows).toHaveCount(3);
  expect(pageErrors).toEqual([]);

  // --- nothing short: the table is replaced by the note, the summary
  //     stays -----------------------------------------------------------
  ctrl.secondAnswer = NONE_SHORT_ANSWER;
  await page.click('.nav-btn[data-view="overview"]');
  await page.click('.nav-btn[data-view="suppliers"]');
  await expect.poll(() => ctrl.secondGets).toBe(secondGetsBefore + 2);
  // the singular: one item, and none of them short
  await expect(summary).toHaveText(
    '1 item relies on one supplier; 0 are short of stock.',
  );
  await expect(shortOnly).not.toBeChecked();
  await expect(secondRows).toHaveCount(1);

  requestsBefore = ctrl.requests.length;
  await shortOnly.check();
  await expect(noneShort).toBeVisible();
  await expect(noneShort).toHaveText('No item is short of stock.');
  await expect(secondRows).toHaveCount(0);
  await expect(secondTable).toHaveCount(0);
  // the summary line stays, beside the still-checked filter
  await expect(summary).toHaveText(
    '1 item relies on one supplier; 0 are short of stock.',
  );
  await expect(shortOnly).toBeChecked();
  expect(ctrl.requests.length).toBe(requestsBefore);
  expect(pageErrors).toEqual([]);

  // --- sign-out unchecks the filter and resets the section -------------
  await page.click('#signout-button');
  await expect(page.locator('#signin-form')).toBeVisible();
  // the reset render stands alone: the section and its filter are gone
  await expect(secondSection).toHaveCount(0);
  await expect(shortOnly).toHaveCount(0);

  // Sign back in: the screen reloads with the filter unchecked.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect.poll(() => ctrl.secondGets).toBe(secondGetsBefore + 3);
  await expect(shortOnly).toBeVisible();
  await expect(shortOnly).not.toBeChecked();
  await expect(summary).toHaveText(
    '1 item relies on one supplier; 0 are short of stock.',
  );
  await expect(secondRows).toHaveCount(1);
  expect(pageErrors).toEqual([]);

  // --- read-only: no request other than a GET in the whole test --------
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(
    true,
  );
});
