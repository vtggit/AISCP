// Proving spec for AIERP issue #1098 — the "Service levels and their
// cost" card on the Settings view (#/settings).
//
// After the intermittent-impact card, the screen appends the card
// [data-testid="service-curve"], fetched separately from
// GET /api/service-levels/curve under its own request-sequence guard
// (a late answer from an older load or from before sign-out is
// dropped; sign-out clears it). The gate serves the static app with
// no backend, so every /api/* call is mocked with page.route (the
// same mocks and sign-in as app/tests/issue699.spec.js: the
