// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user: issue1098's mocks. The one
// route handler is defined before it is registered with page.route.
// `apiMethods` collects every /api request's method (the read-only
// proof) and `apiOrigins` the app origins the /api routes were seen
// on (so the request listener can ignore the IdP's own origin).
async function mockSettingsApi(page, { config, me, entries, impact, curve, apiMethods, apiOrigins }) {
  const api = {
    settingsGets: 0,
    impactGets: 0,
    curveGets: 0,
    current: entries,
    impact, // { status, body }
    curve, // { status, body }
    appOrigin: { value: null },
  };
  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (api.appOrigin.value === null) {
      api.appOrigin.value = url.origin;
    }
    apiOrigins.add(url.origin);
    apiMethods.push(request.method());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      api.impactGets += 1;
      return route.fulfill({
        status: api.impact.status,
        json: api.impact.body,
      });
    }
    if (path === '/api/service-levels/curve' && request.method() === 'GET') {
      api.curveGets += 1;
      return route.fulfill({ status: api.curve.status, json: api.curve.body });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };
  await page.route('**/api/**', handler);
  return api;
}

test('issue1105 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  // Every /api request's method, across the whole test: the
  // read-only proof. Non-GET requests to the app's own origin (never
  // the IdP's) are collected alongside, so a write anywhere in the
  // app is caught.
  const apiMethods = [];
  const apiOrigins = new Set();
  const nonGetAppRequests = [];
  page.on('request', (request) => {
    if (request.method() === 'GET') {
      return;
    }
    let origin;
    try {
      origin = new URL(request.url()).origin;
    } catch (error) {
      return;
    }
    if (apiOrigins.has(origin)) {
      nonGetAppRequests.push(request.method() + ' ' + request.url());
    }
  });

  const api = await mockSettingsApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    entries: [booleanEntry(), enumEntry(), numberEntry()],
    impact: { status: 200, body: impactBody() },
    curve: { status: 200, body: CURVE_BODY },
    apiMethods,
    apiOrigins,
  });

  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // Open the settings view by hash change; the curve read starts with
  // the activation, the way the settings, mappings, budgets and
  // impact reads do.
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);
  await expect.poll(() => api.curveGets).toBeGreaterThanOrEqual(1);

  const card = page.locator('[data-testid="service-curve"]');
  await expect(card).toBeVisible();
  const classBlocks = page.locator('[data-testid="service-curve-class"]');
  await expect(classBlocks).toHaveCount(2);

  const classA = classBlocks.nth(0);
  const classC = classBlocks.nth(1);
  await expect(classA.locator('.service-curve-class-title')).toHaveText(
    'Class A ' + MIDDLE_DOT + ' 3 item-sites ' + MIDDLE_DOT + ' now 95%',
  );
  await expect(classC.locator('.service-curve-class-title')).toHaveText(
    'Class C ' + MIDDLE_DOT + ' 1 item-sites ' + MIDDLE_DOT + ' now 95%',
  );

  // --- header: class A's table headers end with "Fill rate" ----------
  const headersA = await classA.evaluate((blockEl) =>
    Array.from(blockEl.querySelectorAll('thead th')).map((th) => th.textContent),
  );
  expect(headersA).toEqual([
    'Service level',
    'Safety stock (units)',
    'Value',
    'Holding cost a year',
    'Extra cost a year',
    'Fill rate',
  ]);
  expect(headersA[headersA.length - 1]).toBe('Fill rate');

  // --- cells: class A's last cells read 99.53%, 99.79% and "—", in
  // --- point order — the other columns unchanged.
  const cellsA = await classA.evaluate((blockEl) =>
    Array.from(blockEl.querySelectorAll('[data-testid="service-curve-point"]')).map((tr) =>
      Array.from(tr.querySelectorAll('td')).map((td) => td.textContent),
    ),
  );
  expect(cellsA).toEqual([
    ['90%', '1,282', '$12,815.52', '$3,203.88', EM_DASH, '99.53%'],
    ['95% (now)', '1,645', '$16,448.54', '$4,112.13', '+$908.25', '99.79%'],
    ['99.5%', '2,576', '$25,758.29', '$6,439.57', '+$2,327.44', EM_DASH],
  ]);
  expect(cellsA.map((cells) => cells[cells.length - 1])).toEqual([
    '99.53%',
    '99.79%',
    EM_DASH,
  ]);
  // The answer stays valid when the points carry no
  // expected_fill_rate at all: class C's last column reads the em
  // dash in every row.
  const fillCellsC = await classC.evaluate((blockEl) =>
    Array.from(blockEl.querySelectorAll('[data-testid="service-curve-point"]')).map(
      (tr) => Array.from(tr.querySelectorAll('td')).pop().textContent,
    ),
  );
  expect(fillCellsC).toEqual([EM_DASH, EM_DASH, EM_DASH]);

  // --- note: class A shows the fill note under its heading, class C
  // --- shows none (fill_rate_item_sites equal to its item-sites).
  await expect(classA.locator('[data-testid="service-curve-fill-note"]')).toHaveCount(1);
  await expect(classA.locator('[data-testid="service-curve-fill-note"]')).toHaveText(FILL_NOTE_A);
  const notePlacement = await classA.evaluate((blockEl) => {
    const note = blockEl.querySelector('[data-testid="service-curve-fill-note"]');
    const title = blockEl.querySelector('.service-curve-class-title');
    return !!(note && title && note.previousElementSibling === title);
  });
  expect(notePlacement).toBe(true);
  await expect(classC.locator('[data-testid="service-curve-fill-note"]')).toHaveCount(0);

  // --- read-only: across the whole test, every request to the app was
  // --- a GET — the card (and the rest of the screen) sends no write.
  expect(apiMethods.length).toBeGreaterThan(0);
  expect(apiMethods.every((method) => method === 'GET')).toBe(true);
  expect(nonGetAppRequests).toEqual([]);
});
