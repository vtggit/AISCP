// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user: issue1105's mocks. The one
// route handler is defined before it is registered with page.route.
// `apiMethods` collects every /api request's method (the read-only
// proof) and `apiOrigins` the app origins the /api routes were seen
// on (so the request listener can ignore the IdP's own origin). The
// curve's answer is read from `api.curve` at request time, so the
// test can swap the body between reads.
async function mockSettingsApi(page, { config, me, entries, impact, curve, apiMethods, apiOrigins }) {
  const api = {
    settingsGets: 0,
    impactGets: 0,
    curveGets: 0,
    current: entries,
    impact, // { status, body }
    curve, // { status, body }
    appOrigin: { value: null },
  };
  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (api.appOrigin.value === null) {
      api.appOrigin.value = url.origin;
    }
    apiOrigins.add(url.origin);
    apiMethods.push(request.method());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [HOSTILE_MAPPING] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      api.impactGets += 1;
      return route.fulfill({
        status: api.impact.status,
        json: api.impact.body,
      });
    }
    if (path === '/api/service-levels/curve' && request.method() === 'GET') {
      api.curveGets += 1;
      return route.fulfill({ status: api.curve.status, json: api.curve.body });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };
  await page.route('**/api/**', handler);
  return api;
}

test('issue1109 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  // Every /api request's method, across the whole test: the
  // read-only proof. Non-GET requests to the app's own origin (never
  // the IdP's) are collected alongside, so a write anywhere in the
  // app is caught.
  const apiMethods = [];
  const apiOrigins = new Set();
  const nonGetAppRequests = [];
  page.on('request', (request) => {
    if (request.method() === 'GET') {
      return;
    }
    let origin;
    try {
      origin = new URL(request.url()).origin;
    } catch (error) {
      return;
    }
    if (apiOrigins.has(origin)) {
      nonGetAppRequests.push(request.method() + ' ' + request.url());
    }
  });

  const api = await mockSettingsApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    entries: [booleanEntry(), enumEntry(), numberEntry()],
    impact: { status: 200, body: impactBody() },
    curve: { status: 200, body: curveBody('cycle') },
    apiMethods,
    apiOrigins,
  });

  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // Open the settings view by hash change; the curve read starts with
  // the activation, the way the settings, mappings, budgets and
  // impact reads do.
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.curveGets).toBeGreaterThanOrEqual(1);

  const card = page.locator('[data-testid="service-curve"]');
  await expect(card).toBeVisible();
  const rateLine = card.locator('[data-testid="service-curve-rate"]');
  const targetLine = card.locator('[data-testid="service-curve-target"]');
  const classBlocks = card.locator('[data-testid="service-curve-class"]');

  // --- cycle: the target line reads the cycle text and directly
  // --- follows the rate line; the mode line, the rate line and the
  // --- class blocks are unchanged.
  await expect(card.locator('[data-testid="service-curve-mode"]')).toHaveText(MODE_SINGLE);
  await expect(rateLine).toHaveText(RATE_LINE);
  await expect(targetLine).toHaveCount(1);
  await expect(targetLine).toHaveText(TARGET_CYCLE);
  const cyclePlacement = await card.evaluate((cardEl) => {
    const target = cardEl.querySelector('[data-testid="service-curve-target"]');
    const rate = cardEl.querySelector('[data-testid="service-curve-rate"]');
    return !!(target && rate && target.previousElementSibling === rate);
  });
  expect(cyclePlacement).toBe(true);
  await expect(classBlocks).toHaveCount(2);

  // --- fill rate: the same line reads the fill-rate text.
  // --- Leaving settings and coming back re-reads the curve; the
  // --- handler answers with the swapped body.
  api.curve.body = curveBody('fill_rate');
  await page.click('.nav-btn[data-view="overview"]');
  await expect(page.locator('#view-overview')).toHaveClass(/is-active/);
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.curveGets).toBeGreaterThanOrEqual(2);
  await expect(targetLine).toHaveText(TARGET_FILL);
  const fillPlacement = await card.evaluate((cardEl) => {
    const target = cardEl.querySelector('[data-testid="service-curve-target"]');
    const rate = cardEl.querySelector('[data-testid="service-curve-rate"]');
    return !!(target && rate && target.previousElementSibling === rate);
  });
  expect(fillPlacement).toBe(true);

  // --- missing: with the field left out there is no target line and
  // --- the answer is still accepted — the class blocks still show.
  api.curve.body = curveBody(null);
  await page.click('.nav-btn[data-view="overview"]');
  await expect(page.locator('#view-overview')).toHaveClass(/is-active/);
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.curveGets).toBeGreaterThanOrEqual(3);
  // The re-read re-renders the card from scratch (a skeleton in
  // between), so the class-block count is asserted, then the target
  // line's absence, then the class-block count again: only the final
  // re-render — not the skeleton and not the previous answer's card —
  // satisfies all three.
  await expect(classBlocks).toHaveCount(2);
  await expect(targetLine).toHaveCount(0);
  await expect(classBlocks).toHaveCount(2);
  // The mode line and the rate line are still there, unchanged.
  await expect(card.locator('[data-testid="service-curve-mode"]')).toHaveText(MODE_SINGLE);
  await expect(rateLine).toHaveText(RATE_LINE);

  // --- hostile mapping: the one stored mapping the mock serves
  // --- carries a "__proto__" key whose object holds an updated_at.
  // --- The row renders its own values instead of inheriting it: the
  // --- kind, the numeric AIERP code normalized to the string "154",
  // --- the Odoo code, and an Updated cell with no date — had
  // --- normalizeMapping copied the key, the served object would be
  // --- the row's prototype and the cell would read
  // --- "Updated 2001-02-03".
  const mappingRow = page.locator('[data-testid="erp-mapping-row"]');
  await expect(mappingRow).toHaveCount(1);
  await expect(mappingRow).toHaveAttribute('data-mapping-id', '7');
  await expect(mappingRow.locator('.erp-mapping-kind')).toHaveText('Item');
  const mappingCodes = mappingRow.locator('.erp-mapping-code');
  await expect(mappingCodes.first()).toHaveText('154');
  await expect(mappingCodes.nth(1)).toHaveText('OD-154');
  await expect(mappingRow.locator('.erp-mapping-updated')).toHaveText('Updated');

  // --- read-only: across the whole test, every request to the app
  // --- was a GET — the card (and the rest of the screen) sends no
  // --- POST, PUT or DELETE.
  expect(apiMethods.length).toBeGreaterThan(0);
  expect(apiMethods.every((method) => method === 'GET')).toBe(true);
  expect(nonGetAppRequests).toEqual([]);
});
