// Proving spec for AIERP issue #1109 — the service-target line of
// the "Service levels and their cost" card on the Settings view
// (#/settings).
//
// Directly after the rate line ([data-testid="service-curve-rate"]),
// the card gains a line ([data-testid="service-curve-target"]) by the
// answer's service_target: "cycle" reads "The levels are cycle
// service levels: the chance of not running out in a replenishment
// cycle." and "fill_rate" reads "The levels are fill-rate targets:
// the share of demand served straight from stock; safety stock is
// solved to meet them."; with the field missing or any other value
// there is no such line and the answer is still accepted. The mode
// line and its text, the rate line, the class blocks and their
// columns are unchanged, and the card sends no POST, PUT or DELETE.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1105.spec.js does it: the development token card as
// an admin, at 1440x900 on #/settings. The curve route answers three
// ways — service_target "cycle", "fill_rate" and the field left out —
// each answered on a fresh read, the view leaving settings and
// coming back. Proves:
//   * cycle: with service_target "cycle", service-curve-target reads
//     the cycle text and directly follows service-curve-rate;
//   * fill rate: with "fill_rate" it reads the fill-rate text;
//   * missing: with the field left out there is no
//     service-curve-target and the class blocks still show;
//   * hostile mapping: the one stored mapping the mock serves
//     carries a "__proto__" key whose object holds an updated_at —
//     the row renders its own values (the numeric AIERP code as the
//     string "154") and its Updated cell shows no date: the served
//     object never became the row's prototype;
//   * read-only: across the whole test, no request other than a GET
//     was sent to the app.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1109 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

