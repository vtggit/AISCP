// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user: issue1109's mocks plus the
// suggestion route, whose requests are recorded with their query and
// whose answers the test holds — every request is kept until the
// test fulfils its route, one by one. `apiMethods` collects every
// /api request's method (the read-only proof) and `apiOrigins` the
// app origins the /api routes were seen on (so the request listener
// can ignore the IdP's own origin).
async function mockSettingsApi(page, { config, me, entries, impact, curve, apiMethods, apiOrigins }) {
  const api = {
    settingsGets: 0,
    impactGets: 0,
    curveGets: 0,
    suggestionGets: 0,
    suggestionMethods: [],
    suggestionQueries: [],
    suggestionHeld: [],
    meRequests: [],
    current: entries,
    impact, // { status, body }
    curve, // { status, body }
    appOrigin: { value: null },
  };
  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (api.appOrigin.value === null) {
      api.appOrigin.value = url.origin;
    }
    apiOrigins.add(url.origin);
    apiMethods.push(request.method());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      api.meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      api.impactGets += 1;
      return route.fulfill({
        status: api.impact.status,
        json: api.impact.body,
      });
    }
    if (path === '/api/service-levels/curve' && request.method() === 'GET') {
      api.curveGets += 1;
      return route.fulfill({ status: api.curve.status, json: api.curve.body });
    }
    if (path === '/api/service-levels/suggestion') {
      api.suggestionGets += 1;
      api.suggestionMethods.push(request.method());
      api.suggestionQueries.push(url.searchParams.get('target_fill_rate'));
      // Held: the test releases the answers one by one, in the order
      // it chooses, through the route it kept.
      api.suggestionHeld.push(route);
      return;
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };
  await page.route('**/api/**', handler);
  return api;
}

// The production boot's PKCE round-trip, mocked the way the other
// proofs' viewer passes do it: the IdP's auth endpoint answers with a
// page that bounces straight back to the app with a code and the same
// state, and the token endpoint answers with the viewer's token.
async function mockPkceRoundTrip(page, appOrigin) {
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
}

