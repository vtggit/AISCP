// Proving spec for AIERP issue #1122 — the "Cheapest levels for a
// fill-rate target" suggestion block of the "Service levels and
// their cost" card on the Settings view (#/settings).
//
// After the card's last class block — and only while the card shows
// its classes — the block [data-testid="service-curve-suggest"]
// holds, in order, the title
// ([data-testid="service-curve-suggest-title"]), the number input
// ([data-testid="service-curve-suggest-target"]) labelled "Target
// fill rate (%)" (min 50, max 99.9, step 0.1), the button
// ([data-testid="service-curve-suggest-go"], "Suggest levels") and
// the note ([data-testid="service-curve-suggest-note"]). Opening the
// view sends nothing to /api/service-levels/suggestion; a click on
// the button, or an Enter in the input, with a value from 50 to
// 99.9 sends one GET
// /api/service-levels/suggestion?target_fill_rate=<the value
// divided by 100, at most four decimals, no trailing zeros>, and
// the answer reads in [data-testid="service-curve-suggest-result"]
// as the current and the suggested lines — with a null suggested
// (and a highest that has a fill rate) the out-of-reach line
// instead of the suggested one, and with the current combination's
// fill rate null the single nothing-to-measure line; the suggested
// line's last words follow holding_cost_delta (below zero
// "<amount> less", above zero "<amount> more", zero "the same", the
// amount without a sign). A refused value (empty, below 50 or above
// 99.9) shows the invalid line and sends nothing; a non-200 answer,
// a network failure or a body without the current and highest
// objects that each carry levels shows the error line and no
// result. Only the answer to the latest ask is shown; when the card
// reads its curve again the lines are cleared and any answer still
// out is dropped, the typed value kept — and sign-out clears the
// typed value too. No element of the block carries role="alert".
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1109.spec.js does it: the development token card as
// an admin, at 1440x900 on #/settings, a curve of three classes —
// and /api/service-levels/suggestion is added, whose answers the
// test holds and releases one by one and whose requests it records
// with their query. The second pass, in the same test after a full
// reload, runs as a NON-ADMIN (role "user"): it boots the production
// way (the token in the URL hash, /api/auth/config and /api/auth/me
// mocked for that user, the PKCE round-trip mocked) and asserts the
// admin-only controls (the mappings and the budgets add forms, the
// adopt/withdraw actions) are absent while the settings rows and
// the read-only cards — the curve card and its suggestion block
// among them — still render.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1122 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

