// Proving spec for AIERP issue #1126 — the Guidance view (#/guidance).
//
// The view, titled "Guidance" with the subtitle "What AIERP is built
// to do, and the decisions that steer it. Every item has a key you
// can trace.", is last in the nav, directly after the Settings button
// (the shared list in app/tests/nav_order.js carries "guidance" and
// "Guidance" directly after Settings), and is wired into app/js/app.js
// the same way as the across view, including its activate and its
// sign-out reset.
//
// Opening the view sends GET /api/guidance once through app/js/api.js,
// under a request-sequence guard so only the newest answer renders;
// the Refresh button ([data-testid="guidance-refresh"]) sends it
// again. Above the items the source line
// ([data-testid="guidance-source"]) reads "Published <date> from
// <source> by <published_by>.", <date> the first ten characters of
// publication.published_at.
//
// The active and proposed items show in sections by type — "Direction",
// "Boundaries", "Roadmap", "Design guidance" — a type without such
// items has no section; inside a section the items are grouped by
// area, the groups in the order their first item has in the answer,
// each under its area_title. The retired items are listed apart, in a
// last section headed "Retired", in the answer's order and without
// area sub-headings.
//
// One block per item ([data-testid="guidance-item"], the key in its
// data-key attribute): the title; the stamp
// ([data-testid="guidance-stamp"]); the statement; and one line
// ([data-testid="guidance-decided"]) reading "Decided by <decided_by>
// on <decided_on>", followed by " under <decided_under>" when that is
// not null, then " (<decided_ref>)" when that is not null, then a
// full stop, then " Changing it takes: <authority>." when authority
// is not null, then " In AIERP since <date>.", <date> the first ten
// characters of since. A proposed item carries the tag "Proposed", a
// retired item the tag "Retired" ([data-testid="guidance-status"]);
// an active item has no tag.
//
// The find input ([data-testid="guidance-find"]), labelled "Find a key
// or a word", narrows the screen as the user types: an item stays
// when its key, its stamp, its title or its statement contains the
// typed text, without regard to case and after trimming it; a section
// or an area group with no item left is not shown. The count
// ([data-testid="guidance-count"]) reads "<M> items" while the input
// is empty and "<N> of <M> items" otherwise; when nothing matches the
// screen reads "No item matches." in place of the sections. With a
// find value in the hash's query string
// (#/guidance?find=SHOP-B-1), the screen opens with that text,
// URL-decoded, in the find input and already applied.
//
// With publication null the screen reads "No guidance has been
// published to AIERP yet." and shows no source line, no find input and
// no count. A failed fetch shows "The guidance could not be loaded."
// with a "Try again" button that sends the request again, and the
// rest of the app works as before. The screen is read-only: it sends
// no POST, PUT or DELETE through the whole pass. Every API value is
// set as text (a statement of <img src=x onerror=window.__pwned=1>
// renders as text, with window.__pwned undefined). Sign-out clears
// the answer and the find text, and an answer arriving after sign-out
// is discarded. At 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with one page.route('**/api/**', handler): the
// development token card as an admin, at 1440x900, and
// GET /api/guidance, whose answers the test holds and releases and
// whose requests it counts. The mock answers a publication with
