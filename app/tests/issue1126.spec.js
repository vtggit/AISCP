// A fresh copy of the items, for each phase that swaps the answer.
function freshItems(items) {
  return items.map((item) => Object.assign({}, item));
}

// The hostile answer: SHOP-N-1's statement carries the payload — it
// must reach the page as text, and window.__pwned stays undefined.
const XSS_PAYLOAD = '<img src=x onerror=window.__pwned=1>';
const HOSTILE_ITEMS = ITEMS.map((item) =>
  Object.assign({}, item, {
    statement:
      item.key === 'SHOP-N-1' ? XSS_PAYLOAD : item.statement,
  }),
);

// The null-field answer: SHOP-N-1's title, stamp and statement are
// null and its area_title is missing from the answer entirely --
// none of them may reach the page as the words "null" or
// "undefined".
const NULL_FIELD_ITEMS = ITEMS.map((item) => {
  if (item.key !== 'SHOP-N-1') {
    return item;
  }
  const copy = Object.assign({}, item);
  copy.title = null;
  copy.stamp = null;
  copy.statement = null;
  delete copy.area_title;
  return copy;
});

// Mock every /api/* call the app makes. The single handler reads ctrl
// on every request, so the test can steer the guidance answer
// (ctrl.publication / ctrl.items / ctrl.status) and hold the next
// guidance request in flight (ctrl.holdNext; release through
// ctrl.heldRoute.fulfill(...)). Every guidance read is counted, and
// every non-GET method is kept for the read-only check.
async function mockApi(page) {
  const ctrl = {
    me: ADMIN_ME,
    publication: PUBLICATION,
    items: freshItems(ITEMS),
    status: 200,
    holdNext: false,
    heldRoute: null,
    gets: 0,
    nonGets: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/guidance') {
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.gets += 1;
      if (ctrl.holdNext) {
        ctrl.holdNext = false;
        ctrl.heldRoute = route;
        return; // held: the test answers it
      }
      if (ctrl.status !== 200) {
        return route.fulfill({ status: ctrl.status, json: { detail: 'unavailable' } });
      }
      return route.fulfill({
        status: 200,
        json: { publication: ctrl.publication, items: ctrl.items },
      });
    }
    if (request.method() !== 'GET') {
      ctrl.nonGets.push(request.method() + ' ' + path);
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

