// Mock every /api/* call the app makes. The single handler reads ctrl
// on every request, so the test can steer the list answer
// (ctrl.publication / ctrl.items / ctrl.status, the next list request
// held through ctrl.holdNext) and each item's history answer (the
// ctrl.history payload, per-key statuses through ctrl.historyStatus,
// the next request for a key held through ctrl.historyHold). Every
// history read is kept in ctrl.historyGets, and every non-GET method
// is kept for the read-only check.
async function mockApi(page) {
  const ctrl = {
    me: ADMIN_ME,
    publication: PUBLICATION,
    items: ITEMS.map((item) => Object.assign({}, item)),
    status: 200,
    holdNext: false,
    heldRoute: null,
    gets: 0,
    history: freshHistories(),
    historyGets: [],
    historyStatus: {},
    historyHold: {},
    historyHeld: {},
    nonGets: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/guidance') {
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.gets += 1;
      if (ctrl.holdNext) {
        ctrl.holdNext = false;
        ctrl.heldRoute = route;
        return; // held: the test answers it
      }
      if (ctrl.status !== 200) {
        return route.fulfill({ status: ctrl.status, json: { detail: 'unavailable' } });
      }
      return route.fulfill({
        status: 200,
        json: { publication: ctrl.publication, items: ctrl.items },
      });
    }
    const historyMatch = /^\/api\/guidance\/items\/([^/]+)$/.exec(path);
    if (historyMatch) {
      const key = decodeURIComponent(historyMatch[1]);
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.historyGets.push(path);
      if (ctrl.historyHold[key]) {
        ctrl.historyHold[key] = false;
        ctrl.historyHeld[key] = route;
        return; // held: the test answers it
      }
      const status = ctrl.historyStatus[key] || 200;
      if (status !== 200) {
        return route.fulfill({ status: status, json: { detail: 'unavailable' } });
      }
      return route.fulfill({ status: 200, json: ctrl.history[key] });
    }
    if (request.method() !== 'GET') {
      ctrl.nonGets.push(request.method() + ' ' + path);
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

