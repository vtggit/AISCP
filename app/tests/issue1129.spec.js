// Proving spec for AIERP issue #1129 — the item's history on the
// Guidance view (#/guidance).
//
// Every item block ([data-testid="guidance-item"]) carries a "History"
// button ([data-testid="guidance-history"], aria-expanded false while
// closed). Pressing it sends GET /api/guidance/items/<key> once
// through app/js/api.js, the key URL-encoded, marks the button
// aria-expanded true and opens the item's history — a list
// ([data-testid="guidance-versions"]) inside the block, "Loading the
// history..." while the answer is out, and one row
// ([data-testid="guidance-version"]) per entry of the answer's
// versions in the answer's order (the newest first), each with the
// version's stamp, its statement, the line "Decided by <decided_by>
// on <decided_on>" and its period — "In AIERP since <first date>
// (<first source>). Current." for a version with current true,
// "In AIERP from <first date> (<first source>) to <last date>
// (<last source>)." for any other, a date the first ten characters of
// that publication's published_at. A version whose status is proposed
// or retired also carries the word "Proposed" or "Retired". With the
// answer's current false, a line
// ([data-testid="guidance-withdrawn"]) above the rows reads "This item
// is no longer published.". Pressing the button again closes the list
// without a request; opening it again sends the request again. A
// failed request reads "The history could not be loaded." in the
// list's place, and a close and open again sends the request again. A
// 401 shows no local error and leaves the sign-out flow to the shell.
// Only the newest answer renders: one arriving after the list was
// closed, after a newer request for the same item, after a Refresh or
// after the sign-out is discarded, and a Refresh and the sign-out
// close every open history. A re-render of the list (a find keystroke
// or a Refresh) never leaves an item marked expanded while its
// history is absent. The screen stays read-only: no POST, PUT or
// DELETE through the whole pass. Every API value is set as text (a
// version statement of <img src=x onerror=window.__pwned=1> renders as
// text, with window.__pwned undefined), the colours come only from
// tokens.css, and at 390x844 the page does not scroll sideways with a
// history open.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with one page.route('**/api/**', handler): the
// development token card as an admin, at 1440x900, and
// GET /api/guidance, whose answers the test holds and releases and
// whose requests it counts. The mock answers a publication and two
// active design items, SHOP-D-1 and SHOP-D-2. The history mock
// answers, for SHOP-D-1, current true and three versions in this
// order: the stamp SHOP-D-1@caddbcd58d with the PostgreSQL statement,
// active and current, first commit-3 and last commit-4; the stamp
// SHOP-D-1@40ff75ae8d, "PostgreSQL 15", retired, first and last
// commit-2; and the stamp SHOP-D-1@caddbcd58d again, first and last
// commit-1. For SHOP-D-2 it answers current false and one version.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1129 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

