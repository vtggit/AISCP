  ctrl.historyStatus['SHOP-D-1'] = 401;
  await d1History.click(); // close first, no request
  await d1History.click(); // open: the 401 signs the user out
  await expect(page.locator('#signin-form')).toBeVisible();
  await expect(page.locator('#app')).toBeHidden();
  await expect(page.locator('#guidance-root')).not.toContainText(
    'The history could not be loaded.',
  );
  await expect(d1.locator('[data-testid="guidance-versions"]')).toBeHidden();
