// Mock every /api/* call the app makes. The single handler reads ctrl
// on every request, so the test can steer the guidance answer
// (ctrl.items / ctrl.status) and hold it in flight (ctrl.holdNext;
// release through ctrl.heldRoute.fulfill(...)), steer the stamps'
// answers (ctrl.stampPayloads / ctrl.stampStatus) and hold a stamp
// request in flight (ctrl.stampHoldNext; release through
// ctrl.stampHeldRoute.fulfill(...)). Every guidance read and every
// stamp read is counted, and every non-GET method is kept for the
// read-only check.
async function mockApi(page) {
  const ctrl = {
    me: ADMIN_ME,
    publication: PUBLICATION,
    items: freshItems([ITEM]),
    status: 200,
    holdNext: false,
    heldRoute: null,
    gets: 0,
    stampPayloads: freshStamps(STAMPS),
    stampStatus: 200,
    stampHoldNext: false,
    stampHeldRoute: null,
    stampGets: 0,
    stampPaths: [],
    nonGets: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/guidance') {
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.gets += 1;
      if (ctrl.holdNext) {
        ctrl.holdNext = false;
        ctrl.heldRoute = route;
        return; // held: the test answers it
      }
      if (ctrl.status !== 200) {
        return route.fulfill({ status: ctrl.status, json: { detail: 'unavailable' } });
      }
      return route.fulfill({
        status: 200,
        json: { publication: ctrl.publication, items: ctrl.items },
      });
    }
    if (path.startsWith('/api/guidance/stamps/')) {
      if (request.method() !== 'GET') {
        ctrl.nonGets.push(request.method() + ' ' + path);
      }
      ctrl.stampGets += 1;
      ctrl.stampPaths.push(path);
      const stamp = decodeURIComponent(
        path.slice('/api/guidance/stamps/'.length),
      );
      if (ctrl.stampHoldNext) {
        ctrl.stampHoldNext = false;
        ctrl.stampHeldRoute = route;
        return; // held: the test answers it
      }
      if (ctrl.stampStatus !== 200) {
        return route.fulfill({ status: ctrl.stampStatus, json: { detail: 'unavailable' } });
      }
      const payload = ctrl.stampPayloads[stamp];
      if (!payload) {
        return route.fulfill({ status: 404, json: { detail: 'Unknown guidance stamp' } });
      }
      return route.fulfill({ status: 200, json: payload });
    }
    if (request.method() !== 'GET') {
      ctrl.nonGets.push(request.method() + ' ' + path);
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

