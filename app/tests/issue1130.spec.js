// A fresh copy of the one-item answer, for the phases that swap it.
function freshItems(items) {
  return items.map((item) => Object.assign({}, item));
}

// A fresh copy of the stamps' answers, so a phase that steers one
// (the hostile statement) cannot touch the original.
function freshStamps(stamps) {
  const out = {};
  for (const stamp of Object.keys(stamps)) {
    out[stamp] = Object.assign({}, stamps[stamp], {
      versions: stamps[stamp].versions.map((version) =>
        Object.assign({}, version, {
          first: Object.assign({}, version.first),
          last: Object.assign({}, version.last),
        }),
      ),
    });
  }
  return out;
}

