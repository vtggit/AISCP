// Proving spec for AIERP issue #1130 — looking up a stamp from the
// Guidance view's find box (#/guidance).
//
// When the trimmed find text is a stamp (^[A-Z][A-Z0-9]{1,7}-[NRDB]-
// [0-9]{1,4}@ plus ten characters from 0 to 9 and a to f) and no item
// of the answer carries exactly that stamp, the screen sends
// GET /api/guidance/stamps/<stamp> once, the stamp URL-encoded,
// through app/js/api.js; text that is not a stamp, and the stamp an
// item of the answer carries, send nothing, and the same stamp is not
// asked twice in a row while the find text stays the same. The answer
// shows in one block ([data-testid="guidance-lookup"]) above the item
// sections, in place of "No item matches.": headed "<stamp> is an
// earlier version of <key>." when the answer's current is false and
// "<stamp> is the current version of <key>." when it is true, with
// the answer's title and statement, one state line
// ([data-testid="guidance-lookup-state"]) — "The item reads
// differently now." when superseded is true, "The item is no longer
// published." when current and superseded are both false, none when
// current is true — and one row
// ([data-testid="guidance-lookup-version"]) per version, "In AIERP
// from <first date> (<first source>) to <last date> (<last
// source>).". When superseded is true the block carries "Show the
// item as it is now" ([data-testid="guidance-lookup-current"]), which
// puts the answer's key into the find input and applies it. A 404
// shows "AIERP has never held the stamp <stamp>."; any other failure
// shows "The stamp could not be looked up." with a "Try again" button
// ([data-testid="guidance-lookup-retry"]). While the answer is out
// the block reads "Looking up <stamp>...". A find that is no longer
// the stamp removes the block; an answer arriving after the find text
// changed, after a Refresh or after the sign-out is discarded.
// Opening #/guidance?find=<stamp> opens found and looked up, with one
// request. When the find's stamp also matches an item by word, the
// block renders above the visible item sections, not only in place
// of "No item matches.". The screen stays read-only (no POST, PUT or
// DELETE), every API value renders as text, and at 390x844 the page
// does not scroll sideways with the block shown. Finding by key or
// word, and everything else on the Guidance screen, works exactly as
// before.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with one page.route('**/api/**', handler): the
// development token card as an admin, at 1440x900. The /api/guidance
// mock answers a publication and one active design item, SHOP-D-1,
// with the stamp SHOP-D-1@caddbcd58d, the title "One database
// product" and the statement "Every service stores its data in
// PostgreSQL.". The stamps mock answers, for SHOP-D-1@40ff75ae8d:
// key SHOP-D-1, title "One database product", statement "Every
// service stores its data in PostgreSQL 15.", current false,
// superseded true and one version whose first and last both have
// source commit-2 and published_at 2026-11-05T10:00:00+00:00; for
// SHOP-R-1@0282fa9675: key SHOP-R-1, title "T", statement "S.",
// current false, superseded false and two versions; for
// SHOP-N-1@0000000001: key SHOP-N-1, title "T", statement "S.", current
// true, superseded false and one version whose first and last both
// have source commit-2 and published_at 2026-11-05T10:00:00+00:00 —
// and 404 for every other stamp. The "above visible sections" phase
// temporarily steers the /api/guidance answer to a second item whose
// statement quotes the looked-up stamp, and restores it before the
// read-only check.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1130 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

