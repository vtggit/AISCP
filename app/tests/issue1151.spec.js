// Proving spec for AIERP issue #1151 — the statement's formatting on
// the Guidance view (#/guidance).
//
// In every statement the screen shows — the statement of each item
// (the .g-item-statement element inside
// [data-testid="guidance-item"]), the statement of each row of an
// item's history (inside [data-testid="guidance-version"], #1129) and
// the statement in the looked-up block of a stamp (inside
// [data-testid="guidance-lookup"], #1130) — a code run (a backtick,
// one or more characters that are not a backtick, a backtick) shows
// as a code element; a bold run (two asterisks, one or more
// characters that do not include two asterisks in a row, two
// asterisks) shows as a strong element; an italic run (one asterisk,
// then text that starts and ends with a character that is neither a
// space nor an asterisk, then one asterisk) shows as an em element.
// The markers themselves are not shown. Code runs are found first and
// their content shows exactly as written, asterisks included; bold and
// italic runs are then found in the text outside code runs, and a bold
// run may hold a code run. A marker that does not close a run is shown
// as it is: an unpaired backtick or asterisk, a lone asterisk between
// spaces as in "2 * 3 * 4". The statement's text is escaped before the
// forms are applied, so the only elements a statement can produce are
// strong, em and code, none with an attribute, and every other value
// is shown as text exactly as before. The title, key, stamp, the
// decided line and the tags read as before, and the find input still
// matches the statement as published, markers included, so "decision
// layer" finds the item whose statement reads "the **decision layer**
// over". A code element in a statement uses the monospace font and the
// colours from tokens.css only, and a long code run wraps inside its
// block at 390x844.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with one page.route('**/api/**', handler): the
// development token card as an admin, at 1440x900, and
// GET /api/guidance, whose answers the test holds and releases and
// whose requests it counts. The mock answers one publication and four
// active design items in one area, in this order: SHOP-D-1, SHOP-D-2,
// SHOP-D-3 and SHOP-D-4. The history mock answers, for SHOP-D-1,
// current true and one current version with the same statement as the
// item. The stamps mock answers, for SHOP-D-1@40ff75ae8d, key
// SHOP-D-1, current false, superseded true, one version and the
// statement "An **earlier** wording.".
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1151 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

