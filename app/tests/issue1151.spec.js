  const d4Statement = d4.locator('.g-item-statement');
  const d1History = d1.locator('[data-testid="guidance-history"]');
  const d1Rows = d1.locator('[data-testid="guidance-version"]');
  const findInput = page.locator('[data-testid="guidance-find"]');
  const lookup = page.locator('[data-testid="guidance-lookup"]');
  const lookupStatement = lookup.locator('.g-lookup-statement');

  // Inside every statement on the screen, every element is a strong,
  // an em or a code, and none has an attribute; any other element or
  // any attribute is a defect.
  const statementOffenders = () =>
    page.evaluate(() => {
      const statements = Array.from(
        document.querySelectorAll(
          '.g-item-statement, .g-version-statement, .g-lookup-statement',
        ),
      );
      const offenders = [];
      for (const statement of statements) {
        const elements = Array.from(statement.querySelectorAll('*'));
        for (const element of elements) {
          const tag = element.tagName.toLowerCase();
          const allowed = tag === 'strong' || tag === 'em' || tag === 'code';
          if (!allowed || element.hasAttributes()) {
            offenders.push(element.outerHTML.slice(0, 80));
          }
        }
      }
      return offenders;
    });

  // --- sign in through the development token card ---------------------
  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
