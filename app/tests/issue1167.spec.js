// Proving spec for AIERP issue #1167 — the "Order plan" screen
// (#/orders): the supplier minimum line, the short badge and the
// suggested top-ups.
//
// A supplier block whose group carries a `minimum` that is a usable
// number (a number or a numeric string) shows, right after its
// totals line, a line reading "Supplier minimum <minimum>", dollars
// and cents with thousands separators; a block whose group's
// `shortfall` is a usable number above 0 shows, after the risk
// badge, a span reading "Below minimum by <shortfall>". A block
// whose group carries no usable minimum, or a shortfall of 0, shows
// none of them and renders exactly as before, as does the block
// without supplier terms.
//
// When a valid plan answer lands with at least one block whose
// `shortfall` is a usable number above 0, the screen sends exactly
// one GET /api/supply-plan/top-ups?horizon_days=<n> through
// app/js/api.js — n the horizon that plan read asked for — under its
// own request-sequence guard; a plan answer with no such block sends
// no top-ups read. Each short block ends, after its lines' table,
// with a "Suggested top-ups" section: "Looking for top-ups…" while
// the read is out, "Top-ups could not be loaded." on a failed or
// malformed answer (without a page error), otherwise the answer's
// entry for the block as a table — Item and Site, Pulled forward,
// Order by, Quantity, Value, Holding cost — one row per top-up in
// the answer's order, then the outcome line: "Adding these reaches
// the minimum.", "Still short by <still_short> after these." or
// "Nothing due in the next <lookahead_days> days can top this order
// up."; a short block with no entry reads "No top-ups suggested."
// The plan read and the supplier-risk read, their order and their
// counts, the plan's lines, the release flow and the CSV download
// are unchanged, and the screen sends no new POST, PUT or DELETE.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered with page.route, the way
// app/tests/issue1060.spec.js does it. The mocked supply-plan
// answer (horizon 7) has, in order, the blocks S-A (total "1800.00",
// minimum "2500.00", shortfall "700.00"), S-B (total "200.00",
// minimum "1000.00", shortfall "800.00"), S-E (total "50.00",
// minimum "300.00", shortfall "250.00"), S-C (total "400.00",
// minimum "100.00", shortfall "0.00"), S-D (neither key) and the
// block without supplier terms, each with one line; the mocked
// top-ups answer has lookahead_days 30 and entries for S-A (reaches
// the minimum), S-B (still short by 500.00) and S-E (nothing due).
//
// The ADMIN pass signs in through the development token card at
// 1440x900: the badges, the minimum lines, the single top-ups read
// (after the plan read, horizon_days=7), the pending line while the
// answer is held 800 ms, the rows and the outcomes, a second plan
// and top-ups read at horizon_days=14 on the horizon change, no
// top-ups read on a plan answer without a short block, and the
// failure line on a 500 top-ups answer — with no page error. The
// PLANNER pass (role 'user', the identity requirement) runs as a
// second pass after a full reload, booted the production way — the
// token in the URL hash as #access_token=..., /api/auth/config and
// /api/auth/me mocked for that user, the fragment inert through the
// PKCE round-trip — and shows the same badges, rows and outcomes
// while the admin-only Release control is absent. No POST, PUT or
// DELETE is sent in either pass.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1167 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
