  for (const index of [0, 1, 2]) {
    await expect(groups.nth(index).locator('[data-testid="orders-top-ups"]')).toBeVisible();
    await expect(groups.nth(index).locator('[data-testid="orders-top-ups-status"]')).toHaveText(
      'Looking for top-ups\u2026',
    );
  }
  await expect(groups.nth(3).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(4).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(5).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // ... the answer is held 800 ms after the request arrives ...
  await new Promise((resolve) => setTimeout(resolve, 800));
  await expect(groups.nth(0).locator('[data-testid="orders-top-ups-status"]')).toHaveText(
    'Looking for top-ups\u2026',
  );

  // ... and answering it settles the rows.
  ctrl.heldTopUps[0].fulfill({ status: 200, json: topUpsAnswer() });
  ctrl.heldTopUps.length = 0; // later holds start at index 0 again

  // S-A: the two top-ups, in the answer's order ...
  const aRows = groups.nth(0).locator('[data-testid="orders-top-up"]');
  await expect(aRows).toHaveCount(2);
  await expect(aRows.nth(0).locator('td')).toHaveText([
    'X / 159',
    '10 days',
    '2026-10-10',
    '4',
    '$400.00',
    '$2.74',
  ]);
  await expect(aRows.nth(1).locator('td')).toHaveText([
    'Z / 159',
    '20 days',
    '2026-10-20',
    '9',
    '$450.00',
    '$6.16',
  ]);
  // ... and the outcome: the minimum is reached.
  await expect(groups.nth(0).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Adding these reaches the minimum.',
  );
  expect(pageErrors).toEqual([]);

  // S-B: the one top-up, and the remaining shortfall.
  const bRows = groups.nth(1).locator('[data-testid="orders-top-up"]');
  await expect(bRows).toHaveCount(1);
  await expect(bRows.nth(0).locator('td')).toHaveText([
    'U / 77',
    '15 days',
    '2026-10-15',
    '3',
    '$300.00',
    '$3.08',
  ]);
  await expect(groups.nth(1).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Still short by $500.00 after these.',
  );
  expect(pageErrors).toEqual([]);

  // S-E: no top-up is due — no rows, and the lookahead in days.
  await expect(groups.nth(2).locator('[data-testid="orders-top-up"]')).toHaveCount(0);
  await expect(groups.nth(2).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Nothing due in the next 30 days can top this order up.',
  );
  expect(pageErrors).toEqual([]);

  // S-C, S-D and the no-terms block: no top-ups section at all.
  await expect(groups.nth(3).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(4).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(5).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- the horizon change: a second plan and a second top-ups read ------
  await horizon.selectOption('14');
  await expect.poll(() => ctrl.supplyGets).toBe(2);
  await expect.poll(() => ctrl.riskGets).toBe(2);
  await expect.poll(() => ctrl.topUpsGets).toBe(2);
  expect(ctrl.topUpsQueries[1]).toBe('?horizon_days=14');
  // The new plan answer (horizon 14) settles with the same blocks,
  // and its top-ups answer settles into the rows again.
  await expect(summary).toHaveText('6 lines \u00b7 $2,570 across 5 suppliers');
  await expect(groups).toHaveCount(6);
  await expect(aRows).toHaveCount(2);
  await expect(aRows.nth(0).locator('td')).toHaveText([
    'X / 159',
    '10 days',
    '2026-10-10',
    '4',
    '$400.00',
    '$2.74',
  ]);
  await expect(groups.nth(0).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Adding these reaches the minimum.',
  );
  expect(pageErrors).toEqual([]);

  // --- refresh without a short block: no top-ups read -------------------
  ctrl.supplyAnswer = (days) => supplyAnswer(days, { short: false });
  await refresh.click();
  await expect.poll(() => ctrl.supplyGets).toBe(3);
  await expect.poll(() => ctrl.riskGets).toBe(3);
  // The answer settles (the minimum lines come back) ...
  await expect(page.locator('[data-testid="orders-supplier-minimum"]')).toHaveCount(4);
  // ... and no top-ups read went out for a plan without a short block.
  expect(ctrl.topUpsGets).toBe(2);
  await expect(page.locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="orders-supplier-short"]')).toHaveCount(0);
  await expect(groups).toHaveCount(6);
  expect(pageErrors).toEqual([]);

  // --- refresh with a 500 top-ups answer: the failure line --------------
  ctrl.supplyAnswer = supplyAnswer;
  ctrl.topUpsAnswer = { status: 500, json: { detail: 'top-ups boom' } };
  await refresh.click();
  await expect.poll(() => ctrl.supplyGets).toBe(4);
  await expect.poll(() => ctrl.topUpsGets).toBe(3);
  // Each short block reads the failure line, without a page error ...
  for (const index of [0, 1, 2]) {
    await expect(groups.nth(index).locator('[data-testid="orders-top-ups"]')).toBeVisible();
    await expect(groups.nth(index).locator('[data-testid="orders-top-ups-error"]')).toHaveText(
      'Top-ups could not be loaded.',
    );
  }
  // ... and the blocks without a shortfall keep showing no section.
  await expect(groups.nth(3).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(4).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(5).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- planner pass: the production way, a non-admin --------------------
  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for: the sign-in configuration
  // answers production, the fragment stays inert through the PKCE
  // round-trip, and /api/auth/me signs the planner in.
  ctrl.config = PROD_CONFIG;
  ctrl.me = PLANNER_ME;
  ctrl.supplyAnswer = supplyAnswer;
  ctrl.topUpsAnswer = null;
  // The admin pass's session token persists in the tab's
  // sessionStorage: clear it so the reload really boots from the
  // fragment, not from the stored session.
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-planner-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp = ctrl.origin + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  await page.goto('/index.html#access_token=planner-token-1167');

  // The PKCE round-trip completes and the shell renders for the
  // planner ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // ... signed in through /api/auth/me with the IdP's token, the
  // fragment's token never read, stored or sent ...
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-planner-token',
  );
  expect(page.url()).not.toContain('access_token');
  const plannerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(plannerMe.headers()['authorization']).toBe('Bearer pkce-planner-token');

  // The Order plan for the planner: one plan read and one top-ups
  // read again, at the default horizon ...
  await page.click('.nav-btn[data-view="orders"]');
  await expect(page).toHaveURL(/#\/orders$/);
  await expect(page.locator('#view-orders')).toBeVisible();
  await expect.poll(() => ctrl.supplyGets).toBe(5);
  await expect.poll(() => ctrl.topUpsGets).toBe(4);
  expect(ctrl.topUpsQueries[3]).toBe('?horizon_days=7');

  // ... and the same badges, minimum lines, rows and outcomes show.
  await expect(summary).toHaveText('6 lines \u00b7 $2,570 across 5 suppliers');
  await expect(groups).toHaveCount(6);
  for (let i = 0; i < MINIMUM_LINES.length; i++) {
    await expect(groups.nth(i).locator('[data-testid="orders-supplier-minimum"]')).toHaveText(
      MINIMUM_LINES[i],
    );
  }
  await expect(page.locator('[data-testid="orders-supplier-minimum"]')).toHaveCount(4);
  for (let i = 0; i < SHORT_BADGES.length; i++) {
    await expect(groups.nth(i).locator('[data-testid="orders-supplier-short"]')).toHaveText(
      SHORT_BADGES[i],
    );
  }
  await expect(page.locator('[data-testid="orders-supplier-short"]')).toHaveCount(3);
  const vRows = groups.nth(0).locator('[data-testid="orders-top-up"]');
  await expect(vRows).toHaveCount(2);
  await expect(vRows.nth(0).locator('td')).toHaveText([
    'X / 159',
    '10 days',
    '2026-10-10',
    '4',
    '$400.00',
    '$2.74',
  ]);
  await expect(vRows.nth(1).locator('td')).toHaveText([
    'Z / 159',
    '20 days',
    '2026-10-20',
    '9',
    '$450.00',
    '$6.16',
  ]);
  await expect(groups.nth(0).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Adding these reaches the minimum.',
  );
  await expect(groups.nth(1).locator('[data-testid="orders-top-up"]')).toHaveCount(1);
  await expect(groups.nth(1).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Still short by $500.00 after these.',
  );
  await expect(groups.nth(2).locator('[data-testid="orders-top-up"]')).toHaveCount(0);
  await expect(groups.nth(2).locator('[data-testid="orders-top-ups-outcome"]')).toHaveText(
    'Nothing due in the next 30 days can top this order up.',
  );
  await expect(groups.nth(3).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(4).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  await expect(groups.nth(5).locator('[data-testid="orders-top-ups"]')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // ... while the admin-only controls are absent: no Release button
  // on the acumatica blocks, no note on the odoo block — and the
  // page still renders.
  await expect(page.locator('[data-testid="orders-release"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="orders-release-note"]')).toHaveCount(0);
  await expect(groups.nth(0).locator('h2')).toHaveText('Alpha Fasteners');
  await expect(groups.nth(5).locator('h2')).toHaveText('No supplier terms');
  expect(pageErrors).toEqual([]);

  // --- read-only: no POST, PUT or DELETE was sent in either pass ---------
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(true);
