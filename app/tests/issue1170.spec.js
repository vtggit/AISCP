// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route. The handler reads
// ctrl on every request, so the test can steer the sign-in
// (ctrl.config / ctrl.me), the minimums' list (ctrl.minStore, or a
// one-shot ctrl.minFailNext such as the 500) and the save (a
// one-shot ctrl.putHoldNext, which the test answers itself). Every
// read is counted, every PUT body and DELETE path is kept, and each
// request's method and path land in ctrl.requests.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    suppliersAnswer: SUPPLIERS,
    minStore: freshMinimums(),
    nextId: 100,
    perfGets: 0,
    riskGets: 0,
    secondGets: 0,
    suppliersGets: 0,
    minGets: 0,
    meRequests: [],
    puts: [],
    deletes: [],
    requests: [],
    minFailNext: null,
    putHoldNext: false,
    heldPut: null,
  };
  const appOrigin = { value: null };

  // The API's upsert: an existing (source_system, supplier_code)
  // updates its amount, keeping its id; a new pair appends a row.
  const upsert = (body) => {
    const existing = ctrl.minStore.find(
      (row) =>
        row.source_system === body.source_system &&
        row.supplier_code === body.supplier_code,
    );
    if (existing) {
      existing.amount = body.amount;
      existing.updated_at = '2026-11-13T09:00:00+00:00';
      existing.updated_by = 'admin1';
      return existing;
    }
    const row = {
      id: ctrl.nextId++,
      source_system: body.source_system,
      supplier_code: body.supplier_code,
      amount: body.amount,
      updated_at: '2026-11-13T09:00:00+00:00',
      updated_by: 'admin1',
    };
    ctrl.minStore.push(row);
    return row;
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.requests.push({ method: request.method(), path });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.perfGets += 1;
      return route.fulfill({ status: 200, json: PERFORMANCE });
    }
    if (path === '/api/supplier-risk') {
      ctrl.riskGets += 1;
      return route.fulfill({ status: 200, json: RISK_ANSWER });
    }
    if (path === '/api/second-sources') {
      ctrl.secondGets += 1;
      return route.fulfill({ status: 200, json: SECOND_ANSWER });
    }
    if (path === '/api/suppliers') {
      ctrl.suppliersGets += 1;
      return route.fulfill({ status: 200, json: ctrl.suppliersAnswer });
    }
    if (path === '/api/supplier-order-minimums' && request.method() === 'GET') {
      ctrl.minGets += 1;
      if (ctrl.minFailNext) {
        const fail = ctrl.minFailNext;
        ctrl.minFailNext = null;
        return route.fulfill(fail);
      }
      return route.fulfill({
        status: 200,
        json: ctrl.minStore.map((row) => ({ ...row })),
      });
    }
    if (path === '/api/supplier-order-minimums' && request.method() === 'PUT') {
      const body = request.postDataJSON();
      ctrl.puts.push(body);
      if (ctrl.putHoldNext) {
        // Held: the test answers the route itself.
        ctrl.putHoldNext = false;
        ctrl.heldPut = { route, body };
        return;
      }
      const row = upsert(body);
      return route.fulfill({ status: 200, json: { ...row } });
    }
    const deleteMatch = path.match(/^\/api\/supplier-order-minimums\/(.+)$/);
    if (deleteMatch && request.method() === 'DELETE') {
      const id = Number(deleteMatch[1]);
      ctrl.deletes.push(path);
      const index = ctrl.minStore.findIndex((row) => row.id === id);
      if (index === -1) {
        return route.fulfill({
          status: 404,
          json: { detail: 'Unknown supplier order minimum' },
        });
      }
      ctrl.minStore.splice(index, 1);
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

