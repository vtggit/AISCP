// Proving spec for AIERP issue #1170 — the "Order minimums" section
// of the Suppliers screen (#/suppliers), the screen's last section,
// below the Supplier terms.
//
// The section ([data-testid="suppliers-minimums"]) is headed
// "Order minimums". On each load of the screen (the view's
// activation), in the same load call as the risk and second-source
// reads, the screen sends one GET /api/supplier-order-minimums, one
// GET /api/suppliers and one GET /api/auth/me, all through
// app/js/api.js, each under its own request-sequence guard; a window
// change reads none of them again. The table
// ([data-testid="suppliers-minimums-table"]) carries one row
// ([data-testid="suppliers-minimum-row"], with data-source-system
// and data-supplier-code) per stored minimum, in the answer's order:
// Supplier (the label of the GET /api/suppliers entry with the same
// source_system and supplier_code — its name, else its vendor_code,
// else its supplier_code — the supplier_code when the read failed or
// is out), Source (the source_system), Minimum (the amount in dollars
// and cents with thousands separators, "$2,500.00") and Updated
// ("2026-11-12 by admin1": the first ten characters of updated_at,
// " by " and updated_by). While the list read is out a short
// skeleton shows (never the word "Loading"); an empty list reads
// "No order minimums are stored."; a failed or malformed answer reads
// "Order minimums could not be loaded.".
//
// An admin, and only an admin, sees the save form below the table
// ([data-testid="suppliers-minimum-form"]) — the supplier select
// ([data-testid="suppliers-minimum-supplier"]) with "Choose a
// supplier" (an empty value) first, then one option per
// GET /api/suppliers entry in its order reading "<label>
// (<source_system>)"; the amount input
// ([data-testid="suppliers-minimum-amount"], type number, step
// 0.01); the "Save minimum" button
// ([data-testid="suppliers-minimum-save"]) and the message line
// ([data-testid="suppliers-minimum-message"]) — and a "Remove"
// button at the end of each row. Choosing a supplier with a stored
// minimum puts that amount in the amount input. Saving with no
// supplier chosen, or an amount that is not a number above 0 and at
// most 1,000,000,000,000, reads "Choose a supplier and an amount
// above 0." and sends nothing; otherwise the button sends exactly
// one PUT /api/supplier-order-minimums, disabled while it is out: a
// 200 names the supplier and the amount in the message and sends one
// more list read, whose answer replaces the table; any other answer
// reads "The minimum could not be saved." and sends nothing more.
// Removing sends exactly one DELETE
// /api/supplier-order-minimums/<the row's id>, disabled while it is
// out: a 204 names the row's supplier text in the message and sends
// one more list read; any other answer reads "The minimum could not
// be removed.". A save or remove answer that lands after sign-out is
// dropped, and the screen sends no other POST, PUT or DELETE. If the
// minimums list read fails but the suppliers read succeeds, the admin
// form remains enabled.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1094.spec.js does it. The mock keeps the minimums'
// list: a PUT adds or updates its entry and answers 200 with the
// stored row, a DELETE removes the entry and answers 204.
//
// The pass runs as an ADMIN (roles ["admin"]) signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, and the section shows the same table — no form,
// no Remove buttons — while the page still renders, with no PUT or
// DELETE sent. At 390x844 the page does not scroll sideways, and
// there is no page error.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1170 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

