// ---------------------------------------------------------------------
// The source checks: a character-level JavaScript tokenizer and an
// HTML text-node walker, both run in Node over the files on disk.
// ---------------------------------------------------------------------

// A small JavaScript tokenizer: walks the source character by
// character and collects the text of every single-quoted string,
// every double-quoted string and every template-literal text chunk
// (the runs of text between the ${...} holes). Line and block
// comments are skipped whole, so a quoted passage inside a comment is
// never seen as a string; regex literals are skipped by the
// expression-context rule a JavaScript parser uses, so the quoted
// characters inside one are never seen either. Template holes are
// scanned as code (nested templates included), so the chunk a hole
// splits is collected in two. This is a tokenizer, not a regular
// expression over quoted text.
function jsStringLiterals(source) {
  const literals = [];
  const n = source.length;
  // Context stack: the top-level scan is code; a template literal
  // pushes a template context (chunk: the text run being collected);
  // a ${ hole inside a template pushes a code context (depth: the
  // brace nesting inside the hole).
  const stack = [{ mode: 'code', depth: 0 }];
  let i = 0;

  const isSpace = (ch) => ch === ' ' || ch === '\t' || ch === '\r' || ch === '\n';

  function previousSignificantIndex() {
    let j = i - 1;
    while (j >= 0 && isSpace(source[j])) {
      j -= 1;
    }
    return j;
  }

  // A '/' opens a regex (not a division) at the start of an
  // expression: after an operator, an opening bracket, a comma, a
  // semicolon — or after a ')' / keyword that ends an expression.
  function regexAllowed() {
    const j = previousSignificantIndex();
    if (j < 0) {
      return true;
    }
    const ch = source[j];
    if ('(,=:[!&|?{};+-*%~^<>'.indexOf(ch) !== -1) {
      return true;
    }
    if (ch === ')') {
      return /(?:return|typeof|case|in|of|new|delete|void|throw|do|else|instanceof|yield|await)\s*$/.test(
        source.slice(0, j),
      );
    }
    return false;
  }

  // Read one quoted string starting at source[i] (the quote); record
  // its characters — escapes kept as written — and advance i past
  // the closing quote.
  function readQuoted(quote) {
    let j = i + 1;
    let buf = '';
    while (j < n) {
      const ch = source[j];
      if (ch === '\\') {
        buf += source.slice(j, j + 2);
        j += 2;
        continue;
      }
      if (ch === quote) {
        literals.push(buf);
        i = j + 1;
        return;
      }
      if (ch === '\n') {
        throw new Error('unterminated string at offset ' + i);
      }
      buf += ch;
      j += 1;
    }
    throw new Error('unterminated string at offset ' + i);
  }

  // Read one regex literal starting at source[i] (the '/'); advance i
  // past the closing '/'. Character classes may hold a '/'.
  function readRegex() {
    let j = i + 1;
    let inClass = false;
    while (j < n) {
      const ch = source[j];
      if (ch === '\\') {
        j += 2;
        continue;
      }
      if (ch === '[') {
        inClass = true;
      } else if (ch === ']') {
        inClass = false;
      } else if (ch === '/' && !inClass) {
        i = j + 1;
        return;
      } else if (ch === '\n') {
        throw new Error('unterminated regex at offset ' + i);
      }
      j += 1;
    }
    throw new Error('unterminated regex at offset ' + i);
  }

  while (i < n || stack.length > 0) {
    const ctx = stack[stack.length - 1];
    const ch = i < n ? source[i] : '';

    if (ctx.mode === 'template') {
      if (ch === '\\') {
        ctx.chunk.push(source.slice(i, i + 2));
        i += 2;
        continue;
      }
      if (ch === '`') {
        literals.push(ctx.chunk.join(''));
        stack.pop();
        i += 1;
        continue;
      }
      if (ch === '$' && i + 1 < n && source[i + 1] === '{') {
        // The hole ends the text run: record it, then scan the hole
        // as code; the next run starts after the hole's '}'.
        literals.push(ctx.chunk.join(''));
        ctx.chunk = [];
        stack.push({ mode: 'code', depth: 0 });
        i += 2;
        continue;
      }
      if (ch === '') {
        throw new Error('unterminated template literal');
      }
      ctx.chunk.push(ch);
      i += 1;
      continue;
    }

    // Code context: top level, or inside a ${ hole.
    if (ch === '') {
      if (stack.length === 1) {
        break; // the source is over and only the top level is left
      }
      throw new Error('unterminated template hole');
    }
    if (ch === '/' && i + 1 < n && source[i + 1] === '/') {
      const lineEnd = source.indexOf('\n', i);
      i = lineEnd === -1 ? n : lineEnd;
      continue;
    }
    if (ch === '/' && i + 1 < n && source[i + 1] === '*') {
      const blockEnd = source.indexOf('*/', i + 2);
      i = blockEnd === -1 ? n : blockEnd + 2;
      continue;
    }
    if (ch === "'" || ch === '"') {
      readQuoted(ch);
      continue;
    }
    if (ch === '`') {
      stack.push({ mode: 'template', chunk: [] });
      i += 1;
      continue;
    }
    if (ch === '/' && regexAllowed()) {
      readRegex();
      continue;
    }
    if (ch === '{') {
      ctx.depth += 1;
    } else if (ch === '}') {
      ctx.depth -= 1;
      if (ctx.depth < 0) {
        // The hole's closing brace: the enclosing template resumes.
        stack.pop();
        i += 1;
        continue;
      }
    }
    i += 1;
  }
  return literals;
}

// The text nodes of a page's markup: the runs of characters outside
// tags, comments and <script>/<style> content (the content of those
// two is script, not text a reader sees).
function htmlTextNodes(markup) {
  const nodes = [];
  const skip = { script: 0, style: 0 };
  let i = 0;
  const n = markup.length;
  while (i < n) {
    const ch = markup[i];
    if (ch === '<') {
      if (markup.startsWith('<!--', i)) {
        const commentEnd = markup.indexOf('-->', i + 4);
        i = commentEnd === -1 ? n : commentEnd + 3;
        continue;
      }
      if (markup[i + 1] === '!' || markup[i + 1] === '?') {
        // A doctype or processing instruction: skip to its '>'.
        let j = i + 1;
        while (j < n && markup[j] !== '>') {
          j += 1;
        }
        i = j + 1;
        continue;
      }
      const tag = /^<\/?([a-zA-Z][a-zA-Z0-9]*)/.exec(markup.slice(i, i + 128));
      if (tag) {
        const name = tag[1].toLowerCase();
        const closing = markup[i + 1] === '/';
        if (Object.prototype.hasOwnProperty.call(skip, name)) {
          skip[name] += closing ? -1 : 1;
        }
        let j = i + 1;
        let quote = null;
        while (j < n) {
          const c = markup[j];
          if (quote) {
            if (c === quote) {
              quote = null;
            }
          } else if (c === '"' || c === "'") {
            quote = c;
          } else if (c === '>') {
            break;
          }
          j += 1;
        }
        i = j + 1;
        continue;
      }
      i += 1;
      continue;
    }
    const next = markup.indexOf('<', i);
    const j = next === -1 ? n : next;
    if (skip.script === 0 && skip.style === 0) {
      nodes.push(markup.slice(i, j));
    }
    i = j;
  }
  return nodes;
}

// The tokenizer's own fixture: the quoted passages in the comments
