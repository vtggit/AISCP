// Proving spec for AIERP issue #1237 — the "Order plan" screen
// (#/orders): the release sends what the preview sent, and a change
// closes the preview.
//
// The admin's "Release to Acumatica" preview (issue #851, with the
// block's chosen top-ups, issue #1205) POSTs
// /api/supply-plan/release and its answer opens the block's panel.
// This issue pins the confirm to that preview: the preview's request
// body is kept with the block's release state, and "Confirm release"
// sends that body with "confirm": true added — whatever has been
// ticked, unticked or chosen since the preview, nothing else in the
// body changes.
//
// And a change closes the preview: ticking or unticking one of the
// block's top-ups clears that block's release state the way "Cancel"
// does — the panel goes, no request is sent — whether the panel is
// open or the preview's request is still out the door, in which case
// the preview's answer is dropped when it lands and the admin
// previews again. Choosing another horizon does it for every block,
// and a tick in one block leaves the other blocks' panels open.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered with page.route, the way
// app/tests/issue1205.spec.js does it. The mocked supply-plan
// answer (horizon 7) has one block: the acumatica supplier S-A
// ("Alpha Supply") with total "1800.00", minimum "2500.00" and
// shortfall "700.00", one line. The mocked top-ups answer has
// lookahead_days 30 and gives S-A two top-ups: T1 at 159 (value
// "450.00") and T2 at 160 (value "300.00"). The mocked release
// answer keeps T1 among its group's lines (site 159, two lines,
// "2250.00") and lists T2 in unreleasable with the reason "not a
// suggested top-up". The mock's release branch can also hold the
// answer back on a promise (ctrl.releaseHold) so a preview's answer
// can be kept out the door while the screen moves on.
//
// The ADMIN pass signs in through the development token card at
// 1440x900, the way issue1205 signs in, and walks four checks on
// that one block. A tick after the preview: tick T1 and click
// "Release to Acumatica", one preview POST with top_ups [T1]; tick
// T2, the panel closes and no request is sent; click "Release to
// Acumatica" again, the preview's top_ups is [T1, T2]; click
// "Confirm release", the confirm body equals that second preview
// body plus "confirm": true. A late preview answer: the mock holds
// the answer, tick T1 and click Release, untick T1 before the
// answer lands, and once it lands the panel stays closed with no
// "Confirm release" button. The horizon: preview at the default
// horizon, choose 14 days, the panel closes with no release
// request, and the new preview's body carries the new
// horizon_days. Nothing changed: a preview and then a confirm,
// nothing moved between them, send bodies equal apart from
// "confirm": true. The admin pass sends no request but GETs and the
// seven release POSTs.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1237 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

