const ORDER_DATES = ['2026-11-15', '2026-11-12', '2026-11-08', '2026-11-01'];

// The flat text each order's Released cell must read: the date, the
// by line — the grant's order "by standing grant #1", the other
// three actors verbatim.
const EXPECTED_RELEASED_TEXTS = [
  ORDER_DATES[0] + ' by standing grant #1',
  ORDER_DATES[1] + ' by jason',
  ORDER_DATES[2] + ' by standing-grant:abc',
  ORDER_DATES[3] + ' by x-standing-grant:2',
];

// The second line of each cell: " by ..." with its leading space —
// the grant's line re-written, the other three verbatim.
const EXPECTED_BY_LINES = [
  ' by standing grant #1',
  ' by jason',
  ' by standing-grant:abc',
  ' by x-standing-grant:2',
];

// Mock every /api/* call the app makes with ONE route handler,
// defined before it is registered with page.route, the way
// app/tests/issue1211.spec.js does. The handler reads ctrl on every
// request, so the test can steer the sign-in (ctrl.config /
// ctrl.me); every releases read is counted in ctrl.releasesGets and
// each request's method and path land in ctrl.requests.
async function mockReleasesApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    releasesGets: 0,
    meRequests: [],
    requests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.requests.push({ method: request.method(), path, search: url.search });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      return route.fulfill({ status: 200, json: releasesPayload() });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue1310 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  const releasesTable = page.locator('[data-testid="releases-table"]');
  const rows = page.locator('tr.rl-row');
  const releasedCells = page.locator('tr.rl-row td.rl-cell-released');

  // --- admin pass: development sign-in at 1440x900 -------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockReleasesApi(page);

  await page.goto('/');

  // Sign in through the development token card as the admin, the
  // way app/tests/issue1211.spec.js does.
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  const adminMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(adminMe.headers()['authorization']).toBe('Bearer dev-admin-token');
  expect(pageErrors).toEqual([]);

  // --- opening the view: the four orders render in the answer's order
  const releasesGetsBefore = ctrl.releasesGets;
  await page.click('.nav-btn[data-view="releases"]');
  await expect(page).toHaveURL(/#\/releases$/);
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect(releasesTable).toBeVisible();
  await expect(rows).toHaveCount(4);
  // The table's rows came from a read of the route under test.
  await expect.poll(() => ctrl.releasesGets).toBeGreaterThan(releasesGetsBefore);
  expect(pageErrors).toEqual([]);

  // The flat text of each order's Released cell: the date line and
  // the " by ..." line read as one string.
  const flatTexts = await releasedCells.evaluateAll((cells) =>
    cells.map((cell) => cell.textContent),
  );
  expect(flatTexts).toEqual(EXPECTED_RELEASED_TEXTS);

  // The cell's shape stays: its two spans, the date line the date
  // part of released_at, the second line " by ..." with its leading
  // space — the grant's line re-written, the other three verbatim.
  const spanTexts = await releasedCells.evaluateAll((cells) =>
    cells.map((cell) => ({
      date: cell.querySelector('.rl-released-date')
        ? cell.querySelector('.rl-released-date').textContent
        : null,
      by: cell.querySelector('.rl-released-by')
        ? cell.querySelector('.rl-released-by').textContent
        : null,
    })),
  );
  expect(spanTexts.map((span) => span.date)).toEqual(ORDER_DATES);
  expect(spanTexts.map((span) => span.by)).toEqual(EXPECTED_BY_LINES);
  expect(pageErrors).toEqual([]);
});
