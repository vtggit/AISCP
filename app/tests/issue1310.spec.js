// Proving spec for AIERP issue #1310 — the Released cell of the
// Releases screen (#/releases) reads a standing grant's release.
//
// The table's ([data-testid="releases-table"]) Released cell shows
// the date part of released_at on one line, then " by <actor>" on a
// second line in the secondary ink token, so the cell's flat text
// is "DATE by ACTOR". When the actor is exactly "standing-grant:<id>",
// <id> one or more digits, the second line reads " by standing grant
// #<id>" instead — the grant released the order, not a person — so
// the flat text is "DATE by standing grant #<id>". Every other actor
// reads exactly as before, an actor that only starts with
// "standing-grant:" (such as "standing-grant:abc") among them, and so
// does one that merely carries the tag inside a longer value (such as
// "x-standing-grant:2"). The date line, the two spans, their classes,
// the leading space and the escaping stay as they were.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1211.spec.js does: the mock holds the releases
// answer and counts every read of it.
//
// The pass runs as an ADMIN (roles ["admin"]) signed in through the
// development token card at 1440x900, the way
// app/tests/issue1211.spec.js signs in. The mocked
// GET /api/aggregate/releases answer holds four orders, in this
// order — released by "standing-grant:1", by "jason", by
// "standing-grant:abc" and by "x-standing-grant:2" — and the proof
// checks each order's Released cell flat text: "<its date> by
// standing grant #1", "<its date> by jason", "<its date> by
// standing-grant:abc" and "<its date> by x-standing-grant:2", its
// date the date part of the order's released_at.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1310 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

