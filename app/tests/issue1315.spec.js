// "accepted", "action": "expedite"} to /api/stockout/decisions, the
// selected Reorder point row and the selected Excess row show no
// section, and the queue sent no request for the remedy (no new
// endpoint, no new call).
//
// The PLANNER pass (role 'user', the identity requirement) runs as a
// second pass after a full reload, booted the production way — the
// token in the URL hash as #access_token=..., /api/auth/config and
// /api/auth/me mocked for that user, the fragment inert through the
