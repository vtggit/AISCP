// Proving spec for AIERP issue #1315 — the "Proposed remedy" section
// of the Work queue's Stockout risk tab (#/queue).
//
// The Stockout risk list is requested with the remedy:
// GET /api/stockout?limit=1000&include_decided=true&include_remedy=
// true (the Reorder points and Excess list requests are exactly as
// today, and the queue sends no new request). For a selected Stockout
// risk row whose data carries a `remedy` key the detail pane shows a
// "Proposed remedy" section directly after the Why block and before
// the Decision block, built from the row's own data: a proposal line
// starting with the label of the matching action button —
// "Expedite: order <order_nbr> line <line_nbr> from <supplier>,
// <units> units expected <expected_on>.", "Transfer: <units> units
// from site <from_site>." or "Raise order: <units> units from
// <supplier>, order by <order_by>." (<supplier> the supplier_name,
// else the supplier_code, the " from <supplier>" part left out when
// both are null; <units> whole units with thousands separators) and
// the remedy's reason. A remedy that is null or of another kind
// shows "No remedy proposed."; a row without the key shows no
// section, and the Reorder points and Excess tabs never show one.
// The proposal presses or changes no action button: Accept, Dismiss
// and Snooze post exactly what they post today, and the admin's
// "Approve → draft PO" section is unchanged.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route — the queue's three lists, its
// settings, /api/auth/me, /api/erp-sources, the decision history and
// the decision POST, the way app/tests/issue1003.spec.js does it.
// The stockout list holds six rows at site 159 (A expedite, C
// transfer with an HTML-bearing reason, D and E raise_order — E
// without a supplier —, F a null remedy, G no remedy key), the drift
// and the excess lists hold one row each, and the excess row carries
// a remedy like A's (the excess tab never shows it). Each mocked list
// answer also carries a null element — the queue drops it: the
// rendered rows are exactly the rows above, and a null list element
// never crashes the render.
//
// The ADMIN pass signs in through the development token card at
// 1440x900: the stockout list requested once on load with
// include_remedy=true (drift and excess without it), A's section
// after the Why block and before the Decision block with its
