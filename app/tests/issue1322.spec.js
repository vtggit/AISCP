// Proving spec for AIERP issue #1322 — the "Expedite" screen
// (#/expedite): a copy belongs to its draft.
//
// The screen keeps a number (the draft sequence) that advances every
// time the open draft changes: opening a row's draft, Close, a chip
// choice, a new expedite read and the sign-out reset all go through
// the one helper that sets the open draft, empties the status and
// advances the number; a re-render alone never advances it.
//
// Copy notes the number when it is pressed. When the clipboard call
// settles after the number has moved on, the result is dropped: no
// status in the panel or in the state, no focus moved, no text
// selected, no document.execCommand call. While the number has not
// moved, the result lands exactly as #1307 built it: "Copied." on
// success, and on failure the fallback — the text box on the page at
// that moment (a re-render may have replaced the one Copy was
// pressed in) focused, its whole text selected and one
// document.execCommand('copy') call — with the status "Could not
// copy automatically. The text is selected, ready to copy.".
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1307.spec.js does it, mockExpediteApi included:
// the mocked expedite answer has as_of "2026-11-08", stale_excluded
// 0 and the same three lines — A (late, its own promise), B (after
// stockout, the ERP's default promise) and C (an Odoo line, late) —
// and the first and later risk reads are held until the test answers
// them with #1071's risk answer (S-HIGH high, S-LOW low).
//
// The stand-ins: navigator.clipboard is replaced by a stand-in whose
// writeText records its text and answers a promise the test settles
// by hand; document.execCommand is replaced by a spy that records
// each call with the focused element and the selection, the way
// app/tests/issue1307.spec.js's spy does. After each settle the test
// lets the promise's callbacks run (a 50 ms setTimeout inside
// page.evaluate) before it checks.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900, and covers: a copy on the
// first row's draft, replaced by the second row's draft, then
// resolved (the second row's draft stays open with its own text and
// an empty status, and Copy keeps focus), and the same, rejected; a
// copy closed by Close, then settled, resolved and rejected (no
// panel, no fallback call, focus on the row's Draft request button,
// the draft opened again empty); a copy closed by Refresh, then
// resolved (no panel after the new read, the draft opened again
// empty); and the same draft re-rendered by the held supplier-risk
// read — resolved ("Copied.") and rejected (one fallback call on the
// re-rendered text box, focused with its whole text selected, the
// failure status). One writeText call per Copy press, its text the
// draft's. Throughout the page logs no error and the screen sends
// only GETs.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1322 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

