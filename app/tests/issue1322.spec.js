  const panel = page.locator('[data-testid="expedite-draft"]');
  const draftTitle = page.locator('[data-testid="expedite-draft-title"]');
  const draftText = page.locator('[data-testid="expedite-draft-text"]');
  const draftCopy = page.locator('[data-testid="expedite-draft-copy"]');
  const draftClose = page.locator('[data-testid="expedite-draft-close"]');
  const draftStatus = page.locator('[data-testid="expedite-draft-status"]');

  await page.goto('/');

  // No expedite or risk read before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.expediteGets).toBe(0);
  expect(ctrl.riskGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(pageErrors).toEqual([]);

  // --- the stand-ins ----------------------------------------------------
  // navigator.clipboard: writeText records its text and answers a
  // promise the test settles by hand. document.execCommand: a spy
  // that records each call with the focused element and the
  // selection, the way app/tests/issue1307.spec.js's spy does.
  await page.evaluate(() => {
    window.__clipCalls = [];
    window.__clipPending = [];
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: {
        writeText: (text) => {
          window.__clipCalls.push(text);
          return new Promise((resolve, reject) => {
            window.__clipPending.push({ resolve, reject, settled: false });
          });
        },
      },
    });
    window.__copyCalls = [];
    document.execCommand = (command) => {
      const box = document.querySelector('[data-testid="expedite-draft-text"]');
      const active = document.activeElement;
      const start = box ? box.selectionStart : null;
      const end = box ? box.selectionEnd : null;
      window.__copyCalls.push({
        command: command,
        focusedElement: active
          ? active.getAttribute('data-testid') || active.tagName
          : null,
        focused: !!(box && active === box),
        selectedText: box ? box.value.substring(start, end) : null,
        allSelected: !!(box && start === 0 && end === box.value.length),
      });
      return false;
    };
  });

  // Settle the oldest unsettled stand-in call by hand, then let the
  // promise's callbacks run (a 50 ms setTimeout inside page.evaluate)
  // before the test checks.
  const settleClipboard = (outcome) =>
    page.evaluate(
      (which) =>
        new Promise((done) => {
          const pending = window.__clipPending.find((p) => !p.settled);
          if (pending) {
            pending.settled = true;
            if (which === 'reject') {
              pending.reject(new Error('Simulated clipboard failure'));
            } else {
              pending.resolve();
            }
          }
          setTimeout(done, 50);
        }),
      outcome,
    );

  // --- activation: one expedite read, the first risk read held ---------
  ctrl.holdRiskNext = true;
  await page.click('.nav-btn[data-view="expedite"]');
  await expect(page).toHaveURL(/#\/expedite$/);
  await expect(page.locator('#view-expedite')).toBeVisible();
  await expect.poll(() => ctrl.expediteGets).toBe(1);
  await expect.poll(() => ctrl.riskGets).toBe(1);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(3);
  // The held risk read is answered up front: the table re-renders
  // (no draft open yet), and later holds start fresh.
  ctrl.heldRisk[0].fulfill({ status: 200, json: RISK_ANSWER });
  ctrl.heldRisk.length = 0;
  await expect
    .poll(() => rows.nth(0).locator('.ex-cell-supplier [data-testid="expedite-supplier-risk"]').count())
    .toBe(1);
  expect(pageErrors).toEqual([]);

  // --- replaced, then resolved -----------------------------------------
  await openButtons.nth(0).click();
  await expect(panel).toHaveCount(1);
  await expect(draftTitle).toHaveText('Expedite request for PO004101 / 1');
  await expect(draftText).toHaveValue(DRAFT_A);
  await expect(draftStatus).toHaveText('');
  await expect(draftCopy).toBeFocused();

  // Copy on the first row's draft: one stand-in call, its text the
  // draft's, still unsettled.
  await draftCopy.click();
  await expect.poll(() => page.evaluate(() => window.__clipCalls.length)).toBe(1);
  expect(await page.evaluate(() => window.__clipCalls[0])).toBe(DRAFT_A);

  // The second row's Draft request replaces the open draft.
  await openButtons.nth(1).click();
  await expect(panel).toHaveCount(1);
  await expect(draftTitle).toHaveText('Expedite request for PO004102 / 2');
  await expect(draftText).toHaveValue(DRAFT_B);
  await expect(draftStatus).toHaveText('');
  await expect(draftCopy).toBeFocused();

  // The first call now resolves, after the counter has moved on.
  await settleClipboard('resolve');
  // The result is dropped: the second row's draft stays open with
  // its own text and an empty status, Copy keeps focus, and nothing
  // is copied.
  await expect(panel).toHaveCount(1);
  await expect(draftTitle).toHaveText('Expedite request for PO004102 / 2');
  await expect(draftText).toHaveValue(DRAFT_B);
  await expect(draftStatus).toHaveText('');
  await expect(draftCopy).toBeFocused();
  expect(await page.evaluate(() => window.__copyCalls.length)).toBe(0);
  expect(pageErrors).toEqual([]);

  // --- replaced, then rejected -----------------------------------------
  // The same steps, with the call rejecting.
  await draftCopy.click();
  await expect.poll(() => page.evaluate(() => window.__clipCalls.length)).toBe(2);
  expect(await page.evaluate(() => window.__clipCalls[1])).toBe(DRAFT_B);
  await openButtons.nth(0).click();
  await expect(panel).toHaveCount(1);
  await expect(draftTitle).toHaveText('Expedite request for PO004101 / 1');
  await expect(draftText).toHaveValue(DRAFT_A);
  await expect(draftStatus).toHaveText('');
  await expect(draftCopy).toBeFocused();
  await settleClipboard('reject');
  // Dropped: the spy records no call, the status stays empty and
  // Copy keeps focus.
  expect(await page.evaluate(() => window.__copyCalls.length)).toBe(0);
  await expect(draftStatus).toHaveText('');
  await expect(draftCopy).toBeFocused();
  await expect(draftTitle).toHaveText('Expedite request for PO004101 / 1');
  expect(pageErrors).toEqual([]);

  // --- closed, then settled ---------------------------------------------
  // Copy, then Close, then the call resolves.
  await draftCopy.click();
  await expect.poll(() => page.evaluate(() => window.__clipCalls.length)).toBe(3);
  expect(await page.evaluate(() => window.__clipCalls[2])).toBe(DRAFT_A);
  await draftClose.click();
  await expect(panel).toHaveCount(0);
  await expect(openButtons.nth(0)).toBeFocused();
  await settleClipboard('resolve');
  // Dropped: no panel, the spy records no call, and focus stays on
  // the row's Draft request button.
  await expect(panel).toHaveCount(0);
  expect(await page.evaluate(() => window.__copyCalls.length)).toBe(0);
  await expect(openButtons.nth(0)).toBeFocused();
  expect(pageErrors).toEqual([]);

  // The same steps, with the call rejecting.
  await openButtons.nth(0).click();
  await expect(panel).toHaveCount(1);
  await expect(draftStatus).toHaveText('');
  await draftCopy.click();
  await expect.poll(() => page.evaluate(() => window.__clipCalls.length)).toBe(4);
  expect(await page.evaluate(() => window.__clipCalls[3])).toBe(DRAFT_A);
  await draftClose.click();
  await expect(panel).toHaveCount(0);
  await expect(openButtons.nth(0)).toBeFocused();
  await settleClipboard('reject');
  await expect(panel).toHaveCount(0);
  expect(await page.evaluate(() => window.__copyCalls.length)).toBe(0);
  await expect(openButtons.nth(0)).toBeFocused();
  // That row's draft, opened again, shows an empty status.
  await openButtons.nth(0).click();
  await expect(panel).toHaveCount(1);
  await expect(draftText).toHaveValue(DRAFT_A);
  await expect(draftStatus).toHaveText('');
  expect(pageErrors).toEqual([]);

  // --- closed by Refresh --------------------------------------------------
  // Copy, then Refresh, then the call resolves.
  await draftCopy.click();
  await expect.poll(() => page.evaluate(() => window.__clipCalls.length)).toBe(5);
  expect(await page.evaluate(() => window.__clipCalls[4])).toBe(DRAFT_A);
