// Mock every /api/* call the queue (and the shell around it) makes
// with ONE page.route handler, defined before it is registered, the
// way app/tests/issue1315.spec.js does it. The handler reads ctrl on
// every request, so the test can steer the sign-in (ctrl.config /
// ctrl.me); every list request lands in ctrl.listGets with its
// query, every decision POST in ctrl.posts (path and body), the
// answered decisions in ctrl.stored (the history reads' source) and
// each request's method and path in ctrl.requests for the read-only
// check. The app's origin lands on ctrl.origin for the PKCE redirect
// mock of the planner pass.
async function mockQueueApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    origin: null,
    meRequests: [],
    listGets: [],
    posts: [],
    stored: [],
    postSeq: 0,
    requests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (ctrl.origin === null) {
      ctrl.origin = url.origin;
    }
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      ctrl.listGets.push({ kind: path.slice('/api/'.length), query: url.search });
      const rows =
        path === '/api/drift' ? DRIFT_ROWS : path === '/api/excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/erp-sources') {
      return route.fulfill({ status: 200, json: { sources: [], item_sites: [] } });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({ status: 200, json: { synced_at: null, data_through: null } });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (
      path === '/api/drift/decisions' ||
      path === '/api/excess/decisions' ||
      path === '/api/stockout/decisions'
    ) {
      if (request.method() === 'POST') {
        const body = request.postData() || '';
        ctrl.posts.push({ path, body });
        const sent = JSON.parse(body);
        ctrl.postSeq += 1;
        const stored = {
          id: 'dec-1335-' + ctrl.postSeq,
          item_code: sent.item_code,
          site_code: sent.site_code,
          decision: sent.decision,
          action: sent.action === undefined ? null : sent.action,
          decided_by: 'admin1',
          decided_at: '2026-11-06T09:00:00Z',
          reason: sent.reason === undefined ? null : sent.reason,
          snooze_until: sent.snooze_until === undefined ? null : sent.snooze_until,
        };
        ctrl.stored.push(stored);
        return route.fulfill({ status: 200, json: stored });
      }
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      const history = ctrl.stored
        .filter((decision) => decision.item_code === item && decision.site_code === site)
        .reverse();
      return route.fulfill({ status: 200, json: history });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl };
}

