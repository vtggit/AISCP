  await expect(page.locator('#q-accept')).toHaveCount(0);
  await expect(page.locator('#q-dismiss')).toHaveCount(0);
  await expect(page.locator('#q-snooze')).toHaveCount(0);
  await expect(page.locator('[data-testid="queue-draftpo"]')).toHaveCount(0);
  await expect(page.locator('.q-decision')).toHaveCount(1);
  await expect(page.locator('.q-decision-head h3')).toHaveText('Decision');
  expect(pageErrors).toEqual([]);

  // --- read-only: the only POST of either pass is the admin's decision -
