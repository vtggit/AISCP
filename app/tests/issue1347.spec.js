// Proving spec for AIERP issue #1347 — the Exceptions screen's
// proposal line: the answer a row's item-site already chose, under
// the detail.
//
// The screen asks for it: every list fetch goes to GET
// /api/exceptions with include_proposal=true on the query string —
// include_snoozed=true first while "Show snoozed" is ticked — on
// activation, on Refresh, after a successful Acknowledge, Snooze 7
// days or Clear, and on each change of "Show snoozed". The Overview
// keeps its own query-less GET /api/exceptions (app/js/overview.js is
// unchanged), so this spec's viewer pass sees the Overview's query
// first and the screen's parameterised fetch second. A server from
// before #1344 ignores the parameter and answers rows without a
// proposal key; the mock honours that — the rows carry their
// proposal values only while include_proposal is true.
//
// The line: a row whose proposal is an object — not an array — with
// a non-empty string reason shows one div.ex-proposal
// ([data-testid="exceptions-proposal"]) inside the row's Detail
// cell (td.ex-detail), after the detail text — the detail stays the
// cell's first child, a text node, and the line is the cell's only
// element. It reads "Answered by: <reason>", followed, when
// recorded_at is a string starting "YYYY-MM-DD[T ]HH:MM", by "
// Recorded by <name> at <date> <time> UTC." (" Recorded at <date>
// <time> UTC." when recorded_by_name is null, empty or not text);
// any other recorded_at leaves the sentence out. A null or missing
// proposal, a non-object proposal, a missing, empty or non-string
// reason shows nothing new — the Detail cell keeps the detail as its
// only content, with no element inside. The line is built with the
// module's el helper: reason and name reach the page as text, never
// through innerHTML. Acknowledged and snoozed rows show the line
// like any other row; the line presses, fills, disables or hides no
// control, and the screen acknowledges, snoozes and clears nothing
// by itself — no PUT or DELETE leaves the screen until the admin
// clicks one of the Actions buttons (Acknowledge sends exactly
// {"key": <key>}). A non-admin sees the same lines, no Actions
// column and the note "Only an admin can acknowledge exceptions."
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with ONE page.route that answers by url.pathname
// the way issue800's does and records every request's method, path
// and url.search. The mocked answer has as_of 2026-11-02, the
// counts 4 high, 4 medium, 1 acknowledged and 0 new, no failed
// source and eight rows: A, B, C, F and H carry answering
// proposals, D's is null, E's is absent even when asked and G's has
// a null reason.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900 — the page opens on /#/exceptions, so the
// Overview never loads in this pass — and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, the Overview (the default view) sends its own
// query-less GET /api/exceptions, and the screen then renders for
// the viewer — the same five lines — while the admin-only controls
// are absent and the page renders on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1347 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
