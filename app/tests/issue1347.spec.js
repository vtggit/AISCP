// The mocked exceptions answer: as_of 2026-11-02, the counts 4 high,
// 4 medium, 1 acknowledged and 0 new, no failed source and the eight
// rows. The rows carry their proposal values only while
// include_proposal is true, as the server does since #1344 —
// otherwise no row has a proposal key. A fresh copy per call.
function exceptionsAnswer(includeProposal) {
  const rows = ROWS.map((row) => {
    const copy = { ...row };
    if (
      includeProposal &&
      Object.prototype.hasOwnProperty.call(PROPOSALS, copy.key)
    ) {
      copy.proposal = PROPOSALS[copy.key];
    }
    return copy;
  });
  return {
    as_of: '2026-11-02',
    counts: { high: 4, medium: 4, acknowledged: 1, new: 0 },
    rows,
    sources_failed: [],
  };
}

// Mock every /api/* call the app makes. ONE page.route answers by
// url.pathname the way issue800's does and records every request's
// method, path and url.search (ctrl.requests), every list fetch in
// ctrl.exceptionsGets, every PUT in ctrl.puts with its raw body and
// every DELETE key in ctrl.deleteCalls; the sign-in is steered
// through ctrl.config / ctrl.me when the pass switches from the
// admin to the non-admin viewer.
async function mockExceptionsApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    origin: null,
    exceptionsGets: 0,
    requests: [],
    puts: [],
    deleteCalls: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (ctrl.origin === null) {
      ctrl.origin = url.origin;
    }
    ctrl.requests.push({
      method: request.method(),
      path,
      search: url.search,
    });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/exceptions') {
      ctrl.exceptionsGets += 1;
      return route.fulfill({
        status: 200,
        json: exceptionsAnswer(
          url.searchParams.get('include_proposal') === 'true',
        ),
      });
    }
    if (path === '/api/exceptions/ack' && request.method() === 'PUT') {
      const raw = request.postData();
      let body = null;
      try {
        body = raw ? JSON.parse(raw) : null;
      } catch (error) {
        // An unparsable body: the recorded null is the failure's proof.
      }
      ctrl.puts.push({ path, search: url.search, raw, body });
      return route.fulfill({
        status: 200,
        json: {
          key: body && body.key ? body.key : null,
          acknowledged_by: 'u-admin',
          acknowledged_by_name: 'Admin User',
          acknowledged_at: '2026-11-02T10:00:00Z',
          snooze_until: body && body.snooze_until ? body.snooze_until : null,
          note: null,
        },
      });
    }
    if (path === '/api/exceptions/ack' && request.method() === 'DELETE') {
      ctrl.deleteCalls.push({ key: url.searchParams.get('key') });
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({
        status: 200,
        json: { synced_at: null, data_through: null },
      });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

