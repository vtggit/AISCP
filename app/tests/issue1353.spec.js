  await expect.poll(() => ctrl.proposalsGets).toBe(getsBefore + 1);
  await expect(card.locator('.ov-exceptions-counts')).toBeVisible();
  expect(await line.count()).toBe(0);
  await expect(card.locator('h2')).toHaveText('Exceptions today');
