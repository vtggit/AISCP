// Proving spec for AIERP issue #1353 — the Overview's "Exceptions
// today" card measure line: the card's own read beside its list read.
//
// The card's load region (ov-region-exceptions) sends
// GET /api/exceptions/proposals beside the GET /api/exceptions it
// sends today — one Promise.all, the proposals read with its own
// catch that answers null, so it never fails the card. It goes out
// whenever the list read does: the first time the Overview is active
// and on each activation after Overview.invalidate().
//
// The line: with a usable answer — an object whose acknowledged and
// proposed are finite numbers with proposed no greater than
// acknowledged — the card renders as today and gains
// <p class="ov-exceptions-measure" data-testid="ov-exceptions-measure">
// directly before its "Open the inbox" link:
// "AISCP had proposed the answer for <proposed> of <acknowledged>
// acknowledgements (<pct>%)" when acknowledged is above 0 (pct
// Math.round(100 * proposed / acknowledged)), "No acknowledgements
// measured yet." when it is 0. Every number through the file's
// countLabel (whole, thousands separators); the words stay the same
// for a count of 1; the line is built with textContent like the rest
// of the card. A failed read — any status, a network error, or a
// body that is not such an object — leaves the line out: the card
// renders exactly as today, no error text, no Retry, no new
// [role="alert"]. When the list read itself fails, the card is
// removed as today.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// issue805, whose handler gains one branch: /api/exceptions/proposals
// counts each request in ctrl.proposalsGets, records its query string
// in ctrl.proposalsQueries and answers ctrl.proposalsAnswer with the
// status ctrl.proposalsStatus (200 by default; any other status
// answers {"detail": "Internal Server Error"}). The mocked answer
// FIRST has acknowledged 10, proposed 5, without_proposal 5, snoozed
// 3, snoozed_proposed 2 and by_kind stockout_likely 4/3; SECOND is
// FIRST with acknowledged 3 and proposed 2; ZERO has every count 0
// and by_kind empty.
//
// The pass proves, in order, signed in as the ADMIN through the
// development token card at 1440x900 on #/overview:
//   * The first load sends the proposals read once, with no query
//     string; the line reads FIRST's text (50%), is the page's only
//     such element, stands inside the card directly before its Open
//     link, and the card's title, counts line and link read as
//     issue805 expects today; every GET /api/exceptions went out
//     query-less.
//   * No re-read unless stale: the queue round-trip without
//     Overview.invalidate() leaves the line in place and
//     ctrl.proposalsGets at 1.
//   * The re-read: with answer SECOND, reactivateOverview raises
//     ctrl.proposalsGets by exactly 1 and the line reads "AISCP had
//     proposed the answer for 2 of 3 acknowledgements (67%)"; with
//     answer ZERO it reads "No acknowledgements measured yet.".
//   * A failed read: first the status 500, then the status 200 with
//     the body {"acknowledged": 3, "proposed": 4} — the card shows
//     its counts line again without the line, still with its title,
//     counts line and link, and no new [role="alert"].
//   * Phone width: at 390x844 the line is visible and the page does
//     not scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the card shows the same
// line for the viewer. The admin-only controls — the Exceptions
// view's Actions column and its buttons — are absent where "Only an
// admin can acknowledge exceptions." shows instead, while the page
// still renders. Throughout, no page error was raised and every
// request the app sent to the API was a GET.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1353 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

