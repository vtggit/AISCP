// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the
// /api/forecast/overrides/proposals answer (ctrl.overridesAnswer and
// ctrl.overridesStatus, 200 by default; any other status answers
// {"detail": "Internal Server Error"}) and the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the planner to
// the non-admin viewer. Every /api/forecast/overrides/proposals
// request is counted in ctrl.overridesGets with its query string in
// ctrl.overridesQuery, and every /api/ request's method is recorded
// in ctrl.apiRequests.
async function mockApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    abcAnswer: abcPayload(),
    exceptionsAnswer: exceptionsPayload(),
    summaryAnswer: summaryPayload(),
    summaryStatus: 200,
    summaryGets: 0,
    overridesAnswer: ANSWER_FIRST,
    overridesStatus: 200,
    overridesGets: 0,
    overridesQuery: '',
    meRequests: [],
    apiRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.apiRequests.push(request.method());
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/abc') {
      return route.fulfill({ status: 200, json: ctrl.abcAnswer });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: releasesPayload() });
    }
    if (path === '/api/exceptions') {
      return route.fulfill({ status: 200, json: ctrl.exceptionsAnswer });
    }
    if (path === '/api/supply-plan/summary') {
      ctrl.summaryGets += 1;
      if (ctrl.summaryStatus !== 200) {
        return route.fulfill({
          status: ctrl.summaryStatus,
          json: { detail: 'Internal Server Error' },
        });
      }
      return route.fulfill({ status: 200, json: ctrl.summaryAnswer });
    }
    if (path === '/api/forecast/overrides/proposals') {
      ctrl.overridesGets += 1;
      ctrl.overridesQuery = url.search;
      if (ctrl.overridesStatus !== 200) {
        return route.fulfill({
          status: ctrl.overridesStatus,
          json: { detail: 'Internal Server Error' },
        });
      }
      return route.fulfill({ status: 200, json: ctrl.overridesAnswer });
    }
    if (path === '/api/forecast') {
      // The Demand view's list: empty, so the view renders its empty
      // state with no chosen row and no detail-pane requests.
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/supply-plan') {
      return route.fulfill({ status: 200, json: planPayload() });
    }
    if (path === '/api/supply-plan/transfers') {
      return route.fulfill({ status: 200, json: { suggestions: [] } });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// Mark the figures stale and take the Overview off and on again: the
// next activation re-requests every region,
// /api/forecast/overrides/proposals included.
async function reactivateOverview(page) {
  await page.evaluate(() => {
    window.Overview.invalidate();
  });
  await page.evaluate(() => {
    window.location.hash = '#/queue';
  });
  await expect(page.locator('#view-queue')).toBeVisible();
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await expect(page.locator('#view-overview')).toBeVisible();
}

