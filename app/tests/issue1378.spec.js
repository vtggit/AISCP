// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the corrections answer
// (ctrl.corrections / ctrl.correctionsStatus / ctrl.correctionsDelayMs)
// and the sign-in (ctrl.config / ctrl.me) when the pass switches from
// the admin to the non-admin viewer. Every /api request is recorded
// (ctrl.requests) so the spec can assert they are all GETs, and the
// /api/forecast, the by-key, the two /api/forecast/accuracy, the
// /api/forecast/accuracy/signals and the
// /api/forecast/accuracy/corrections requests are all counted so the
// spec can inspect them.
async function mockDemandApi(page, options) {
  const {
    signals = SIGNALS_BETTER,
    signalsStatus = 200,
    signalsDelayMs = 0,
    corrections = CORRECTIONS_BETTER,
    correctionsStatus = 200,
    correctionsDelayMs = 0,
    rows = ROWS,
    details = DETAILS,
  } = options || {};
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    signals,
    signalsStatus,
    signalsDelayMs,
    corrections,
    correctionsStatus,
    correctionsDelayMs,
    requests: [],
    listGets: 0,
    byKeyGets: [],
    accuracyGets: [],
    signalsGets: 0,
    signalsFulfilled: false,
    correctionsGets: 0,
    correctionsSearches: [],
    correctionsFulfilled: false,
    meRequests: [],
    overrideGets: 0,
  };
  const appOrigin = { value: null };
  ctrl.appOrigin = appOrigin;

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.requests.push({ method: request.method(), path, search: url.search });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/forecast') {
      ctrl.listGets += 1;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      ctrl.byKeyGets.push({ item, site });
      const detail = details[item + '|' + site];
      if (!detail) {
        return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
      }
      return route.fulfill({ status: 200, json: detail });
    }
    if (path === '/api/forecast/overrides') {
      ctrl.overrideGets += 1;
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/forecast/accuracy') {
      ctrl.accuracyGets.push({
        bucketIndex: url.searchParams.get('bucket_index'),
        limit: url.searchParams.get('limit'),
      });
      const isAhead = url.searchParams.get('bucket_index') === '1';
      return route.fulfill({ status: 200, json: isAhead ? ACCURACY_AHEAD : ACCURACY_ALL });
    }
    if (path === '/api/forecast/accuracy/signals') {
      ctrl.signalsGets += 1;
      const respond = () => {
        ctrl.signalsFulfilled = true;
        if (ctrl.signalsStatus === 200) {
          return route.fulfill({ status: 200, json: ctrl.signals });
        }
        return route.fulfill({ status: ctrl.signalsStatus, json: { detail: 'unavailable' } });
      };
      if (ctrl.signalsDelayMs > 0) {
        setTimeout(respond, ctrl.signalsDelayMs);
        return;
      }
      return respond();
    }
    if (path === '/api/forecast/accuracy/corrections') {
      ctrl.correctionsGets += 1;
      ctrl.correctionsSearches.push(url.search);
      const respond = () => {
        ctrl.correctionsFulfilled = true;
        if (ctrl.correctionsStatus === 200) {
          return route.fulfill({ status: 200, json: ctrl.corrections });
        }
        return route.fulfill({ status: ctrl.correctionsStatus, json: { detail: 'unavailable' } });
      };
      if (ctrl.correctionsDelayMs > 0) {
        setTimeout(respond, ctrl.correctionsDelayMs);
        return;
      }
      return respond();
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

