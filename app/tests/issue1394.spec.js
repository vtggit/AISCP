// defaults (100 compared buckets, 30% history error, 20% forecast
// error, the forecast 10 points nearer), overridden per entry.
function basisSite(code, overrides) {
  return Object.assign(
    {
      item_code: code,
      site_code: 'S1',
      compared_buckets: 100,
      history_wape: 0.3,
      forecast_wape: 0.2,
      value_added: 0.1,
    },
    overrides || {},
  );
}

// The first `count` item-sites, I01 up, at site S1 — I02's forecast
// measures were never computed: null.
function basisSites(count) {
  const sites = [];
  for (let i = 1; i <= count; i += 1) {
    const code = 'I' + String(i).padStart(2, '0');
    sites.push(basisSite(code, i === 2 ? { forecast_wape: null, value_added: null } : {}));
  }
  return sites;
}

