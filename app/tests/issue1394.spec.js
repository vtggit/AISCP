// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user: issue1122's mocks plus the
// basis read, whose requests are counted in ctrl.basisGets with
// their query string, answered with ctrl.basis at ctrl.basisStatus
// (any status other than 200 answering {"detail": "unavailable"}),
// and the work-queue lists the re-read sub-scenario passes through.
// `apiMethods` collects every /api request's method (the read-only
// proof) and `apiOrigins` the app origins the /api routes were seen
// on (so the request listener can ignore the IdP's own origin).
async function mockSettingsApi(page, options) {
  const config = options.config;
  const me = options.me;
  const entries = options.entries;
  const impact = options.impact;
  const curve = options.curve;
  const basis = options.basis !== undefined ? options.basis : BASIS_FORECAST;
  const basisStatus = options.basisStatus !== undefined ? options.basisStatus : 200;
  const apiMethods = options.apiMethods;
  const apiOrigins = options.apiOrigins;
  const ctrl = {
    settingsGets: 0,
    impactGets: 0,
    curveGets: 0,
    basisGets: 0,
    basisMethods: [],
    basisQueries: [],
    basis,
    basisStatus,
    meRequests: [],
    current: entries,
    impact,
    curve,
    appOrigin: { value: null },
  };
  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (ctrl.appOrigin.value === null) {
      ctrl.appOrigin.value = url.origin;
    }
    apiOrigins.add(url.origin);
    apiMethods.push(request.method());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      ctrl.settingsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      ctrl.impactGets += 1;
      return route.fulfill({ status: ctrl.impact.status, json: ctrl.impact.body });
    }
    if (path === '/api/service-levels/curve' && request.method() === 'GET') {
      ctrl.curveGets += 1;
      return route.fulfill({ status: ctrl.curve.status, json: ctrl.curve.body });
    }
    if (path === '/api/forecast/accuracy/basis') {
      ctrl.basisGets += 1;
      ctrl.basisMethods.push(request.method());
      ctrl.basisQueries.push(url.search);
      if (ctrl.basisStatus !== 200) {
        return route.fulfill({ status: ctrl.basisStatus, json: { detail: 'unavailable' } });
      }
      return route.fulfill({ status: 200, json: ctrl.basis });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/erp-sources') {
      return route.fulfill({ status: 200, json: {} });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };
  await page.route('**/api/**', handler);
  return ctrl;
}

// The production boot's PKCE round-trip, mocked the way the other
// proofs' viewer passes do it: the IdP's auth endpoint answers with a
// page that bounces straight back to the app with a code and the same
// state, and the token endpoint answers with the viewer's token.
async function mockPkceRoundTrip(page, appOrigin) {
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
}

