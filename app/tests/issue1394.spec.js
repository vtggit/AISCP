// Proving spec for AIERP issue #1394 — the "Demand basis: history
// or forecast" card of the Settings view (#/settings).
//
// Below the "Service levels and their cost" card (its next element
// sibling), the card [data-testid="demand-basis"] reads
// GET /api/forecast/accuracy/basis?bucket_index=1 with its own load:
// one request when the view opens, its own state and its own
// request-sequence guard (an answer that arrives after a newer load
// has started is ignored), and the card is absent while its read is
// out. The current line
// ([data-testid="demand-basis-current"]) reads "Reorder points use
// the history." when the screen's own GET /api/settings answer holds
// the replenishment.demand_basis entry with the value "history",
// "Reorder points use the forecast." with "forecast" — no such line
// without the entry or with any other value. With compared_buckets
// 0 the card shows only the none line
// ([data-testid="demand-basis-none"]) "No period with a stored
// history quantity has completed yet." and nothing after it;
// otherwise the summary line
// ([data-testid="demand-basis-summary"]) "One period ahead, over
// <compared_buckets, thousands-separated> periods: <history_wape as
// a percent to one decimal> error on the history, <forecast_wape as
// a percent to one decimal> on the forecast.", the verdict
// ([data-testid="demand-basis-verdict"]) — "The forecast was
// <value_added times 100, absolute, to one decimal> points nearer
// what sold." for a positive value_added, "The history was … points
// nearer what sold." for a negative one, "Both were as near as each
// other." for 0 — and the table (table.demand-basis-table,
// [data-testid="demand-basis-table"]) inside its own sideways-scroll
// container: one [data-testid="demand-basis-row"] per each of the
// first 10 entries of item_sites, in the answer's order — the codes,
// compared_buckets thousands-separated, the two wapes as percents to
// one decimal and value_added times 100 to one decimal with a
// leading "+" above 0 and the minus sign U+2212 below 0 followed by
// " pts", a null or non-numeric value as an em dash. With more than
// 10 entries the more line
// ([data-testid="demand-basis-more"]) "The 10 item-sites with the
// most demand of <the count, thousands-separated>.". A usable
// answer is an object whose compared_buckets is a whole number of at
// least 0 and whose item_sites is an array, the three top-level
// measures finite numbers when compared_buckets is above 0;
// anything else, a non-2xx answer or a network failure renders no
// card and no message, every other card untouched.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1122.spec.js does it: the development token card as
// an admin, at 1440x900 on #/settings, the same settings entries
// (plus the replenishment.demand_basis enum entry — system scope,
// allowed "history" and "forecast", value "history"), the same
// impact and curve answers — and /api/forecast/accuracy/basis, whose
// requests the mock counts in ctrl.basisGets with their query
// string, answering ctrl.basis (BASIS_FORECAST by default) with
// ctrl.basisStatus (200 by default), any other status answering
// {"detail": "unavailable"}. The second pass, in the same test after
// a full reload, runs as a NON-ADMIN (role "user"): it boots the
// production way (the token in the URL hash, /api/auth/config and
// /api/auth/me mocked for that user, the PKCE round-trip mocked) and
// asserts the admin-only controls (the mappings and the budgets add
// forms, the editable number control) are absent while the settings
// rows and the read-only cards — the curve card and the demand-basis
// card among them — still render.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1394 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

