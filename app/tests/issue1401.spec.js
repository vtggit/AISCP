// The card ([data-testid="demand-basis"] of #/settings, the issue
// #1394 card) reads three entries of the screen's own
// GET /api/settings answer, through entryByKey:
// replenishment.demand_basis, exceptions.basis_switch_margin and
// exceptions.basis_switch_min_periods. There is a proposal when the
// card's answer has compared_buckets at least the fewest periods and
// either the basis is "history" and value_added times 100 is at
// least the margin, which proposes the forecast, or the basis is
// "forecast" and minus value_added times 100 is at least the margin,
// which proposes the history. There is no proposal when either
// threshold entry is missing or not a finite number, or the basis
// entry is missing or has another value. The line
// ([data-testid="demand-basis-proposal"], the verdict line's next
// element sibling) reads "Proposed: switch reorder points to the
// forecast. The exceptions inbox shows the same proposal; an admin
// makes the switch with the demand basis setting above." — with
// "the history" in place of "the forecast" for the mirror case — and
// is absent otherwise, the rest of the card unchanged.
//
// The label: #/exceptions reads the row's kind through its kind map,
// and since this issue the map carries
// demand_basis_switch: 'Demand basis to review', so the row's
// Signal cell reads that label and the Signal filter
// ([data-testid="exceptions-kind-filter"]) offers it as an option.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the way
// app/tests/issue1394.spec.js (the card: the development token card
// as the admin at 1440x900 on #/settings, the same entries plus the
// two exceptions.basis_switch_* number entries of system scope, the
// same impact and curve answers, and
// /api/forecast/accuracy/basis) and app/tests/issue1347.spec.js
// (the label: #/exceptions, the answer holding one
// demand_basis_switch row — severity medium, item_code and
// site_code null, key "demand_basis_switch:forecast" and #1397's
// detail for the forecast case) do it. The second pass of each
// screen runs as a NON-ADMIN (role "user"): it boots the production
// way (the token in the URL hash, /api/auth/config and /api/auth/me
