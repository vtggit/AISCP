// Mock every /api/* call the app makes, the way
// app/tests/issue975.spec.js does: one page.route answers by
// url.pathname; the handler reads ctrl on every request, so the
// test can steer the review answer (ctrl.sopAnswer, either a
// payload or a { status, json } failure) and the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the admin to
// the non-admin viewer. Every review request is counted
// (ctrl.sopGets) with its months query recorded in ctrl.sopQueries,
// and the forecast-signals read beside the review is answered 200
// (ctrl.signalsGets), never the 404 fallback.
async function mockSopApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    sopAnswer: null,
    sopGets: 0,
    sopQueries: [],
    signoffListGets: 0,
    signoffListQueries: [],
    signoffDetailGets: [],
    meRequests: [],
    summaryGets: 0,
    signalsGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/sop/review') {
      ctrl.sopGets += 1;
      ctrl.sopQueries.push(url.searchParams.get('months'));
      return answerOrFulfill(route, ctrl.sopAnswer, sopBase());
    }
    if (path === '/api/sop/signoffs') {
      ctrl.signoffListGets += 1;
      ctrl.signoffListQueries.push(url.searchParams.get('limit'));
      return route.fulfill({ status: 200, json: [signoffRow1()] });
    }
    if (/^\/api\/sop\/signoffs\/[^/]+$/.test(path)) {
      const id = path.slice('/api/sop/signoffs/'.length);
      ctrl.signoffDetailGets.push(id);
      if (id === '1') {
        return route.fulfill({
          status: 200,
          json: Object.assign({}, signoffRow1(), { figures: signoffFigures1() }),
        });
      }
      return route.fulfill({ status: 404, json: { detail: 'sign-off not found' } });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/forecast/accuracy/signals') {
      ctrl.signalsGets += 1;
      return route.fulfill({ status: 200, json: SIGNALS_ANSWER });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

