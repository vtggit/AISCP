// Proving spec for AIERP issue #1407 — the S&OP status card's
// sign-off proposal line (#/sop): after the sign-off line
// ([data-testid="sop-signoff"]) and its note — when there is one —
// and before the sign-off button, the line
// ([data-testid="sop-signoff-proposal"]) reads the server's
// proposal to sign the month off, from the review answer the screen
// already loads (signoff_proposal) — it sends no request of its
// own.
//
// A usable proposal is an object whose proposed is a boolean,
// max_change a finite number and since_month a non-empty string.
// PROPOSED (proposed true, largest_change 0.0196): the line reads
// "Proposed: sign off 2026-11. Since the 2026-10 sign-off, no value
// figure moved more than 2.0% (the limit is 5.0%).", carries the
// base class sop-signoff-proposal with is-proposed, and is the
// sign-off line's next element sibling.
// NOT_PROPOSED (proposed false, largest_change 0.0909,
// largest_field supply_value, largest_month 2026-12): "Not proposed:
// Open supply value for 2026-12 moved 9.1% since the 2026-10
// sign-off (the limit is 5.0%).", without is-proposed. NOTHING
// (proposed false, the largest_* figures null): "Not proposed: no
// value figure of the 2026-10 sign-off can be compared with this
// review." With signoff_proposal null, with the key missing from
// the answer, with proposed the string "yes", or with proposed true
// but largest_change missing or non-finite there is no line at all
// — the card never reads "0.0%" or "NaN%" — and the sign-off line
// and button read as before. Every case
// runs on its own fresh page in the same context, and at 390x844
// with PROPOSED the line is visible and the page does not scroll
// sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #975 spec, whose review answer — review month 2026-11, no
// sign-off of it, the 2026-10 since_signoff of "Pat Admin" — this
// proof reuses). The pass runs as an ADMIN signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, the screen then renders the same PROPOSED line
// for the viewer, and the screen's admin-only control (the sign-off
// button) is absent while the page renders on.
//
// Throughout: no page error was raised, the screen sends no request
// other than the ones the issue #975 run sends, every /api/ request
// it sends is a GET, and the required forecast-signals read beside
// the review lands a 200 — never the 404 fallback.
//
// The test is TOP-LEVEL and its title is the full proof name
