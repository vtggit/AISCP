  const rows = page.locator('[data-testid="purchase-budget-row"]');

  await page.goto('/#/settings');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // --- the card, as before: the stored rows and the set form ----------
  await expect(card).toBeVisible();
  await expect(card.locator('.settings-card-title')).toHaveText('Purchasing budget');
  await expect(rows).toHaveCount(2);
  await expect(rows.nth(0)).toContainText('Nov 2026');
  await expect(rows.nth(0)).toContainText('$250,001');
  await expect(rows.nth(1)).toContainText('Dec 2026');
  await expect(rows.nth(1)).toContainText('$125,000');
  await expect(form).toBeVisible();
  await expect(saveButton).toBeEnabled();

  // --- AC-1: the load read, beside the two reads -----------------------
  // The card's load sent the proposals read once, beside the roles
  // read and the budgets read.
  await expect(proposals).toBeVisible();
  expect(ctrl.proposalsGets).toBe(1);
  expect(ctrl.budgetsGets).toBe(1);
  expect(
    ctrl.requests.some(
      (entry) => entry.method === 'GET' && entry.path === '/api/purchase-budgets/proposals',
    ),
  ).toBe(true);

  // --- AC-2: the note ---------------------------------------------------
  // margin 0.05 times 100 is 5, with at most one decimal — no
