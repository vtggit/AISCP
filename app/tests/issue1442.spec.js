// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the proposals answer (with or
// without its record) and read the full request log — every /api
// request the app sent, with its method, path and body.
async function mockApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    budgets: initialBudgets(),
    proposals: { status: 200, body: proposalAnswer(RECORD_TAKEN_BELOW) },
    budgetsGets: 0,
    proposalsGets: 0,
    budgetPuts: [],
    requests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    let body = null;
    if (request.method() !== 'GET') {
      try {
        body = request.postDataJSON();
      } catch (error) {
        body = null;
      }
    }
    ctrl.requests.push({ method: request.method(), path, body });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      ctrl.budgetsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.budgets });
    }
    if (path === '/api/purchase-budgets/proposals' && request.method() === 'GET') {
      ctrl.proposalsGets += 1;
      const answer = ctrl.proposals;
      return route.fulfill({ status: answer.status, json: answer.body });
    }
    const budgetMonth = /^\/api\/purchase-budgets\/([^/]+)$/.exec(path);
    if (budgetMonth && request.method() === 'PUT') {
      const month = decodeURIComponent(budgetMonth[1]);
      ctrl.budgetPuts.push({ month, body });
      const existing = ctrl.budgets.find((row) => row.month === month);
      if (existing) {
        existing.amount = body.amount;
        existing.updated_at = '2026-10-19T08:00:00+00:00';
        existing.updated_by = 'planner1';
      } else {
        ctrl.budgets.push({
          id: 100 + ctrl.budgets.length,
          month,
          amount: body.amount,
          updated_at: '2026-10-19T08:00:00+00:00',
          updated_by: 'planner1',
        });
      }
      return route.fulfill({
        status: 200,
        json: ctrl.budgets.find((row) => row.month === month),
      });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 404, json: { detail: 'item site not found' } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue1442 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
  });

  const card = page.locator('[data-testid="purchase-budgets"]');
  const proposals = page.locator('[data-testid="purchase-budget-proposals"]');
  const proposalNote = page.locator('[data-testid="purchase-budget-proposals-note"]');
  const recordLine = page.locator('[data-testid="purchase-budget-proposals-record"]');
  const proposalRows = page.locator('[data-testid="purchase-budget-proposal"]');
  const useButtons = page.locator('[data-testid="purchase-budget-use"]');
  const form = page.locator('[data-testid="purchase-budget-form"]');
  const rows = page.locator('[data-testid="purchase-budget-row"]');

  await page.goto('/#/settings');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // --- the card, as before: the stored rows and the set form ----------
  await expect(card).toBeVisible();
  await expect(card.locator('.settings-card-title')).toHaveText('Purchasing budget');
  await expect(rows).toHaveCount(2);
  await expect(rows.nth(0)).toContainText('Nov 2026');
  await expect(rows.nth(0)).toContainText('$250,001');
  await expect(rows.nth(1)).toContainText('Dec 2026');
  await expect(rows.nth(1)).toContainText('$125,000');
  await expect(form).toBeVisible();

  // The section as before: the note and the two proposal rows.
  const sectionAsBefore = async () => {
    await expect(proposals).toBeVisible();
    await expect(proposalNote).toHaveText(
      "Proposed from the plan's committed and planned spend, plus 5%.",
    );
    await expect(proposalRows).toHaveCount(2);
    await expect(proposalRows.nth(0)).toHaveAttribute('data-month', '2026-12');
    await expect(proposalRows.nth(1)).toHaveAttribute('data-month', '2027-01');
  };

  // The record line's placement: inside the section, directly after
  // the note.
  const linePlacement = () =>
    page.evaluate(() => {
      const blockEl = document.querySelector('[data-testid="purchase-budget-proposals"]');
      const noteEl = document.querySelector('[data-testid="purchase-budget-proposals-note"]');
      const lineEl = document.querySelector('[data-testid="purchase-budget-proposals-record"]');
      if (!blockEl || !noteEl || !lineEl) {
        return null;
      }
      return {
        inBlock: blockEl.contains(lineEl),
        directlyAfterNote: noteEl.nextElementSibling === lineEl,
      };
    });

  // --- the record {saved 3, with_proposal 2, taken 1, below 1, above 0}
  // ---
  ctrl.proposals = { status: 200, body: proposalAnswer(RECORD_TAKEN_BELOW) };
  await page.reload();
  await sectionAsBefore();
  await expect(recordLine).toHaveCount(1);
  await expect(recordLine).toHaveText(
    'Budgets saved at the proposal: 1 of 2 (1 below, 0 above)',
  );
  expect(await linePlacement()).toEqual({ inBlock: true, directlyAfterNote: true });

  // --- the record {saved 1, with_proposal 1, taken 1, below 0, above 0}
  // --- no below/above tail while both are at 0.
  ctrl.proposals = { status: 200, body: proposalAnswer(RECORD_ALL_TAKEN) };
  await page.reload();
  await sectionAsBefore();
  await expect(recordLine).toHaveText('Budgets saved at the proposal: 1 of 1');
  expect(await linePlacement()).toEqual({ inBlock: true, directlyAfterNote: true });

  // --- the record {saved 2, with_proposal 0, taken 0, below 0, above 0}
  // --- with_proposal at 0: the empty record note.
  ctrl.proposals = { status: 200, body: proposalAnswer(RECORD_NO_PROPOSAL) };
  await page.reload();
  await sectionAsBefore();
  await expect(recordLine).toHaveText('No budget saved against a proposal yet.');

  // --- the line left out -----------------------------------------------
  // Each of these leaves the record line out — while the note and the
  // proposal rows still render.
  const lineLeftOut = async () => {
    await expect(recordLine).toHaveCount(0);
    await sectionAsBefore();
  };

  // The answer without the record key.
  ctrl.proposals = { status: 200, body: proposalAnswer() };
  await page.reload();
  await lineLeftOut();

  // The answer whose record's taken is a string.
  ctrl.proposals = {
    status: 200,
    body: proposalAnswer({ saved: 3, with_proposal: 2, taken: '1', below: 1, above: 0 }),
  };
  await page.reload();
  await lineLeftOut();

  // --- narrow (390x844): the page does not scroll sideways --------------
  ctrl.proposals = { status: 200, body: proposalAnswer(RECORD_TAKEN_BELOW) };
  await page.reload();
  await sectionAsBefore();
  await expect(recordLine).toHaveText(
    'Budgets saved at the proposal: 1 of 2 (1 below, 0 above)',
  );
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(card).toBeVisible();
  await expect(recordLine).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(
    390,
  );
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ------------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  ctrl.budgets = initialBudgets();
  ctrl.proposals = { status: 200, body: proposalAnswer(RECORD_TAKEN_BELOW) };
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );

  // ... and the budget card renders for the viewer: the note and the
  // rows render ...
  await page.click('.nav-btn[data-view="settings"]');
  await expect(card).toBeVisible();
  await sectionAsBefore();
  // ... with the record line — the viewer sees it too ...
  await expect(recordLine).toHaveText(
    'Budgets saved at the proposal: 1 of 2 (1 below, 0 above)',
  );
  // ... with no Use button and no set form — the admin-only controls
  // are absent ...
  await expect(useButtons).toHaveCount(0);
  await expect(form).toHaveCount(0);
  // ... while the stored budgets and the rest of the card still render.
  await expect(rows).toHaveCount(2);
  await expect(rows.nth(0)).toContainText('Nov 2026');
  await expect(rows.nth(0)).toContainText('$250,001');
  await expect(rows.nth(1)).toContainText('Dec 2026');
  await expect(rows.nth(1)).toContainText('$125,000');
  await expect(card).toContainText('Only an admin can change this.');
  expect(pageErrors).toEqual([]);
});
