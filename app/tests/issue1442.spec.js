// Proving spec for AIERP issue #1442 — the record line of the
// "Proposed" section of the Purchasing budget card of the Settings
// view: directly after the section's note, the line
// ([data-testid="purchase-budget-proposals-record"]) reads the
// answer's record measure of the budgets saved at the proposal,
// beside the note and the proposal rows the card renders as before.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route. Proves, signed in through the
// development token card as an admin (/api/auth/me roles ["admin"])
// with GET /api/purchase-budgets returning 2026-11 (250000.5,
// updated by "jason") and 2026-12 (125000) and the proposals answer
// of margin 0.05 and two months (2026-12 and 2027-01):
//   * the record {saved 3, with_proposal 2, taken 1, below 1,
//     above 0} reads the line "Budgets saved at the proposal: 1 of
//     2 (1 below, 0 above)", directly after the note and inside the
//     section;
//   * the record {saved 1, with_proposal 1, taken 1, below 0,
//     above 0} reads "Budgets saved at the proposal: 1 of 1" — no
//     below/above tail while both are at 0;
//   * the record {saved 2, with_proposal 0, taken 0, below 0,
//     above 0} reads "No budget saved against a proposal yet.";
//   * the answer without the record key, and the answer whose
//     record's taken is a string, each leave the line out while the
//     note and the proposal rows still render;
//   * at 390x844 the page does not scroll sideways;
//   * the pass ends as a NON-ADMIN (role 'user') after a full
//     reload: the token arrives in the URL hash as
//     #access_token=..., /api/auth/config and /api/auth/me are
//     mocked for that user, the IdP's auth and token endpoints
//     carry the PKCE round-trip, and the admin-only controls (the
//     per-row Use button and the set form) are absent — with the
//     line, the note and the rows still rendering.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1442 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

