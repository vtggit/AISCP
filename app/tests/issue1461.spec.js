// Mock every /api/* call the demand view makes. The by-key route
// answers detailDelayMs after the request (the delay is in the mock,
// not a fixed wait in the page) — but while api.holdDetail is true
// each by-key request is held, not answered, until the test calls
// api.releaseDetail(); releaseDetail() sets holdDetail to false and
// answers every held request in the order it arrived, each with the
// answer it would have had: the 500 for the row bound via
// api.failKey, the 404 for an unknown item-site, or the detail.
async function mockDemandApiHeld(page, { rows, details, detailDelayMs = 0 } = {}) {
  const held = []; // by-key responders held while api.holdDetail is true
  const api = {
    byKeyGets: [],
    byKeyFails: [], // the item-site of every by-key request answered 500
    answeredOrder: [], // the item-site of every by-key answer, in answer order
    rows,
    details,
    detailDelayMs,
    failKey: null, // { item, site } whose next detail request responds 500
    holdDetail: false,
    releaseDetail() {
      api.holdDetail = false;
      const released = held.splice(0, held.length);
      released.forEach((respond) => respond());
    },
  };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (url.pathname === '/api/forecast') {
      return route.fulfill({ status: 200, json: api.rows });
    }
    if (url.pathname === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.byKeyGets.push({ item, site });
      const detail = api.details[item + '|' + site];
      const respond = () => {
        api.answeredOrder.push({ item, site });
        if (api.failKey && api.failKey.item === item && api.failKey.site === site) {
          api.failKey = null;
          api.byKeyFails.push({ item, site });
          return route.fulfill({ status: 500, json: { detail: FAIL_DETAIL_MESSAGE } });
        }
        if (!detail) {
          return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
        }
        return route.fulfill({ status: 200, json: detail });
      };
      if (api.holdDetail) {
        held.push(respond);
        return;
      }
      if (api.detailDelayMs > 0) {
        return new Promise((resolve) => {
          setTimeout(resolve, api.detailDelayMs);
        }).then(respond);
      }
      return respond();
    }
    if (url.pathname === '/api/forecast/overrides') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (url.pathname === '/api/forecast/accuracy') {
      const isAhead = url.searchParams.get('bucket_index') === '1';
      return route.fulfill({ status: 200, json: isAhead ? ACCURACY_AHEAD : ACCURACY_ALL });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}


