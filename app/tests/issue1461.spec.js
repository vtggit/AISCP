test('issue1461 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // --- the spec contracts: both amendments, pinned --------------------
  checkIssue329Amendment();
  checkIssue638Amendment();

  // --- spec 329's mechanics against the real demand view --------------
  const rowsList = rows12();
  const api = await mockDemandApiHeld(page, {
    rows: rowsList,
    details: detailsFor(rowsList),
    detailDelayMs: 0,
  });

  await page.goto('/#/demand');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  const rows = page.locator('[data-testid="demand-row"]');
  await expect(rows).toHaveCount(12);

  // The first row is chosen when the view opens, and with holdDetail
  // false and no delay its by-key answer lands straight away.
  await expect(page.locator('.d-detail-title')).toHaveText('BIG-0001 \u00b7 WH-2');
  expect(api.byKeyGets[0]).toEqual({ item: 'BIG-0001', site: 'WH-2' });

  // A held detail stays in flight until the test releases it: with no
  // delay an unheld answer would be instant, so the skeleton still
  // showing 1.5 s after the click means the request is held, not
  // merely delayed.
  const first = rows.nth(1);
  await expect(first).toHaveAttribute('data-item', 'BIG-0002');
  api.holdDetail = true;
  await first.click();
  await expect(first).toHaveAttribute('aria-current', 'true');
  expect(await detailInFlight(page)).toBe(true);
  await page.waitForTimeout(1500);
  expect(await detailInFlight(page)).toBe(true);
  api.releaseDetail();
  await expect(page.locator('.d-detail-title')).toHaveText('BIG-0002 \u00b7 WH-3');

  // Two held requests are answered in the order they arrived, and the
  // view shows the last chosen row's detail.
  const second = rows.nth(2);
  const third = rows.nth(3);
  api.holdDetail = true;
  await second.click();
  await expect(second).toHaveAttribute('aria-current', 'true');
  await third.click();
  await expect(third).toHaveAttribute('aria-current', 'true');
  expect(await detailInFlight(page)).toBe(true);
  api.releaseDetail();
  await expect(page.locator('.d-detail-title')).toHaveText('BIG-0004 \u00b7 WH-2');
  expect(api.answeredOrder).toEqual([
    { item: 'BIG-0001', site: 'WH-2' },
    { item: 'BIG-0002', site: 'WH-3' },
    { item: 'BIG-0003', site: 'WH-1' },
    { item: 'BIG-0004', site: 'WH-2' },
  ]);

  // A held request bound to failKey still answers the 500 to that
  // row's own request when it is released.
  const failing = rows.nth(4);
  api.failKey = { item: 'BIG-0005', site: 'WH-3' };
  api.holdDetail = true;
  await failing.click();
  await expect(failing).toHaveAttribute('aria-current', 'true');
  expect(await detailInFlight(page)).toBe(true);
  await page.waitForTimeout(1500);
  expect(await detailInFlight(page)).toBe(true);
  api.releaseDetail();
  await expect(page.locator('.d-detail-error-msg')).toHaveText(FAIL_DETAIL_MESSAGE);
  await expect(page.locator('#demand-detail-retry')).toHaveText('Try again');
  expect(api.byKeyFails).toEqual([{ item: 'BIG-0005', site: 'WH-3' }]);

  // --- spec 638's mechanics against the real work queue ---------------
  // The demand mock steps aside for the queue's: unroute it, then the
  // queue mock answers every /api/* call. The app is already signed
  // in (its token sits in sessionStorage), so the hash change mounts
  // the queue without a reload.
  await page.unroute('**/api/**');
  const { api: queueApi } = await mockQueueApi(page, { config: DEV_CONFIG, me: ADMIN_ME });
  await page.evaluate(() => {
    window.location.hash = '#/queue';
  });
  await expect(page.locator('.q-tab[data-kind="drift"]')).toHaveText('Reorder points 4');
  await expect.poll(() => queueApi.listGets.length).toBe(3);

  // The 120-character description wraps inside the row: the retrying
  // check reads the box and the line height afresh each try and
  // passes when the line height is a finite number above 0 and the
  // height is more than 1.5 times it.
  const longDesc = page.locator('.q-row[data-item="LONGDESC"][data-site="154"] .q-item-desc');
  await expect(longDesc).toHaveText(LONG_DESC);
  expect(LONG_DESC.length).toBe(120);
  await expect.poll(async () => {
    const longFit = await longDesc.evaluate((descEl) => ({
      height: descEl.getBoundingClientRect().height,
      lineHeight: parseFloat(getComputedStyle(descEl).lineHeight),
    }));
    if (!Number.isFinite(longFit.lineHeight) || longFit.lineHeight <= 0) {
      return false;
    }
    expect(longFit.height).toBeGreaterThan(1.5 * longFit.lineHeight);
    return true;
  }).toBeTruthy();

  // The list never widens to fit the run.
  const listFit = await page.locator('.q-list-body').evaluate((listEl) => ({
    scrollWidth: listEl.scrollWidth,
    clientWidth: listEl.clientWidth,
  }));
  expect(listFit.scrollWidth).toBeLessThanOrEqual(listFit.clientWidth);
});
