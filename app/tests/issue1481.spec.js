// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the plan, the zones and the
// section answers (either a payload or a { status, json } failure,
// a one-shot via the *Next keys), steer the record answer
// (ctrl.recordAnswer), steer the adjustment add (ctrl.postNext) and
// steer the sign-in (ctrl.config / ctrl.me) when the pass switches
// from the admin to the non-admin viewer. Every request is counted
// and every POST body is recorded.
async function mockBuffersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    planAnswer: null,
    planNext: null,
    zonesAnswer: null,
    zonesNext: null,
    candidatesAnswer: null,
    candidatesNext: null,
    adjustmentsAnswer: null,
    adjustmentsNext: null,
    proposalsAnswer: null,
    proposalsNext: null,
    performanceAnswer: null,
    performanceNext: null,
    recordAnswer: null,
    recordNext: null,
    postNext: null,
    planGets: 0,
    zonesGets: 0,
    candidatesGets: 0,
    adjustmentsGets: 0,
    proposalsGets: 0,
    performanceGets: 0,
    recordGets: 0,
    postBodies: [],
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/ddmrp/plan') {
      ctrl.planGets += 1;
      if (ctrl.planNext) {
        const next = ctrl.planNext;
        ctrl.planNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.planAnswer, planPayloadBase());
    }
    if (path === '/api/ddmrp/zones') {
      ctrl.zonesGets += 1;
      if (ctrl.zonesNext) {
        const next = ctrl.zonesNext;
        ctrl.zonesNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.zonesAnswer, zonesPayloadBase());
    }
    if (path === '/api/ddmrp/candidates') {
      ctrl.candidatesGets += 1;
      if (ctrl.candidatesNext) {
        const next = ctrl.candidatesNext;
        ctrl.candidatesNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.candidatesAnswer, candidatesPayloadBase());
    }
    if (path === '/api/ddmrp/adjustments/proposals') {
      ctrl.proposalsGets += 1;
      if (ctrl.proposalsNext) {
        const next = ctrl.proposalsNext;
        ctrl.proposalsNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.proposalsAnswer, proposalsPayloadBase());
    }
    if (path === '/api/ddmrp/adjustments') {
      if (request.method() === 'POST') {
        let body = null;
        try {
          body = request.postDataJSON();
        } catch (error) {
          // An unparsable body: the recorded null is the failure's proof.
        }
        ctrl.postBodies.push(body);
        if (ctrl.postNext) {
          const next = ctrl.postNext;
          ctrl.postNext = null;
          return route.fulfill(next);
        }
        return route.fulfill({
          status: 201,
          json: {
            id: 'adj-new',
            item_code: body && body.item_code !== undefined ? body.item_code : null,
            site_code: body && body.site_code !== undefined ? body.site_code : null,
            start_on: body ? body.start_on : null,
            end_on: body ? body.end_on : null,
            factor: body ? body.factor : null,
            note: body && body.note !== undefined ? body.note : null,
            created_by: 'u-admin',
            created_by_name: 'Admin User',
            created_at: '2026-10-29T10:05:00Z',
          },
        });
      }
      ctrl.adjustmentsGets += 1;
      if (ctrl.adjustmentsNext) {
        const next = ctrl.adjustmentsNext;
        ctrl.adjustmentsNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.adjustmentsAnswer, adjustmentsPayloadBase());
    }
    if (path.indexOf('/api/ddmrp/adjustments/') === 0 && request.method() === 'DELETE') {
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/ddmrp/adjustments/record') {
      ctrl.recordGets += 1;
      if (ctrl.recordNext) {
        const next = ctrl.recordNext;
        ctrl.recordNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.recordAnswer, null);
    }
    if (path === '/api/ddmrp/performance') {
      ctrl.performanceGets += 1;
      if (ctrl.performanceNext) {
        const next = ctrl.performanceNext;
        ctrl.performanceNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.performanceAnswer, performancePayloadBase());
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}


test('issue1481 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in --------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockBuffersApi(page);
  // The record read answers from this variable; the test sets it for
  // each scenario before the screen opens (again).
  ctrl.recordAnswer = { saved: 5, with_proposal: 3, taken: 1, below: 1, above: 1 };

  const table = page.locator('[data-testid="buffers-table"]');
  const refresh = page.locator('[data-testid="buffers-refresh"]');
  const adjustments = page.locator('[data-testid="buffers-adjustments"]');
  const proposals = page.locator('[data-testid="buffers-adjust-proposals"]');
  const recordLine = page.locator('[data-testid="buffers-adjust-record"]');

  await page.goto('/');

  // No buffers request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.planGets).toBe(0);
  expect(ctrl.recordGets).toBe(0);

  // Sign in through the development token card as the admin.
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  // The buffers view is not active yet (the default view is): no
  // buffers request.
  expect(ctrl.planGets).toBe(0);
  expect(ctrl.recordGets).toBe(0);
  expect(pageErrors).toEqual([]);

  await page.click('.nav-btn[data-view="buffers"]');
  await expect(page).toHaveURL(/#\/buffers$/);
  await expect(page.locator('#view-buffers')).toBeVisible();
  await expect(page.locator('#page-title')).toHaveText('Buffers');

  // Activation fetches the plan, the zones and the sections — the
  // record read goes out once with them — and the answers render.
  await expect.poll(() => ctrl.planGets).toBe(1);
  await expect.poll(() => ctrl.zonesGets).toBe(1);
  await expect.poll(() => ctrl.candidatesGets).toBe(1);
  await expect.poll(() => ctrl.adjustmentsGets).toBe(1);
  await expect.poll(() => ctrl.performanceGets).toBe(1);
  await expect.poll(() => ctrl.proposalsGets).toBe(1);
  await expect.poll(() => ctrl.recordGets).toBe(1);
  await expect(table).toBeVisible();
  expect(pageErrors).toEqual([]);

  // The record line: the section has its adjustments answer and the
  // record answer is usable, so the line shows — the whole numbers
  // with separators, the note class, set as text, never as markup.
  await expect(adjustments).toBeVisible();
  await expect(proposals).toBeVisible();
  await expect(recordLine).toHaveCount(1);
  await expect(recordLine).toHaveClass('bf-note');
  await expect(recordLine).toHaveText(
    'Saved at the proposal: 1 of 3 adjustments saved where a factor was proposed (1 below it, 1 above it)',
  );
  expect(await recordLine.innerHTML()).not.toContain('<');
  // The line sits directly after the proposals block and before the
  // add form.
  const sectionOrder = await page.evaluate(() => {
    const section = document.querySelector('[data-testid="buffers-adjustments"]');
    const block = section.querySelector('[data-testid="buffers-adjust-proposals"]');
    const line = section.querySelector('[data-testid="buffers-adjust-record"]');
    const form = section.querySelector('[data-testid="buffers-adjust-add"]');
    if (!block || !line || !form) {
      return { ok: false, lineRightAfterBlock: false, formAfterLine: false };
    }
    return {
      ok: true,
      lineRightAfterBlock: line.previousElementSibling === block,
      formAfterLine: (line.compareDocumentPosition(form) & 0x04) !== 0,
    };
  });
  expect(sectionOrder.ok).toBe(true);
  expect(sectionOrder.lineRightAfterBlock).toBe(true);
  expect(sectionOrder.formAfterLine).toBe(true);
  // The record read was sent exactly once on activation.
  expect(ctrl.recordGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // Other answers, each after the screen is opened again (Refresh
  // re-fetches the sections, and the record read goes with them).
  ctrl.recordAnswer = { saved: 2, with_proposal: 0, taken: 0, below: 0, above: 0 };
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(2);
  await expect(recordLine).toHaveText(
    'No adjustment has been saved where a factor was proposed yet.',
  );
  expect(pageErrors).toEqual([]);

  ctrl.recordAnswer = {
    saved: 2500,
    with_proposal: 2000,
    taken: 1234,
    below: 500,
    above: 266,
  };
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(3);
  await expect(recordLine).toHaveText(
    'Saved at the proposal: 1,234 of 2,000 adjustments saved where a factor was proposed (500 below it, 266 above it)',
  );
  expect(pageErrors).toEqual([]);

  // No line at all: a failed read (500) leaves the line out, with no
  // error note, while the proposals block still shows.
  ctrl.recordAnswer = { status: 500, json: { detail: 'upstream unavailable' } };
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(4);
  await expect(recordLine).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-adjust-record-error"]')).toHaveCount(0);
  await expect(proposals).toBeVisible();
  await expect(table).toBeVisible();
  expect(pageErrors).toEqual([]);

  // ... and an answer whose figures are numeric strings is not
  // usable: no line, no error note, the proposals block still shows.
  ctrl.recordAnswer = {
    saved: '5',
    with_proposal: '3',
    taken: '1',
    below: '1',
    above: '1',
  };
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(5);
  await expect(recordLine).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-adjust-record-error"]')).toHaveCount(0);
  await expect(proposals).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- narrow screens: the line shown, no sideways scroll ------------
  ctrl.recordAnswer = {
    saved: 2500,
    with_proposal: 2000,
    taken: 1234,
    below: 500,
    above: 266,
  };
  await refresh.click();
  await expect(recordLine).toHaveText(
    'Saved at the proposal: 1,234 of 2,000 adjustments saved where a factor was proposed (500 below it, 266 above it)',
  );
  page.setViewportSize({ width: 390, height: 844 });
  const narrow = await page.evaluate(() => ({
    scrollWidth: document.documentElement.scrollWidth,
    innerWidth: window.innerWidth,
  }));
  expect(narrow.scrollWidth).toBeLessThanOrEqual(narrow.innerWidth);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload -----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const planGetsBeforeViewer = ctrl.planGets;
  const zonesGetsBeforeViewer = ctrl.zonesGets;
  const candidatesGetsBeforeViewer = ctrl.candidatesGets;
  const adjustmentsGetsBeforeViewer = ctrl.adjustmentsGets;
  const proposalsGetsBeforeViewer = ctrl.proposalsGets;
  const performanceGetsBeforeViewer = ctrl.performanceGets;
  const recordGetsBeforeViewer = ctrl.recordGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  const summaryGetsBeforeViewer = ctrl.summaryGets;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and no buffers fetch went out before the view is activated:
  // the Overview view (the default) loads on its own ...
  await expect.poll(() => ctrl.summaryGets).toBeGreaterThan(summaryGetsBeforeViewer);
  // ... and the Buffers screen has not asked for its data yet.
  expect(ctrl.planGets).toBe(planGetsBeforeViewer);
  expect(ctrl.zonesGets).toBe(zonesGetsBeforeViewer);
  expect(ctrl.candidatesGets).toBe(candidatesGetsBeforeViewer);
  expect(ctrl.adjustmentsGets).toBe(adjustmentsGetsBeforeViewer);
  expect(ctrl.proposalsGets).toBe(proposalsGetsBeforeViewer);
  expect(ctrl.performanceGets).toBe(performanceGetsBeforeViewer);
  expect(ctrl.recordGets).toBe(recordGetsBeforeViewer);

  // Activating the view for the viewer: the screen renders, with the
  // plan, the zones and the sections fetched alongside — the record
  // read goes out once more with them.
  await page.click('.nav-btn[data-view="buffers"]');
  expect(page.url()).toContain('#/buffers');
  await expect(page.locator('#view-buffers')).toBeVisible();
  await expect.poll(() => ctrl.planGets).toBe(planGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.zonesGets).toBe(zonesGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.candidatesGets).toBe(candidatesGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.adjustmentsGets).toBe(adjustmentsGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.performanceGets).toBe(performanceGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.proposalsGets).toBe(proposalsGetsBeforeViewer + 1);
  await expect.poll(() => ctrl.recordGets).toBe(recordGetsBeforeViewer + 1);
  await expect(table).toBeVisible();

  // The line still shows for the viewer: a sign-out and sign-in again
  // re-reads the record, and the answer is usable ...
  await expect(recordLine).toHaveCount(1);
  await expect(recordLine).toHaveText(
    'Saved at the proposal: 1,234 of 2,000 adjustments saved where a factor was proposed (500 below it, 266 above it)',
  );
  // ... while the admin-only controls are absent and the page still
  // renders: the plan table, the proposals block and the sections.
  await expect(page.locator('[data-testid="buffers-adjust-add"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-adjust-delete"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-add"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-remove"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="buffers-designate"]')).toHaveCount(0);
  await expect(proposals).toBeVisible();
  await expect(page.locator('[data-testid="buffers-candidates"]')).toBeVisible();
  await expect(page.locator('[data-testid="buffers-adjustments"]')).toBeVisible();
  await expect(page.locator('[data-testid="buffers-performance"]')).toBeVisible();
  expect(pageErrors).toEqual([]);
});
