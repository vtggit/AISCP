// Proving spec for AIERP issue #1481 — the record line inside the
// "Planned adjustments" section of the Buffers screen (#/buffers):
//
//   * The read: GET /api/ddmrp/adjustments/record, fetched through
//     app/js/api.js with the sections on activation and on Refresh,
//     under its own request-sequence guard (recordSeq). A usable
//     answer is an object whose "saved", "with_proposal", "taken",
//     "below" and "above" are all whole numbers of zero or more, of
//     the number type (a numeric string is not usable); a failed
//     read (any status or a network error) or any other body leaves
//     the line out, with no note and no loading placeholder — the
//     section renders exactly as before.
//   * The line ([data-testid="buffers-adjust-record"]): shown when
//     the section has its adjustments answer and the record answer
//     is usable, directly after the proposals block
//     ([data-testid="buffers-adjust-proposals"]) — or where the
//     block would be without it — and before the add form, reusing
//     the note class and set as text, never as markup: "Saved at
//     the proposal: <taken> of <with_proposal> adjustments saved
//     where a factor was proposed (<below> below it, <above> above
//     it)" (whole numbers with separators) for a with_proposal
//     above zero, or "No adjustment has been saved where a factor
//     was proposed yet." without.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route handler the way
// app/tests/issue1468.spec.js does — that spec's plan, zones,
// candidates, adjustments, performance and proposals answers — and
// /api/ddmrp/adjustments/record answers from a variable the test
// sets.
//
