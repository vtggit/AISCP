// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the development admin: issue1122's mocks plus
// the demand-basis answer and the reached route, whose requests are
// recorded in ctrl.reachedGets with their method and query string;
// the first answer is held (ctrl.reachedHeld) when holdReached is
// set, and every answer goes out at ctrl.reachedStatus with
// ctrl.reached (a non-200 status answering {"detail":
// "unavailable"}). `apiMethods` collects every /api request's method
// (the read-only proof) and `apiOrigins` the app origins the /api
// routes were seen on.
async function mockSettingsApi(page, options) {
  const config = options.config;
  const me = options.me;
  const entries = options.entries;
  const impact = options.impact;
  const curve = options.curve;
  const reached = options.reached !== undefined ? options.reached : REACHED_THREE;
  const reachedStatus = options.reachedStatus !== undefined ? options.reachedStatus : 200;
  const holdReached = options.holdReached === true;
  const apiMethods = options.apiMethods;
  const apiOrigins = options.apiOrigins;
  const ctrl = {
    settingsGets: 0,
    impactGets: 0,
    curveGets: 0,
    reachedGets: 0,
    reachedMethods: [],
    reachedQueries: [],
    reachedHeld: [],
    meRequests: [],
    current: entries,
    impact,
    curve,
    reached,
    reachedStatus,
    appOrigin: { value: null },
  };
  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (ctrl.appOrigin.value === null) {
      ctrl.appOrigin.value = url.origin;
    }
    apiOrigins.add(url.origin);
    apiMethods.push(request.method());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      ctrl.settingsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      ctrl.impactGets += 1;
      return route.fulfill({ status: ctrl.impact.status, json: ctrl.impact.body });
    }
    if (path === '/api/service-levels/curve' && request.method() === 'GET') {
      ctrl.curveGets += 1;
      return route.fulfill({ status: ctrl.curve.status, json: ctrl.curve.body });
    }
    if (path === '/api/service-levels/reached' && request.method() === 'GET') {
      ctrl.reachedGets += 1;
      ctrl.reachedMethods.push(request.method());
      ctrl.reachedQueries.push(url.search);
      // Held: the main pass releases its answer through the route it
      // kept, so the card can be read while the read is out.
      if (holdReached && ctrl.reachedHeld.length === 0) {
        ctrl.reachedHeld.push(route);
        return;
      }
      if (ctrl.reachedStatus !== 200) {
        return route.fulfill({ status: ctrl.reachedStatus, json: { detail: 'unavailable' } });
      }
      return route.fulfill({ status: 200, json: ctrl.reached });
    }
    if (path === '/api/forecast/accuracy/basis' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: BASIS_NONE });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };
  await page.route('**/api/**', handler);
  return ctrl;
}

