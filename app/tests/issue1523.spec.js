    await fresh.goto('/');
    await expect(fresh.locator('#signin-form')).toBeVisible();
    await fresh.fill('#token-input', 'dev-admin-token');
    await fresh.click('#signin-button');
    await expect(fresh.locator('#app')).toBeVisible();
    await fresh.click('.nav-btn[data-view="settings"]');
    await expect(fresh.locator('#view-settings')).toHaveClass(/is-active/);
    await expect.poll(() => freshCtrl.reachedGets).toBe(1);
