// Proving spec for AIERP issue #1523 — the "Service reached" block
// of the "Service levels and their cost" card on the Settings view
// (#/settings).
//
// Inside the card [data-testid="service-curve"], after its last
// class block and before its suggestion block (which stays the
// card's last child), and only while the card shows its classes,
// the block [data-testid="service-reached"] reads
// GET /api/service-levels/reached with no query, so the route's
// default window of 30 days applies: with its own state, its own
// request-sequence guard (an answer that arrives after a newer load
// has started is ignored) and its own re-render, the way the
// demand-basis card reads for its card — started with the
// activation beside the curve's read, reset() bumps its sequence and
// clears its state, and a re-render never starts it. Its heading
// (an h3) reads "Service reached."; with as_of null it holds only
// the heading and the none note
// ([data-testid="service-reached-none"]) "No daily on-hand snapshot
// yet." — and nothing else follows the heading. Otherwise, in
// order: the window line ([data-testid="service-reached-window"])
// "Days in stock over the last <days> days, from <snapshot_dates>
// daily on-hand snapshots up to <as_of>.", one line per class
// ([data-testid="service-reached-class"]) in the answer's order —
// with item_site_days above 0, "Class <abc_class> · level <level> ·
// in stock on <share> of <item_site_days> item-site days
// (<item_sites> item-sites)", with item_site_days 0, "Class
// <abc_class> · level <level> · no item-site with demand and a
// snapshot in the window" — the unclassified line
// ([data-testid="service-reached-unclassified"]) "<n> item-sites
// with demand have no ABC class and are not counted." only when
// unclassified_item_sites is above 0, and the note
// ([data-testid="service-reached-note"]) "Days in stock, not a fill
// rate: a sale lost while out of stock is not counted.". The level
// and the share go through formatPercent, a null level reads as an
// em dash, and a count of 1 reads in the singular: "1 daily
// on-hand snapshot", "1 item-site day", "(1 item-site)" and "1
// item-site with demand has no ABC class and is not counted.". The
// block is built from the elements and classes the card already
// styles, so no stylesheet changes. While the read is out, after a
// non-200 answer, after a network failure and after a 200 whose body
// is malformed, the block is absent and nothing says why — the
// classes and the suggestion block show as before.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered, the way
// app/tests/issue1122.spec.js does it: the development token card as
// an admin, at 1440x900 on #/settings, the same settings entries,
// impact and curve answers (the curve answers that spec's by-class
// payload) and the demand-basis answer — plus
// /api/service-levels/reached, whose requests the mock records with
// their query and whose answer the main pass holds until the test
// releases it, the sub-scenarios serving (fresh pages in the same
// context, each with its own mock and its own sign-in) the singular
// answer, the none answer, the failed and the malformed answers and
// the narrow width.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1523 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

