// Proving spec for AIERP issue #1529 — the "Push to ERP" screen
// (#/writeback) gains the writeback record: GET
// /api/parameter-writeback/record, no query, fetched through
// app/js/api.js beside the preview and the history — on activation
// and on the Refresh button ([data-testid="writeback-refresh"]), and
// again after a confirmed push. The preview's and the history's own
// Retry buttons do not start it. It keeps its own state and its own
// request-sequence guard, and reset() bumps the sequence and clears
// the state; a re-render never starts it. Whether the record read is
// out never changes the Refresh button's disabled state.
//
// The record block ([data-testid="writeback-record"], a div) sits
// directly after the bar (.wb-bar) and before the outstanding pane
// (.wb-outstanding). Each line is a p with the class wb-note, reorder
// points first, then buffers; a kind whose pushed is 0 has no line,
// and with no line at all the block is absent. With read above 0 a
// line reads "<kind> still as pushed in the ERP: <unchanged> of
// <read> read back (<pct>%)" with pct Math.round(100 * unchanged /
// read) worked out from the counts, never from the answer's rate
// field; with read 0 it reads "<kind> pushed: <pushed>; none read
// back by a sync yet", <kind> "Reorder points"
// ([data-testid="writeback-record-reorder-points"]) or "Buffer
// levels" ([data-testid="writeback-record-buffers"]). While the read
// is out, after a non-200 answer or a network failure, and after a
// 200 whose body is malformed (not an object holding the objects
// reorder_points and buffers, or either of them with pushed, read or
// unchanged not whole numbers of at least 0, unchanged above read,
// or read above pushed), the block is absent and nothing says why.
// The summary line, the outstanding table, pushing, the results and
// the history table keep their behaviour and texts.
//
// The gate serves the static app with no backend, so every /api/*
// call is answered by one page.route('**/api/**', handler). The pass
// runs as an ADMIN signed in through the development token card at
// 1440x900. TWO: at activation the record route answers
// reorder_points {pushed 5, read 4, unchanged 3, rate 0.75} and
// buffers {pushed 3, read 2, unchanged 1, rate 0.5}; the block's
// previous element sibling is the bar and its next one the
// outstanding pane, the two lines read exactly "Reorder points still
// as pushed in the ERP: 3 of 4 read back (75%)" and "Buffer levels
// still as pushed in the ERP: 1 of 2 read back (50%)" in that order,
// and the record route was requested exactly once, as GET
// /api/parameter-writeback/record with no query. NOT READ:
// reorder_points all 0, buffers {pushed 2, read 0, unchanged 0, rate
// null} — the block holds one line, "Buffer levels pushed: 2; none
// read back by a sync yet". FROM THE COUNTS: reorder_points
// {pushed 10, read 10, unchanged 1, rate 0.5}, buffers all 0 — the
// one line reads "Reorder points still as pushed in the ERP: 1 of 10
// read back (10%)", the 10% worked out from the counts, not the 0.5
