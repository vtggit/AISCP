// Mock every /api/* call the app makes (the same mocks and sign-in
// as the #628 proof). The handler records every request's method
// and path so the proof can check that every request is a GET.
async function mockIssue1560Api(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    expediteGets: 0,
    expediteAnswer: expeditePayloadBase,
    releasesGets: 0,
    releasesAnswer: releasesPayloadBase,
    meRequests: [],
    requests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.requests.push({ method: request.method(), path });
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/expedite') {
      ctrl.expediteGets += 1;
      return route.fulfill({ status: 200, json: ctrl.expediteAnswer() });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      return route.fulfill({ status: 200, json: ctrl.releasesAnswer() });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue1560 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in, 1440x900 --------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockIssue1560Api(page);

  const releasesTable = page.locator('[data-testid="releases-table"]');
  const releaseRows = page.locator('tr.rl-row');
  const lines = page.locator('[data-testid="releases-lines"]');

  await page.goto('/');

  // No releases request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.releasesGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // The Overview (the default view) fetches the releases answer for
  // its Released orders card.
  await expect.poll(() => ctrl.releasesGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // --- Releases: the expanded line table carries the badges ----------
  await page.click('.nav-btn[data-view="releases"]');
  await expect(page).toHaveURL(/#\/releases$/);
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(2);
  await expect(releasesTable).toBeVisible();
  await expect(releaseRows).toHaveCount(1);

  const requestsBeforeExpand = ctrl.requests.length;
  await releaseRows.nth(0).click();
  await expect(lines).toHaveCount(1);
  const lineRows = lines.locator('tbody tr');
  await expect(lineRows).toHaveCount(5);
  // Expanding is a client-side toggle: the screen sends no new
  // request.
  expect(ctrl.releasesGets).toBe(2);
  expect(ctrl.requests.length).toBe(requestsBeforeExpand);
  expect(pageErrors).toEqual([]);

  // Exactly two badges in the line table — one in L1's Item cell
  // and one in L2's ...
  await expect(lines.locator('[data-testid="releases-line-source"]')).toHaveCount(2);
  await expect(lineRows.nth(0).locator('td.rl-cell-line-item [data-testid="releases-line-source"]')).toHaveCount(1);
  await expect(lineRows.nth(1).locator('td.rl-cell-line-item [data-testid="releases-line-source"]')).toHaveCount(1);
  // ... each the last element of its cell, reading "Buffer" with the
  // class rl-line-source and the title.
  const badgeLastness = await page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-testid="releases-line-source"]')).map((badge) => {
      const cell = badge.closest('td.rl-cell-line-item');
      return cell !== null && cell.lastElementChild === badge;
    }),
  );
  expect(badgeLastness).toEqual([true, true]);
  const l1Badge = lineRows.nth(0).locator('[data-testid="releases-line-source"]');
  const l2Badge = lineRows.nth(1).locator('[data-testid="releases-line-source"]');
  for (const badge of [l1Badge, l2Badge]) {
    await expect(badge).toHaveText('Buffer');
    await expect(badge).toHaveClass('rl-line-source');
    await expect(badge).toHaveAttribute('title', "Ordered on its DDMRP buffer's order signal");
  }
  // L1's cell still shows its description above its code, as #628's
  // proof reads them, followed by the badge.
  const l1Item = lineRows.nth(0).locator('td.rl-cell-line-item');
  await expect(l1Item.locator('.rl-line-item-desc')).toHaveText('Recycled Shipping Carton 40x30x20');
  await expect(l1Item.locator('.rl-line-item-code')).toHaveText('CARTON4030');
  await expect(l1Item).toHaveText(/Recycled Shipping Carton 40x30x20\s*CARTON4030/);
  // L2's cell shows its code, then the badge.
  const l2Item = lineRows.nth(1).locator('td.rl-cell-line-item');
  await expect(l2Item).toHaveText(/GLASSBOTT\s*Buffer/);
  await expect(l2Item.locator('.rl-line-item-desc')).toHaveCount(0);
  await expect(l2Item.locator('.rl-line-item-code')).toHaveCount(0);
  // L3's, L4's and L5's Item cells have no badge, and they read
  // exactly as #628's proof reads a line's cell.
  await expect(lineRows.nth(2).locator('td.rl-cell-line-item [data-testid="releases-line-source"]')).toHaveCount(0);
  await expect(lineRows.nth(2).locator('td.rl-cell-line-item')).toHaveText('REORDER999');
  await expect(lineRows.nth(3).locator('td.rl-cell-line-item [data-testid="releases-line-source"]')).toHaveCount(0);
  await expect(lineRows.nth(3).locator('td.rl-cell-line-item')).toHaveText('NOSRC1234');
  await expect(lineRows.nth(4).locator('td.rl-cell-line-item [data-testid="releases-line-source"]')).toHaveCount(0);
  await expect(lineRows.nth(4).locator('td.rl-cell-line-item')).toHaveText('NULLSRC001');
  // Every request so far is a GET.
  expect(ctrl.requests.filter((entry) => entry.method !== 'GET')).toEqual([]);
  expect(pageErrors).toEqual([]);

  // --- 390x844: the page does not scroll sideways ---------------------
  // The order stays expanded, so the badge renders at the narrow
  // width.
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#view-releases')).toBeVisible();
  const narrow = await page.evaluate(() => document.documentElement.scrollWidth);
  expect(narrow).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ----------
  // The token arrives in the URL hash the way the identity
  // requirement describes; since the hash is no longer a token
  // delivery path the production boot completes through the PKCE
  // round-trip, so the IdP's auth and token endpoints carry the
  // viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const releasesGetsBeforeViewer = ctrl.releasesGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and the Overview (the default view) fetches the releases
  // answer for its Released orders card, nothing else for the screen.
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 1);

  // Activating the Releases view for the viewer: the screen still
  // renders, with the line table and its badges ...
  await page.click('.nav-btn[data-view="releases"]');
  expect(page.url()).toContain('#/releases');
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 2);
  await expect(releasesTable).toBeVisible();
  await expect(releaseRows).toHaveCount(1);
  await releaseRows.nth(0).click();
  await expect(lines).toHaveCount(1);
  await expect(lines.locator('tbody tr')).toHaveCount(5);
  await expect(lines.locator('[data-testid="releases-line-source"]')).toHaveCount(2);

  // ... and the admin-only control is absent: the standing grants'
  // create form does not render for the non-admin, while the
  // sections every signed-in user sees still render.
  await expect(page.locator('[data-testid="releases-grant-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="releases-transfers-show"]')).toBeVisible();
  await expect(page.locator('[data-testid="releases-grants-show"]')).toBeVisible();

  // Every request across both passes is a GET, and no page error.
  expect(ctrl.requests.filter((entry) => entry.method !== 'GET')).toEqual([]);
  expect(pageErrors).toEqual([]);
});
