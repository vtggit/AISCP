// Proving spec for AIERP issue #1560 — the buffer source badge on
// the Releases screen: a release line whose source is exactly the
// string "buffer" shows one small badge in its Item cell
// ([data-testid="releases-line-source"], class rl-line-source)
// reading "Buffer" with the title "Ordered on its DDMRP buffer's
// order signal", right after the item code; a line whose source is
// anything else — "reorder_point", "top_up", missing, null or
// another value — shows no such element, and its cell reads exactly
// as before. The badge is a client-side read of the line's source:
// the screen sends no new request.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as the
// item-description spec (issue #628): the planner signs in through
// the development token card at 1440x900, and the pass ends as a
// NON-ADMIN (role 'user') after a full reload: the token arrives in
// the URL hash as #access_token=..., /api/auth/config and
// /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, the Releases screen then
// renders for the viewer — line table and badges included — and the
// admin-only control (the standing grants' create form) is absent
// where the page still renders.
//
// Checked, in order:
//
//   * the releases answer has one order of five lines — L1 with an
//     item_description and source "buffer", L2 with no description
//     and source "buffer", L3 with source "reorder_point", L4 with
//     no source key at all and L5 with a null source;
//   * after expanding the order, the line table has exactly two
//     badges — one in L1's Item cell and one in L2's — each the last
//     element of its cell, with the text "Buffer", the class
//     rl-line-source and the title above;
//   * L1's cell still shows its description above its code, as
//     #628's proof reads them, and L2's cell shows its code and then
//     the badge; L3's, L4's and L5's Item cells have no badge and
//     read exactly as #628's proof reads a line's cell;
//   * the expansion sends no new request, and every request is a
//     GET;
//   * at 390x844 the document does not scroll sideways;
//   * there is no page error.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1560 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

