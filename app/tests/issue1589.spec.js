// Mock every /api/* call the app makes, the way
// app/tests/issue1529.spec.js does. The handler reads ctrl on every
// request, so the test can steer the preview and the record answers
// and hold the record answer (ctrl.recordHold, a promise the handler
// awaits before fulfilling). Every writeback request is counted
// (ctrl.previewGets, ctrl.historyGets, ctrl.recordGets) and every
// record request is recorded in ctrl.recordRequests with its method,
// path and query.
async function mockWritebackApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    previewAnswer: null,
    previewNext: null,
    historyAnswer: HISTORY_EMPTY,
    historyNext: null,
    recordAnswer: RECORD_EXCESS,
    recordNext: null,
    recordHold: null,
    confirmAnswer: null,
    confirmNext: null,
    previewGets: 0,
    historyGets: 0,
    recordGets: 0,
    confirmBodies: [],
    recordRequests: [],
  };

  const handler = async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/parameter-writeback/preview') {
      ctrl.previewGets += 1;
      if (ctrl.previewNext) {
        const next = ctrl.previewNext;
        ctrl.previewNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: ctrl.previewAnswer || previewPayloadBase() });
    }
    if (path === '/api/parameter-writeback/history') {
      ctrl.historyGets += 1;
      if (ctrl.historyNext) {
        const next = ctrl.historyNext;
        ctrl.historyNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: ctrl.historyAnswer || HISTORY_EMPTY });
    }
    if (path === '/api/parameter-writeback/record') {
      ctrl.recordGets += 1;
      ctrl.recordRequests.push({
        method: request.method(),
        path: url.pathname,
        search: url.search,
      });
      if (ctrl.recordHold) {
        await ctrl.recordHold;
      }
      if (ctrl.recordNext) {
        const next = ctrl.recordNext;
        ctrl.recordNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: ctrl.recordAnswer || RECORD_EXCESS });
    }
    if (path === '/api/parameter-writeback/confirm' && request.method() === 'POST') {
      let body = null;
      try {
        body = request.postDataJSON();
      } catch (error) {
        // An unparsable body: the recorded null is the failure's proof.
      }
      ctrl.confirmBodies.push(body);
      if (ctrl.confirmNext) {
        const next = ctrl.confirmNext;
        ctrl.confirmNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: ctrl.confirmAnswer || confirmPayloadBase() });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, handler };
}

test('issue1589 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl } = await mockWritebackApi(page);

  const record = page.locator('[data-testid="writeback-record"]');
  const recordLines = record.locator('p.wb-note');
  const rpLine = page.locator('[data-testid="writeback-record-reorder-points"]');
  const bufLine = page.locator('[data-testid="writeback-record-buffers"]');
  const excessLine = page.locator('[data-testid="writeback-record-excess"]');
  const summary = page.locator('[data-testid="writeback-summary"]');
  const table = page.locator('[data-testid="writeback-table"]');
  const rows = page.locator('[data-testid="writeback-table"] tbody tr');
  const sourceCells = page
    .locator('[data-testid="writeback-table"] tbody')
    .locator('.wb-cell-source');
  const refresh = page.locator('[data-testid="writeback-refresh"]');

  await page.goto('/');

  // No record request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.recordGets).toBe(0);

  // Sign in through the development token card as the admin.
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  // The writeback view is not active yet (the default view is): the
  // one record request so far is the Overview's — the default view's
  // Reorder points card read the record on sign-in.
  await expect.poll(() => ctrl.recordGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // Activate the Push to ERP view.
  await page.click('.nav-btn[data-view="writeback"]');
  await expect(page).toHaveURL(/#\/writeback$/);
  await expect(page.locator('#view-writeback')).toBeVisible();

  // Activation fetches the preview, the history and the record.
  await expect.poll(() => ctrl.previewGets).toBe(1);
  await expect.poll(() => ctrl.historyGets).toBe(1);
  await expect.poll(() => ctrl.recordGets).toBe(2);
  expect(pageErrors).toEqual([]);

  // --- ROWS: the Source cells and the summary -------------------------
  // The four rows in the answer's order: one "decision", one "ddmrp"
  // and two "excess" — the Source cells read the basis, and the
  // summary counts the buffer rows and the excess stops.
  await expect(rows).toHaveCount(4);
  expect(await sourceCells.allTextContents()).toEqual([
    'Decision',
    'DDMRP buffer',
    'Stop replenishing',
    'Stop replenishing',
  ]);
  await expect(summary).toHaveText(
    '4 outstanding · 4 ready to push · 1 from buffers · 2 to stop replenishing',
  );
  expect(pageErrors).toEqual([]);

  // --- EXCESS: the third line after the buffers line ------------------
  ctrl.recordAnswer = RECORD_EXCESS;
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(3);
  await expect(record).toBeVisible();
  await expect(recordLines).toHaveCount(3);
  await expect(recordLines.nth(0)).toHaveAttribute(
    'data-testid',
    'writeback-record-reorder-points',
  );
  await expect(recordLines.nth(1)).toHaveAttribute(
    'data-testid',
    'writeback-record-buffers',
  );
  await expect(recordLines.nth(2)).toHaveAttribute(
    'data-testid',
    'writeback-record-excess',
  );
  expect(await recordLines.allTextContents()).toEqual([
    'Reorder points still as pushed in the ERP: 3 of 4 read back (75%)',
    'Buffer levels still as pushed in the ERP: 1 of 2 read back (50%)',
    'Replenishment stops still as pushed in the ERP: 1 of 2 read back (50%)',
  ]);
  await expect(summary).toHaveText(
    '4 outstanding · 4 ready to push · 1 from buffers · 2 to stop replenishing',
  );
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(4);
  expect(pageErrors).toEqual([]);

  // --- EXCESS NOT READ: pushed, no sync read them back yet ------------
  ctrl.recordAnswer = RECORD_EXCESS_NOT_READ;
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(4);
  await expect(record).toBeVisible();
  await expect(recordLines).toHaveCount(3);
  await expect(rpLine).toHaveText('Reorder points still as pushed in the ERP: 3 of 4 read back (75%)');
  await expect(bufLine).toHaveText('Buffer levels still as pushed in the ERP: 1 of 2 read back (50%)');
  await expect(excessLine).toHaveText('Replenishment stops pushed: 2; none read back by a sync yet');
  expect(pageErrors).toEqual([]);

  // --- EXCESS NONE: never pushed — no excess line ----------------------
  ctrl.recordAnswer = RECORD_EXCESS_NONE;
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(5);
  await expect(record).toBeVisible();
  await expect(recordLines).toHaveCount(2);
  await expect(excessLine).toHaveCount(0);
  expect(await recordLines.allTextContents()).toEqual([
    'Reorder points still as pushed in the ERP: 3 of 4 read back (75%)',
    'Buffer levels still as pushed in the ERP: 1 of 2 read back (50%)',
  ]);
  expect(pageErrors).toEqual([]);

  // --- NO EXCESS: the answer without the key — the two lines as before
  ctrl.recordAnswer = RECORD_NO_EXCESS;
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(6);
  await expect(record).toBeVisible();
  await expect(recordLines).toHaveCount(2);
  await expect(excessLine).toHaveCount(0);
  expect(await recordLines.allTextContents()).toEqual([
    'Reorder points still as pushed in the ERP: 3 of 4 read back (75%)',
    'Buffer levels still as pushed in the ERP: 1 of 2 read back (50%)',
  ]);
  expect(pageErrors).toEqual([]);

  // --- MALFORMED: the excess's read above its pushed — no block -------
  ctrl.recordAnswer = RECORD_EXCESS_MALFORMED;
  await refresh.click();
  await expect.poll(() => ctrl.recordGets).toBe(7);
  await expect(record).toHaveCount(0);
  await expect(excessLine).toHaveCount(0);
  await expect(summary).toHaveText(
    '4 outstanding · 4 ready to push · 1 from buffers · 2 to stop replenishing',
  );
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(4);
  expect(pageErrors).toEqual([]);

  // --- NO EXCESS ROW: the summary has no stop part --------------------
  // The Refresh button re-fetches the preview beside the record, so
  // this read is the seventh: the activation's one plus the six
  // Refresh presses of the record scenarios above.
  ctrl.previewAnswer = previewNoExcess();
  await refresh.click();
  await expect.poll(() => ctrl.previewGets).toBe(7);
  await expect(rows).toHaveCount(2);
  expect(await sourceCells.allTextContents()).toEqual([
    'Decision',
    'DDMRP buffer',
  ]);
  await expect(summary).toHaveText(
    '2 outstanding · 2 ready to push · 1 from buffers',
  );
  expect(pageErrors).toEqual([]);
});
