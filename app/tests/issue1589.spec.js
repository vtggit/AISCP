// Proving spec for AIERP issue #1589 — the "Push to ERP" screen
// (#/writeback) shows the excess stops: a row whose basis is
// "excess" reads "Stop replenishing" in its Source cell ("Decision"
// for a "decision" basis, "DDMRP buffer" for a "ddmrp" basis, an em
// dash without one or for anything else — unchanged), the summary
// line ([data-testid="writeback-summary"]) gains " · <n> to stop
// replenishing" after " · <n> from buffers" whenever any row's basis
// is "excess" (n the number of such rows) and nothing otherwise, and
// the writeback record block ([data-testid="writeback-record"])
// gains a third line after the buffers line: a p with the class
// wb-note and [data-testid="writeback-record-excess"], labelled
// "Replenishment stops", built like the other lines — with read
// above 0 "Replenishment stops still as pushed in the ERP:
// <unchanged> of <read> read back (<pct>%)", with read 0
// "Replenishment stops pushed: <pushed>; none read back by a sync
// yet", with pushed 0 no line. An answer without an excess shows
// the other lines as now, and an excess that fails the count checks
// the other kinds pass makes the body malformed and the block
// absent. The rows' order, the selection, pushing and the results
// are unchanged.
//
// The gate serves the static app with no backend, so every /api/*
// call is answered by one page.route('**/api/**', handler) — the
// mocks and the development-token sign-in of
// app/tests/issue1529.spec.js, reused as they are. The pass runs as
// an ADMIN signed in through the development token card at 1440x900.
//
// ROWS: the preview has one "decision" row, one "ddmrp" row and two
// "excess" rows in the answer's order, count 4, writable_count 4 —
// the Source cells read "Decision", "DDMRP buffer", "Stop
// replenishing" and "Stop replenishing", and the summary reads "4
// outstanding · 4 ready to push · 1 from buffers · 2 to stop
// replenishing". With a preview without an excess row (one
// "decision", one "ddmrp") the summary reads "2 outstanding · 2
// ready to push · 1 from buffers" — no stop part.
//
// RECORD: excess {pushed 3, read 2, unchanged 1} beside the two
// kinds read back part way adds the third line after the buffers
// line, "Replenishment stops still as pushed in the ERP: 1 of 2
// read back (50%)"; excess {pushed 2, read 0, unchanged 0} reads
// "Replenishment stops pushed: 2; none read back by a sync yet";
// excess {pushed 0, read 0, unchanged 0} gives no excess line; an
// answer without an excess shows the two lines as before; excess
// {pushed 1, read 2, unchanged 0} — read above pushed — leaves the
// block absent, the summary line and the outstanding table showing.
// No page error at any point.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1589 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


