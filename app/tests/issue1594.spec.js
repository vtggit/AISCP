// Proving spec for AIERP issue #1594 — the "Order plan" screen
// (#/orders): a confirm always shows its answer.
//
// The rule holds from the click on a block's "Confirm release"
// button ([data-testid="orders-release-confirm"]) until that confirm
// request answers, with success or with failure: held still. While it
// is out the door the horizon select ([data-testid="orders-horizon"]),
// the Refresh button ([data-testid="orders-refresh"]) and every
// top-up checkbox ([data-testid="orders-top-up-choose"]) of that
// block's are disabled, and their change and click handlers do
// nothing. The other blocks' top-up checkboxes stay enabled, and a
// tick in one never touches the block that is confirming. When the
// confirm answers, its block shows the outcome
// ([data-testid="orders-release-outcome"]) or the error
// ([data-testid="orders-release-error"]) exactly as before, and the
// controls are enabled again.
//
// The block's existing busy flag also covers the preview, so the
// confirm carries its own marker: a preview in flight disables none
// of the horizon select, the Refresh or the block's top-up
// checkboxes, and a preview's answer is still discarded when the
// planner unticks a top-up while it is out the door — the panel goes
// with the tick, and the answer that lands finds no state to render
// into. The Release, Confirm and Cancel buttons' own busy behaviour
// is unchanged: disabled while their block's request is out, so a
// double click sends one request.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with one page.route('**/api/**', handler), the
// handler defined before it is registered with page.route, the way
// app/tests/issue1237.spec.js does it. The mocked supply-plan answer
// (horizon 7) has two acumatica blocks: S-A ("Alpha Supply") with
// total "1800.00", minimum "2500.00" and shortfall "700.00", one
// line, and S-B ("Beta Supply") with total "1200.00", minimum
// "1500.00" and shortfall "300.00", one line. The mocked top-ups
// answer has lookahead_days 30 and gives S-A two top-ups — T1 at 159
// (value "450.00") and T2 at 160 (value "300.00") — and S-B one: T3
// at 161 (value "300.00"). The mocked release answer keeps T1 among
// its group's lines (site 159, two lines, "2250.00") and lists T2 in
// unreleasable with the reason "not a suggested top-up"; its confirm
// lands the "created" outcome "PO-8801". The mock's release branch
// can hold the answer back on a promise (ctrl.releaseHold) and
// answer a held confirm with status 500 (ctrl.releaseStatus), read
// when the request arrives.
//
// The ADMIN pass signs in through the development token card at
// 1440x900, the way issue1237 signs in, and walks the one block S-A
// through a held confirm that answers with success — while it is
// held, the horizon select, the Refresh and both of S-A's top-up
// checkboxes are disabled, S-B's checkbox is enabled, and ticking
// S-B's leaves S-A's panel shown with no new request; once it
// answers, the block shows "Draft PO PO-8801 created on hold", the
// controls are enabled again, and exactly one confirm request went
// out — and a held confirm that answers with 500, which shows
// "The release could not be completed." in
// [data-testid="orders-release-error"], enables the same controls
// again, and is likewise one confirm request. A preview is as
// before: held out the door, it disables none of the horizon select,
// the Refresh or the block's top-up checkboxes (only its own Release
// button is busy), and unticking a top-up while it is held closes
// the block's release — the panel the answer would have opened never
// appears when it lands. The admin pass sends no request but GETs
// and the five release POSTs (three previews, two confirms).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1594 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

