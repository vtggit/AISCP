// A recorded decision for the log. The hostile code may travel in
// item_code and must render as plain text.
function decisionRow(kind, itemCode, index) {
  const decision = index % 3 === 0 ? 'accepted' : index % 3 === 1 ? 'dismissed' : 'snoozed';
  return {
    id: 'dec-' + kind + '-' + index,
    item_code: itemCode,
    site_code: 'WHOLESALE',
    decision: decision,
    action: null,
    reason: decision === 'dismissed' ? 'cut list reason ' + index : null,
    snooze_until: decision === 'snoozed' ? '2026-12-01' : null,
    as_of: '2026-10-01',
    money_at_stake: index,
    money_tied_up: index,
    money_at_risk: index,
    decided_by: 'planner1',
    decided_at: new Date(Date.UTC(2026, 9, 1) + index * 1000 + (kind === 'stockout' ? 1000000 : 0)).toISOString(),
  };
}

function makeDecisions(kind, count) {
  const rows = [];
  for (let i = 0; i < count; i += 1) {
    rows.push(decisionRow(kind, 'DEC-' + kind.toUpperCase() + '-' + String(i).padStart(4, '0'), i));
  }
  return rows;
}

// Mock every /api/* call the shell, the queue and the log make, the
// way issue1534 mocks the queue and issue263 mocks the log. The three
// list answers and the three decision answers come from the mutable
// ctrl scenario state, so the pass can steer the row counts and
// re-load the views; every request's method, path and query land in
// ctrl.requests / ctrl.listGets / ctrl.decisionLimitGets, and the
// handler reads ctrl on every request, so the pass can also switch
// the sign-in (ctrl.phase) from the admin planner to the non-admin
// viewer.
async function mockApi(page) {
  const ctrl = {
    phase: 'admin', // 'admin' | 'viewer'
    driftRows: [],
    excessRows: [],
    stockoutRows: [],
    driftDecisions: [],
    excessDecisions: [],
    stockoutDecisions: [],
    meRequests: [],
    listGets: [], // { kind, query } of the three list reads
    decisionLimitGets: [], // { kind, query } of the log's decision reads
    requests: [], // every { method, path }
    appOrigin: null,
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (ctrl.appOrigin === null) {
      ctrl.appOrigin = url.origin;
    }
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.phase === 'viewer' ? PROD_CONFIG : DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.phase === 'viewer' ? VIEWER_ME : ADMIN_ME });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/erp-sources') {
      return route.fulfill({ status: 200, json: { sources: [], item_sites: [] } });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({
        status: 200,
        json: { synced_at: null, oldest_synced_at: null, data_through: null },
      });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.split('/')[2];
      ctrl.listGets.push({ kind, query: url.search });
      return route.fulfill({ status: 200, json: ctrl[kind + 'Rows'] });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      if (request.method() !== 'GET') {
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      const kind = decisions[1];
      const params = new URLSearchParams(url.search);
      if (params.has('item_code')) {
        // The queue's decision-history read for the selected row.
        return route.fulfill({ status: 200, json: [] });
      }
      ctrl.decisionLimitGets.push({ kind, query: url.search });
      return route.fulfill({ status: 200, json: ctrl[kind + 'Decisions'] });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 200, json: {} });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });

  // The IdP's PKCE endpoints, used by the production-boot viewer pass.
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const stateParam = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      ctrl.appOrigin + '/?code=fake-pkce-code&state=' + encodeURIComponent(stateParam);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  return ctrl;
}

// Re-visit #/log the SPA way: leave the view, then come back. Every
// switch into #/log re-activates the log, which re-fetches the three
// decision lists from the (steered) mocks. A page.goto to the same
// #/log hash would be a same-document no-op — no hashchange, no
// re-fetch — so the steered data would never land.
async function revisitLog(page) {
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await page.evaluate(() => {
    window.location.hash = '#/log';
  });
  await expect(page.locator('#view-log')).toBeVisible();
}

