// Proving spec for AIERP issue #1600 — the "the list is cut" lines of
// the Work queue and the Decision log.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route the way app/tests/issue1534.spec.js mocks
// the queue and app/tests/issue263.spec.js mocks the log: the pass
// signs in through the development token card on 1440x900 as the admin
// planner1, and it ends as a NON-ADMIN (role 'user') after a full
// reload the production way — the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, and the IdP's auth and token endpoints carry the PKCE
// round-trip — asserting the admin-only decision controls are absent
// while the queue still renders.
//
// Proves, in order:
//   * QUEUE, FULL — with the excess answer holding exactly 1,000 rows
//     and the drift and stockout answers holding 3 rows each: on the
//     excess tab, [data-testid="queue-list-cut"] is shown once,
//     directly before the list pane's .q-list-body inside
//     section.q-list, with the exact text "Showing the first 1,000
//     rows of this list. There may be more."; on the drift tab and on
//     the stockout tab it is absent;
//   * QUEUE, FILTERS — on the excess tab, after choosing the "All"
//     decision filter chip (other than the current "To decide"), the
//     line is still shown: it describes what was loaded, not what the
//     chips or the ERP filter show;
//   * QUEUE, NOT FULL — with the excess answer holding 999 rows (the
//     lists are re-loaded on a full reload, and the line is decided
//     again from the new answers), no [data-testid="queue-list-cut"]
//     is on the page on any tab;
//   * LOG, FULL — with the drift and stockout decision answers
//     holding exactly 1,000 entries each and the excess answer 2
//     entries, [data-testid="log-cut"] is shown once, directly before
//     the card's .log-scroll, with the exact text "Showing the first
//     1,000 decisions of: Reorder point, Stockout risk. There may be
//     more.", and the merged table still holds all 2,002 rows;
//   * LOG, NOT FULL — with every decision answer under 1,000
//     entries, no [data-testid="log-cut"] is on the page;
//   * ESCAPING — a queue row and a log row whose item_code is
//     <img src=x onerror=window.__pwned=1> render as plain text and
//     window.__pwned stays undefined;
//   * UNCHANGED — the three list reads still go out as
//     /api/drift?limit=1000&include_decided=true and the matching
//     excess and stockout reads with include_remedy=true, the three
//     decision reads still as /api/<kind>/decisions?limit=1000, the
//     tab counts still read 3 / 1000 / 3, every loaded row still
//     renders in its order, and every request the run sends is a GET.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1600 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
