// Proving spec for AIERP issue #1620 — the one shared HTML escaper.
//
// The fifteen views in app/js used to each carry their own copy of
// the same HTML escaper. Issue #1620 pulls that logic into one place:
//
//   * app/js/shared.js defines the escaper once and exposes it as
//     window.Shared.esc: it turns any value into a string with
//     String(value) and replaces &, <, >, " and ' with &amp;, &lt;,
//     &gt;, &quot; and &#39; — exactly what every copy did.
//   * app/index.html loads js/shared.js immediately after js/api.js
//     and before every view script, so the escaper exists before any
//     view binds it.
//   * None of the fifteen views defines its own esc any more: each
//     binds its local esc to window.Shared.esc, and it still calls
//     esc everywhere it did before — a hostile API value still
//     reaches the page as text, never as HTML.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route the way app/tests/issue1600.spec.js
// mocks the queue and the log: the pass signs in through the
// development token card on 1440x900 as the admin planner1.
//
// Proves, in order:
//   * LOAD ORDER — app/index.html carries a js/shared.js script
//     immediately after js/api.js and before every one of the
//     fifteen view scripts and before js/app.js, and
//     window.Shared.esc is a function on load;
//   * EXACT BEHAVIOR — Shared.esc turns the number 7, null and
//     undefined into '7', 'null' and 'undefined' through
//     String(value), and it maps & to &amp;, < to &lt;, > to &gt;,
//     " to &quot; and ' to &#39; — one character at a time and in
//     one combined hostile string (& is replaced first, so an
//     existing &lt; becomes &amp;lt;);
//   * ONE DEFINITION — fetched over the network: none of the
//     fifteen view files defines its own esc any more, each binds
//     esc to window.Shared.esc, and the five-entity replace chain
//     lives in js/shared.js, in no view;
//   * ESCAPING, QUEUE — a drift row whose item_code is
//     <img src=x onerror=window.__pwned=1> renders as plain text in
//     the list row and the detail title, and the payload never runs
//     and never becomes an element;
//   * ESCAPING, LOG — a decision whose item_code is the same payload
//     renders as plain text in the Decision log's item-site link;
//   * NO PAGE ERRORS — no uncaught error anywhere in the pass, and
//     every request the run sends is a GET.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue1620 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

