// Mock every /api/* call the shell, the queue and the log make, the
// way issue1600 mocks them: the three list answers and the three
// decision answers come from the mutable ctrl state, so the pass can
// steer the rows; every request lands in ctrl.requests.
async function mockApi(page) {
  const ctrl = {
    driftRows: [],
    excessRows: [],
    stockoutRows: [],
    driftDecisions: [],
    excessDecisions: [],
    stockoutDecisions: [],
    requests: [],
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    ctrl.requests.push({ method: request.method(), path: url.pathname });
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/erp-sources') {
      return route.fulfill({ status: 200, json: { sources: [], item_sites: [] } });
    }
    if (path === '/api/feed/status') {
      return route.fulfill({
        status: 200,
        json: { synced_at: null, oldest_synced_at: null, data_through: null },
      });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.split('/')[2];
      return route.fulfill({ status: 200, json: ctrl[kind + 'Rows'] });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      const params = new URLSearchParams(url.search);
      if (params.has('item_code')) {
        // The queue's decision-history read for the selected row.
        return route.fulfill({ status: 200, json: [] });
      }
      const kind = decisions[1];
      return route.fulfill({ status: 200, json: ctrl[kind + 'Decisions'] });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 200, json: {} });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return ctrl;
}

test('issue1620 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  page.setViewportSize({ width: 1440, height: 900 });

  const ctrl = await mockApi(page);
  // One hostile item_code per view: the drift row and the log
  // decision the pass will read.
  ctrl.driftRows = [driftRow(XSS, 1), driftRow('DR-002', 2), driftRow('DR-003', 3)];
  ctrl.excessRows = [excessRow(0), excessRow(1), excessRow(2)];
  ctrl.stockoutRows = [stockoutRow('SO-001'), stockoutRow('SO-002'), stockoutRow('SO-003')];
  ctrl.driftDecisions = [decisionRow('drift', XSS, 0)];
  ctrl.excessDecisions = [];
  ctrl.stockoutDecisions = [];

  /* ------------------------ shared.js: load order ---------------------- */
  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();

  // js/shared.js is in the document, sits immediately after
  // js/api.js, and comes before every view script and js/app.js.
  const scriptSrcs = await page.evaluate(() =>
    Array.from(document.querySelectorAll('script[src]')).map((el) => el.getAttribute('src'))
  );
  const apiIndex = scriptSrcs.indexOf('js/api.js');
  const sharedIndex = scriptSrcs.indexOf('js/shared.js');
  expect(apiIndex, 'js/api.js must load').toBeGreaterThanOrEqual(0);
  expect(sharedIndex, 'js/shared.js must load').toBe(apiIndex + 1);
  for (const view of VIEWS) {
    const viewIndex = scriptSrcs.indexOf(view);
    expect(viewIndex, view + ' must load').toBeGreaterThanOrEqual(0);
    expect(sharedIndex, view + ' must load after js/shared.js').toBeLessThan(viewIndex);
  }
  expect(
    sharedIndex,
    'js/app.js must load after js/shared.js'
  ).toBeLessThan(scriptSrcs.indexOf('js/app.js'));

  // The escaper is live on load: window.Shared.esc is a function.
  expect(await page.evaluate(() => typeof window.Shared)).toBe('object');
  expect(await page.evaluate(() => typeof window.Shared.esc)).toBe('function');

  /* ----------------------- exact escaper behavior ---------------------- */
  // String(value) for non-strings, and the five entity replacements:
  // one character at a time, and in one combined hostile string.
  const behavior = await page.evaluate(() => ({
    number: window.Shared.esc(7),
    nullValue: window.Shared.esc(null),
    undefinedValue: window.Shared.esc(undefined),
    ampersand: window.Shared.esc('a&b'),
    lt: window.Shared.esc('<b>'),
    gt: window.Shared.esc('c>d'),
    quote: window.Shared.esc('"q"'),
    apostrophe: window.Shared.esc("'s'"),
    combined: window.Shared.esc('<a href="x" onclick=\'y\'>t&b</a>'),
    alreadyEscaped: window.Shared.esc('&lt;'),
  }));
  expect(behavior.number).toBe('7');
  expect(behavior.nullValue).toBe('null');
  expect(behavior.undefinedValue).toBe('undefined');
  expect(behavior.ampersand).toBe('a&amp;b');
  expect(behavior.lt).toBe('&lt;b&gt;');
  expect(behavior.gt).toBe('c&gt;d');
  expect(behavior.quote).toBe('&quot;q&quot;');
  expect(behavior.apostrophe).toBe('&#39;s&#39;');
  expect(behavior.combined).toBe(
    '&lt;a href=&quot;x&quot; onclick=&#39;y&#39;&gt;t&amp;b&lt;/a&gt;'
  );
  // & is replaced first: an existing &lt; becomes &amp;lt;.
  expect(behavior.alreadyEscaped).toBe('&amp;lt;');

  /* --------------------- one definition, fifteen bindings -------------- */
  // The sixteen scripts over the network: the five-entity chain lives
  // in js/shared.js and in no view, no view defines its own esc any
  // more, and every view binds esc to window.Shared.esc.
  const sources = await page.evaluate(async (viewNames) => {
    const read = async (name) => (await fetch(name)).text();
    const shared = await read('js/shared.js');
    const views = {};
    for (const name of viewNames) {
      views[name] = await read(name);
    }
    return { shared, views };
  }, VIEWS);
  for (const pattern of ENTITY_PATTERNS) {
    expect(sources.shared, 'js/shared.js must define the escaper').toMatch(pattern);
  }
  for (const view of VIEWS) {
    const source = sources.views[view];
    expect(source.match(OWN_ESC_DEFINITION) || [], view + ' must not define its own esc any more').toEqual([]);
    expect(source, view + ' must bind esc to window.Shared.esc').toMatch(/window\.Shared\.esc/);
    for (const pattern of ENTITY_PATTERNS) {
      expect(source.match(pattern) || [], view + ' must not carry the escaper chain').toEqual([]);
    }
  }

  /* -------------------------- queue: hostile text ---------------------- */
  await page.fill('#token-input', 'issue1620-dev-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-queue')).toBeVisible();
  await expect(page.locator('#view-queue .q-row').first()).toBeVisible();
  expect(pageErrors).toEqual([]);

  // The first drift row's item_code is the hostile payload: it
  // renders as plain text in the list row and the detail title, and
  // the payload never runs and never becomes an element.
  const xssRow = page.locator('#view-queue .q-row').first();
  await expect(xssRow).toContainText(XSS);
  expect(await xssRow.locator('.q-item-site').evaluate((el) => el.innerHTML)).toContain(
    XSS_ESCAPED
  );
  await expect(page.locator('#view-queue .q-detail-title')).toHaveText(XSS);
  expect(await page.locator('#view-queue img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  /* --------------------------- log: hostile text ------------------------ */
  // The switch to the Decision log re-activates the log, which
  // re-fetches the three decision lists from the (steered) mocks.
  await page.evaluate(() => {
    window.location.hash = '#/log';
  });
  await expect(page.locator('#view-log')).toBeVisible();
  const logLink = page.locator('#view-log .log-item-link').first();
  await expect(logLink).toContainText(XSS);
  expect(await logLink.evaluate((el) => el.innerHTML)).toContain(XSS_ESCAPED);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  expect(pageErrors).toEqual([]);

  // The run only reads: every request is a GET.
  expect(ctrl.requests.length).toBeGreaterThan(0);
  expect(ctrl.requests.every((request) => request.method === 'GET')).toBe(true);
});
