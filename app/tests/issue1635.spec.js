// A one-item-site answer: the summary carries the dollar figures under
// test, the row keeps the table and the totals consistent. A pipeline
// figure of undefined keeps the key out of the answer.
function buildAnswer(dollarImpact, pipelineDollarImpact) {
  const summary = {
    item_sites: 1,
    reorder_point_units_delta_total: 15,
    safety_stock_units_delta_total: 8,
    reorder_point_up: 1,
    reorder_point_down: 0,
    reorder_point_unchanged: 0,
    dollar_impact: dollarImpact,
    item_sites_without_unit_cost: 0,
    levers: { service_level: 0.98, demand_multiplier: 1.2, lead_time_multiplier: null },
  };
  if (pipelineDollarImpact !== undefined) {
    summary.pipeline_dollar_impact = pipelineDollarImpact;
  }
  return {
    summary,
    item_sites: [
      {
        item_code: 'I001',
        site_code: 'S1',
        baseline: {
          reorder_point: 499.6,
          reorder_point_units: 500,
          safety_stock: 89.6,
          safety_stock_units: 90,
        },
        scenario: {
          reorder_point: 514.6,
          reorder_point_units: 515,
          safety_stock: 97.6,
          safety_stock_units: 98,
        },
        reorder_point_units_delta: 15,
        safety_stock_units_delta: 8,
      },
    ],
  };
}

// The mocked API, the way app/tests/issue430.spec.js mocks it: every
// POST /api/scenarios/simulate is held — pushed onto ctrl.runs with
// its route — and the test answers it, in the order it chooses.
async function mockScenarioApi(page, ctrl) {
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (url.pathname === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (url.pathname === '/api/scenarios/simulate' && request.method() === 'POST') {
      ctrl.runs.push({ body: request.postDataJSON(), route });
      return; // held: the test answers it, in the order it chooses
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

async function signIn(page) {
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
}

// The uncaught exceptions of the page so far.
function collectPageErrors(page) {
  const errors = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  return errors;
}

// The summary's stats in render order: the label, the value element's
// test id and the value. The callback reads only the DOM.
function readStats(page) {
  return page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-testid="scenario-summary"] .sc-stat')).map(
      (stat) => {
        const label = stat.querySelector('.sc-stat-label');
        const value = stat.querySelector('.sc-stat-value');
        return {
          label: label ? label.textContent.trim() : null,
          valueTestId: value ? value.getAttribute('data-testid') : null,
          value: value ? value.textContent.trim() : null,
        };
      },
    ),
  );
}

// Every element whose whole text reads "Dollar impact" — the old
// label, wherever it might still live. The callback reads only the DOM.
function readDollarImpactLabels(page) {
  return page.evaluate(() =>
    Array.from(document.querySelectorAll('body *'))
      .filter((el) => (el.textContent || '').trim() === 'Dollar impact')
      .map((el) => el.tagName.toLowerCase() + '.' + (el.getAttribute('class') || '')),
  );
}

test('issue1635 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    runs: [],
    meRequests: [],
  };
  await mockScenarioApi(page, ctrl);
  const pageErrors = collectPageErrors(page);

  await page.goto('/');
  await signIn(page);
  await page.click('.nav-btn[data-view="scenario"]');
  await expect(page.locator('#view-scenario')).toHaveClass(/is-active/);
  await expect(page.locator('[data-testid="scenario-levers"]')).toBeVisible();

  // One run: the levers, the held request, the answer.
  async function runScenario(answer) {
    await page.fill('[data-testid="scenario-service-level"]', '98');
    await page.fill('[data-testid="scenario-demand-change"]', '20');
    await page.fill('[data-testid="scenario-lead-time-change"]', '0');
    const before = ctrl.runs.length;
    await page.click('[data-testid="scenario-run"]');
    await expect.poll(() => ctrl.runs.length).toBe(before + 1);
    expect(ctrl.runs[before].body).toEqual({
      service_level: 0.98,
      demand_multiplier: 1.2,
      lead_time_multiplier: null,
    });
    ctrl.runs[before].route.fulfill({ status: 200, json: answer });
    // The skeleton is up while the answer is out the door and is
    // replaced by the fresh summary: wait for that render.
    await expect(page.locator('[data-testid="scenario-skeleton"]')).toHaveCount(0);
    await expect(page.locator('[data-testid="scenario-summary"]')).toBeVisible();
  }

  // --- dollar_impact 3, pipeline_dollar_impact 10 ----------------------
  await runScenario(buildAnswer(3, 10));
  await expect(page.locator('[data-testid="scenario-dollar-impact"]')).toHaveText('$3.00');
  await expect(page.locator('[data-testid="scenario-pipeline-impact"]')).toHaveText('$10.00');
  // The first two stats, in order: the renamed stat and the new one.
  expect((await readStats(page)).slice(0, 2)).toEqual([
    { label: 'Safety-stock investment', valueTestId: 'scenario-dollar-impact', value: '$3.00' },
    { label: 'Pipeline (on order)', valueTestId: 'scenario-pipeline-impact', value: '$10.00' },
  ]);
  expect(await readDollarImpactLabels(page)).toEqual([]);

  // --- dollar_impact -84210.55, pipeline_dollar_impact -1500 -----------
  await runScenario(buildAnswer(-84210.55, -1500));
  await expect(page.locator('[data-testid="scenario-dollar-impact"]')).toHaveText('-$84,210.55');
  await expect(page.locator('[data-testid="scenario-pipeline-impact"]')).toHaveText('-$1,500.00');
  expect((await readStats(page)).slice(0, 2)).toEqual([
    { label: 'Safety-stock investment', valueTestId: 'scenario-dollar-impact', value: '-$84,210.55' },
    { label: 'Pipeline (on order)', valueTestId: 'scenario-pipeline-impact', value: '-$1,500.00' },
  ]);
  expect(await readDollarImpactLabels(page)).toEqual([]);

  // --- no pipeline_dollar_impact in the answer --------------------------
  await runScenario(buildAnswer(-84210.55, undefined));
  await expect(page.locator('[data-testid="scenario-pipeline-impact"]')).toHaveText('\u2014');
  // ... and the safety-stock value still shows.
  await expect(page.locator('[data-testid="scenario-dollar-impact"]')).toHaveText('-$84,210.55');
  expect((await readStats(page)).slice(0, 2)).toEqual([
    { label: 'Safety-stock investment', valueTestId: 'scenario-dollar-impact', value: '-$84,210.55' },
    { label: 'Pipeline (on order)', valueTestId: 'scenario-pipeline-impact', value: '\u2014' },
  ]);
  expect(await readDollarImpactLabels(page)).toEqual([]);

  expect(pageErrors).toEqual([]);
});
