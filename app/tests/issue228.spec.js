// Proving spec for AIERP issue #228 — the planner-screen shell and sign-in.
//
// The gate serves the static app with no backend, so every /api/* call is
// mocked with page.route. Proves:
//   * development mode: sign-in card, bearer token on /api/auth/me, shell
//     with the user's name in the sidebar;
//   * navigation: view switch without a page load, #/queue in the URL hash,
//     aria-current moves, and a reload keeps Work queue;
//   * no page scroll at 1440x900 (document height equals the viewport);
//   * narrow layout: at 390x844 the sidebar sits above the main area;
//   * a 401 from /api/auth/me returns to the sign-in card;
//   * production mode: redirect to the IdP auth endpoint with PKCE.
// It also re-proves the review defects: the body's default margin must not
// make the 1440x900 document scrollable and must not push the sign-in card
// out of the viewport (the body margin is zero on every screen).
// The "(viewer)" pass boots the production way — no session and no
// fragment token: the PKCE round-trip against the mocked IdP endpoints
// (auth navigation captured, token exchange at the issuer URL from
// config.issuer) establishes the session — as a NON-ADMIN and asserts
// the admin-only control is absent while the page still renders.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue228 freeform"): the merge gate builds its junit nodeids from the
// Playwright test title, and a describe() block would join the titles with
// a "›" the contract nodeid does not carry, so the proof would read as
// "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


// The freeform pass runs many sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const PROD_CONFIG = {
  authEnabled: true,
  authMode: 'production',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

const VIEWER_ME = {
  authenticated: true,
  user: { sub: 'v1', username: 'viewer1', roles: ['user'], groups: [] },
};

// Mock every /api/* call; records the /api/auth/me requests so the spec can
// inspect the Authorization header.
async function mockApi(page, { config = DEV_CONFIG, me = ADMIN_ME, meStatus = 200 } = {}) {
  const meRequests = [];
  const appOrigin = { value: null };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      return route.fulfill({
        status: meStatus,
        json: meStatus === 200 ? me : { detail: 'Not authenticated' },
      });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests, appOrigin };
}

// Escape a string for use inside a RegExp (the IdP endpoint patterns are
// built from config.issuer, which is data, not a literal).
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

test('issue228 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const { meRequests, appOrigin } = await mockApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
  });

  // --- development mode: the sign-in card shows ---------------------
  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await expect(page.locator('label[for="token-input"]')).toHaveText('Token');
  await expect(page.locator('#app')).toBeHidden();

  // --- review defect: the body margin overflowed the sign-in screen -
  // The browser's default body margin would push the 100vh sign-in screen
  // (and its centred card) 8px below the top edge, making the document
  // scrollable and overflowing the card past the viewport bottom. The
  // body margin is zero and the card sits fully inside the viewport.
  const signInLayout = await page.evaluate(() => {
    const card = document.querySelector('.auth-card').getBoundingClientRect();
    return {
      docHeight: document.documentElement.scrollHeight,
      viewport: window.innerHeight,
      bodyMargin: getComputedStyle(document.body).margin,
      cardTop: card.top,
      cardRight: card.right,
      cardBottom: card.bottom,
      cardLeft: card.left,
    };
  });
  expect(signInLayout.bodyMargin).toBe('0px');
  expect(signInLayout.docHeight).toBe(signInLayout.viewport);
  expect(signInLayout.cardTop).toBeGreaterThanOrEqual(0);
  expect(signInLayout.cardBottom).toBeLessThanOrEqual(signInLayout.viewport);
  expect(signInLayout.cardLeft).toBeGreaterThanOrEqual(0);
  expect(signInLayout.cardRight).toBeLessThanOrEqual(1440);

  // --- entering a token signs in with that bearer token -------------
  await page.fill('#token-input', 'dev-token-123');
  await page.click('#signin-button');
  await expect.poll(() => meRequests.length).toBeGreaterThan(0);
  expect(meRequests[0].headers()['authorization']).toBe('Bearer dev-token-123');

  // The mocked /api/auth/me shows the shell with the username in the
  // sidebar, and the entered token never reaches the page source.
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-overview')).toBeVisible();
  expect(await page.content()).not.toContain('dev-token-123');

  // --- navigation: Work queue, hash, aria-current, reload -----------
  await page.click('.nav-btn[data-view="queue"]');
  await expect(page.locator('#view-queue')).toBeVisible();
  await expect(page.locator('#view-overview')).toBeHidden();
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/queue');
  await expect(page.locator('.nav-btn[data-view="queue"]')).toHaveAttribute(
    'aria-current',
    'page',
  );
  await expect(page.locator('.nav-btn[data-view="overview"]')).not.toHaveAttribute(
    'aria-current',
  );

  // A reload keeps the view: the token and the hash both survive it.
  await page.reload();
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-queue')).toBeVisible();
  await expect(page.locator('.nav-btn[data-view="queue"]')).toHaveAttribute(
    'aria-current',
    'page',
  );

  // --- no page scroll at 1440x900 ------------------------------------
  // Review defect: the body's default margin made the document taller
  // than the viewport, so the page scrolled. The body margin is zero
  // and the document has no scrollable overflow.
  const { docHeight, viewportHeight, bodyMargin, rootOverflow } = await page.evaluate(
    () => ({
      docHeight: document.documentElement.scrollHeight,
      viewportHeight: window.innerHeight,
      bodyMargin: getComputedStyle(document.body).margin,
      rootOverflow:
        document.documentElement.scrollHeight > document.documentElement.clientHeight ||
        document.documentElement.scrollWidth > document.documentElement.clientWidth,
    }),
  );
  expect(docHeight).toBe(viewportHeight);
  expect(bodyMargin).toBe('0px');
  expect(rootOverflow).toBe(false);

  // --- narrow layout: the sidebar sits above the main area ----------
  await page.setViewportSize({ width: 390, height: 844 });
  const sidebarBox = await page.locator('#sidebar').boundingBox();
  const mainBox = await page.locator('#main').boundingBox();
  expect(sidebarBox.y + sidebarBox.height).toBeLessThanOrEqual(mainBox.y);

  // --- a 401 from /api/auth/me returns to the sign-in card -----------
  const page401 = await page.context().newPage();
  page401.setViewportSize({ width: 1440, height: 900 });
  await page401.addInitScript(() => {
    window.sessionStorage.setItem('aierp_token', 'stale-token');
  });
  await page401.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({
        status: 401,
        json: { detail: 'Not authenticated' },
      });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  await page401.goto('/');
  await expect(page401.locator('#signin-form')).toBeVisible();
  expect(await page401.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();
  await page401.close();
});

test('issue228 freeform (viewer)', async ({ page }) => {
  // NON-ADMIN pass: boot the production way — no session and no fragment
  // token: /api/auth/config and /api/auth/me are mocked for a user with
  // only the "user" role, and the merged auth.js establishes the session
  // through its supported flow, the PKCE round-trip. The page must still
  // render, and the admin-only control must be absent.
  page.setViewportSize({ width: 1440, height: 900 });
  const { meRequests, appOrigin } = await mockApi(page, {
    config: PROD_CONFIG,
    me: VIEWER_ME,
  });
  // The IdP endpoints are anchored to the issuer the (mocked) backend
  // reports — config.issuer plus the OpenID Connect path — so the mocks
  // can only ever see the IdP's own endpoints, never the app's /api/**.
  // The authorization navigation is captured (its query, PKCE parameters
  // included) the moment it happens — before the code is ever exchanged.
  let authNavRequest = null;
  // Set at the moment the token exchange runs: true only if the auth
  // navigation had already been captured.
  let exchangeSawAuthCapture = null;
  await page.route(PROD_CONFIG.issuer + '/protocol/openid-connect/token', (route) => {
    exchangeSawAuthCapture = authNavRequest !== null;
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(
    new RegExp('^' + escapeRegExp(PROD_CONFIG.issuer) + '/protocol/openid-connect/auth(\\?|$)'),
    (route) => {
      const request = route.request();
      if (request.isNavigationRequest() && authNavRequest === null) {
        authNavRequest = request;
      }
      const state = new URL(request.url()).searchParams.get('state') || '';
      const backToApp =
        appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
      return route.fulfill({
        status: 200,
        contentType: 'text/html',
        body:
          '<!doctype html><html><body><script>window.location.replace(' +
          JSON.stringify(backToApp) +
          ');</script></body></html>',
      });
    },
  );

  // No fragment token is seeded: the PKCE round-trip is the sign-in.
  await page.goto('/');

  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect(page.locator('#view-overview')).toBeVisible();

  // The session is the token the IdP issued on the PKCE round-trip, moved
  // to sessionStorage, out of the address bar.
  await expect.poll(() => meRequests.length).toBeGreaterThan(0);
  expect(meRequests[0].headers()['authorization']).toBe('Bearer pkce-viewer-token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  expect(page.url()).not.toContain('access_token');

  // The admin-only control is absent for a non-admin ...
  await expect(page.locator('[data-admin-only]')).toHaveCount(0);
  // ... while the page still renders read-only.
  await expect(page.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  await expect(page.locator('#signout-button')).toBeVisible();

  // The production-boot shell fills exactly the viewport as well: zero
  // body margin, no scrollable document at 1440x900.
  const viewerLayout = await page.evaluate(() => ({
    docHeight: document.documentElement.scrollHeight,
    viewport: window.innerHeight,
    bodyMargin: getComputedStyle(document.body).margin,
  }));
  expect(viewerLayout.bodyMargin).toBe('0px');
  expect(viewerLayout.docHeight).toBe(viewerLayout.viewport);

  // The captured authorization navigation is a top-level navigation to
  // the IdP's auth endpoint and carries the PKCE parameters ...
  expect(authNavRequest).not.toBeNull();
  expect(authNavRequest.isNavigationRequest()).toBe(true);
  const authParams = new URL(authNavRequest.url()).searchParams;
  expect(authParams.get('client_id')).toBe(PROD_CONFIG.clientId);
  expect(authParams.get('response_type')).toBe('code');
  expect(authParams.get('scope')).toBe('openid');
  expect(authParams.get('code_challenge_method')).toBe('S256');
  expect(authParams.get('code_challenge')).toBeTruthy();
  expect(authParams.get('state')).toBeTruthy();
  expect(authParams.get('redirect_uri')).toBe(appOrigin.value + '/');
  // ... and the token exchange only ran after that capture existed.
  expect(exchangeSawAuthCapture).toBe(true);
});
