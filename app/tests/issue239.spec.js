// Proving spec for AIERP issue #239 — the URL hash is not a sign-in path.
//
// The gate serves the static app with no backend, so every /api/* call is
// mocked with page.route and /api/auth/config answers authMode development.
// Proves:
//   * opening /#access_token=attacker-token shows the sign-in card; no
//     request carries Authorization: Bearer attacker-token; sessionStorage
//     holds no token; and the URL hash becomes #/overview;
//   * signing in through the development token card afterwards still works
//     (bearer token on /api/auth/me, shell with the user's name); sign-out
//     clears the session back to the card, and a rejected token — answered
//     401 by the mock, which the spec verifies — shows the error with no
//     stored session;
//   * a code exchange with sessionStorage unavailable (storage access
//     throws) does not crash: the sign-in card renders, the code is refused
//     with the mismatch error, and the code is never sent as a bearer token;
//   * an existing sessionStorage session survives a load with a foreign
//     hash fragment — neither cleared nor replaced by it;
//   * no other fragment (#random-junk) establishes a session or survives in
//     the address bar, while a view-route hash (#/queue?kind=excess) is
//     left in place.
// The "(viewer)" pass runs as a NON-ADMIN (role 'user'): the production way
// boots with the token in the URL hash as #access_token=... and /api/auth/
// config and /api/auth/me mocked for that user — the fragment stays inert
// through the PKCE round-trip, the admin-only control is absent, and the
// page still renders; the development card then signs the same non-admin in.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue239 freeform"): the merge gate builds its junit nodeids from the
// Playwright test title, and a describe() block would join the titles with
// a "›" the contract nodeid does not carry, so the proof would read as
// "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


// The freeform pass runs many sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const PROD_CONFIG = {
  authEnabled: true,
  authMode: 'production',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

const VIEWER_ME = {
  authenticated: true,
  user: { sub: 'v1', username: 'viewer1', roles: ['user'], groups: [] },
};

const HASH_TOKEN = 'attacker-token';

// The bearer token a request carries ('' when it carries none).
function bearerOf(request) {
  const header = request.headers()['authorization'] || '';
  return header.toLowerCase().startsWith('bearer ') ? header.slice(7) : '';
}

// No request in the list carries the given token as a bearer token.
function assertNoBearerToken(requests, token) {
  const offenders = requests.filter((request) => request.headers()['authorization'] === 'Bearer ' + token);
  expect(offenders).toEqual([]);
}

// Mock every /api/* call in development mode; records the /api/auth/me
// requests so the spec can inspect their Authorization header. A token in
// rejectTokens answers 401 the way the real backend does.
async function mockDevApi(page, { me = ADMIN_ME, rejectTokens = [] } = {}) {
  const meRequests = [];
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      if (rejectTokens.indexOf(bearerOf(route.request())) !== -1) {
        return route.fulfill({ status: 401, json: { detail: 'Not authenticated' } });
      }
      return route.fulfill({ status: 200, json: me });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests };
}

test('issue239 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // --- the hash token is not a sign-in path ----------------------------
  const allRequests = [];
  page.on('request', (request) => allRequests.push(request));
  // The mock answers 401 for this one token, the way the real backend does,
  // so the rejected-token scenario below exercises the genuine sign-out path.
  const { meRequests } = await mockDevApi(page, { rejectTokens: ['bad-token'] });

  await page.goto('/#access_token=' + HASH_TOKEN);

  // The sign-in card shows ...
  await expect(page.locator('#signin-form')).toBeVisible();
  await expect(page.locator('label[for="token-input"]')).toHaveText('Token');
  await expect(page.locator('#app')).toBeHidden();

  // ... the fragment is replaced by the default view route ...
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/overview');

  // ... without storing a token ...
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();

  // ... and without sending it anywhere: no request carries the bearer
  // token, and /api/auth/me was never even called (no session to check).
  assertNoBearerToken(allRequests, HASH_TOKEN);
  expect(meRequests.length).toBe(0);

  // --- the token card still signs in ------------------------------------
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');

  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe('dev-admin-token');
  expect(meRequests.length).toBeGreaterThan(0);
  expect(bearerOf(meRequests[meRequests.length - 1])).toBe('dev-admin-token');
  expect(await page.evaluate(() => window.location.hash)).toBe('#/overview');

  // --- sign-out clears the session back to the card ---------------------
  await page.click('#signout-button');
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();

  // --- a rejected token shows the error and stores nothing --------------
  await page.fill('#token-input', 'bad-token');
  await page.click('#signin-button');
  await expect(page.locator('#signin-form')).toBeVisible();
  await expect(page.locator('#auth-error')).toBeVisible();
  await expect(page.locator('#auth-error')).toHaveText('The token was rejected. Please try again.');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();

  // The mock genuinely rejected the bad token: the /api/auth/me request that
  // carried it was answered 401 — the error above is the 401 sign-out path,
  // not an artefact of a mock that approves every token.
  const rejectedMeRequests = meRequests.filter((request) => bearerOf(request) === 'bad-token');
  expect(rejectedMeRequests.length).toBeGreaterThan(0);
  for (const request of rejectedMeRequests) {
    expect((await request.response()).status()).toBe(401);
  }

  // --- an existing session is neither cleared nor replaced by a foreign
  // --- hash fragment ------------------------------------------------------
  const seededPage = await page.context().newPage();
  seededPage.setViewportSize({ width: 1440, height: 900 });
  const seededRequests = [];
  seededPage.on('request', (request) => seededRequests.push(request));
  await seededPage.addInitScript(() => {
    window.sessionStorage.setItem('aierp_token', 'existing-session-token');
  });
  const seededMe = await mockDevApi(seededPage);
  await seededPage.goto('/#access_token=' + HASH_TOKEN);

  // The pre-existing session signs the user in; the fragment is ignored.
  await expect(seededPage.locator('#app')).toBeVisible();
  await expect(seededPage.locator('#user-name')).toHaveText('planner1');
  await expect.poll(() => seededPage.evaluate(() => window.location.hash)).toBe('#/overview');
  expect(await seededPage.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'existing-session-token',
  );
  expect(seededMe.meRequests.length).toBe(1);
  expect(bearerOf(seededMe.meRequests[0])).toBe('existing-session-token');
  assertNoBearerToken(seededRequests, HASH_TOKEN);
  await seededPage.close();

  // --- any other fragment is inert too ------------------------------------
  const junkPage = await page.context().newPage();
  junkPage.setViewportSize({ width: 1440, height: 900 });
  const junkRequests = [];
  junkPage.on('request', (request) => junkRequests.push(request));
  const junkMe = await mockDevApi(junkPage);
  await junkPage.goto('/#random-junk');
  await expect(junkPage.locator('#signin-form')).toBeVisible();
  await expect.poll(() => junkPage.evaluate(() => window.location.hash)).toBe('#/overview');
  expect(await junkPage.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();
  expect(junkMe.meRequests.length).toBe(0);
  assertNoBearerToken(junkRequests, 'random-junk');
  await junkPage.close();

  // --- a view-route hash is left in place ----------------------------------
  const viewPage = await page.context().newPage();
  viewPage.setViewportSize({ width: 1440, height: 900 });
  const viewMe = await mockDevApi(viewPage);
  await viewPage.goto('/#/queue?kind=excess');
  await expect(viewPage.locator('#signin-form')).toBeVisible();
  expect(await viewPage.evaluate(() => window.location.hash)).toBe('#/queue?kind=excess');
  expect(await viewPage.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();
  expect(viewMe.meRequests.length).toBe(0);
  await viewPage.close();

  // --- exchangeCode survives an unavailable sessionStorage ---------------
  // Storage that throws on access (blocked storage, sandboxed frame) must
  // not crash the code exchange: the sign-in card renders and the code is
  // refused with the mismatch error instead of the page going blank.
  const brokenPage = await page.context().newPage();
  brokenPage.setViewportSize({ width: 1440, height: 900 });
  const brokenPageErrors = [];
  brokenPage.on('pageerror', (error) => brokenPageErrors.push(error));
  await brokenPage.addInitScript(() => {
    Object.defineProperty(window, 'sessionStorage', {
      configurable: true,
      get() {
        throw new DOMException('storage is unavailable', 'SecurityError');
      },
    });
  });
  const brokenRequests = [];
  brokenPage.on('request', (request) => brokenRequests.push(request));
  await mockDevApi(brokenPage);
  await brokenPage.goto('/?code=fake-pkce-code&state=fake-state');

  await expect(brokenPage.locator('#signin-form')).toBeVisible();
  await expect(brokenPage.locator('#auth-error')).toBeVisible();
  await expect(brokenPage.locator('#auth-error')).toHaveText(
    'Sign-in failed: the security check did not match. Please try again.',
  );
  expect(brokenPageErrors).toEqual([]);
  assertNoBearerToken(brokenRequests, 'fake-pkce-code');
  await brokenPage.close();
});

test('issue239 freeform (viewer)', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // --- the production way, as a NON-ADMIN: the hash token stays inert -----
  // The token arrives in the URL hash the way production used to deliver
  // it; the PKCE round-trip that actually establishes the session lands a
  // user with only the "user" role. The fragment must never become the
  // bearer token, the admin-only control must be absent, and the page must
  // still render.
  const allRequests = [];
  page.on('request', (request) => allRequests.push(request));
  const meRequests = [];
  let appOrigin = null;
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (appOrigin === null) {
      appOrigin = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: PROD_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      return route.fulfill({ status: 200, json: VIEWER_ME });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp = appOrigin + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  await page.goto('/#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the non-admin
  // user ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect(page.locator('#view-overview')).toBeVisible();
  await expect(page.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  await expect(page.locator('#signout-button')).toBeVisible();

  // ... the session is the one the IdP issued, not the fragment's ...
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  expect(meRequests.length).toBe(1);
  expect(bearerOf(meRequests[0])).toBe('pkce-viewer-token');

  // ... and the fragment's token was never read, stored or sent ...
  assertNoBearerToken(allRequests, 'viewer-token-abc');
  expect(page.url()).not.toContain('access_token');
  expect(page.url()).not.toContain('code=');
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/overview');

  // The admin-only control is absent for the non-admin.
  await expect(page.locator('[data-admin-only]')).toHaveCount(0);

  // --- the development token card, as the same NON-ADMIN -------------------
  // A fresh tab boots with a foreign hash fragment and no session: the
  // sign-in card shows, and signing in through the card lands the non-admin
  // user — admin-only control absent, page still rendered.
  const cardPage = await page.context().newPage();
  cardPage.setViewportSize({ width: 1440, height: 900 });
  const cardRequests = [];
  cardPage.on('request', (request) => cardRequests.push(request));
  const cardMe = await mockDevApi(cardPage, { me: VIEWER_ME });
  await cardPage.goto('/#access_token=attacker-viewer-token');

  await expect(cardPage.locator('#signin-form')).toBeVisible();
  await expect(cardPage.locator('#app')).toBeHidden();
  await expect.poll(() => cardPage.evaluate(() => window.location.hash)).toBe('#/overview');
  expect(await cardPage.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBeNull();
  assertNoBearerToken(cardRequests, 'attacker-viewer-token');

  await cardPage.fill('#token-input', 'viewer-card-token');
  await cardPage.click('#signin-button');

  await expect(cardPage.locator('#app')).toBeVisible();
  await expect(cardPage.locator('#user-name')).toHaveText('viewer1');
  await expect(cardPage.locator('[data-admin-only]')).toHaveCount(0);
  await expect(cardPage.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  await expect(cardPage.locator('#signout-button')).toBeVisible();
  expect(await cardPage.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'viewer-card-token',
  );
  expect(cardMe.meRequests.length).toBe(1);
  expect(bearerOf(cardMe.meRequests[0])).toBe('viewer-card-token');
  await cardPage.close();
});
