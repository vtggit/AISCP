// Proving spec for AIERP issue #247 — PKCE sign-in without a secure context.
//
// The gate serves the static app with no backend, so every /api/* call is
// mocked with page.route. Proves:
//   * Auth.pkceChallenge(verifier) is a Promise of the base64url (no
//     padding) SHA-256 of the verifier — the RFC 7636 Appendix B value for
//     its verifier — byte-identical through crypto.subtle and through the
//     self-contained fallback, cross-checked with Node's crypto;
//   * with crypto.subtle undefined (a non-secure context) and
//     /api/auth/config answering production with issuer
//     http://idp.test/realms/r, the sign-in redirect navigates to
//     http://idp.test/realms/r/protocol/openid-connect/auth carrying
//     code_challenge_method=S256 and the code_challenge Node's crypto
//     computes as base64url(SHA-256) of the verifier the page stored in
//     sessionStorage — no "Could not start sign-in" error is shown;
//   * the "(viewer)" pass boots the production way as a NON-ADMIN
//     (role 'user') with crypto.subtle undefined and the token in the URL
//     hash as #access_token=...: the fragment stays inert, the subtle-less
//     PKCE round-trip signs the non-admin in, the admin-only control is
//     absent, and the page still renders.
// It also re-proves the review defects: the IdP auth and token mocks are
// anchored to the issuer's exact origin and path (the same path on another
// origin must never be intercepted), and the authorize request's PKCE
// parameters (code_challenge = S256 of the verifier, code_challenge_method)
// are asserted in both the redirect pass and the full round-trip pass.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue247 freeform"): the merge gate builds its junit nodeids from the
// Playwright test title, and a describe() block would join the titles with
// a "›" the contract nodeid does not carry, so the proof would read as
// "not collected".

const { test, expect } = require('@playwright/test');
const nodeCrypto = require('crypto');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs several sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const RFC7636_VERIFIER = 'dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk';
const RFC7636_CHALLENGE = 'E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM';

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const PROD_CONFIG = {
  authEnabled: true,
  authMode: 'production',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

const VIEWER_ME = {
  authenticated: true,
  user: { sub: 'v1', username: 'viewer1', roles: ['user'], groups: [] },
};

// Where the app keeps the PKCE pair (app/js/auth.js).
const VERIFIER_KEY = 'aierp_pkce_verifier';
const STATE_KEY = 'aierp_oauth_state';

// base64url(SHA-256(value)) without padding — Node's crypto side of the
// cross-check (the same encoding the app must produce).
function base64UrlSha256(value) {
  return nodeCrypto.createHash('sha256').update(value, 'utf8').digest('base64url');
}

// Leave crypto in place but take crypto.subtle away, exactly like a
// non-secure context (plain http) does. A plain assignment would silently
// fail (subtle is a getter-only prototype property), so the property is
// redefined on the instance instead.
async function hideSubtle(page) {
  await page.addInitScript(() => {
    Object.defineProperty(window.crypto, 'subtle', {
      configurable: true,
      enumerable: true,
      get() {
        return undefined;
      },
    });
  });
}

// Mock every /api/* call; records the /api/auth/me requests so the spec can
// inspect the Authorization header.
async function mockApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const meRequests = [];
  const appOrigin = { value: null };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      return route.fulfill({ status: 200, json: me });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests, appOrigin };
}

test('issue247 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // --- 1. Auth.pkceChallenge through crypto.subtle ----------------------
  const { appOrigin } = await mockApi(page, { config: DEV_CONFIG, me: ADMIN_ME });
  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(await page.evaluate(() => window.crypto.subtle !== undefined)).toBe(true);

  // The exposed shape: a Promise that resolves to the challenge string.
  const returnsAPromise = await page.evaluate(
    () => window.Auth.pkceChallenge('probe') instanceof Promise,
  );
  expect(returnsAPromise).toBe(true);

  const subtleValue = await page.evaluate(
    (verifier) => window.Auth.pkceChallenge(verifier),
    RFC7636_VERIFIER,
  );
  expect(subtleValue).toBe(RFC7636_CHALLENGE);

  // --- 2. Auth.pkceChallenge with crypto.subtle undefined ---------------
  const fallbackPage = await page.context().newPage();
  fallbackPage.setViewportSize({ width: 1440, height: 900 });
  await hideSubtle(fallbackPage);
  await mockApi(fallbackPage, { config: DEV_CONFIG, me: ADMIN_ME });
  await fallbackPage.goto('/');
  await expect(fallbackPage.locator('#signin-form')).toBeVisible();

  // The page genuinely runs without the subtle API ...
  expect(await fallbackPage.evaluate(() => window.crypto.subtle === undefined)).toBe(true);

  // ... and the fallback path returns the same RFC 7636 value.
  const fallbackValue = await fallbackPage.evaluate(
    (verifier) => window.Auth.pkceChallenge(verifier),
    RFC7636_VERIFIER,
  );
  expect(fallbackValue).toBe(RFC7636_CHALLENGE);

  // Byte-identity beyond the appendix vector: both paths match Node's
  // crypto for a fresh random verifier.
  const randomVerifier = nodeCrypto.randomBytes(32).toString('base64url');
  const expectedRandom = base64UrlSha256(randomVerifier);
  expect(
    await page.evaluate((verifier) => window.Auth.pkceChallenge(verifier), randomVerifier),
  ).toBe(expectedRandom);
  expect(
    await fallbackPage.evaluate((verifier) => window.Auth.pkceChallenge(verifier), randomVerifier),
  ).toBe(expectedRandom);
  await fallbackPage.close();

  // --- 3. Production sign-in without a secure context --------------------
  const prodPage = await page.context().newPage();
  prodPage.setViewportSize({ width: 1440, height: 900 });
  await hideSubtle(prodPage);
  await mockApi(prodPage, { config: PROD_CONFIG, me: ADMIN_ME });

  // Record, from the app's document, every auth error that is shown and
  // every PKCE value the app stores, so the assertions below do not race
  // the navigation away to the (mock) IdP.
  const shownErrors = [];
  const storedValues = {};
  await prodPage.exposeBinding('__recordAuthError', (source, message) => {
    shownErrors.push(String(message));
  });
  await prodPage.exposeBinding('__recordStoredPkce', (source, key, value) => {
    storedValues[String(key)] = String(value);
  });
  await prodPage.addInitScript(() => {
    const recordError = () => {
      const el = document.getElementById('auth-error');
      if (el && !el.hidden && el.textContent) {
        window.__recordAuthError(el.textContent);
      }
    };
    const installObserver = () => {
      const el = document.getElementById('auth-error');
      if (!el) return;
      recordError();
      new MutationObserver(recordError).observe(el, {
        attributes: true,
        childList: true,
        characterData: true,
        subtree: true,
      });
    };
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', installObserver);
    } else {
      installObserver();
    }

    const originalSetItem = Storage.prototype.setItem.bind(window.sessionStorage);
    window.sessionStorage.setItem = function (key, value) {
      originalSetItem(key, value);
      if (key === 'aierp_pkce_verifier' || key === 'aierp_oauth_state') {
        window.__recordStoredPkce(key, value);
      }
    };
  });

  // The mock is anchored to the issuer's exact origin and path: a bare
  // /protocol\/openid-connect\/auth/ regex matched any origin and any path,
  // so the mock could answer requests it was never meant to see.
  let idpRequest = null;
  let idpAuthHits = 0;
  await prodPage.route(
    /^http:\/\/idp\.test\/realms\/r\/protocol\/openid-connect\/auth\?/,
    (route) => {
      idpAuthHits += 1;
      idpRequest = route.request();
      return route.fulfill({
        status: 200,
        contentType: 'text/html',
        body: '<!doctype html><html><body></body></html>',
      });
    },
  );

  await prodPage.goto('/');
  await expect.poll(() => idpRequest).not.toBeNull();

  // The redirect goes to the IdP's authorize endpoint, exactly as before.
  const idpUrl = new URL(idpRequest.url());
  expect(idpUrl.origin + idpUrl.pathname).toBe(
    'http://idp.test/realms/r/protocol/openid-connect/auth',
  );
  expect(idpUrl.searchParams.get('client_id')).toBe('aierp-app');
  expect(idpUrl.searchParams.get('response_type')).toBe('code');
  expect(idpUrl.searchParams.get('scope')).toBe('openid');
  expect(idpUrl.searchParams.get('redirect_uri')).toBe(appOrigin.value + '/');
  expect(idpUrl.searchParams.get('code_challenge_method')).toBe('S256');

  // ... carrying the state it stored ...
  expect(storedValues[STATE_KEY]).toBeTruthy();
  expect(idpUrl.searchParams.get('state')).toBe(storedValues[STATE_KEY]);

  // ... and the code_challenge that Node's crypto computes as
  // base64url(SHA-256) of the verifier the page stored in sessionStorage.
  expect(storedValues[VERIFIER_KEY]).toBeTruthy();
  expect(idpUrl.searchParams.get('code_challenge')).toBe(
    base64UrlSha256(storedValues[VERIFIER_KEY]),
  );

  // The subtle-less sign-in started cleanly: no auth error was shown.
  expect(shownErrors).toEqual([]);

  // The anchored route stays anchored: the same path on another origin is
  // not intercepted by the mock (the handler saw exactly one request) —
  // the navigation goes to the real network and fails there, where no
  // such host exists.
  let imposterError = null;
  try {
    await prodPage.goto(
      'http://imposter.test/realms/r/protocol/openid-connect/auth?client_id=aierp-app',
      { timeout: 20000 },
    );
  } catch (error) {
    imposterError = error;
  }
  expect(idpAuthHits).toBe(1);
  expect(imposterError).not.toBeNull();
  expect(String(imposterError)).toMatch(/net::ERR_/);
  await prodPage.close();
});

test('issue247 freeform (viewer)', async ({ page }) => {
  // NON-ADMIN pass: boot the production way — the token arrives in the URL
  // hash the way production used to deliver it, /api/auth/config answers
  // production, /api/auth/me answers for a user with only the "user" role,
  // and crypto.subtle is undefined (no secure context). The subtle-less
  // PKCE round-trip must sign the non-admin in, the admin-only control must
  // be absent, and the page must still render.
  page.setViewportSize({ width: 1440, height: 900 });
  await hideSubtle(page);

  const allRequests = [];
  page.on('request', (request) => allRequests.push(request));
  const { meRequests, appOrigin } = await mockApi(page, {
    config: PROD_CONFIG,
    me: VIEWER_ME,
  });

  // Anchored to the issuer's exact origin and path, like in the redirect
  // pass: the mocks must only ever see the IdP's own endpoints.
  let viewerTokenRequest = null;
  await page.route(
    /^http:\/\/idp\.test\/realms\/r\/protocol\/openid-connect\/token(\?|$)/,
    (route) => {
      viewerTokenRequest = route.request();
      return route.fulfill({
        status: 200,
        json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
      });
    },
  );
  let viewerAuthorizeRequest = null;
  await page.route(
    /^http:\/\/idp\.test\/realms\/r\/protocol\/openid-connect\/auth\?/,
    (route) => {
      viewerAuthorizeRequest = route.request();
      const state = new URL(route.request().url()).searchParams.get('state') || '';
      const backToApp =
        appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
      return route.fulfill({
        status: 200,
        contentType: 'text/html',
        body:
          '<!doctype html><html><body><script>window.location.replace(' +
          JSON.stringify(backToApp) +
          ');</script></body></html>',
      });
    },
  );

  await page.goto('/#access_token=viewer-token-abc');

  // The subtle-less PKCE round-trip completes and the shell renders for the
  // non-admin user ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect(page.locator('#view-overview')).toBeVisible();
  await expect(page.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  await expect(page.locator('#signout-button')).toBeVisible();

  // ... the session is the token the IdP issued, not the fragment's ...
  await expect.poll(() => meRequests.length).toBeGreaterThan(0);
  expect(meRequests[0].headers()['authorization']).toBe('Bearer pkce-viewer-token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  expect(page.url()).not.toContain('access_token');
  expect(page.url()).not.toContain('code=');

  // ... and the fragment's token was never sent anywhere.
  const offenders = allRequests.filter(
    (request) => request.headers()['authorization'] === 'Bearer viewer-token-abc',
  );
  expect(offenders).toEqual([]);

  // The round-trip carried real PKCE, not just a code: the authorize
  // request went to the issuer's auth endpoint with
  // code_challenge_method=S256, and its code_challenge is base64url(SHA-256)
  // of the very verifier the page later posted as code_verifier — computed
  // here with Node's crypto.
  await expect.poll(() => viewerAuthorizeRequest).not.toBeNull();
  await expect.poll(() => viewerTokenRequest).not.toBeNull();
  const viewerAuthorizeUrl = new URL(viewerAuthorizeRequest.url());
  expect(viewerAuthorizeUrl.origin + viewerAuthorizeUrl.pathname).toBe(
    'http://idp.test/realms/r/protocol/openid-connect/auth',
  );
  expect(viewerAuthorizeUrl.searchParams.get('code_challenge_method')).toBe('S256');
  const viewerTokenUrl = new URL(viewerTokenRequest.url());
  expect(viewerTokenUrl.origin + viewerTokenUrl.pathname).toBe(
    'http://idp.test/realms/r/protocol/openid-connect/token',
  );
  const tokenForm = new URLSearchParams(viewerTokenRequest.postData());
  expect(tokenForm.get('code_verifier')).toBeTruthy();
  expect(viewerAuthorizeUrl.searchParams.get('code_challenge')).toBe(
    base64UrlSha256(tokenForm.get('code_verifier')),
  );

  // The admin-only control is absent for a non-admin.
  await expect(page.locator('[data-admin-only]')).toHaveCount(0);
});
