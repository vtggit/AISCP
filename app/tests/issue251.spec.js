// Proving spec for AIERP issue #251 — the Work queue view (the
// planner's page, #/queue).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]):
//   * the tab bar — Reorder points, Excess and dead stock and Stockout
//     risk, each with its count of undecided rows — and the filter
//     chips To decide (the default), Decided and All;
//   * the Reorder points tab loads
//     GET /api/drift?limit=1000&include_decided=true and lists the
//     mocked undecided rows in API order, with the columns rank, item
//     and site, "current → recommended" ("not set" when the ERP has no
//     reorder point), whole-dollar money and the decision badge;
//     every row is a button and the selected row carries
//     aria-current="true";
//   * the detail pane: the kind and rank, the item code and site, two
//     figure tiles, the one-sentence Why, the single-column inputs and
//     the monospace arithmetic;
//   * #/queue?kind=drift&item=B&site=S1 selects row B and shows its
//     detail, including its arithmetic;
//   * Accept posts {"decision": "accepted"} with item_code and
//     site_code to POST /api/drift/decisions; the row's badge changes
//     to Accepted in place, the tab count drops by one and the history
//     updates — no page load;
//   * Dismiss with a blank reason shows the inline error and sends no
//     request; with a reason it posts
//     {"decision": "dismissed", "reason": "…"};
//   * Snooze 14 days posts snooze_until 14 days after today
//     (YYYY-MM-DD, local date);
//   * a 422 response shows its detail inline and the row stays
//     undecided;
//   * an item code of <img src=x onerror=alert(1)> renders as text,
//     never as markup, and fires no dialog;
//   * at 1440x900 the document does not scroll; at 390x844 the detail
//     pane sits below the list pane and nothing scrolls sideways.
// The "(viewer)" pass boots the production way (token in the URL hash)
// as a NON-ADMIN (role "user") and asserts the admin-only decision
// buttons are absent while the queue still renders read-only.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue251 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

