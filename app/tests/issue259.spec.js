// Proving spec for AIERP issue #259 — the production PKCE redirect.
//
// The gate serves the static app with no backend, so /api/auth/config is
// mocked with page.route as a PRODUCTION configuration (issuer
// http://idp.test/realms/r, clientId aierp-frontend). crypto.subtle is
// left in place on purpose: the code challenge must come from the real
// Web Crypto SHA-256 digest, not a stub.
// Proves that loading / with no session navigates to the IdP's
// /protocol/openid-connect/auth endpoint — the navigation is captured
// with page.route and fulfilled with an empty page — and that the
// request carries:
//   * client_id=aierp-frontend, response_type=code, scope=openid;
//   * code_challenge_method=S256 and a non-empty state;
//   * redirect_uri equal to the page origin plus "/";
//   * a code_challenge equal to base64url(SHA-256(verifier)), where the
//     verifier is the value the app stored in sessionStorage and the
//     expected digest is computed in this test with Node's crypto.
// The page values are captured WITHOUT evaluating page code while the
// navigation is pending — while the auth route handler runs, the
// cross-origin navigation has not committed yet (the commit waits for
// the handler's fulfil), so a page.evaluate there can never resolve and
// hangs the proof until the test ends ("page.evaluate: Test ended" in
// the route callback):
//   * the PKCE verifier is mirrored out of sessionStorage with the
//     technique issue #247 uses: an init script wraps
//     sessionStorage.setItem and reports the value to Node through
//     exposeBinding, synchronously inside the app's setItem call, so
//     Node holds the exact stored value before the navigation starts;
//   * the page origin is the origin of the mocked /api/auth/config
//     request — the app fetches its API same-origin, so the request
//     origin is the page origin (issue #228's pattern).
// Every route handler therefore stays synchronous, and the only
// page.evaluate calls run after the navigation has committed.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue259 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');
const nodeCrypto = require('node:crypto');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs many sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const PROD_CONFIG = {
  authEnabled: true,
  authMode: 'production',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-frontend',
  audience: 'aierp-frontend',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const VERIFIER_KEY = 'aierp_pkce_verifier';

// base64url(SHA-256(verifier)) without padding — the RFC 7636 S256
// challenge, computed in this test with Node's crypto.
function base64UrlSha256(verifier) {
  return nodeCrypto
    .createHash('sha256')
    .update(verifier, 'utf8')
    .digest('base64url');
}

test('issue259 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // The PKCE verifier, mirrored from sessionStorage at the very moment
  // the app stores it: the wrapper runs synchronously inside the app's
  // setItem call and reports the value to Node through the binding, so
  // the exact stored value is in hand before the navigation starts.
  const storedVerifier = { value: null };
  await page.exposeBinding('__issue259RecordPkceVerifier', (source, value) => {
    storedVerifier.value = String(value);
  });
  await page.addInitScript(() => {
    const originalSetItem = Storage.prototype.setItem.bind(window.sessionStorage);
    window.sessionStorage.setItem = function (key, value) {
      originalSetItem(key, value);
      if (key === 'aierp_pkce_verifier') {
        window.__issue259RecordPkceVerifier(value);
      }
    };
  });

  // Production configuration from the (mocked) backend; no session token
  // exists, so /api/auth/me is never consulted before the redirect. The
  // first /api request also fixes the page origin: the app fetches its
  // API same-origin, so the request origin is the page origin. The
  // overview data calls fired by the shell before sign-in resolves
  // simply 404 — the app screen stays hidden behind the auth gate.
  const appOrigin = { value: null };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: PROD_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({ status: 401, json: { detail: 'Not authenticated' } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });

  // Capture the IdP auth navigation and fulfil it with an empty page.
  // Anchored to the issuer's exact origin and path (issue #247's
  // pattern), so the mock can only ever see the IdP's own endpoint. The
  // handler stays synchronous — see the header for why no page JS may
  // run while this navigation is pending.
  let authRequest = null;
  await page.route(
    /^http:\/\/idp\.test\/realms\/r\/protocol\/openid-connect\/auth\?/,
    (route) => {
      // Review defect: the capture is the top-level navigation alone.
      // A fetch or XHR that merely hits the same URL is not the
      // redirect this proof is about, so it is fulfilled but never
      // recorded.
      const request = route.request();
      if (request.isNavigationRequest()) {
        authRequest = request;
      }
      return route.fulfill({ status: 200, contentType: 'text/html', body: '' });
    },
  );

  await page.goto('/');

  // The production boot must redirect to the IdP auth endpoint, and the
  // capture must hold the verifier the app stored. Each value is set by
  // exactly one synchronous handler step, so polling the combination
  // can never observe a half-populated capture.
  await expect
    .poll(
      () => authRequest !== null && storedVerifier.value !== null && appOrigin.value !== null,
      {
        timeout: 15000,
        message:
          'the app never navigated to the IdP auth endpoint, or the PKCE verifier was not captured from sessionStorage',
      },
    )
    .toBe(true);

  // Review defect: the recorded request is the top-level navigation to
  // the IdP auth endpoint, not a fetch or XHR that happened to hit the
  // same URL.
  expect(authRequest.isNavigationRequest()).toBe(true);
  expect(authRequest.resourceType()).toBe('document');

  const authUrl = new URL(authRequest.url());
  expect(authUrl.origin + authUrl.pathname).toBe(
    'http://idp.test/realms/r/protocol/openid-connect/auth',
  );

  const params = authUrl.searchParams;
  expect(params.get('client_id')).toBe('aierp-frontend');
  expect(params.get('response_type')).toBe('code');
  expect(params.get('scope')).toBe('openid');
  expect(params.get('code_challenge_method')).toBe('S256');
  // A non-empty state, asserted on the URL alone: the AC requires
  // non-empty, and comparing it against the app's internal storage key
  // would couple the proof to an implementation detail.
  expect(params.get('state')).toBeTruthy();
  // redirect_uri is the page origin plus "/", exactly where the IdP
  // will send the code back to.
  expect(params.get('redirect_uri')).toBe(appOrigin.value + '/');

  // The challenge is base64url(SHA-256(verifier)) of the verifier the
  // app stored in sessionStorage — recomputed here with Node's crypto.
  expect(storedVerifier.value).toBeTruthy();
  expect(params.get('code_challenge')).toBe(base64UrlSha256(storedVerifier.value));

  // ... and the redirect actually landed: the fulfilled empty page is
  // now the document, sitting on the IdP's auth URL. The body check
  // polls (null until the committed document has its body) so it can
  // never race the commit.
  await expect(page).toHaveURL(
    /^http:\/\/idp\.test\/realms\/r\/protocol\/openid-connect\/auth\?/,
  );
  await expect
    .poll(() => page.evaluate(() => (document.body ? document.body.innerHTML : null)))
    .toBe('');
});
