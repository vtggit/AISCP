// Proving spec for AIERP issue #260 — the #228 viewer pass on the merged
// auth.js.
//
// The gate serves the static app with no backend, so every /api/* call is
// mocked with page.route and the IdP's auth and token endpoints are mocked
// to carry a NON-ADMIN (role 'user') through the production PKCE
// round-trip. The single freeform pass re-proves the amended #228 viewer
// setup from a clean boot:
//   * no fragment token is seeded (AC-2): the page boots at / with no
//     session and no #access_token=... hash; the session is established
//     entirely by the merged auth.js's supported flow — the PKCE
//     round-trip — with /api/auth/config and /api/auth/me mocked for the
//     viewer;
//   * the PKCE token exchange is intercepted at the IdP issuer URL derived
//     from config.issuer — http://idp.test/realms/r/protocol/openid-
//     connect/token — not under /api/** (AC-3);
//   * the IdP authorization navigation query, PKCE parameters included,
//     is captured before the token exchange runs (AC-4): the capture is
//     the top-level navigation to the issuer's auth endpoint, its query
//     carries client_id, response_type=code, scope=openid, a non-empty
//     state, a non-empty code_challenge and code_challenge_method=S256,
//     and redirect_uri equal to the page origin plus "/"; the state
//     equals the value the app stored, and the challenge is
//     base64url(SHA-256(verifier)) of the stored verifier, recomputed
//     here with Node's crypto (issue #259's technique: the verifier and
//     state are mirrored out of sessionStorage through exposeBinding at
//     the moment the app stores them);
//   * the non-admin sees the shell — the user name, Overview, the Work
//     queue nav and sign out — without the admin-only control while the
//     page still renders, and the production-boot shell fills exactly
//     the viewport (AC-1, Identity).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue260 freeform"): the merge gate builds its junit nodeids from the
// Playwright test title, and a describe() block would join the titles with
// a "›" the contract nodeid does not carry, so the proof would read as
// "not collected".

const { test, expect } = require('@playwright/test');
const nodeCrypto = require('node:crypto');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs many sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const PROD_CONFIG = {
  authEnabled: true,
  authMode: 'production',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const VIEWER_ME = {
  authenticated: true,
  user: { sub: 'v1', username: 'viewer1', roles: ['user'], groups: [] },
};

const IDP_TOKEN_PATH = '/protocol/openid-connect/token';
const IDP_AUTH_PATH = '/protocol/openid-connect/auth';

// Escape a string for use inside a RegExp (the IdP endpoint patterns are
// built from config.issuer, which is data, not a literal).
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// base64url(SHA-256(verifier)) without padding — the RFC 7636 S256
// challenge, computed in this test with Node's crypto.
function base64UrlSha256(verifier) {
  return nodeCrypto
    .createHash('sha256')
    .update(verifier, 'utf8')
    .digest('base64url');
}

test('issue260 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });

  // Mirror the PKCE verifier and state out of sessionStorage at the very
  // moment the app stores them (issue #259's technique): the init-script
  // wrapper runs synchronously inside the app's setItem call and reports
  // the value to Node through the binding, so the exact stored values are
  // in hand before the IdP navigation starts. Every route handler stays
  // synchronous for the same reason: while the auth navigation is
  // pending, page JS cannot run (issue #259's constraint).
  const storedPkce = { verifier: null, state: null };
  await page.exposeBinding('__issue260RecordPkce', async (source, key, value) => {
    if (key === 'aierp_pkce_verifier') {
      storedPkce.verifier = String(value);
    }
    if (key === 'aierp_oauth_state') {
      storedPkce.state = String(value);
    }
  });
  await page.addInitScript(() => {
    const originalSetItem = Storage.prototype.setItem.bind(window.sessionStorage);
    window.sessionStorage.setItem = function (key, value) {
      originalSetItem(key, value);
      if (key === 'aierp_pkce_verifier' || key === 'aierp_oauth_state') {
        window.__issue260RecordPkce(key, value);
      }
    };
  });

  // /api/** mocked for the NON-ADMIN viewer: the production config and
  // the viewer identity on /api/auth/me. The first /api request also
  // fixes the page origin: the app fetches its API same-origin, so the
  // request origin is the page origin (issue #228's pattern).
  const meRequests = [];
  const appOrigin = { value: null };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: PROD_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      return route.fulfill({ status: 200, json: VIEWER_ME });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });

  // AC-4: capture the IdP authorization navigation — the top-level
  // navigation only, query included — at the issuer's exact origin and
  // path. The fulfil completes the round-trip the way a real IdP would:
  // a page that sends the browser back to the app with code + state.
  let authNavRequest = null;
  await page.route(
    new RegExp('^' + escapeRegExp(PROD_CONFIG.issuer) + IDP_AUTH_PATH + '(\\?|$)'),
    (route) => {
      const request = route.request();
      if (request.isNavigationRequest() && authNavRequest === null) {
        authNavRequest = request;
      }
      const state = new URL(request.url()).searchParams.get('state') || '';
      const backToApp =
        appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
      return route.fulfill({
        status: 200,
        contentType: 'text/html',
        body:
          '<!doctype html><html><body><script>window.location.replace(' +
          JSON.stringify(backToApp) +
          ');</script></body></html>',
      });
    },
  );

  // AC-3: the PKCE token exchange is intercepted at the IdP issuer URL
  // derived from config.issuer — never under /api/**.
  const tokenEndpoint = PROD_CONFIG.issuer + IDP_TOKEN_PATH;
  let tokenExchangeRequest = null;
  // Set at the moment the exchange runs: true only if the auth navigation
  // had already been captured (the AC-4 ordering).
  let exchangeSawAuthCapture = null;
  await page.route(tokenEndpoint, (route) => {
    tokenExchangeRequest = route.request();
    exchangeSawAuthCapture = authNavRequest !== null;
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-issue260-token', token_type: 'Bearer' },
    });
  });

  // AC-2: no fragment token is seeded. The page boots the merged
  // auth.js's supported way — no session, no #access_token=... — and the
  // PKCE round-trip establishes the viewer session.
  await page.goto('/');

  // The shell renders for the NON-ADMIN ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect(page.locator('#view-overview')).toBeVisible();
  await expect(page.locator('.nav-btn[data-view="queue"]')).toBeVisible();
  await expect(page.locator('#signout-button')).toBeVisible();
  // ... without the admin-only control.
  await expect(page.locator('[data-admin-only]')).toHaveCount(0);

  // The session is the token the IdP issued on the round-trip: stored,
  // sent as the bearer, and out of the address bar. The one-time PKCE
  // state and verifier are consumed by the exchange.
  await expect.poll(() => meRequests.length).toBeGreaterThan(0);
  expect(meRequests.length).toBe(1);
  expect(meRequests[0].headers()['authorization']).toBe('Bearer pkce-issue260-token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-issue260-token',
  );
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_oauth_state'))).toBeNull();
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_pkce_verifier'))).toBeNull();
  expect(page.url()).not.toContain('access_token');
  expect(page.url()).not.toContain('code=');

  // AC-3: the exchange went to the issuer-derived token URL, as the
  // authorization-code grant carrying the one-time verifier.
  expect(tokenExchangeRequest).not.toBeNull();
  expect(tokenExchangeRequest.method()).toBe('POST');
  expect(new URL(tokenExchangeRequest.url()).href).toBe(tokenEndpoint);
  const exchangeForm = new URLSearchParams(tokenExchangeRequest.postData() || '');
  expect(exchangeForm.get('grant_type')).toBe('authorization_code');
  expect(exchangeForm.get('code')).toBeTruthy();
  expect(exchangeForm.get('code_verifier')).toBeTruthy();
  expect(exchangeForm.get('client_id')).toBe(PROD_CONFIG.clientId);

  // AC-4: the authorization navigation was captured, with the PKCE
  // parameters, before the token exchange ran.
  expect(authNavRequest).not.toBeNull();
  expect(authNavRequest.isNavigationRequest()).toBe(true);
  const authUrl = new URL(authNavRequest.url());
  expect(authUrl.origin + authUrl.pathname).toBe(PROD_CONFIG.issuer + IDP_AUTH_PATH);
  const params = authUrl.searchParams;
  expect(params.get('client_id')).toBe(PROD_CONFIG.clientId);
  expect(params.get('response_type')).toBe('code');
  expect(params.get('scope')).toBe('openid');
  expect(params.get('code_challenge_method')).toBe('S256');
  expect(params.get('state')).toBeTruthy();
  expect(params.get('code_challenge')).toBeTruthy();
  expect(params.get('redirect_uri')).toBe(appOrigin.value + '/');

  // The captured values are the ones the app stored before redirecting:
  // the state equals the stored state, and the challenge is
  // base64url(SHA-256(verifier)) of the stored verifier, recomputed with
  // Node's crypto.
  expect(storedPkce.state).toBeTruthy();
  expect(storedPkce.verifier).toBeTruthy();
  expect(params.get('state')).toBe(storedPkce.state);
  expect(params.get('code_challenge')).toBe(base64UrlSha256(storedPkce.verifier));

  // ... and the exchange only ran after the capture existed.
  expect(exchangeSawAuthCapture).toBe(true);

  // The production-boot shell fills exactly the viewport as well: zero
  // body margin, no scrollable document at 1440x900.
  const viewerLayout = await page.evaluate(() => ({
    docHeight: document.documentElement.scrollHeight,
    viewport: window.innerHeight,
    bodyMargin: getComputedStyle(document.body).margin,
  }));
  expect(viewerLayout.bodyMargin).toBe('0px');
  expect(viewerLayout.docHeight).toBe(viewerLayout.viewport);
});
