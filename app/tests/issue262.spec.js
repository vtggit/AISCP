// Proving spec for AIERP issue #262 — deciding on Excess and dead stock
// and Stockout risk rows in the Work queue, and the Overview refreshing
// after any decision (docs/design/planner-screen.md).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]):
//   * the Excess and dead stock detail pane offers the kind's three
//     action options (Stop replenishing, Reduce, Dispose) as option
//     buttons using aria-pressed, none pressed at first (the settings
//     read fails here, so the action choice stays required); pressing
//     one retitles the primary button to "Accept: <action label>";
//   * Accept posts one request to POST /api/excess/decisions with the
//     row's item_code and site_code, decision "accepted" and the chosen
//     action; the row's badge reads "Accepted · <action label>" and the
//     tab's to-decide count falls by one — no page load;
//   * the same for Stockout risk: Expedite, Raise order, Transfer and
//     POST /api/stockout/decisions with the chosen action;
//   * Dismiss requires a reason: a blank one shows the inline alert and
//     sends no request; with a reason it posts decision "dismissed"
//     with the reason;
//   * Snooze offers 7, 14 and 90 days for excess and 7, 14 and 30 days
//     (the maximum) for stockout, and posts snooze_until as the date
//     that many days after today (YYYY-MM-DD, local date);
//   * the decision history under the Decision block comes from the
//     kind's GET /api/excess/decisions or GET /api/stockout/decisions
//     with the row's item_code and site_code; it lists the row's
//     decisions newest first, with the action label on accepted
//     entries;
//   * a failed history read for the row just picked clears the block —
//     it never leaves the previous row's stale entries in the pane;
//   * the Overview loads its figures the first time it is shown, and
//     after a decision recorded in the Work queue the next visit to
//     #/overview re-requests GET /api/decisions/summary and the three
//     lists and shows the new figures — the mock returns different
//     summary and list data after the first POST, and the value tiles,
//     the Excess card and the attention list all show that post-POST
//     data, with no page reload.
// The "(viewer)" pass boots the production way (token in the URL hash)
// as a NON-ADMIN (role "user") and asserts the Excess and Stockout
// detail panes are read-only: the pane still renders, but there are no
// action options and no Accept, Dismiss or Snooze buttons.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue262 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

