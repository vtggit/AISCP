// Mock every /api/* call the queue (and the shell around it) makes.
// The decision endpoints are stateful: a POST stores a new decision
// (newest first) in the per item-site history a later GET reads back,
// and the decision switches the summary and the lists to their
// post-decision data — the Overview's second visit must show that data.
async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const meRequests = [];
  const appOrigin = { value: null };
  const state = {
    posted: [],
    summaryGets: 0,
    listGets: [],
    historyGets: [],
    // item|site keys whose history GET the mock answers 500 with —
    // proves a failed history read clears the block instead of leaving
    // the previous row's stale entries in the pane.
    failHistory: {},
    store: { 'X1|S1': SEED_HISTORY['X1|S1'].map((entry) => ({ ...entry })) },
    decided: {},
  };

  const buildList = (kind) => {
    const base =
      kind === 'drift' ? DRIFT_ROWS : kind === 'excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
    return base.map((row) => {
      const stored = state.decided[row.item_code + '|' + row.site_code];
      return stored ? { ...row, decision: stored } : { ...row };
    });
  };

  const storedFor = (kind, body) => {
    const source =
      kind === 'drift'
        ? DRIFT_ROWS
        : kind === 'excess'
          ? EXCESS_ROWS
          : STOCKOUT_ROWS;
    const row = source.find(
      (candidate) =>
        candidate.item_code === body.item_code && candidate.site_code === body.site_code,
    );
    const stored = {
      id: 'dec-posted-' + (state.posted.length + 1),
      item_code: body.item_code,
      site_code: body.site_code,
      decision: body.decision,
      action: body.action || null,
      reason: body.reason || null,
      snooze_until: body.snooze_until || null,
      as_of: '2026-10-09',
      decided_by: 'planner1',
      decided_at: '2026-10-09T07:30:00+00:00',
    };
    if (row) {
      Object.assign(stored, {
        category: row.category,
        dead_reason: row.dead_reason || null,
        on_hand_units: row.on_hand_units,
        excess_units: row.excess_units != null ? row.excess_units : null,
        money_tied_up: row.money_tied_up != null ? row.money_tied_up : null,
        money_at_stake: row.money_at_stake != null ? row.money_at_stake : null,
        money_at_risk: row.money_at_risk != null ? row.money_at_risk : null,
      });
    }
    return stored;
  };

  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.slice('/api/'.length);
      state.listGets.push({ kind, query: url.search });
      return route.fulfill({ status: 200, json: buildList(kind) });
    }
    if (path === '/api/decisions/summary') {
      state.summaryGets += 1;
      const summary = state.posted.length ? SUMMARY_AFTER : SUMMARY_BEFORE;
      return route.fulfill({ status: 200, json: summary });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      const kind = decisions[1];
      if (request.method() === 'POST') {
        const body = request.postDataJSON();
        state.posted.push({ kind, path, body });
        const stored = storedFor(kind, body);
        const key = body.item_code + '|' + body.site_code;
        state.store[key] = [stored].concat(state.store[key] || []);
        state.decided[key] = stored;
        return route.fulfill({ status: 201, json: stored });
      }
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      const historyKey = (item || '') + '|' + (site || '');
      state.historyGets.push({ kind, item, site });
      if (state.failHistory[historyKey]) {
        return route.fulfill({ status: 500, json: { detail: 'History unavailable' } });
      }
      return route.fulfill({ status: 200, json: state.store[historyKey] || [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests, appOrigin, state };
}

// Today + n days as YYYY-MM-DD in the page's local date — the same
// "today" the app's snooze button uses.
const snoozeDateInPage = (page, days) =>
  page.evaluate((d) => {
    const date = new Date();
    date.setDate(date.getDate() + d);
    const pad = (value) => (value < 10 ? '0' : '') + value;
    return date.getFullYear() + '-' + pad(date.getMonth() + 1) + '-' + pad(date.getDate());
  }, days);

