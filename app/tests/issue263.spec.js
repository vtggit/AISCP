// Proving spec for AIERP issue #263 — the Decision log view (#/log).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin:
//   * the view is a single card holding a table of every recorded
//     decision, the data coming from
//     GET /api/drift/decisions?limit=1000,
//     GET /api/excess/decisions?limit=1000 and
//     GET /api/stockout/decisions?limit=1000, merged and sorted
//     newest first by decided_at (the mock rows are interleaved across
//     the three lists in decided_at order, never in list order);
//   * each column's text for an accepted (with action), a dismissed
//     and a snoozed decision: the List label ("Reorder point",
//     "Excess and dead stock" or "Stockout risk"), the item and site
//     "<item_code> · <site_code>", the reason after a dismissal,
//     "until <snooze_until>" after a snooze, and the action label
//     (Reduce, Expedite) after an accept that recorded an action;
//   * the queue link target: the item and site is a link to
//     #/queue?kind=<kind>&item=<item_code>&site=<site_code> (the code
//     URL-encoded); clicking it lands the queue on that target;
//   * the money column formatted exactly as the Overview formats
//     money, with an em dash for a null money figure;
//   * the Status badge reading Accepted, Dismissed or Snoozed;
//   * the Decided column carrying decided_by and the decided_at date;
//   * a decision whose reason and item_code contain
//     <img src=x onerror=window.__pwned=1> renders as literal text and
//     window.__pwned stays undefined;
//   * with 300 decisions the page does not scroll vertically at
//     1440x900: #log-root fills the view without growing past it
//     (the flex height constraint), so the table body scrolls inside
//     its own region and the table header stays in place;
//   * at 390x844 the page itself does not scroll, neither sideways
//     nor vertically: the table scrolls inside its card instead;
//   * with no decisions the card reads "No decisions recorded yet.";
//   * a failed request shows an inline error with a Retry button that
//     repeats the requests and recovers;
//   * every action label (Stop replenishing, Reduce, Dispose,
//     Expedite, Raise order, Transfer) after an accept that recorded
//     an action;
//   * the view is read-only: it carries no controls at all, and no
//     decision endpoint is ever posted to.
// The viewer pass boots the production way after a full reload (the
// token in the URL hash as #access_token=..., /api/auth/config and
// /api/auth/me mocked for a NON-ADMIN with only the "user" role, the
// IdP's auth and token endpoints mocked to carry the viewer through
// the PKCE round-trip) and asserts the log still renders read-only —
// no admin-only control is present.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue263 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

