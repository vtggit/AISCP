// 300 decisions in total (150 + 75 + 75) for the no-page-scroll pass.
function bigDecisions(kind) {
  const count = kind === 'drift' ? 150 : 75;
  const rows = [];
  for (let i = 0; i < count; i++) {
    const decidedAt = new Date(Date.UTC(2026, 8, 1) + i * 7 * 60000).toISOString();
    const decision = i % 3 === 0 ? 'accepted' : i % 3 === 1 ? 'dismissed' : 'snoozed';
    const row = {
      id: 'big-' + kind + '-' + i,
      item_code: 'BIG' + i,
      site_code: 'S1',
      decision,
      action: null,
      reason: decision === 'dismissed' ? 'bulk reason ' + i : null,
      snooze_until: decision === 'snoozed' ? '2026-11-30' : null,
      as_of: '2026-09-01',
      money_at_stake: null,
      money_tied_up: null,
      money_at_risk: null,
      decided_by: 'planner1',
      decided_at: decidedAt,
    };
    if (kind === 'drift') {
      row.money_at_stake = i * 10;
    }
    if (kind === 'excess') {
      row.action = decision === 'accepted' ? 'reduce' : null;
      row.category = 'excess';
      row.dead_reason = null;
      row.on_hand_units = 100;
      row.excess_units = 40;
      row.money_tied_up = i * 10;
    }
    if (kind === 'stockout') {
      row.action = decision === 'accepted' ? 'expedite' : null;
      row.category = 'at_risk';
      row.p_stockout = 0.5;
      row.on_hand_units = 10;
      row.open_supply_units = 0;
      row.expected_units_short = 4;
      row.money_at_risk = i * 10;
    }
    rows.push(row);
  }
  return rows;
}

// Mock every /api/* call the shell and the log view make. The three
// decision list endpoints answer from the mutable scenario state;
// anything else (the overview and queue list endpoints) answers 404 —
// those views are not the subject of this proof.
async function mockLogApi(page) {
  const state = {
    phase: 'admin', // 'admin' | 'viewer'
    mode: 'base', // 'base' | 'big' | 'empty' | 'error' | 'actions'
    decisionGets: [],
    postCount: 0,
    meRequests: [],
    appOrigin: null,
  };
  const baseLists = {
    drift: DRIFT_DECISIONS,
    excess: EXCESS_DECISIONS,
    stockout: STOCKOUT_DECISIONS,
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (state.appOrigin === null) {
      state.appOrigin = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: state.phase === 'viewer' ? PROD_CONFIG : DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      state.meRequests.push(request);
      return route.fulfill({ status: 200, json: state.phase === 'viewer' ? VIEWER_ME : ADMIN_ME });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      const kind = decisions[1];
      if (request.method() !== 'GET') {
        state.postCount += 1;
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      state.decisionGets.push({ kind, query: url.search, mode: state.mode, phase: state.phase });
      if (state.mode === 'error' && kind === 'stockout') {
        return route.fulfill({ status: 500, json: { detail: ERROR_DETAIL } });
      }
      if (state.mode === 'empty') {
        return route.fulfill({ status: 200, json: [] });
      }
      if (state.mode === 'big') {
        return route.fulfill({ status: 200, json: bigDecisions(kind) });
      }
      if (state.mode === 'actions') {
        return route.fulfill({ status: 200, json: ACTION_DECISIONS[kind] });
      }
      return route.fulfill({ status: 200, json: baseLists[kind] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });

  // The IdP's PKCE endpoints, used by the production-boot viewer pass.
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const stateParam = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      state.appOrigin + '/?code=fake-pkce-code&state=' + encodeURIComponent(stateParam);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  return state;
}

// Re-visit #/log the SPA way: leave the view, then come back. Every
// switch into #/log re-activates the log, which re-fetches the three
// decision lists from the (mode-switched) mocks. A page.goto to the
// same #/log hash would be a same-document no-op — no hashchange, no
// re-fetch — so the mode-switched data would never land.
async function revisitLog(page) {
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await page.evaluate(() => {
    window.location.hash = '#/log';
  });
}

