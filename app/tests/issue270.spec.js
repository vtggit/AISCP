// Mock every /api/* call the queue (and the shell around it) makes.
async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const listGets = [];
  const historyGets = [];
  const history = {
    'N2|S2': [DRIFT_ROWS[3].decision],
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift') {
      listGets.push({ kind: 'drift', query: url.search });
      return route.fulfill({ status: 200, json: DRIFT_ROWS });
    }
    if (path === '/api/excess') {
      listGets.push({ kind: 'excess', query: url.search });
      return route.fulfill({ status: 200, json: EXCESS_ROWS });
    }
    if (path === '/api/stockout') {
      listGets.push({ kind: 'stockout', query: url.search });
      return route.fulfill({ status: 200, json: STOCKOUT_ROWS });
    }
    if (path === '/api/drift/decisions') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      historyGets.push({ item, site });
      return route.fulfill({
        status: 200,
        json: history[(item || '') + '|' + (site || '')] || [],
      });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { listGets, historyGets };
}

test('issue270 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const { listGets } = await mockQueueApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  // --- boot: development sign-in card, straight onto #/queue ----------
  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-queue')).toBeVisible();

  await expect.poll(() => listGets.some((g) => g.kind === 'drift')).toBe(true);

  // --- the To decide list: the "#" column, no bare dashes -------------
  // Ranked rows, then the two no_reorder_point rows, then the unknown-
  // money drift row; the first row (M1) is selected by default.
  const rows = page.locator('.q-row');
  await expect(rows).toHaveCount(4);
  expect(
    await rows.evaluateAll((rs) => rs.map((r) => r.getAttribute('data-item'))),
  ).toEqual(['M1', 'M2', 'N1', 'U1']);
  await expect(page.locator('.q-row[data-item="M1"]')).toHaveAttribute('aria-current', 'true');

  await expect(page.locator('.q-row[data-item="M1"] .q-rank')).toHaveText('1');
  await expect(page.locator('.q-row[data-item="M2"] .q-rank')).toHaveText('2');
  await expect(page.locator('.q-row[data-item="N1"] .q-rank')).toHaveText('No ROP');
  await expect(page.locator('.q-row[data-item="U1"] .q-rank')).toHaveText('No cost');
  expect(
    await page.locator('.q-row .q-rank').evaluateAll((els) => els.map((el) => el.textContent)),
  ).toEqual(['1', '2', 'No ROP', 'No cost']);

  // --- the divider: text, count and position --------------------------
  const divider = page.locator('.q-group');
  await expect(divider).toHaveCount(1);
  await expect(divider).toHaveText(DIVIDER_PREFIX + '1)');
  // A div (never a .q-row), and the .q-row counts do not include it.
  expect(
    await divider.evaluate((el) => ({
      tag: el.tagName,
      isQRow: el.classList.contains('q-row'),
    })),
  ).toEqual({ tag: 'DIV', isQRow: false });
  await expect(page.locator('.q-row.q-group')).toHaveCount(0);
  // Full width: the same width as the rows it sits between.
  const widths = await page
    .locator('.q-row[data-item="M1"], .q-group')
    .evaluateAll((els) => els.map((el) => el.getBoundingClientRect().width));
  expect(widths[1]).toBeCloseTo(widths[0], 0);
  // Directly before the first no_reorder_point row in the list.
  expect(
    await page.locator('.q-row[data-item="N1"]').evaluate((el) => {
      const prev = el.previousElementSibling;
      return {
        prevTag: prev ? prev.tagName : null,
        prevClass: prev ? prev.getAttribute('class') : null,
        prevText: prev ? prev.textContent : null,
        prevFollowedByRow: !!(prev && prev.nextElementSibling === el),
      };
    }),
  ).toEqual({
    prevTag: 'DIV',
    prevClass: 'q-group',
    prevText: DIVIDER_PREFIX + '1)',
    prevFollowedByRow: true,
  });

  // --- the divider is not focusable and not selectable ----------------
  const dividerProps = await divider.evaluate((el) => ({
    tabIndex: el.tabIndex,
    userSelect: getComputedStyle(el).userSelect,
  }));
  expect(dividerProps.tabIndex).toBe(-1);
  expect(dividerProps.userSelect).toBe('none');
  // A Tab walk over the page never focuses the divider.
  const focused = [];
  for (let i = 0; i < 50; i++) {
    await page.keyboard.press('Tab');
    focused.push(
      await page.evaluate(() => {
        const el = document.activeElement;
        return el
          ? el.tagName + (el.getAttribute('class') ? '.' + String(el.getAttribute('class')).split(/\s+/)[0] : '')
          : '';
      }),
    );
  }
  expect(focused.some((hit) => hit.includes('q-group'))).toBe(false);
  // Clicking it selects no row: the selection stays on M1.
  await divider.click();
  await expect(page.locator('.q-row[data-item="M1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-detail-title')).toHaveText('M1');

  // --- the detail of a no_reorder_point row ---------------------------
  await page.click('.q-row[data-item="N1"]');
  await expect(page.locator('.q-row[data-item="N1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-detail-title')).toHaveText('N1');
  await expect(page.locator('.q-detail-kind')).toHaveText('Reorder point \u00b7 not ranked');
  await expect(page.locator('.q-row[data-item="N1"] .q-figure')).toHaveText('not set → 180');
  await expect(page.locator('.q-why-text')).toHaveText(N1_WHY);

  // --- the count follows the filters ----------------------------------
  await page.click('.q-chip[data-filter="decided"]');
  await expect(page.locator('.q-row')).toHaveCount(1);
  expect(await page.locator('.q-row').evaluateAll((rs) => rs.map((r) => r.getAttribute('data-item')))).toEqual([
    'N2',
  ]);
  await expect(page.locator('.q-group')).toHaveCount(1);
  await expect(page.locator('.q-group')).toHaveText(DIVIDER_PREFIX + '1)');
  // Still directly before the first no_reorder_point row now shown.
  expect(
    await page.locator('.q-row[data-item="N2"]').evaluate((el) => {
      const prev = el.previousElementSibling;
      return prev ? prev.getAttribute('class') : null;
    }),
  ).toBe('q-group');

  await page.click('.q-chip[data-filter="all"]');
  await expect(page.locator('.q-row')).toHaveCount(5);
  expect(
    await page.locator('.q-row').evaluateAll((rs) => rs.map((r) => r.getAttribute('data-item'))),
  ).toEqual(['M1', 'M2', 'N1', 'N2', 'U1']);
  await expect(page.locator('.q-group')).toHaveCount(1);
  await expect(page.locator('.q-group')).toHaveText(DIVIDER_PREFIX + '2)');
  expect(
    await page.locator('.q-row[data-item="N1"]').evaluate((el) => {
      const prev = el.previousElementSibling;
      return prev ? prev.getAttribute('class') : null;
    }),
  ).toBe('q-group');

  // --- the other two tabs are unchanged --------------------------------
  // No divider, and the unranked rows keep the bare dash in the "#"
  // column — the drift-only "No ROP"/"No cost" labels never leak into
  // these tabs (EX1 and SY1 both mock rank: null).
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-row')).toHaveCount(1);
  await expect(page.locator('.q-row .q-item-site')).toHaveText('EX1 · S1');
  await expect(page.locator('.q-group')).toHaveCount(0);
  await expect(page.locator('.q-row[data-item="EX1"] .q-rank')).toHaveText('\u2014');
  expect(
    await page.locator('.q-row[data-item="EX1"] .q-rank').evaluate((el) => el.getAttribute('class')),
  ).toBe('q-rank');
  expect(
    await page.locator('.q-row .q-rank').evaluateAll((els) => els.map((el) => el.textContent)),
  ).not.toContain('No ROP');
  expect(
    await page.locator('.q-row .q-rank').evaluateAll((els) => els.map((el) => el.textContent)),
  ).not.toContain('No cost');

  await page.click('.q-tab[data-kind="stockout"]');
  await expect(page.locator('.q-row')).toHaveCount(1);
  await expect(page.locator('.q-row .q-item-site')).toHaveText('SY1 · S1');
  await expect(page.locator('.q-group')).toHaveCount(0);
  await expect(page.locator('.q-row[data-item="SY1"] .q-rank')).toHaveText('\u2014');
  expect(
    await page.locator('.q-row[data-item="SY1"] .q-rank').evaluate((el) => el.getAttribute('class')),
  ).toBe('q-rank');
  expect(
    await page.locator('.q-row .q-rank').evaluateAll((els) => els.map((el) => el.textContent)),
  ).not.toContain('No ROP');
  expect(
    await page.locator('.q-row .q-rank').evaluateAll((els) => els.map((el) => el.textContent)),
  ).not.toContain('No cost');
});
