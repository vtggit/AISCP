// Mock every /api/* call the Overview, the queue (and the shell around
// them) make. No decision is recorded in this proof: the lists and the
// summary are static, and every history read comes back empty.
async function mockQuantityApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      const kind = path.slice('/api/'.length);
      const rows =
        kind === 'drift' ? DRIFT_ROWS : kind === 'excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (/^\/api\/(drift|excess|stockout)\/decisions$/.test(path)) {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

test('issue271 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  await mockQuantityApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  // --- boot: development sign-in card, straight onto #/overview --------
  await page.goto('/#/overview');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // --- the Overview's attention list: largest money first --------------
  // X1 ($26,152), then D1 ($17,585), then Y1 ($350); D2 has no money and
  // comes last.
  const attention = page.locator('#ov-attention-body .attn-row');
  await expect(attention).toHaveCount(4);
  const items = await attention.evaluateAll((rows) =>
    rows.map((row) => row.querySelector('.attn-item').textContent.trim()),
  );
  expect(items).toEqual(['X1 · S1', 'D1 · S1', 'Y1 · S1', 'D2 · S2']);

  // The excess row's 10460.72 excess units read "10,461 units" — whole
  // number, thousands separator — in the Overview line.
  await expect(attention.nth(0).locator('.attn-why')).toHaveText(
    '10,461 units beyond justified cover',
  );
  await expect(attention.nth(0).locator('.attn-money')).toHaveText('$26,152');

  // The drift row's -1465.42 gap is shown as its absolute value, whole,
  // with a separator: no signed decimal next to the direction word.
  await expect(attention.nth(1).locator('.attn-why')).toHaveText(
    'ERP point 1,465 units below the recommended point',
  );
  await expect(attention.nth(1).locator('.attn-money')).toHaveText('$17,585');

  // The stockout row's 12.94 lead time shows one decimal.
  await expect(attention.nth(2).locator('.attn-why')).toHaveText(
    '67% chance of stockout within 12.9 days',
  );

  // A null units_gap keeps its direction word and shows "—".
  await expect(attention.nth(3).locator('.attn-why')).toHaveText(
    'ERP point — units below the recommended point',
  );
  await expect(attention.nth(3).locator('.attn-money')).toHaveText('—');

  // No attention line combines a signed gap with a direction word, and
  // no raw wire decimal leaks onto the page.
  const attentionText = await page.locator('#ov-attention-body').textContent();
  expect(attentionText).not.toMatch(/-\s?\d/);
  expect(attentionText).not.toContain('1465.42');
  expect(attentionText).not.toContain('10460.72');

  // --- the Work queue: the drift row's Why sentence and its inputs ----
  await page.evaluate(() => {
    window.location.hash = '#/queue?kind=drift&item=D1&site=S1';
  });
  await expect(page.locator('.q-row[data-item="D1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-detail-title')).toHaveText('D1');

  // The list's figure column: whole numbers, separators.
  await expect(page.locator('.q-row[data-item="D1"]').locator('.q-figure')).toHaveText(
    '980 → 2,445',
  );
  // The figure tiles agree.
  await expect(page.locator('.q-figure-value').nth(0)).toHaveText('980');
  await expect(page.locator('.q-figure-value').nth(1)).toHaveText('2,445');

  // The Why sentence: absolute gap, whole, with a separator.
  await expect(page.locator('.q-why-text')).toHaveText(
    'The ERP reorder point sits 1,465 units below the recommended point.',
  );

  // The inputs: whole unit values with separators, two-decimal k, whole
  // dollars for the money.
  const driftInputs = page.locator('.q-input');
  await expect(driftInputs).toHaveCount(5);
  expect(
    await driftInputs.evaluateAll((els) =>
      els.map((el) => el.querySelector('dt').textContent),
    ),
  ).toEqual([
    'Average lead-time demand',
    'Lead-time demand variability (std dev)',
    'Service level the ERP point gives (k)',
    'Recommended safety stock',
    'Money at stake',
  ]);
  await expect(driftInputs.nth(0).locator('dd')).toHaveText('1,235');
  await expect(driftInputs.nth(1).locator('dd')).toHaveText('250');
  await expect(driftInputs.nth(2).locator('dd')).toHaveText('1.99');
  await expect(driftInputs.nth(3).locator('dd')).toHaveText('501');
  await expect(driftInputs.nth(4).locator('dd')).toHaveText('$17,585');

  // The null-gap row D2: its service factor input is null and shows "—".
  await page.click('.q-row[data-item="D2"]');
  await expect(page.locator('.q-detail-title')).toHaveText('D2');
  await expect(page.locator('.q-why-text')).toHaveText(
    'The ERP reorder point sits — units below the recommended point.',
  );
  const d2Inputs = page.locator('.q-input');
  await expect(d2Inputs.nth(0).locator('dd')).toHaveText('300');
  await expect(d2Inputs.nth(2).locator('dd')).toHaveText('—');

  // --- the excess tab: the list's figure column for 10460.72 units ----
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-row[data-item="X1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-row[data-item="X1"]').locator('.q-figure')).toHaveText(
    '10,461 units',
  );
  await expect(page.locator('.q-figure-value').nth(0)).toHaveText('12,000');
  await expect(page.locator('.q-figure-value').nth(1)).toHaveText('10,461');
  await expect(page.locator('.q-why-text')).toHaveText(
    'Stock on hand is 10,461 units beyond justified cover.',
  );
  const excessInputs = page.locator('.q-input');
  await expect(excessInputs).toHaveCount(4);
  await expect(excessInputs.nth(0).locator('dd')).toHaveText('12,000');
  await expect(excessInputs.nth(1).locator('dd')).toHaveText('1,539');
  await expect(excessInputs.nth(2).locator('dd')).toHaveText('18.3');
  await expect(excessInputs.nth(3).locator('dd')).toHaveText('$26,152');

  // --- the stockout tab: days with one decimal, units whole -----------
  await page.click('.q-tab[data-kind="stockout"]');
  await expect(page.locator('.q-row[data-item="Y1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-why-text')).toHaveText(
    '67% chance of stockout within 12.9 days.',
  );
  const stockoutInputs = page.locator('.q-input');
  await expect(stockoutInputs).toHaveCount(4);
  expect(
    await stockoutInputs.evaluateAll((els) =>
      els.map((el) => el.querySelector('dt').textContent),
    ),
  ).toEqual(['Lead time', 'Days of cover', 'Expected units short', 'Money at risk']);
  await expect(stockoutInputs.nth(0).locator('dd')).toHaveText('12.9 days');
  await expect(stockoutInputs.nth(1).locator('dd')).toHaveText('0.7');
  await expect(stockoutInputs.nth(2).locator('dd')).toHaveText('35');
  await expect(stockoutInputs.nth(3).locator('dd')).toHaveText('$350');
});
