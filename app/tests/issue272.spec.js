  expect(await inputLabels(page)).toEqual([
    'Lead time',
    'Days of cover',
    'Expected units short',
    'Money at risk',
  ]);
  await expectSingleColumnList(page);

  // --- 390x844: the stacked narrow layout ----------------------------
