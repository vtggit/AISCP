  // --- excess: the previous labels, the same one-column contract -----
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-detail-title')).toHaveText('X3');
  expect(await inputLabels(page)).toEqual([
    'On hand',
    'Justified units',
    'Months of cover',
    'Money tied up',
  ]);
  await expectSingleColumnList(page);

  // --- stockout: the previous labels, the same one-column contract ---
