// Proving spec for AIERP issue #273 — the Decision log's empty state.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin, at 1440x900:
//   * with no decisions the Decision log card centres an empty state
//     both horizontally and vertically: it shows the heading
//     "No decisions recorded yet", the sentence "Decisions you accept,
//     dismiss or snooze in the Work queue appear here, newest first."
//     and a link reading "Open the Work queue" to #/queue, and the
//     empty state's centre lies within 10% of the card's centre on
//     both axes;
//   * following the link shows the Work queue at #/queue without a
//     page reload: a window marker set just before the click
//     (anything a full load would clear) survives it, and the queue
//     renders from the mocked lists;
//   * with one decision the table renders and the empty state is
//     absent — nothing changes when decisions exist.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue273 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

test.setTimeout(90000);

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

// The single decision of the "decisions exist" pass: one drift row,
// the other two lists empty.
const ONE_DECISION = {
  id: 'dec-273',
  item_code: 'D1',
  site_code: 'S1',
  decision: 'accepted',
  reason: null,
  snooze_until: null,
  as_of: '2026-10-09',
  recommended_reorder_point_units: 210,
  current_reorder_point: 290,
  money_at_stake: 18720.5,
  decided_by: 'planner1',
  decided_at: '2026-10-09T08:15:00+00:00',
};

// Mock every /api/* call the shell and the two views make. The three
// decision list endpoints answer from the mutable scenario state
// ('empty' or 'one'); the three queue list endpoints answer empty so
// the Work queue the link follows lands on renders its empty note;
// anything else answers 404 — no view in this proof reads it.
async function mockLogApi(page) {
  const state = {
    decisionMode: 'empty', // 'empty' | 'one'
    decisionGets: [],
    queueGets: [],
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      if (request.method() !== 'GET') {
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      state.decisionGets.push({ kind: decisions[1], query: url.search, mode: state.decisionMode });
      if (state.decisionMode === 'one' && decisions[1] === 'drift') {
        return route.fulfill({ status: 200, json: [ONE_DECISION] });
      }
      return route.fulfill({ status: 200, json: [] });
    }
    const list = /^\/api\/(drift|excess|stockout)$/.exec(path);
    if (list) {
      state.queueGets.push({ kind: list[1], query: url.search });
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return state;
}

test('issue273 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const api = await mockLogApi(page);

  // --- boot: development sign-in card, straight onto #/log ------------
  await page.goto('/#/log');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-log')).toBeVisible();

  // The three decision lists, each with limit=1000, all empty.
  await expect.poll(() => api.decisionGets.length).toBe(3);
  expect(api.decisionGets.map((g) => g.kind).sort()).toEqual(['drift', 'excess', 'stockout']);
  for (const get of api.decisionGets) {
    expect(get.query).toBe('?limit=1000');
    expect(get.mode).toBe('empty');
  }

  // --- the empty state: heading, sentence, link ----------------------
  await expect(page.locator('#view-log .card')).toHaveCount(1);
  await expect(page.locator('.log-empty-title')).toHaveText('No decisions recorded yet');
  await expect(page.locator('.log-empty-text')).toHaveText(
    'Decisions you accept, dismiss or snooze in the Work queue appear here, newest first.',
  );
  const link = page.locator('.log-empty-link');
  await expect(link).toHaveText('Open the Work queue');
  expect(await link.getAttribute('href')).toBe('#/queue');
  // No table while there are no decisions.
  expect(await page.locator('.log-table').count()).toBe(0);

  // --- centred on both axes at 1440x900 ------------------------------
  // The empty state's centre is the centre of the heading/sentence/
  // link block; it must lie within 10% of the card's centre on both
  // axes (a horizontal-only, or top-aligned, centring fails the y or
  // the x bound).
  const centres = await page.evaluate(() => {
    const card = document.querySelector('.log-card').getBoundingClientRect();
    const boxes = [
      document.querySelector('.log-empty-title'),
      document.querySelector('.log-empty-text'),
      document.querySelector('.log-empty-link'),
    ].map((el) => el.getBoundingClientRect());
    const left = Math.min(...boxes.map((box) => box.left));
    const right = Math.max(...boxes.map((box) => box.right));
    const top = Math.min(...boxes.map((box) => box.top));
    const bottom = Math.max(...boxes.map((box) => box.bottom));
    return {
      cardCx: card.left + card.width / 2,
      cardCy: card.top + card.height / 2,
      cardW: card.width,
      cardH: card.height,
      stateCx: (left + right) / 2,
      stateCy: (top + bottom) / 2,
    };
  });
  expect(centres.cardW).toBeGreaterThan(0);
  expect(centres.cardH).toBeGreaterThan(0);
  expect(Math.abs(centres.stateCx - centres.cardCx)).toBeLessThanOrEqual(0.1 * centres.cardW);
  expect(Math.abs(centres.stateCy - centres.cardCy)).toBeLessThanOrEqual(0.1 * centres.cardH);

  // --- following the link: #/queue, no reload ------------------------
  // A full page load would clear every window property: the marker
  // set here must still be set after the click, proving the view
  // switch was a hash navigation, not a reload.
  await page.evaluate(() => {
    window.__issue273_no_reload = 'marker-set-before-click';
  });
  await link.click();
  await expect(page.locator('#view-queue')).toBeVisible();
  expect(await page.evaluate(() => window.location.hash)).toBe('#/queue');
  expect(await page.evaluate(() => window.__issue273_no_reload)).toBe('marker-set-before-click');
  // The Work queue itself rendered, from the mocked (empty) lists.
  await expect(page.locator('.q-list-empty')).toBeVisible();
  expect(api.queueGets.map((g) => g.kind).sort()).toEqual(['drift', 'excess', 'stockout']);
  for (const get of api.queueGets) {
    expect(get.query).toBe(
      get.kind === 'drift'
        ? '?limit=1000&include_decided=true'
        : '?limit=1000&include_decided=true&include_remedy=true',
    );
  }

  // --- one decision: the table renders, the empty state is gone ------
  api.decisionMode = 'one';
  const getsBefore = api.decisionGets.length;
  // One hash hop re-activates the log (hashchange -> Log.activate()),
  // which re-fetches the three decision lists from the mocks.
  await page.evaluate(() => {
    window.location.hash = '#/log';
  });
  await expect(page.locator('#view-log')).toBeVisible();
  await expect(page.locator('.log-table')).toBeVisible();
  await expect(page.locator('.log-row')).toHaveCount(1);
  expect(await page.locator('.log-empty').count()).toBe(0);
  expect(api.decisionGets.length).toBe(getsBefore + 3);
  expect(api.decisionGets.slice(-3).map((g) => g.mode)).toEqual(['one', 'one', 'one']);
  // The single decision rendered from the API data.
  await expect(page.locator('.log-row .log-item-link')).toHaveText('D1 \u00b7 S1');
  await expect(page.locator('.log-row .badge')).toHaveText('Accepted');
});
