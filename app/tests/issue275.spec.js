// The GET /api/settings body for one pair of setting values, in the
// shape the backend serves (every registered setting, ordered by key).
function settingsBody(requireActionChoice, defaultFilter) {
  return [
    {
      key: 'decisions.require_action_choice',
      scope: 'system',
      type: 'boolean',
      allowed: null,
      default: true,
      description:
        'Accept on an excess or stockout row stays disabled until an action is chosen.',
      value: requireActionChoice,
      source: 'default',
      editable: true,
      updated_by: null,
      updated_at: null,
    },
    {
      key: 'queue.default_filter',
      scope: 'user',
      type: 'enum',
      allowed: ['open', 'decided', 'all'],
      default: 'open',
      description: 'The filter the Work queue opens with.',
      value: defaultFilter,
      source: 'default',
      editable: true,
      updated_by: null,
      updated_at: null,
    },
  ];
}

// Mock every /api/* call the queue (and the shell around it) makes.
// The settings response is parameterised per sub-scenario; the decision
// endpoints record their POSTs.
async function mockQueueApi(page, { requireActionChoice, defaultFilter, settingsStatus }) {
  const api = {
    posted: [],
    settingsGets: 0,
    listGets: [],
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (path === '/api/settings') {
      api.settingsGets += 1;
      if (settingsStatus === 200) {
        return route.fulfill({
          status: 200,
          json: settingsBody(requireActionChoice, defaultFilter),
        });
      }
      return route.fulfill({
        status: settingsStatus,
        json: { detail: 'Internal Server Error' },
      });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      api.listGets.push(path.slice('/api/'.length));
      const rows =
        path === '/api/drift' ? DRIFT_ROWS : path === '/api/excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      if (request.method() === 'POST') {
        const body = request.postDataJSON();
        api.posted.push({ kind: decisions[1], path, body });
        return route.fulfill({
          status: 201,
          json: { ...body, decided_by: 'planner1', decided_at: '2026-10-09T07:30:00+00:00' },
        });
      }
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

// Boot one fresh context onto #/queue with the given settings and sign
// in through the development token card as the admin.
async function openQueue(browser, settings) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const api = await mockQueueApi(page, settings);
  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  return { context, page, api };
}

test('issue275 freeform', async ({ page, browser }) => {
  // --- the default: the choice of action is required -------------------
  {
    const api = await mockQueueApi(page, {
      requireActionChoice: true,
      defaultFilter: 'open',
      settingsStatus: 200,
    });
    await page.goto('/#/queue');
    await expect(page.locator('#signin-form')).toBeVisible();
    await page.fill('#token-input', 'dev-admin-token');
    await page.click('#signin-button');
    await expect(page.locator('#app')).toBeVisible();
    await expect(page.locator('#user-name')).toHaveText('planner1');

    // The queue reads its settings once when it activates.
    await expect.poll(() => api.settingsGets).toBe(1);
    await expect(page.locator('.q-row')).toHaveCount(1);
    await expect(page.locator('.q-detail-title')).toHaveText('D1');

    // queue.default_filter "open": the To decide chip is the one pressed.
    await expect(page.locator('.q-chip[data-filter="open"]')).toHaveAttribute(
      'aria-pressed',
      'true',
    );
    await expect(page.locator('.q-chip[data-filter="decided"]')).toHaveAttribute(
      'aria-pressed',
      'false',
    );
    await expect(page.locator('.q-chip[data-filter="all"]')).toHaveAttribute(
      'aria-pressed',
      'false',
    );

    // Reorder-point rows are unaffected: no action options, Accept stays
    // enabled with its own label.
    await expect(page.locator('.q-action-pick')).toHaveCount(0);
    await expect(page.locator('#q-accept')).toHaveText('Accept new reorder point');
    await expect(page.locator('#q-accept')).toBeEnabled();

    // Excess: the pane opens with no action option pressed ...
    await page.click('.q-tab[data-kind="excess"]');
    await expect(page.locator('.q-row')).toHaveCount(2);
    await expect(page.locator('.q-detail-title')).toHaveText('X1');
    const excessActions = page.locator('.q-action-pick .q-option');
    await expect(excessActions).toHaveCount(3);
    expect(
      await excessActions.evaluateAll((els) => els.map((el) => el.getAttribute('aria-pressed'))),
    ).toEqual(['false', 'false', 'false']);
    // ... and Accept is disabled with its "choose an action" text.
    await expect(page.locator('#q-accept')).toHaveText('Accept: choose an action');
    await expect(page.locator('#q-accept')).toBeDisabled();

    // Clicking the disabled Accept sends no request.
    await page.click('#q-accept', { force: true });
    expect(api.posted.length).toBe(0);

    // Pressing Reduce enables Accept with the action's label ...
    await page.click('.q-action-pick .q-option[data-action="reduce"]');
    expect(
      await excessActions.evaluateAll((els) => els.map((el) => el.getAttribute('aria-pressed'))),
    ).toEqual(['false', 'true', 'false']);
    await expect(page.locator('#q-accept')).toHaveText('Accept: Reduce');
    await expect(page.locator('#q-accept')).toBeEnabled();
    // ... and Accept posts the chosen action.
    await page.click('#q-accept');
    await expect.poll(() => api.posted.length).toBe(1);
    expect(api.posted[0].path).toBe('/api/excess/decisions');
    expect(api.posted[0].body).toEqual({
      item_code: 'X1',
      site_code: 'S1',
      decision: 'accepted',
      action: 'reduce',
    });

    // Switching rows clears the choice: the next row opens with no
    // option pressed and Accept disabled again.
    await page.click('.q-row[data-item="X2"]');
    await expect(page.locator('.q-detail-title')).toHaveText('X2');
    expect(
      await excessActions.evaluateAll((els) => els.map((el) => el.getAttribute('aria-pressed'))),
    ).toEqual(['false', 'false', 'false']);
    await expect(page.locator('#q-accept')).toHaveText('Accept: choose an action');
    await expect(page.locator('#q-accept')).toBeDisabled();
    expect(api.posted.length).toBe(1);
  }

  // --- the opt-out: the first action is pre-selected --------------------
  {
    const { context, page: pageB, api: apiB } = await openQueue(browser, {
      requireActionChoice: false,
      defaultFilter: 'open',
      settingsStatus: 200,
    });
    await expect.poll(() => apiB.settingsGets).toBe(1);
    await expect(pageB.locator('.q-row')).toHaveCount(1);
    await pageB.click('.q-tab[data-kind="excess"]');
    await expect(pageB.locator('.q-detail-title')).toHaveText('X1');
    const actionsB = pageB.locator('.q-action-pick .q-option');
    expect(
      await actionsB.evaluateAll((els) => els.map((el) => el.getAttribute('aria-pressed'))),
    ).toEqual(['true', 'false', 'false']);
    await expect(pageB.locator('#q-accept')).toHaveText('Accept: Stop replenishing');
    await expect(pageB.locator('#q-accept')).toBeEnabled();
    await context.close();
  }

  // --- queue.default_filter "all": the queue opens with the All chip ----
  {
    const { context, page: pageC, api: apiC } = await openQueue(browser, {
      requireActionChoice: true,
      defaultFilter: 'all',
      settingsStatus: 200,
    });
    await expect.poll(() => apiC.settingsGets).toBe(1);
    await expect(pageC.locator('.q-row')).toHaveCount(1);
    await expect(pageC.locator('.q-chip[data-filter="all"]')).toHaveAttribute(
      'aria-pressed',
      'true',
    );
    await expect(pageC.locator('.q-chip[data-filter="open"]')).toHaveAttribute(
      'aria-pressed',
      'false',
    );
    // "all" really slices in the decided rows: the accepted excess row X3
    // shows up in the list.
    await pageC.click('.q-tab[data-kind="excess"]');
    await expect(pageC.locator('.q-row')).toHaveCount(3);
    await expect(pageC.locator('.q-row[data-item="X3"] .badge')).toHaveText('Accepted · Reduce');
    await context.close();
  }

  // --- a 500 from /api/settings: the defaults still load the queue ------
  {
    const { context, page: pageD, api: apiD } = await openQueue(browser, {
      requireActionChoice: true,
      defaultFilter: 'open',
      settingsStatus: 500,
    });
    // The settings read was attempted ...
    await expect.poll(() => apiD.settingsGets).toBe(1);
    // ... and the queue loaded anyway, on the defaults: To decide ...
    await expect(pageD.locator('.q-row')).toHaveCount(1);
    await expect(pageD.locator('.q-detail-title')).toHaveText('D1');
    await expect(pageD.locator('.q-chip[data-filter="open"]')).toHaveAttribute(
      'aria-pressed',
      'true',
    );
    await expect(pageD.locator('.q-chip[data-filter="all"]')).toHaveAttribute(
      'aria-pressed',
      'false',
    );
    // ... and the action choice required on excess rows.
    await pageD.click('.q-tab[data-kind="excess"]');
    await expect(pageD.locator('.q-detail-title')).toHaveText('X1');
    expect(
      await pageD
        .locator('.q-action-pick .q-option')
        .evaluateAll((els) => els.map((el) => el.getAttribute('aria-pressed'))),
    ).toEqual(['false', 'false', 'false']);
    await expect(pageD.locator('#q-accept')).toHaveText('Accept: choose an action');
    await expect(pageD.locator('#q-accept')).toBeDisabled();
    await context.close();
  }
});
