  await expect(systemRow.locator('.settings-row-error')).toHaveText(detail422);
  // The previous value (false, set by the earlier PUT) is back.
  await expect(sysSwitch).toHaveAttribute('aria-checked', 'false');
  await expect(systemRow.locator('.settings-source')).toHaveText('Set by planner1 on 2026-10-09');
  await expect(systemRow.locator('.settings-reset')).toHaveCount(1);

  // --- the layout: no page scroll at 1440x900 -------------------------
