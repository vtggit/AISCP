test('issue276 freeform (viewer)', async ({ page }) => {
  // NON-ADMIN pass: boot the production way — the token arrives in the
  // URL hash the way production used to deliver it, /api/auth/config
  // answers production, /api/auth/me answers for a user with only the
  // "user" role. The fragment stays inert, the PKCE round-trip
  // establishes the session, and the page still renders.
  page.setViewportSize({ width: 1440, height: 900 });
  const allRequests = [];
  page.on('request', (request) => allRequests.push(request));
  const meRequests = [];
  let appOrigin = null;
  const api = { settingsGets: 0 };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin === null) {
      appOrigin = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: PROD_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(request);
      return route.fulfill({ status: 200, json: VIEWER_ME });
    }
    if (url.pathname === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: viewerEntries() });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp = appOrigin + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  await page.goto('/#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect(page.locator('#view-overview')).toBeVisible();
  await expect(page.locator('#signout-button')).toBeVisible();

  // ... the session is the token the IdP issued, not the fragment's ...
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => meRequests.length).toBeGreaterThan(0);
  expect(meRequests[0].headers()['authorization']).toBe('Bearer pkce-viewer-token');
  expect(page.url()).not.toContain('access_token');

  // ... and the fragment's token was never sent anywhere.
  const offenders = allRequests.filter(
    (request) => request.headers()['authorization'] === 'Bearer viewer-token-abc',
  );
  expect(offenders).toEqual([]);

  // The settings view renders for the viewer: both cards, one row each.
  await page.click('.nav-btn[data-view="settings"]');
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/settings');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);
  const systemCard = page.locator('.settings-card[data-scope="system"]');
  const personalCard = page.locator('.settings-card[data-scope="user"]');
  await expect(systemCard).toBeVisible();
  await expect(personalCard).toBeVisible();
  await expect(systemCard.locator('h2')).toHaveText('System');
  await expect(personalCard.locator('h2')).toHaveText('Personal');
  const systemRow = page.locator('.settings-row[data-key="decisions.require_action_choice"]');
  const userRow = page.locator('.settings-row[data-key="queue.default_filter"]');
  await expect(systemRow).toBeVisible();
  await expect(userRow).toBeVisible();
  await expect(systemRow.locator('.settings-source')).toHaveText('Set by planner1 on 2026-10-09');
  await expect(userRow.locator('.settings-source')).toHaveText('Set by viewer1 on 2026-10-08');

  // The admin-only control is absent for a non-admin: the system row's
  // control and its Reset are disabled and the row reads the note ...
  const sysSwitch = systemRow.locator('.settings-switch');
  await expect(sysSwitch).toBeDisabled();
  await expect(systemRow.locator('.settings-reset')).toBeDisabled();
  await expect(systemRow.locator('.settings-row-note')).toHaveText('Only an admin can change this.');

  // ... while the personal row stays fully editable.
  const enabledChoices = await userRow
    .locator('.settings-choice')
    .evaluateAll((buttons) => buttons.filter((b) => !b.disabled).length);
  expect(enabledChoices).toBe(3);
  await expect(userRow.locator('.settings-choice[data-value="decided"]')).toHaveAttribute(
    'aria-pressed',
    'true',
  );
  await expect(userRow.locator('.settings-reset')).not.toBeDisabled();
  await expect(userRow.locator('.settings-row-note')).toHaveCount(0);

  // The production-boot shell fills exactly the viewport: no page
  // scroll at 1440x900.
  const layout = await page.evaluate(() => ({
    docHeight: document.documentElement.scrollHeight,
    viewport: window.innerHeight,
  }));
  expect(layout.docHeight).toBe(layout.viewport);
});
