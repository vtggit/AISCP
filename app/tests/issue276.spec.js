  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/settings');
  expect(await page.evaluate(() => window.__noReloadMark)).toBe('issue276');

  // The view is active, the others are not, the header follows the view.
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect(page.locator('#view-overview')).not.toBeVisible();
  await expect(page.locator('#view-log')).not.toBeVisible();
  await expect(page.locator('#page-title')).toHaveText('Settings');

  // --- the view reads GET /api/settings and shows both cards ----------
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);
  const systemCard = page.locator('.settings-card[data-scope="system"]');
  const personalCard = page.locator('.settings-card[data-scope="user"]');
  await expect(systemCard).toBeVisible();
  await expect(personalCard).toBeVisible();
