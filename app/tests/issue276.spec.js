// Proving spec for AIERP issue #276 — the Settings view (#/settings).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]), at 1440x900:
//   * the sidebar gains a "Settings" item after "Decision log" that
//     opens #/settings without a page reload;
//   * the view reads GET /api/settings and shows the two cards, System
//     (scope "system") and Personal (scope "user"), one row per
//     setting: the description, a switch (role="switch", aria-checked)
//     for the boolean, one aria-pressed button per allowed value for
//     the enum — To decide, Decided and All for queue.default_filter,
//     — the source ("Default" / "Set by <updated_by> on <date>") and
//     "Reset to default" only while the value differs from the default;
//   * toggling the boolean PUTs {"value": false} to
//     /api/settings/decisions.require_action_choice and the row updates
//     from the response (switch off, source "Set by planner1 on
//     2026-10-09", Reset appears);
//   * choosing All PUTs {"value": "all"} to
//     /api/settings/queue.default_filter and the row updates (All
//     pressed, source text, Reset appears);
//   * Reset DELETEs the key and the row returns to "Default";
//   * a 422 from a change shows its `detail` inline under that row and
//     restores the previous value;
//   * a description containing <img src=x onerror=window.__pwned=1>
//     renders as text — window.__pwned stays undefined;
//   * no page scroll at 1440x900 and no horizontal page scroll at
//     390x844.
//
// The "(viewer)" pass boots the production way as a NON-ADMIN
// (role 'user'): the token arrives in the URL hash as
// #access_token=..., /api/auth/config answers production and
// /api/auth/me answers for the viewer — the fragment stays inert and
// the PKCE round-trip establishes the session. The page still renders,
// and the system setting is read-only: its control and its Reset are
// disabled and the row reads "Only an admin can change this."
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue276 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

