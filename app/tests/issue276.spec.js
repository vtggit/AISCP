  await expect(personalCard.locator('h2')).toHaveText('Personal');
  await expect(systemCard.locator('.settings-row')).toHaveCount(1);
  await expect(personalCard.locator('.settings-row')).toHaveCount(1);

  const systemRow = page.locator('.settings-row[data-key="decisions.require_action_choice"]');
  const userRow = page.locator('.settings-row[data-key="queue.default_filter"]');
  await expect(systemRow).toBeVisible();
  await expect(userRow).toBeVisible();

  // --- the boolean row: the switch, the source, no reset yet ----------
