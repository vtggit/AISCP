// Mock every /api/* call the shell, the log and the settings views
// make. The three decision lists and the settings list answer from
// the mock state; anything else (the overview and queue endpoints)
// answers 404 — those views are not the subject of this proof.
async function mockApi(page) {
  const state = {
    mode: 'base', // 'base' | 'hostile'
    decisionGets: 0,
    settingsGets: 0,
    postCount: 0,
  };
  const lists = {
    drift: DRIFT_DECISIONS,
    excess: EXCESS_DECISIONS,
    stockout: STOCKOUT_DECISIONS,
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      if (request.method() !== 'GET') {
        state.postCount += 1;
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      state.decisionGets += 1;
      return route.fulfill({ status: 200, json: lists[decisions[1]] });
    }
    if (path === '/api/settings') {
      if (request.method() !== 'GET') {
        state.postCount += 1;
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      state.settingsGets += 1;
      return route.fulfill({ status: 200, json: settingsEntries(state.mode) });
    }
    if (/^\/api\/settings\//.test(path)) {
      state.postCount += 1;
      return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return state;
}

// Re-visit a view the SPA way: leave it for the overview, then come
// back. Every switch into a view re-activates it, which re-fetches
// from the (mode-switched) mocks. A page.goto to the same hash would
// be a same-document no-op — no hashchange, no re-fetch.
async function revisit(page, hash) {
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  // The target hash goes in as an argument: the evaluate body runs in
  // the page, where the Node-side parameter is not in scope.
  await page.evaluate((target) => {
    window.location.hash = target;
  }, hash);
}

test('issue292 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const api = await mockApi(page);

  // --- boot: development sign-in card, straight onto #/log ------------
  await page.goto('/#/log');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-log')).toBeVisible();

  // The three decision lists, each with limit=1000.
  await expect.poll(() => api.decisionGets).toBe(3);

  // --- the log keeps its six columns ----------------------------------
  await expect(page.locator('#view-log .card')).toHaveCount(1);
  await expect(page.locator('.log-table thead th')).toHaveText([
    'List',
    'Item and site',
    'Decision',
    'Money',
    'Status',
    'Decided',
  ]);

  const rows = page.locator('.log-row');
  await expect(rows).toHaveCount(5);

  // Row 0 — the jason name: the Decided column shows the name, not
  // the subject, beside the decided_at date the column already had.
  {
    const row = rows.nth(0);
    await expect(row.locator('.log-decided-by')).toHaveText('jason');
    await expect(row.locator('.log-decided-at')).toHaveText('2026-10-09 09:00 UTC');
    expect(await row.textContent()).not.toContain('sub-292-jason');
  }

  // Row 1 — a null name (a row written before names were recorded):
  // the Decided column shows the decided_by subject.
  {
    const row = rows.nth(1);
    await expect(row.locator('.log-decided-by')).toHaveText('legacy-sub-292');
    await expect(row.locator('.log-decided-at')).toHaveText('2026-10-09 08:00 UTC');
  }

  // Row 2 — a whitespace-only name falls back to the subject too.
  await expect(rows.nth(2).locator('.log-decided-by')).toHaveText('sub-292-ws');

  // Row 3 — the payload name: literal text, never markup.
  {
    const row = rows.nth(3);
    await expect(row.locator('.log-decided-by')).toHaveText(XSS);
    expect(await row.evaluate((el) => el.innerHTML)).toContain(
      '&lt;img src=x onerror=window.__pwned=1&gt;',
    );
    expect(await row.locator('img').count()).toBe(0);
  }

  // Row 4 — an empty-string name falls back to the subject as well.
  await expect(rows.nth(4).locator('.log-decided-by')).toHaveText('sub-292-e');

  expect(await page.locator('#view-log img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // --- the Settings view: the source line carries the display name ----
  await page.evaluate(() => {
    window.location.hash = '#/settings';
  });
  await expect(page.locator('#view-settings')).toBeVisible();
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);

  const systemRow = page.locator('.settings-row[data-key="' + SYS_KEY + '"]');
  const userRow = page.locator('.settings-row[data-key="' + USR_KEY + '"]');
  await expect(systemRow).toBeVisible();
  await expect(userRow).toBeVisible();

  // The jason setting: "Set by jason on …", never its subject.
  {
    const source = systemRow.locator('.settings-source');
    await expect(source).toHaveText('Set by jason on 2026-10-09');
    expect(await source.textContent()).not.toContain('sub-292-jason');
  }

  // The null-name setting: "Set by <updated_by> on …".
  await expect(userRow.locator('.settings-source')).toHaveText(
    'Set by legacy-sub-292 on 2026-10-08',
  );

  // Nothing else in the rows changed: description, control, reset.
  await expect(systemRow.locator('.settings-desc')).toHaveText(
    'Accept on an excess or stockout row stays disabled until an action is chosen.',
  );
  await expect(systemRow.locator('.settings-switch')).toHaveAttribute('aria-checked', 'false');
  await expect(systemRow.locator('.settings-reset')).toHaveText('Reset to default');
  await expect(userRow.locator('.settings-choice')).toHaveCount(3);
  await expect(userRow.locator('.settings-reset')).toHaveText('Reset to default');

  // --- hostile mode: payload and whitespace names ---------------------
  api.mode = 'hostile';
  await revisit(page, '#/settings');
  await expect(systemRow).toBeVisible();

  // The payload name renders as text in the source line.
  {
    const source = systemRow.locator('.settings-source');
    await expect(source).toHaveText('Set by ' + XSS + ' on 2026-10-09');
    expect(await source.evaluate((el) => el.innerHTML)).toContain(
      '&lt;img src=x onerror=window.__pwned=1&gt;',
    );
    expect(await source.textContent()).not.toContain('sub-292-x');
    expect(await systemRow.locator('img').count()).toBe(0);
  }

  // The whitespace-only name falls back to updated_by.
  await expect(userRow.locator('.settings-source')).toHaveText('Set by sub-292-ws on 2026-10-07');

  // The payload never ran in either view.
  expect(await page.locator('#view-settings img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // Read-only: no decision or setting was ever written.
  expect(api.postCount).toBe(0);
});
