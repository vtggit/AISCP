// Proving spec for AIERP issue #301 — the Settings view: every save or
// reset ends with the row usable again.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (roles ["admin"]), at 1440x900, on the boolean
// switch (decisions.require_action_choice):
//   * a well-formed 200 still updates the row — the switch flips and
//     the source text becomes "Set by planner1 on 2026-10-09";
//   * each failure ends with the row usable again: the switch shows the
//     value it showed before the change, the switch and its Reset are
//     enabled again, and the inline message under the row is the
//     response's detail when there is one, else "The change could not
//     be saved. Try again.":
//       - a 500 with a detail;
//       - a 200 whose body is "ok" (not a setting entry);
//       - a 200 whose body is an object missing value;
//       - an aborted request (no HTTP answer at all);
//   * after the failures the row is still usable: a well-formed 200
//     updates it and a well-formed reset (DELETE) returns it to
//     "Default".
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue301 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs several sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

const SYS_KEY = 'decisions.require_action_choice';
const USR_KEY = 'queue.default_filter';
const SET_SOURCE = 'Set by planner1 on 2026-10-09';
const FALLBACK_MESSAGE = 'The change could not be saved. Try again.';
const DETAIL_500 = 'The settings store is unavailable.';

const SYS_DESCRIPTION =
  'Accept on an excess or stockout row stays disabled until an action is chosen.';

// Both registered settings, exactly the GET /api/settings shape: the
// boolean on its default (the switch starts ON, no Reset) and the enum
// on its default.
function settingsEntries() {
  return [
    {
      key: SYS_KEY,
      scope: 'system',
      type: 'boolean',
      allowed: null,
      default: true,
      description: SYS_DESCRIPTION,
      value: true,
      source: 'default',
      editable: true,
      updated_by: null,
      updated_by_name: null,
      updated_at: null,
    },
    {
      key: USR_KEY,
      scope: 'user',
      type: 'enum',
      allowed: ['open', 'decided', 'all'],
      default: 'open',
      description: 'The filter the Work queue opens with.',
      value: 'open',
      source: 'default',
      editable: true,
      updated_by: null,
      updated_by_name: null,
      updated_at: null,
    },
  ];
}

// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the admin. The settings mock is an echo like the
// real API: a PUT stores the body's value (source becomes the scope,
// planner1 is the changer) and a DELETE restores the default — both
// answering with the updated entry. `failNext` makes the NEXT PUT or
// DELETE answer in one of three failure shapes:
//   { kind: 'http', status, detail } — a 4xx/5xx with the given detail;
//   { kind: 'ok', body }              — a 200 whose body is `body`, a
//                                       raw string or a JSON value that
//                                       is not a setting entry;
//   { kind: 'abort' }                 — the request is aborted, so there
//                                       is no HTTP answer at all.
async function mockAdminApi(page) {
  const api = {
    settingsGets: 0,
    calls: [], // { method, key, body, contentType } for PUT/DELETE
    failNext: null,
    current: settingsEntries(),
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    const match = /^\/api\/settings\/([^/]+)$/.exec(path);
    if (match && (request.method() === 'PUT' || request.method() === 'DELETE')) {
      const key = decodeURIComponent(match[1]);
      const entry = api.current.find((e) => e.key === key);
      if (!entry) {
        return route.fulfill({ status: 404, json: { detail: 'Unknown setting: ' + key } });
      }
      const body = request.method() === 'PUT' ? request.postDataJSON() : null;
      api.calls.push({
        method: request.method(),
        key,
        body,
        contentType: request.headers()['content-type'] || null,
      });
      if (api.failNext) {
        const failure = api.failNext;
        api.failNext = null;
        if (failure.kind === 'abort') {
          return route.abort();
        }
        if (failure.kind === 'http') {
          return route.fulfill({ status: failure.status, json: { detail: failure.detail } });
        }
        // kind 'ok': a 200 whose body is not a setting entry.
        if (typeof failure.body === 'string') {
          return route.fulfill({ status: 200, contentType: 'application/json', body: failure.body });
        }
        return route.fulfill({ status: 200, json: failure.body });
      }
      if (request.method() === 'PUT') {
        entry.value = body.value;
        entry.source = entry.scope;
        entry.updated_by = 'planner1';
        entry.updated_at = '2026-10-09T07:30:00+00:00';
      } else {
        entry.value = entry.default;
        entry.source = 'default';
        entry.updated_by = null;
        entry.updated_at = null;
      }
      return route.fulfill({ status: 200, json: entry });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

test('issue301 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const api = await mockAdminApi(page);
  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // Open the settings view by hash change and wait for the rows.
  await page.click('.nav-btn[data-view="settings"]');
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/settings');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);

  const systemRow = page.locator('.settings-row[data-key="' + SYS_KEY + '"]');
  const sysSwitch = systemRow.locator('.settings-switch');
  const sysReset = systemRow.locator('.settings-reset');
  const rowError = systemRow.locator('.settings-row-error');

  // --- initial state: the default value, no Reset, no message --------
  await expect(sysSwitch).toHaveAttribute('role', 'switch');
  await expect(sysSwitch).toHaveAttribute('aria-checked', 'true');
  await expect(sysSwitch).toBeEnabled();
  await expect(systemRow.locator('.settings-source')).toHaveText('Default');
  await expect(sysReset).toHaveCount(0);
  await expect(rowError).toHaveCount(0);

  // --- a well-formed 200 still updates the row -----------------------
  await sysSwitch.click();
  await expect.poll(() => api.calls.length).toBe(1);
  expect(api.calls[0]).toEqual({
    method: 'PUT',
    key: SYS_KEY,
    body: { value: false },
    contentType: 'application/json',
  });
  await expect(sysSwitch).toHaveAttribute('aria-checked', 'false');
  await expect(systemRow.locator('.settings-source')).toHaveText(SET_SOURCE);
  await expect(sysReset).toBeVisible();
  await expect(sysReset).toHaveText('Reset to default');
  await expect(rowError).toHaveCount(0);

  // Run one failed change from the row's current state (value OFF, the
  // Reset visible) and check the row is usable again afterwards: the
  // switch is back at the value it showed before the change, the switch
  // and its Reset are enabled again, the message is the one given, and
  // the source text is untouched.
  async function failedChange(expectedCalls, failNext, expectedMessage) {
    api.failNext = failNext;
    await sysSwitch.click();
    await expect.poll(() => api.calls.length).toBe(expectedCalls);
    const call = api.calls[expectedCalls - 1];
    expect(call.method).toBe('PUT');
    expect(call.key).toBe(SYS_KEY);
    expect(call.body).toEqual({ value: true });
    await expect(rowError).toHaveText(expectedMessage);
    await expect(sysSwitch).toHaveAttribute('aria-checked', 'false');
    await expect(sysSwitch).toBeEnabled();
    await expect(sysReset).toBeEnabled();
    await expect(systemRow.locator('.settings-source')).toHaveText(SET_SOURCE);
  }

  // --- a 500 with a detail: the detail shows, the row is usable ------
  await failedChange(2, { kind: 'http', status: 500, detail: DETAIL_500 }, DETAIL_500);

  // --- a 200 whose body is "ok": not an entry, the fallback shows ----
  await failedChange(3, { kind: 'ok', body: '"ok"' }, FALLBACK_MESSAGE);

  // --- a 200 whose body is an object missing value -------------------
  const missingValueBody = {
    key: SYS_KEY,
    scope: 'system',
    type: 'boolean',
    allowed: null,
    default: true,
    description: SYS_DESCRIPTION,
    source: 'system',
    editable: true,
    updated_by: 'planner1',
    updated_by_name: null,
    updated_at: '2026-10-09T07:30:00+00:00',
  };
  await failedChange(4, { kind: 'ok', body: missingValueBody }, FALLBACK_MESSAGE);

  // --- an aborted request: no HTTP answer at all, the fallback shows -
  await failedChange(5, { kind: 'abort' }, FALLBACK_MESSAGE);

  // --- the row is usable again: a well-formed 200 updates it ---------
  await sysSwitch.click();
  await expect.poll(() => api.calls.length).toBe(6);
  expect(api.calls[5]).toEqual({
    method: 'PUT',
    key: SYS_KEY,
    body: { value: true },
    contentType: 'application/json',
  });
  await expect(sysSwitch).toHaveAttribute('aria-checked', 'true');
  await expect(systemRow.locator('.settings-source')).toHaveText(SET_SOURCE);
  await expect(sysReset).toBeVisible();
  await expect(rowError).toHaveCount(0);

  // --- and a well-formed reset returns the row to "Default" ----------
  await sysReset.click();
  await expect.poll(() => api.calls.length).toBe(7);
  expect(api.calls[6]).toEqual({
    method: 'DELETE',
    key: SYS_KEY,
    body: null,
    contentType: null,
  });
  await expect(sysSwitch).toHaveAttribute('aria-checked', 'true');
  await expect(systemRow.locator('.settings-source')).toHaveText('Default');
  await expect(sysReset).toHaveCount(0);
  await expect(rowError).toHaveCount(0);
});
