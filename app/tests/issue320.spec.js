//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]), at 1440x900:
//   * the sidebar holds a "Demand" button after "Work queue";
//   * #/demand opens the view: its title and subtitle, the view
//     section active, aria-current="page" on the button;
//   * while the list is in flight the list pane shows skeleton rows;
//     when it lands, the first row is chosen (aria-current="true") and
//     its detail loads from /api/forecast/by-key with the row's
//     item_code and site_code in the request;
//   * a row shows the item, the site, the demand class, the method,
//     the 12-bucket total (with thousands separators) and the backtest
//     error as a percentage — an em dash for a row with no backtest;
//   * the filter chips: "All" (pressed by default) and one chip per
//     demand class present, each with its count; choosing a chip
//     narrows the list with no request sent, and when a chip hides the
//     chosen row the first row still listed becomes the chosen one —
//     the tint, the aria-current and the detail pane move to it;
//   * choosing another row moves aria-current and replaces the detail;
//   * the detail: the heading with the item and site codes, the demand
//     class and the as-of date, an svg[data-testid="demand-chart"]
//     holding one history bar per history bucket and one forecast bar
//     per forecast bucket, history first, a <title> on each bar with
//     its date range and its quantity as-is (never rounded to whole
//     units); "How this forecast was made" with
//     the method, the parameters, the history bucket count and the
//     arithmetic string ([data-testid="demand-arithmetic"]); "Backtest"
//     with the method's MAE beside the baseline's and the error and
//     bias percentages — or the "Not enough history" note for a row
//     whose backtest is null;
//   * the loading skeleton, the empty state ("No forecasts yet") and
//     the error state with a "Try again" button that loads again;
//   * with 300 rows at 1440x900 neither the document nor the view
//     scrolls, and the list pane scrolls under its sticky header and
//     the detail pane scrolls on its own;
//   * an item code of <img src=x onerror=window.__pwned=1> renders as
