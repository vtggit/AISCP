// The detail requests stay open this long inside the mocked route so
// the spec can observe the moment between the choice and the detail
// landing (or failing).
const DETAIL_DELAY_MS = 600;

function isoDay(ms) {
  return new Date(ms).toISOString().slice(0, 10);
}

// count 30-day buckets ending on 2026-10-09, oldest first.
function historyBuckets(count, quantities) {
  const starts = [];
  const ends = [];
  let end = Date.UTC(2026, 9, 9);
  for (let i = 0; i < count; i += 1) {
    ends.unshift(isoDay(end));
    const start = end - 29 * 86400000;
    starts.unshift(isoDay(start));
    end = start - 86400000;
  }
  const buckets = [];
  for (let i = 0; i < count; i += 1) {
    buckets.push({
      bucket_start: starts[i],
      bucket_end: ends[i],
      quantity: quantities[i % quantities.length],
    });
  }
  return buckets;
}

// 12 buckets of 30 days starting the day after 2026-10-09. No override
// covers any bucket: the effective quantity is the statistical one and
// override_days is 0.
function forecastBuckets(quantities) {
  const buckets = [];
  let start = Date.UTC(2026, 9, 10);
  for (let i = 0; i < quantities.length; i += 1) {
    const end = start + 29 * 86400000;
    buckets.push({
      bucket_start: isoDay(start),
      bucket_end: isoDay(end),
      quantity: quantities[i],
      effective_quantity: quantities[i],
      override_days: 0,
    });
    start = end + 86400000;
  }
  return buckets;
}

// 300 rows, one per item-site, in the order the API returns them.
// The API may send codes as numbers: item code 10 (row 10) and the
// demand class of every 50th row arrive as numbers, and the view must
// choose and filter them through the text form of the value.
function rows300() {
  const rows = [];
  for (let i = 1; i <= 300; i += 1) {
    const row = {
      item_code: 'BIG-' + String(i).padStart(4, '0'),
      site_code: 'WH-' + ((i % 3) + 1),
      as_of: AS_OF,
      demand_class: CLASSES[i % 4],
      method: 'ses',
      params: { alpha: 0.3 },
      history_buckets: 12,
      total_forecast: 3000 - i,
      total_effective_forecast: 3000 - i,
      overridden_buckets: 0,
      backtest: { mae: 1.5, baseline_mae: 2.0, wape: 0.1, bias: 0.0 },
    };
    if (i === 10) {
      row.item_code = 10;
    }
    if (i % 50 === 0) {
      row.demand_class = 7;
    }
    rows.push(row);
  }
  return rows;
}

// The list rows carry no buckets; the by-key detail adds them back.
function detailsFor(rows) {
  const details = {};
  rows.forEach((row) => {
    details[row.item_code + '|' + row.site_code] = Object.assign({}, row, {
      history: historyBuckets(12, [5, 6, 5, 6]),
      forecast: forecastBuckets(new Array(12).fill(10)),
      arithmetic:
        'ses: level = 0.3 \u00d7 quantity + 0.7 \u00d7 level; forecast = final level, repeated for each of the 12 buckets',
    });
  });
  return details;
}

// Mock every /api/* call; records the /api/forecast and
// /api/forecast/by-key requests. The by-key route holds each response
// open for detailDelayMs (the delay is in the mock, not a fixed wait in
// the page) and answers 500 to the next detail request for the row
// bound via api.failKey — the failure is bound to that row's own
// request, never to whatever else is in flight.
async function mockDemandApi(page, { rows, details, detailDelayMs = 0 } = {}) {
  const api = {
    listGets: 0,
    byKeyGets: [],
    byKeyFails: [], // the item-site of every by-key request answered 500
    accuracyGets: [],
    overrideGets: [],
    rows,
    details,
    detailDelayMs,
    failKey: null, // { item, site } whose next detail request responds 500
  };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (url.pathname === '/api/forecast') {
      api.listGets += 1;
      return route.fulfill({ status: 200, json: api.rows });
    }
    if (url.pathname === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.byKeyGets.push({ item, site });
      const detail = api.details[item + '|' + site];
      const respond = () => {
        if (api.failKey && api.failKey.item === item && api.failKey.site === site) {
          api.failKey = null;
          api.byKeyFails.push({ item, site });
          return route.fulfill({ status: 500, json: { detail: FAIL_DETAIL_MESSAGE } });
        }
        if (!detail) {
          return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
        }
        return route.fulfill({ status: 200, json: detail });
      };
      if (api.detailDelayMs > 0) {
        return new Promise((resolve) => {
          setTimeout(resolve, api.detailDelayMs);
        }).then(respond);
      }
      return respond();
    }
    if (url.pathname === '/api/forecast/overrides') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.overrideGets.push({ item, site, limit: url.searchParams.get('limit') });
      return route.fulfill({ status: 200, json: [] });
    }
    if (url.pathname === '/api/forecast/accuracy') {
      api.accuracyGets.push({
        bucketIndex: url.searchParams.get('bucket_index'),
        limit: url.searchParams.get('limit'),
      });
      const isAhead = url.searchParams.get('bucket_index') === '1';
      return route.fulfill({ status: 200, json: isAhead ? ACCURACY_AHEAD : ACCURACY_ALL });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

