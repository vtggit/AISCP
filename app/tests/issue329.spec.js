// Proving spec for AIERP issue #329 — choosing an item-site in the
// Demand view must not disturb the list.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]), at 1440x900
// with 300 mocked rows (the list scrolls on its own under its sticky
// header):
//   * the list scrolled to 2,000 px: a row in view chosen by click
//     keeps the scroll position straight after the click and again
//     after that row's detail has loaded — the detail request is
//     delayed in the mocked route, not with a fixed wait in the page,
//     so both moments are observed — and the chosen row is not moved
//     out of view;
//   * the same when the detail request fails — the 500 is bound to the
//     chosen row's own request, never to another in flight: the scroll
//     position is kept and the detail pane shows the error with a
//     "Try again" button;
//   * the focus is on the chosen row after the click and after its
//     detail has loaded;
//   * a row chosen with the keyboard (focus on it, then Enter)
//     becomes the chosen row, keeps the focus, and the list has not
//     moved; pressing Tab then moves the focus to the next row;
//   * a pressed filter chip shows its narrowed list from its top and
//     the focus stays on that chip; a chip that hides the chosen row
//     still makes the first row listed the chosen one, with the
//     detail pane showing it;
//   * numeric API fields stay choosable and filterable: item code 10
//     (a number) is chosen by click and its detail loads, and the
//     numeric demand class 7 narrows the list through its chip — the
//     rows carry both as attribute strings, so the view matches them
//     through their text form, not by strict equality.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue329 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "\u203a" the contract nodeid does not carry, so the proof
// would read as "not collected".

