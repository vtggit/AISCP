// Mock every /api/* call; records the /api/forecast, the
// /api/forecast/by-key and the two /api/forecast/accuracy requests so
// the spec can inspect them. failList makes the list answer 500 (until
// it is cleared), failAccuracy makes both accuracy requests answer 500
// (until cleared), and delayAccuracyMs holds the accuracy responses
// open inside the mocked route (the delay is in the mock, not a fixed
// wait in the page).
async function mockDemandApi(page, options) {
  const {
    rows = ROWS,
    details = DETAILS,
    ahead = ACCURACY_AHEAD,
    all = ACCURACY_ALL,
    failList = false,
    failAccuracy = false,
    delayAccuracyMs = 0,
  } = options || {};
  const api = {
    listGets: 0,
    byKeyGets: [],
    accuracyGets: [],
    overrideGets: [],
    rows,
    details,
    ahead,
    all,
    failList,
    failAccuracy,
    delayAccuracyMs,
  };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (url.pathname === '/api/forecast') {
      api.listGets += 1;
      if (api.failList) {
        return route.fulfill({
          status: 500,
          json: { detail: 'The forecast service is unavailable.' },
        });
      }
      return route.fulfill({ status: 200, json: api.rows });
    }
    if (url.pathname === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.byKeyGets.push({ item, site });
      const detail = api.details[item + '|' + site];
      if (!detail) {
        return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
      }
      return route.fulfill({ status: 200, json: detail });
    }
    if (url.pathname === '/api/forecast/overrides') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.overrideGets.push({ item, site, limit: url.searchParams.get('limit') });
      return route.fulfill({ status: 200, json: [] });
    }
    if (url.pathname === '/api/forecast/accuracy') {
      api.accuracyGets.push({
        bucketIndex: url.searchParams.get('bucket_index'),
        limit: url.searchParams.get('limit'),
      });
      const respond = () => {
        if (api.failAccuracy) {
          return route.fulfill({
            status: 500,
            json: { detail: 'The accuracy service is unavailable.' },
          });
        }
        const isAhead = url.searchParams.get('bucket_index') === '1';
        return route.fulfill({ status: 200, json: isAhead ? api.ahead : api.all });
      };
      if (api.delayAccuracyMs > 0) {
        return new Promise((resolve) => {
          setTimeout(resolve, api.delayAccuracyMs);
        }).then(respond);
      }
      return respond();
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

