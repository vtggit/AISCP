  await expect(page.locator('.d-detail-title')).toHaveText('A \u00b7 S1');
  expect(api.accuracyGets.length).toBe(2);
  expect(api.byKeyGets.length).toBe(byKeyBefore + 1);

  // A null wape and bias: the error and the bias are em dashes.
  expect(await realisedFacts(page)).toEqual([
    ['Forecast total', '240'],
    ['Actual total', '215.5'],
    ['Error', EM_DASH],
    ['Bias', EM_DASH],
    ['Periods compared', '500'],
  ]);

  // D has no demand in the compared periods: the totals and the count
  // are shown with the "No demand" sentence.
  await page.click('[data-testid="demand-row"][data-item="D"]');
  await expect(page.locator('.d-detail-title')).toHaveText('D \u00b7 S2');
  expect(await realisedFacts(page)).toEqual([
    ['Forecast total', '36'],
    ['Actual total', '0'],
    ['Error', EM_DASH],
    ['Bias', EM_DASH],
    ['Periods compared', '10'],
  ]);
  await expect(realised.locator('.d-realised-note')).toHaveText(DETAIL_NO_DEMAND);
  expect(api.accuracyGets.length).toBe(2);

  // C is not in the response: the section reads the sentence.
  await page.click('[data-testid="demand-row"][data-item="C"]');
  await expect(page.locator('.d-detail-title')).toHaveText('C \u00b7 S2');
  expect(await realised.locator('.d-fact').count()).toBe(0);
  await expect(realised.locator('.d-realised-note')).toHaveText(DETAIL_NONE);
  expect(api.accuracyGets.length).toBe(2);

  // --- choosing chips sends no accuracy request ------------------------
  await page.click('.d-chip[data-filter="smooth"]');
  await expect(rows).toHaveCount(2);
  expect(api.accuracyGets.length).toBe(2);
  await page.click('.d-chip[data-filter="all"]');
  await expect(rows).toHaveCount(5);
  expect(api.accuracyGets.length).toBe(2);

  // --- the hostile item code in the accuracy response renders as text --
  // The code is a row of the list and an item-site of the accuracy
  // response: the row shows it escaped, the column shows its wape, and
  // the detail title carries it as text only.
  const imgRow = rows.nth(4);
  await expect(imgRow).toHaveAttribute('data-item', IMG_CODE);
  expect(await imgRow.locator('.d-item').evaluate((el) => el.innerHTML)).toBe(
    '&lt;img src=x onerror=window.__pwned=1&gt;',
  );
  await imgRow.click();
  await expect(page.locator('.d-detail-title')).toContainText(IMG_CODE);
  expect(await page.locator('.d-detail-title').evaluate((el) => el.innerHTML)).toContain(
    '&lt;img src=x onerror=window.__pwned=1&gt;',
  );
  expect(await imgRow.locator('.d-realised').textContent()).toBe('50%');
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  expect(await page.locator('#demand-root img').count()).toBe(0);
  expect(api.accuracyGets.length).toBe(2);

  // --- delayed accuracy: list and detail show while loading ------------
  const delayPage = await page.context().newPage();
  delayPage.setViewportSize({ width: 1440, height: 900 });
  await mockDemandApi(delayPage, { delayAccuracyMs: 4000 });
  await delayPage.goto('/#/demand');
  await signIn(delayPage);
  await expect(delayPage.locator('[data-testid="demand-row"]')).toHaveCount(5);
  // The first row's detail has landed, but the accuracy responses are
  // still held open in the mocked route: the summary reads loading and
  // the column shows an em dash.
  await expect(delayPage.locator('.d-detail-title')).toHaveText('B \u00b7 S1');
  await expect(delayPage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_LOADING);
  expect(
    await delayPage.locator('[data-testid="demand-row"][data-item="B"] .d-realised').textContent(),
  ).toBe(EM_DASH);
  // The detail section waits with the loading note.
  await expect(delayPage.locator('[data-testid="demand-realised-detail"] .d-realised-note')).toHaveText(
    SUMMARY_LOADING,
  );
  // Once the (delayed) responses land, the full line and the column.
  await expect(delayPage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_FULL);
  expect(
    await delayPage.locator('[data-testid="demand-row"][data-item="B"] .d-realised').textContent(),
  ).toBe('18%');
  expect(await delayPage.locator('.d-row .d-realised').evaluateAll((els) => els.map((el) => el.textContent))).toEqual([
    '18%',
    EM_DASH,
    EM_DASH,
    EM_DASH,
    '50%',
  ]);
  await delayPage.close();

  // --- a 500 from the accuracy: not available, everything else works ---
  const errPage = await page.context().newPage();
  errPage.setViewportSize({ width: 1440, height: 900 });
  const errApi = await mockDemandApi(errPage, { failAccuracy: true });
  await errPage.goto('/#/demand');
  await signIn(errPage);
  await expect(errPage.locator('[data-testid="demand-row"]')).toHaveCount(5);
  await expect(errPage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_NOT_AVAILABLE);
  // The list column shows em dashes everywhere.
  expect(
    await errPage.locator('.d-row .d-realised').evaluateAll((els) => els.map((el) => el.textContent)),
  ).toEqual(Array(5).fill(EM_DASH));
  // The detail section reads the same sentence — and the detail
  // otherwise works: the first row's detail loaded, and choosing
  // another row replaces it.
  await expect(errPage.locator('.d-detail-title')).toHaveText('B \u00b7 S1');
  await expect(errPage.locator('[data-testid="demand-realised-detail"] .d-realised-note')).toHaveText(
    SUMMARY_NOT_AVAILABLE,
  );
  await errPage.click('[data-testid="demand-row"][data-item="A"]');
  await expect(errPage.locator('.d-detail-title')).toHaveText('A \u00b7 S1');
  expect(errApi.byKeyGets.length).toBe(2);
  await expect(errPage.locator('[data-testid="demand-realised-detail"] .d-realised-note')).toHaveText(
    SUMMARY_NOT_AVAILABLE,
  );
  await errPage.close();

  // --- "Try again" after a list error sends the accuracy again ---------
  const retryPage = await page.context().newPage();
  retryPage.setViewportSize({ width: 1440, height: 900 });
  const retryApi = await mockDemandApi(retryPage, { failList: true });
  await retryPage.goto('/#/demand');
  await signIn(retryPage);
  await expect(retryPage.locator('.d-error-msg')).toHaveText('The forecast service is unavailable.');
  // The first load sent the two accuracy requests with the list.
  await expect.poll(() => retryApi.accuracyGets.length).toBe(2);
  await retryPage.click('#demand-retry');
  await expect.poll(() => retryApi.listGets).toBe(2);
  // The retry sent the two accuracy requests again, with the list.
  await expect.poll(() => retryApi.accuracyGets.length).toBe(4);
  await expect(retryPage.locator('.d-error-msg')).toHaveText('The forecast service is unavailable.');
  // The next retry lands a healthy list: the rows and the summary
  // render from the fresh accuracy responses.
  retryApi.failList = false;
  await retryPage.click('#demand-retry');
  await expect.poll(() => retryApi.listGets).toBe(3);
  await expect(retryPage.locator('[data-testid="demand-row"]')).toHaveCount(5);
  await expect.poll(() => retryApi.accuracyGets.length).toBe(6);
  await expect(retryPage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_FULL);
  await retryPage.close();

  // --- nothing compared: the one-period-ahead has compared_buckets 0 ---
  const noneAhead = JSON.parse(JSON.stringify(ACCURACY_AHEAD));
  noneAhead.compared_buckets = 0;
  noneAhead.overall = { forecast_total: 0, actual_total: 0, wape: null, bias: null };
  noneAhead.item_sites = [];
  const nonePage = await page.context().newPage();
  nonePage.setViewportSize({ width: 1440, height: 900 });
  await mockDemandApi(nonePage, { ahead: noneAhead });
  await nonePage.goto('/#/demand');
  await signIn(nonePage);
  await expect(nonePage.locator('[data-testid="demand-row"]')).toHaveCount(5);
  await expect(nonePage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_NONE_YET);
  // No item-site is in the response: the column is all em dashes, and
  // the detail section reads the nothing-compared sentence.
  expect(
    await nonePage.locator('.d-row .d-realised').evaluateAll((els) => els.map((el) => el.textContent)),
  ).toEqual(Array(5).fill(EM_DASH));
  await expect(nonePage.locator('[data-testid="demand-realised-detail"] .d-realised-note')).toHaveText(
    DETAIL_NONE,
  );
  await nonePage.close();

  // --- 300 rows at 1440x900: no document/view scroll, the choice keeps
  //     the list at 2,000 px ---------------------------------------------
  const bigPage = await page.context().newPage();
  bigPage.setViewportSize({ width: 1440, height: 900 });
  const bigRowsList = bigRows();
  const bigApi = await mockDemandApi(bigPage, {
    rows: bigRowsList,
    details: bigDetails(bigRowsList),
  });
  await bigPage.goto('/#/demand');
  await signIn(bigPage);
  await expect(bigPage.locator('[data-testid="demand-row"]')).toHaveCount(300);
  // The first row's detail is in hand before the layout checks.
  await expect(bigPage.locator('.d-detail-title')).toHaveText('BIG-0001 \u00b7 WH-2');
  await expect(bigPage.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_FULL);
  await expect.poll(() => bigApi.accuracyGets.length).toBe(2);

  const layout = await bigPage.evaluate(() => {
    const view = document.getElementById('view-demand');
    return {
      docScrollHeight: document.documentElement.scrollHeight,
      docClientHeight: document.documentElement.clientHeight,
      docScrollWidth: document.documentElement.scrollWidth,
      viewScroll: view.scrollHeight,
      viewClient: view.clientHeight,
    };
  });
  expect(layout.docScrollHeight).toBe(layout.docClientHeight);
  expect(layout.docScrollWidth).toBeLessThanOrEqual(1440);
  expect(layout.viewScroll).toBeLessThanOrEqual(layout.viewClient);

  // The list scrolls to 2,000 px, a row in view is chosen, and the
  // scroll position survives the re-renders the choice causes.
  await bigPage.evaluate(() => {
    document.querySelector('.d-list-body').scrollTop = 2000;
  });
  expect(await bigPage.evaluate(() => document.querySelector('.d-list-body').scrollTop)).toBe(2000);
  const clicked = await pickVisibleRow(bigPage, 0);
  expect(clicked).not.toBeNull();
  await bigPage.locator('[data-testid="demand-row"]').nth(clicked.index).click();
  await expect(bigPage.locator('.d-detail-title')).toHaveText(clicked.item + ' \u00b7 ' + clicked.site);
  expect(await bigPage.evaluate(() => document.querySelector('.d-list-body').scrollTop)).toBe(2000);
  await bigPage.close();

  // --- 390x844: the panes stack, no sideways scroll, the line wraps ----
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('[data-testid="demand-realised"]')).toHaveText(SUMMARY_FULL);
  const narrow = await page.evaluate(() => ({
    scrollWidth: document.documentElement.scrollWidth,
    innerWidth: window.innerWidth,
  }));
  expect(narrow.scrollWidth).toBeLessThanOrEqual(narrow.innerWidth);
  // The summary line wraps inside the view's width: more than one
  // text line at this width.
  const summaryBox = await page.locator('[data-testid="demand-realised"]').boundingBox();
  expect(summaryBox.height).toBeGreaterThan(30);
  await page.setViewportSize({ width: 1440, height: 900 });
