// The first row fully visible in the list (below the sticky header),
// skipping the first skipIndex rows; null when there is none.
async function pickVisibleRow(page, skipIndex) {
  return page.evaluate((skip) => {
    const body = document.querySelector('.d-list-body');
    const header = document.querySelector('.d-row-head');
    const list = Array.from(document.querySelectorAll('[data-testid="demand-row"]'));
    const top = header.getBoundingClientRect().bottom;
    const bottom = body.getBoundingClientRect().bottom;
    for (let i = skip; i < list.length; i += 1) {
      const rect = list[i].getBoundingClientRect();
      if (rect.top >= top - 1 && rect.bottom <= bottom + 1) {
        return {
          index: i,
          item: list[i].getAttribute('data-item'),
          site: list[i].getAttribute('data-site'),
        };
      }
    }
    return null;
  }, skipIndex);
}

// The line of the `const AS_OF` declaration and the line of the first
// use of the binding in the named spec, or -1 when absent. A use on a
// line before the declaration is a temporal-dead-zone crash: the spec
// throws at collection before a single test could run. The spec files
// sit next to this one in app/tests; the fallbacks cover a gate that
// copies the proof elsewhere before running it.
function asOfSpecPath(specName) {
  const candidates = [
    path.join(__dirname, specName),
    path.join(__dirname, '..', '..', 'app', 'tests', specName),
    path.join(__dirname, 'app', 'tests', specName),
  ];
  const found = candidates.find((candidate) => fs.existsSync(candidate));
  if (!found) {
    throw new Error('superseded proof ' + specName + ' not found next to the proof');
  }
  return found;
}

function asOfDeclarationOrder(specName) {
  const lines = fs.readFileSync(asOfSpecPath(specName), 'utf8').split('\n');
  let declaredAt = -1;
  let firstUseAt = -1;
  for (let i = 0; i < lines.length; i += 1) {
    if (declaredAt === -1 && /^\s*const\s+AS_OF\s*=/.test(lines[i])) {
      declaredAt = i;
    } else if (i !== declaredAt && firstUseAt === -1 && /\bAS_OF\b/.test(lines[i])) {
      firstUseAt = i;
    }
  }
  return { declaredAt, firstUseAt };
}

