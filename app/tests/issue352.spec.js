// The first row fully visible in the list (below the sticky header),
// skipping the first skipIndex rows; null when there is none.
async function pickVisibleRow(page, skipIndex) {
  return page.evaluate((skip) => {
    const body = document.querySelector('.d-list-body');
    const header = document.querySelector('.d-row-head');
    const list = Array.from(document.querySelectorAll('[data-testid="demand-row"]'));
    const top = header.getBoundingClientRect().bottom;
    const bottom = body.getBoundingClientRect().bottom;
    for (let i = skip; i < list.length; i += 1) {
      const rect = list[i].getBoundingClientRect();
      if (rect.top >= top - 1 && rect.bottom <= bottom + 1) {
        return {
          index: i,
          item: list[i].getAttribute('data-item'),
          site: list[i].getAttribute('data-site'),
        };
      }
    }
    return null;
  }, skipIndex);
}

// The spec's own copy of the quantity formatting for the expected
// values: thousands separators on the integer part, never rounded.
function fmtQty(value) {
  const text = String(value);
  const dot = text.indexOf('.');
  const intPart = dot === -1 ? text : text.slice(0, dot);
  const fracPart = dot === -1 ? '' : text.slice(dot);
  return intPart.replace(/\B(?=(\d{3})+(?!\d))/g, ',') + fracPart;
}

// The expected cells of one "Forecast periods" row: the period's
// dates, the statistical quantity — always shown — the effective
// quantity (an em dash for a bucket no override covers) and the
// coverage note. Every mocked period is 30 days long.
function periodCells(forecast) {
  return forecast.map((bucket) => [
    bucket.bucket_start,
    bucket.bucket_start + ' ' + EN_DASH + ' ' + bucket.bucket_end,
    fmtQty(bucket.quantity),
    bucket.override_days > 0 ? fmtQty(bucket.effective_quantity) : EM_DASH,
    bucket.override_days > 0
      ? bucket.override_days >= 30
        ? 'Overridden'
        : bucket.override_days + ' of 30 days overridden'
      : EM_DASH,
  ]);
}

// The five cells of each row of the named table, in row order.
async function periodTable(page) {
  return page
    .locator('[data-testid="demand-periods"] [data-testid="demand-period"]')
    .evaluateAll((rows) =>
      rows.map((row) => [
        row.getAttribute('data-period-start'),
        row.querySelector('.d-p-dates').textContent,
        row.querySelector('.d-p-stat').textContent,
        row.querySelector('.d-p-eff').textContent,
        row.querySelector('.d-p-cov').textContent,
      ]),
    );
}

