function isoDay(ms) {
  return new Date(ms).toISOString().slice(0, 10);
}

// count 30-day buckets ending on 2026-10-09, oldest first.
function historyBuckets(count, quantities) {
  const starts = [];
  const ends = [];
  let end = Date.UTC(2026, 9, 9);
  for (let i = 0; i < count; i += 1) {
    ends.unshift(isoDay(end));
    const start = end - 29 * 86400000;
    starts.unshift(isoDay(start));
    end = start - 86400000;
  }
  const buckets = [];
  for (let i = 0; i < count; i += 1) {
    buckets.push({
      bucket_start: starts[i],
      bucket_end: ends[i],
      quantity: quantities[i % quantities.length],
    });
  }
  return buckets;
}

// 12 buckets of 30 days starting the day after 2026-10-09. overrides
// maps a bucket index to { days, effective } for the overridden
// buckets; every other bucket has no overridden days, so its
// effective quantity is the statistical one.
function forecastBuckets(quantities, overrides) {
  const overridesByIndex = overrides || {};
  const buckets = [];
  let start = Date.UTC(2026, 9, 10);
  for (let i = 0; i < quantities.length; i += 1) {
    const end = start + 29 * 86400000;
    const overridden = overridesByIndex[i];
    buckets.push({
      bucket_start: isoDay(start),
      bucket_end: isoDay(end),
      quantity: quantities[i],
      effective_quantity: overridden ? overridden.effective : quantities[i],
      override_days: overridden ? overridden.days : 0,
    });
    start = end + 86400000;
  }
  return buckets;
}

