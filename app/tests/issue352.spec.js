// Mock every /api/* call; records the /api/forecast, the
// /api/forecast/by-key, the /api/forecast/accuracy and the
// /api/forecast/overrides requests so the spec can inspect them.
// failOverrides makes the overrides route answer 500; overrideGates
// holds the named item-sites' overrides open inside the mocked route
// (the delay is in the mock, not a fixed wait in the page) until the
// spec resolves the gate — api.overrideFulfilled then records that the
// response was delivered.
async function mockDemandApi(
  page,
  {
    rows = ROWS,
    details = DETAILS,
    overrides = OVERRIDES,
    failOverrides = false,
    overrideGates = null,
  } = {},
) {
  const api = {
    listGets: 0,
    byKeyGets: [],
    accuracyGets: [],
    overrideGets: [],
    overrideFulfilled: {},
    rows,
    details,
    overrides,
    failOverrides,
    overrideGates: overrideGates || {},
  };
  await page.route('**/api/**', (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: DEV_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ADMIN_ME });
    }
    if (url.pathname === '/api/forecast') {
      api.listGets += 1;
      return route.fulfill({ status: 200, json: api.rows });
    }
    if (url.pathname === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.byKeyGets.push({ item, site });
      const detail = api.details[item + '|' + site];
      if (!detail) {
        return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
      }
      return route.fulfill({ status: 200, json: detail });
    }
    if (url.pathname === '/api/forecast/overrides') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.overrideGets.push({ item, site, limit: url.searchParams.get('limit') });
      const key = item + '|' + site;
      const respond = () => {
        if (api.failOverrides) {
          return route.fulfill({
            status: 500,
            json: { detail: 'The overrides service is unavailable.' },
          });
        }
        return route.fulfill({ status: 200, json: api.overrides[key] || [] });
      };
      const gate = api.overrideGates[key];
      if (gate) {
        return gate.promise.then(() => {
          api.overrideFulfilled[key] = true;
          return respond();
        });
      }
      return respond();
    }
    if (url.pathname === '/api/forecast/accuracy') {
      api.accuracyGets.push({
        bucketIndex: url.searchParams.get('bucket_index'),
        limit: url.searchParams.get('limit'),
      });
      const isAhead = url.searchParams.get('bucket_index') === '1';
      return route.fulfill({ status: 200, json: isAhead ? ACCURACY_AHEAD : ACCURACY_ALL });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

