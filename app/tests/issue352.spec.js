// Proving spec for AIERP issue #352 — planner overrides in the Demand
// view (#/demand).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]), at 1440x900,
// for the chosen item-site:
//   * each detail load sends GET /api/forecast/overrides with the
//     row's item_code and site_code and limit=200 — once per detail
//     load, as often as the by-key requests — and the detail does not
//     wait for it: while the mocked route holds the response open the
//     "Current overrides" section reads "Loading overrides…" with the
//     chart, the periods table and the method already on screen;
//   * the "Forecast periods" section
//     ([data-testid="demand-periods"]) holds one row per forecast
//     bucket ([data-testid="demand-period"], carrying
//     data-period-start): the period's dates, the statistical
//     quantity — always shown — and the effective quantity: an em
//     dash for a bucket no override covers, the effective quantity
//     with "Overridden" for a period an override covers in full,
//     "20 of 30 days overridden" for a partly covered one;
//   * the "Current overrides" section
//     ([data-testid="demand-overrides"]) lists each stored row whose
//     applies is true ([data-testid="override-row"], carrying
//     data-period-start) in period order with the period's dates, the
//     quantity, the reason, who made it (created_by_name) and when —
//     a row whose applies is false is never listed; "No overrides for
//     this item-site." with none applying;
//   * a forecast bucket with overridden days is a third chart series:
//     the bar carries data-series="override", is drawn at its
//     effective quantity, its <title> gives the statistical and the
//     effective quantity, and the legend names the third series — the
//     other bars are as before;
//   * a list row whose overridden_buckets is above 0 shows the
//     [data-testid="demand-row-overridden"] marker (the accessible
//     text "Has overrides"); a row with none has no marker;
//   * an overrides response that arrives after another item-site has
//     been chosen changes nothing on screen;
//   * a failed overrides request (500) leaves only the "Current
//     overrides" section unavailable: "Overrides are not available."
//     with the periods table, the chart, the method and the backtest
//     still shown;
//   * a reason of <img src=x onerror=window.__pwned=1> renders as
//     text, with window.__pwned undefined;
//   * with 300 rows at 1440x900 neither the document nor the view
//     scrolls, and the list scrolled to 2,000 px stays at 2,000 px
//     after a row is chosen;
//   * at 390x844 the panes stack with no horizontal page scroll.
//
// The delays live in the mocked routes (gates the spec resolves),
// never as fixed waits in the page.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue352 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "\u203a" the contract nodeid does not carry, so the proof
