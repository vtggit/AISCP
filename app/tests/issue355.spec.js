// The two error cells of one list row, their column header, and the
// computed box model of each: background colour, the four paddings,
// the four margins, the display and the rendered width.
async function rowErrorBox(page) {
  return page.evaluate(() => {
    const row = document.querySelector('[data-testid="demand-row"][data-item="A"]');
    const cell = row.querySelector('.d-bt-error');
    const realised = row.querySelector('.d-realised');
    const header = document.querySelector('.d-row-head .d-h-error');
    const pick = (el) => {
      const cs = getComputedStyle(el);
      return {
        backgroundColor: cs.backgroundColor,
        paddingTop: cs.paddingTop,
        paddingRight: cs.paddingRight,
        paddingBottom: cs.paddingBottom,
        paddingLeft: cs.paddingLeft,
        marginTop: cs.marginTop,
        marginRight: cs.marginRight,
        marginBottom: cs.marginBottom,
        marginLeft: cs.marginLeft,
        display: cs.display,
        width: el.getBoundingClientRect().width,
      };
    };
    return {
      cellClass: cell.getAttribute('class'),
      cell: pick(cell),
      realised: pick(realised),
      headerWidth: pick(header).width,
    };
  });
}

// The element the focus is on, by the hooks the proof checks: its
// data-testid and the row identity of a repeated control (the
// button's own data-period-start / data-override-id).
async function focusHooks(page) {
  return page.evaluate(() => {
    const el = document.activeElement;
    if (!el || !el.getAttribute) {
      return { testid: null, periodStart: null, overrideId: null };
    }
    return {
      testid: el.getAttribute('data-testid'),
      periodStart: el.getAttribute('data-period-start'),
      overrideId: el.getAttribute('data-override-id'),
    };
  });
}

