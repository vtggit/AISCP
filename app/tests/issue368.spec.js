// Mock every /api/* call the queue (and the shell around it) makes.
async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const listGets = [];
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/drift') {
      listGets.push({ kind: 'drift', query: url.search });
      return route.fulfill({ status: 200, json: DRIFT_ROWS });
    }
    if (path === '/api/excess') {
      listGets.push({ kind: 'excess', query: url.search });
      return route.fulfill({ status: 200, json: EXCESS_ROWS });
    }
    if (path === '/api/stockout') {
      listGets.push({ kind: 'stockout', query: url.search });
      return route.fulfill({ status: 200, json: STOCKOUT_ROWS });
    }
    if (path === '/api/drift/decisions') {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { listGets };
}

test('issue368 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => {
    pageErrors.push(String(error));
  });

  page.setViewportSize({ width: 1440, height: 900 });
  const { listGets } = await mockQueueApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  // --- boot: development sign-in card, straight onto #/queue ----------
  await page.goto('/#/queue');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(page.locator('#view-queue')).toBeVisible();

  await expect.poll(() => listGets.some((g) => g.kind === 'drift')).toBe(true);

  // All five drift rows are to decide, so the default To decide filter
  // shows them in API order and selects the first (B1).
  await expect(page.locator('.q-row')).toHaveCount(5);
  expect(
    await page.locator('.q-row').evaluateAll((rs) => rs.map((r) => r.getAttribute('data-item'))),
  ).toEqual(['B1', 'B2', 'B3', 'B4', 'B5']);

  // --- B1: built on history, the other basis with a negative difference
  const basis = page.locator('[data-testid="q-basis"]');
  const otherBasis = page.locator('[data-testid="q-other-basis"]');

  await expect(page.locator('.q-row[data-item="B1"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-detail-title')).toHaveText('B1');
  await expect(basis).toHaveCount(1);
  await expect(basis).toHaveText('Built on history');
  await expect(otherBasis).toHaveCount(1);
  await expect(otherBasis).toHaveText(D1_OTHER_LINE);

  // The lines sit in the Why section, directly under the inputs and
  // above the arithmetic.
  expect(
    await page.locator('.q-basis-lines').evaluate((el) => ({
      insideWhy: !!el.closest('section.q-why'),
      prevClass: el.previousElementSibling ? el.previousElementSibling.getAttribute('class') : null,
      nextClass: el.nextElementSibling ? el.nextElementSibling.getAttribute('class') : null,
    })),
  ).toEqual({ insideWhy: true, prevClass: 'q-inputs', nextClass: 'q-arithmetic' });

  // Unchanged around the new lines: the figure tiles, the "Why" text,
  // the inputs and the arithmetic keep their values and their places.
  const tiles = page.locator('.q-figures .q-figure-tile');
  await expect(tiles).toHaveCount(2);
  await expect(tiles.nth(0).locator('.q-figure-value')).toHaveText('36,000');
  await expect(tiles.nth(1).locator('.q-figure-value')).toHaveText('31,888');
  await expect(page.locator('.q-why-text')).toHaveText(
    'The ERP reorder point sits 4,112 units above the recommended point.',
  );
  await expect(page.locator('.q-inputs .q-input')).toHaveCount(5);
  await expect(page.locator('.q-arithmetic')).toHaveText(
    'ROP = d·LT + k·σ_L = 27,775.5 + 1.645 × 2,500 = 31,888 → 31,888 units',
  );

  // --- B2: built on the forecast, the other basis with a positive difference
  await page.click('.q-row[data-item="B2"]');
  await expect(page.locator('.q-row[data-item="B2"]')).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('.q-detail-title')).toHaveText('B2');
  await expect(basis).toHaveText('Built on the forecast');
  await expect(otherBasis).toHaveText(D2_OTHER_LINE);
  expect(await otherBasis.evaluate((el) => el.textContent.startsWith('On history:'))).toBe(true);

  // --- B3: both bases agree — no difference in brackets --------------
  await page.click('.q-row[data-item="B3"]');
  await expect(page.locator('.q-detail-title')).toHaveText('B3');
  await expect(basis).toHaveText('Built on history');
  await expect(otherBasis).toHaveText(D3_OTHER_LINE);
  expect(await otherBasis.evaluate((el) => /\(.+\)/.test(el.textContent))).toBe(false);

  // --- B4: other_basis null — the first line only ---------------------
  await page.click('.q-row[data-item="B4"]');
  await expect(page.locator('.q-detail-title')).toHaveText('B4');
  await expect(basis).toHaveCount(1);
  await expect(basis).toHaveText('Built on the forecast');
  await expect(otherBasis).toHaveCount(0);

  // --- B5: no demand_basis at all (an older deploy) -------------------
  // Neither line, and the page raises no error for it.
  await page.click('.q-row[data-item="B5"]');
  await expect(page.locator('.q-detail-title')).toHaveText('B5');
  await expect(basis).toHaveCount(0);
  await expect(otherBasis).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- the excess row: neither line ------------------------------------
  await page.click('.q-tab[data-kind="excess"]');
  await expect(page.locator('.q-row')).toHaveCount(1);
  await expect(page.locator('.q-detail-title')).toHaveText('E1');
  await expect(basis).toHaveCount(0);
  await expect(otherBasis).toHaveCount(0);

  // --- the stockout row: neither line ----------------------------------
  await page.click('.q-tab[data-kind="stockout"]');
  await expect(page.locator('.q-row')).toHaveCount(1);
  await expect(page.locator('.q-detail-title')).toHaveText('K1');
  await expect(basis).toHaveCount(0);
  await expect(otherBasis).toHaveCount(0);

  // No page error anywhere in the proof, in any tab.
  expect(pageErrors).toEqual([]);
});
