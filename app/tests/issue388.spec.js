// The "label, value" pairs of the realised detail section, in order.
async function realisedFacts(page) {
  return page
    .locator('[data-testid="demand-realised-detail"] .d-fact')
    .evaluateAll((els) =>
      els.map((el) => [el.querySelector('dt').textContent, el.querySelector('dd').textContent]),
    );
}

// The uncaught exceptions of the page so far.
function collectPageErrors(page) {
  const errors = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  return errors;
}

