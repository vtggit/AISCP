// The mocked API. Every POST /api/scenarios/simulate is held — pushed
// onto ctrl.runs with its route — and the test answers it, in the
// order it chooses, so responses can land out of order.
async function mockScenarioApi(page, ctrl) {
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (url.pathname === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (url.pathname === '/api/scenarios/simulate' && request.method() === 'POST') {
      ctrl.runs.push({ body: request.postDataJSON(), route });
      return; // held: the test answers it, in the order it chooses
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

