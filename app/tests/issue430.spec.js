// Proving spec for AIERP issue #430 — the Scenario screen (#/scenario).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route against a mocked
// POST /api/scenarios/simulate. Proves, signed in through the
// development token card as an admin (/api/auth/me roles ["admin"]),
// at 1440x900:
//   * the nav gains a "Scenario" button between "Demand" and
//     "Decision log"; the view section exists; clicking the button
//     shows the scenario view and sets the hash to #/scenario, and a
//     reload on that hash keeps the view;
//   * the levers form ([data-testid="scenario-levers"]) carries the
//     three labelled fields — target service level (a percentage,
//     50-99.9, optional) plus the demand and lead-time changes (each
//     -90..500, defaulting to 0, the no-change value) — and the "Run
//     scenario" button;
//   * running with a service level of 98%, a demand change of +20%
//     and a lead-time change of 0 sends
//     {service_level: 0.98, demand_multiplier: 1.2,
//      lead_time_multiplier: null}; while the request is out the
//     button is disabled and a skeleton shows;
//   * the answer renders the summary — the dollar impact as currency,
//     the signed unit totals with thousands separators, the
//     up/down/unchanged counts — and the table, one row per item-site
//     with the baseline, scenario and signed delta, in response order;
//     item_sites_without_unit_cost of 3 shows the exclusion note;
//   * two quick runs, the first answered last, render only the second
//     run's result — the older response is ignored;
//   * a 422 (an out-of-range lever) shows the server's message and
//     leaves the screen usable; another failure shows the Retry, and
//     Retry re-sends the same levers the failed request carried;
//   * a value from the API containing
//     <img src=x onerror=window.__pwned=1> renders as text with
//     window.__pwned undefined;
//   * at 1440x900 the document does not scroll while the table rows
//     scroll inside their own region, and at 390x844 the page does
//     not scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the scenario screen renders
// and runs with no admin-only control present.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue430 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

