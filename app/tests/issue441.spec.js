// The mocked API. GET /api/scenarios is a stateful resource: the store
// in ctrl reflects create (201, newest first), update (PUT) and delete
// (204). Every request can be held (the test answers it, in the order
// it chooses, so the in-flight button states are observable), failed
// once (listFailNext) or rejected once (createReject).
function apiHandler(route) {
  const request = route.request();
  const url = new URL(request.url());
  const ctrl = apiHandler.ctrl;
  if (url.pathname === '/api/auth/config') {
    return route.fulfill({ status: 200, json: ctrl.config });
  }
  if (url.pathname === '/api/auth/me') {
    ctrl.meRequests.push(request);
    return route.fulfill({ status: 200, json: ctrl.me });
  }
  if (url.pathname === '/api/scenarios' && request.method() === 'GET') {
    ctrl.listRequests += 1;
    if (ctrl.listFailNext) {
      ctrl.listFailNext = false;
      return route.fulfill({ status: 500, json: { detail: 'internal error' } });
    }
    if (ctrl.listHoldNext) {
      ctrl.listHoldNext = false;
      ctrl.heldLists.push({ route, body: ctrl.store.map((s) => ({ ...s })) });
      return; // held: the test answers it
    }
    ctrl.lists += 1;
    return route.fulfill({ status: 200, json: ctrl.store.map((s) => ({ ...s })) });
  }
  if (url.pathname === '/api/scenarios' && request.method() === 'POST') {
    const body = request.postDataJSON();
    if (ctrl.createReject) {
      const reject = ctrl.createReject;
      ctrl.createReject = null;
      return route.fulfill({ status: reject.status, json: { detail: reject.detail } });
    }
    // Stateful create: the store reflects it (newest first) before the
    // response goes out.
    const row = {
      id: 'sc-' + ctrl.nextId,
      name: body.name,
      service_level: body.service_level == null ? null : body.service_level,
      demand_multiplier: body.demand_multiplier == null ? null : body.demand_multiplier,
      lead_time_multiplier: body.lead_time_multiplier == null ? null : body.lead_time_multiplier,
      created_at: '2026-10-17T09:00:00Z',
      updated_at: '2026-10-17T09:00:00Z',
    };
    ctrl.nextId += 1;
    ctrl.store.unshift(row);
    ctrl.created.push({ body, row });
    if (ctrl.createHoldNext) {
      ctrl.createHoldNext = false;
      ctrl.heldCreates.push({ body, row, route });
      return; // held: the test answers it
    }
    return route.fulfill({ status: 201, json: row });
  }
  const idMatch = /^\/api\/scenarios\/([^/]+)$/.exec(url.pathname);
  if (idMatch) {
    const id = decodeURIComponent(idMatch[1]);
    if (request.method() === 'PUT') {
      // Stateful update: merge the posted fields into the row.
      const index = ctrl.store.findIndex((s) => s.id === id);
      if (index === -1) {
        return route.fulfill({ status: 404, json: { detail: 'scenario not found' } });
      }
      const body = request.postDataJSON() || {};
      ctrl.store[index] = Object.assign({}, ctrl.store[index], body, {
        id,
        updated_at: '2026-10-17T09:05:00Z',
      });
      return route.fulfill({ status: 200, json: ctrl.store[index] });
    }
    if (request.method() === 'DELETE') {
      // Stateful delete: the store reflects it before the response.
      const index = ctrl.store.findIndex((s) => s.id === id);
      if (index === -1) {
        ctrl.deleted.push(id);
        return route.fulfill({ status: 404, json: { detail: 'scenario not found' } });
      }
      ctrl.store.splice(index, 1);
      ctrl.deleted.push(id);
      if (ctrl.deleteHoldNext) {
        ctrl.deleteHoldNext = false;
        ctrl.heldDeletes.push({ id, route });
        return; // held: the test answers it
      }
      return route.fulfill({ status: 204 });
    }
  }
  if (url.pathname === '/api/scenarios/simulate' && request.method() === 'POST') {
    ctrl.runs.push({ body: request.postDataJSON() });
    return route.fulfill({ status: 200, json: ctrl.runResponse });
  }
  return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
}

