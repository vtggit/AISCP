// 40 item-sites, in response order: a +15/-10/+25/0 delta pattern plus
// one large item-site so the thousands separators are on screen. The
// summary is built from the rows, so the mock is internally
// consistent — the same shape the #430 proof uses.
function buildResponse(options) {
  const opts = options || {};
  const prefix = opts.prefix || 'I';
  const rows = [];
  for (let i = 0; i < 40; i += 1) {
    const baseline = 500 + i * 37;
    const delta = i % 4 === 0 ? 15 : i % 4 === 1 ? -10 : i % 4 === 2 ? 25 : 0;
    const ssDelta = Math.round(delta / 2);
    rows.push({
      item_code: prefix + String(i + 1).padStart(3, '0'),
      site_code: i % 3 === 0 ? 'S1' : 'S2',
      baseline: {
        reorder_point: baseline - 0.4,
        reorder_point_units: baseline,
        safety_stock: 90 + i,
        safety_stock_units: 90 + i,
      },
      scenario: {
        reorder_point: baseline + delta - 0.4,
        reorder_point_units: baseline + delta,
        safety_stock: 90 + i + ssDelta,
        safety_stock_units: 90 + i + ssDelta,
      },
      reorder_point_units_delta: delta,
      safety_stock_units_delta: ssDelta,
    });
  }
  rows[7] = {
    item_code: prefix + 'BIG',
    site_code: 'S9',
    baseline: {
      reorder_point: 1234567.2,
      reorder_point_units: 1234567,
      safety_stock: 99999.1,
      safety_stock_units: 99999,
    },
    scenario: {
      reorder_point: 1246912.2,
      reorder_point_units: 1246912,
      safety_stock: 100014.1,
      safety_stock_units: 100014,
    },
    reorder_point_units_delta: 12345,
    safety_stock_units_delta: 15,
  };
  const total = (key) => rows.reduce((acc, row) => acc + row[key], 0);
  return {
    summary: {
      item_sites: rows.length,
      reorder_point_units_delta_total: total('reorder_point_units_delta'),
      safety_stock_units_delta_total: total('safety_stock_units_delta'),
      reorder_point_up: rows.filter((r) => r.reorder_point_units_delta > 0).length,
      reorder_point_down: rows.filter((r) => r.reorder_point_units_delta < 0).length,
      reorder_point_unchanged: rows.filter((r) => r.reorder_point_units_delta === 0).length,
      dollar_impact: opts.dollarImpact != null ? opts.dollarImpact : -84210.55,
      item_sites_without_unit_cost: opts.withoutCost != null ? opts.withoutCost : 3,
      levers: { service_level: 0.98, demand_multiplier: 1.2, lead_time_multiplier: null },
    },
    item_sites: rows,
  };
}

