// Proving spec for AIERP issue #441 — save and load of named scenarios
// on the Scenario screen (#/scenario).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. GET /api/scenarios is mocked as a
// STATEFUL resource that reflects create, update and delete operations
// (not a static list); POST /api/scenarios answers 201 echoing the
// posted body with a new id; DELETE /api/scenarios/{id} answers 204
// (404 for an unknown id); POST /api/scenarios/simulate answers a
// summary-and-rows answer as in the #430 proof. Proves, signed in
// through the development token card as an admin (/api/auth/me roles
// ["admin"]), at 1440x900:
//   * on activation the select is populated from GET /api/scenarios in
//     the order returned (newest first) — the first option a
//     non-selectable placeholder, each remaining option its scenario id
//     and name — the hostile name
//     <img src=x onerror=window.__pwned=1> reaching the page as text
//     with window.__pwned undefined; while the list is out the Save and
//     Delete buttons are disabled and the levers still run;
//   * selecting the first scenario fills the fields "98"/"20"/"0" from
//     the stored {service_level 0.98, demand_multiplier 1.2,
//     lead_time_multiplier null} and enables Delete, running nothing,
//     and a subsequent Run sends
//     {service_level: 0.98, demand_multiplier: 1.2,
//      lead_time_multiplier: null};
//   * a name plus Save sends POST /api/scenarios with
//     {name, service_level, demand_multiplier, lead_time_multiplier}
//     matching the current fields; while it is out the Save and Delete
//     buttons are disabled (the Run button is not); after it the list
//     is re-fetched, the new scenario is the selected option (newest
//     first), the save status reads "Saved" and the name input is
//     cleared; a blank name sends no POST and shows
//     "Enter a name to save";
//   * with a scenario selected, Delete sends DELETE
//     /api/scenarios/{id} for that id; while it is out the Save and
//     Delete buttons are disabled; after it the list is re-fetched, the
//     select is back on the placeholder with Delete disabled, the save
//     status reads "Deleted" and the lever fields are unchanged;
//   * a POST /api/scenarios answered 422 shows the server's message in
//     the save status region and leaves the screen usable (the run
//     status region is untouched); a failed GET /api/scenarios shows a
//     non-blocking error in the save status region and leaves the
//     control and the levers usable; a successful save whose list
//     refresh fails shows "Saved", leaves the select on the placeholder
//     (no optimistic insert) and keeps the controls usable;
//   * at 1440x900 the document does not scroll (the table rows still
//     scroll inside their own region) while at 390x844 the page does
//     not scroll sideways, with the saved-scenarios control present;
//   * a save answered 401 leaves the save status region untouched
//     locally — the sign-out is the global auth flow's.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the scenario screen renders
// (with the saved-scenarios control) and runs with no admin-only
// control present.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue441 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

