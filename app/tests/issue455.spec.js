// Proving spec for AIERP issue #455 — the admin-only "Approve → draft
// PO" section of the Work queue detail pane (#/queue).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900:
//   * selecting a Stockout risk row shows the "Approve → draft PO"
//     section, with the quantity prefilled "45" and the unit price
//     prefilled "12.5" from the mocked GET
//     /api/recommendations/by-key (suggested_order_quantity 45,
//     unit_cost 12.5) and the supplier blank; a Reorder point row
//     shows it too (blank on a 404 by-key, prefilled from its own
//     by-key otherwise, and a late/stale 404 for a previous row never
//     clobbers a newer row's prefill or throws); an Excess row does NOT
//     show it — and the
//     existing decision controls, the tab counts, the routing and the
//     sign-in flow are untouched;
//   * Preview is disabled while a request is out and while the
//     supplier is blank or the quantity is not >= 1 or the unit price
//     is not >= 0 (the Create button shares the same gates); with the
//     supplier filled it sends POST
//     /api/replenishment/actions/draft-po with confirm:false and the
//     row's item/site plus the three values as numbers/text, and
//     renders "Would create a draft purchase order" with the returned
//     origin — or, with a mocked existing order, "A draft purchase
//     order already exists: <name>";
//   * Create sends the same body with confirm:true and renders
//     "Draft purchase order created: <name>" (or "… already existed:
//     <name>" when existing is present); a mocked 409 renders "Odoo
//     writes are disabled", a 502 the server's upstream detail and a
//     422 the validation detail — each escaped, the section staying
//     usable and no decision or row state touched (no decision POST,
//     badge and tab counts unchanged);
//   * a hostile name/origin of <img src=x onerror=window.__pwned=1>
//     reaches the page as text with window.__pwned undefined;
//   * at 390x844 the page does not scroll sideways with the section
//     on screen.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, the queue still renders
// read-only and the admin-only section is absent on the Stockout risk
// and Reorder point rows alike (with no by-key prefill fetch).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue455 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
