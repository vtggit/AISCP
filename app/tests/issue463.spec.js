// Proving spec for AIERP issue #463 — the read-only "Aggregate"
// planning screen (#/aggregate).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900:
//   * app/index.html carries the "Aggregate" nav button (after
//     Scenario, before Decision log) and the #view-aggregate section
//     with its #aggregate-root, and app/js/app.js registers the view:
//     clicking the button shows the view and sets the hash to
//     #/aggregate, and a reload on that hash keeps it (the token in
//     sessionStorage survives the reload and the view re-fetches);
//   * the grid ([data-testid="aggregate-grid"]) renders the mocked
//     GET /api/aggregate/projection answer — two site groups ("S1"
//     and "S2") in the order returned, six monthly buckets as
//     columns and the three metric rows (Projected demand, Projected
//     supply, Projected on-hand) as whole units with thousands
//     separators; the bucket the server marks projected_shortfall
//     carries [data-testid="aggregate-shortfall"], the bucket whose
//     on-hand is >= 3x its demand [data-testid="aggregate-excess"],
//     and above zero the item_sites_without_unit_cost figure (2 in
//     the mock) shows the exclusion note;
//   * the units/dollars toggle
//     ([data-testid="aggregate-unit-toggle"]) switches the
//     demand/supply figures to whole dollars (and the on-hand row to
//     an em dash) with no second request, and back again;
//   * the months control ([data-testid="aggregate-months"], a select
//     of 3/6/9/12, default 6) re-fetches with the chosen window on
//     change (the mock answers months=12 with twelve columns);
//   * while a fetch is out a skeleton shows and both controls are
//     disabled; two quick re-fetches (the second started by
//     re-activating the view while the first is held) render only the
//     latest — a stale answer carrying a "STALE" group never reaches
//     the grid (the request sequence guard);
//   * before a load, and on a load that returns no groups, an empty
//     note shows; a malformed (non-object) payload and a 500 both
//     show the inline error with a Retry — never the empty note — and
//     the Retry re-fetches the current months;
//   * a hostile site code of <img src=x onerror=window.__pwned=1>
//     reaches the page as text with window.__pwned undefined;
//   * at 1440x900 the document does not scroll (the grid scrolls in
//     its own region) and at 390x844 the page does not scroll
//     sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, no projection fetch goes out
// before Auth.bootstrap has completed (and none until the view is
// activated), and the Aggregate screen then renders read-only for the
// viewer — the months and figure controls work, and no mutating
// control of any kind exists on the screen.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue463 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

