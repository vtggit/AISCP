// The projection answer for a window: the two groups, in order, each
// with the first ``months`` buckets and the 2 excluded item-sites.
function projectionFor(months) {
  const n = parseInt(months, 10);
  const count = [3, 6, 9, 12].indexOf(n) === -1 ? 6 : n;
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets: S1_BUCKETS.slice(0, count),
      item_sites_without_unit_cost: 2,
    },
    {
      group: { dimension: 'site', code: 'S2' },
      buckets: S2_BUCKETS.slice(0, count),
      item_sites_without_unit_cost: 2,
    },
  ];
}

// The stale-fetch marker: a group that only a superseded answer
// carries — it must never reach the grid.
function staleProjection() {
  return [
    {
      group: { dimension: 'site', code: 'STALE' },
      buckets: [bucket('2099-01', 1, 1, 1, false, 1, 1)],
      item_sites_without_unit_cost: 0,
    },
  ];
}

// The hostile answer: S1's site code carries the XSS payload.
function xssProjection() {
  const groups = projectionFor(12);
  groups[0].group.code = XSS_PAYLOAD;
  return groups;
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can swap the config/me for the viewer
// pass, steer one-shot answers (ctrl.projectionNext) and hold
// projection requests until it releases them (ctrl.projectionHoldNext
// / ctrl.heldProjections) for the stale-fetch scenario.
async function mockAggregateApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    projectionGets: [],
    projectionHoldNext: false,
    heldProjections: [],
    projectionNext: null,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/projection') {
      const months = url.searchParams.get('months') || '6';
      ctrl.projectionGets.push({ months, url: request.url() });
      if (ctrl.projectionHoldNext) {
        ctrl.projectionHoldNext = false;
        ctrl.heldProjections.push({ route, months });
        return; // held: the test answers it (the stale-fetch scenario)
      }
      if (ctrl.projectionNext) {
        const next = ctrl.projectionNext;
        ctrl.projectionNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: projectionFor(months) });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

