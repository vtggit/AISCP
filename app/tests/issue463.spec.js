const XSS_PAYLOAD = '<img src=x onerror=window.__pwned=1>';

const EM_DASH = '\u2014';

function bucket(month, demand, supply, onHand, shortfall, demandValue, supplyValue) {
  return {
    month,
    projected_demand_units: demand,
    projected_supply_units: supply,
    projected_on_hand_units: onHand,
    projected_shortfall: shortfall,
    projected_demand_value: demandValue,
    projected_supply_value: supplyValue,
  };
}

