// Proving spec for AIERP issue #475 — the two planner-screen additions:
// the "ERP code mappings" card of the Settings view and the Odoo target
// codes in the draft-PO result of the Work queue.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900:
//   * the Settings view shows the "ERP code mappings" card
//     ([data-testid="erp-mappings"]) after the System and Personal
//     cards, one row per stored mapping in the order GET
//     /api/erp-mappings returns them — the kind (Item / Site /
//     Vendor), the AIERP code, the Odoo code and when the mapping was
//     last updated;
//   * the admin's add form ([data-testid="erp-mapping-form"] — a kind
//     select of item/site/vendor, a labelled AIERP-code input and a
//     labelled Odoo-code input, each limited to 255 characters, and a
//     Save button) sends PUT /api/erp-mappings with
//     {kind, target_system: "odoo", source_code, target_code}; the
//     stored row the response carries appears as a row, and a second
//     save of the same kind and AIERP code updates that row instead of
//     adding one;
//   * Save is disabled while either code is blank or while a request
//     is out;
//   * a row's Delete button sends DELETE /api/erp-mappings/{id} and
//     the row disappears;
//   * a 422 on save shows its detail inline and leaves the card usable
//     (the stored row unchanged, the form and Save still working);
//   * a failed mappings load shows an inline error with a Retry that
//     re-sends the read, the System and Personal cards untouched;
//   * in the Work queue, a mocked draft-PO dry-run answer carrying
//     `target` shows the Odoo codes
//     ([data-testid="queue-draftpo-target"]) in the result region,
//     reading "Odoo item DESK0005 · site WH · vendor Gemini
//     Furniture" — and a confirm answer with `target` does too — while
//     an answer without `target` shows no target line and renders
//     exactly as before;
//   * a mapping code or a target code carrying
//     <img src=x onerror=window.__pwned=1> reaches the page as text
//     with window.__pwned undefined;
//   * at 390x844 neither the Settings view nor the Work queue scrolls
//     sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the mappings card is
// read-only — no form, no Delete, "Only an admin can change this." —
// while the stored mappings and the rest of the page still render.
//
