// Mock every /api/* call the app makes. The handler reads ctrl on every
// request, so the test can swap the config/me for the viewer pass,
// steer the erp-mappings store (a one-shot putFailNext /
// mappingsFailNext, or holding the next PUT until the test answers it)
// and steer the draft-po answers (a one-shot ctrl.draftPoNext).
async function mockApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    meRequests: [],
    listGets: [],
    settingsGets: 0,
    mappingsGets: 0,
    mappingPuts: [],
    mappingDeletes: [],
    draftPoPosts: [],
    store: initialMappings(),
    nextId: 100,
    putFailNext: null,
    mappingsFailNext: false,
    putHoldNext: false,
    heldPut: null,
    draftPoNext: null,
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/settings') {
      ctrl.settingsGets += 1;
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      ctrl.mappingsGets += 1;
      if (ctrl.mappingsFailNext) {
        ctrl.mappingsFailNext = false;
        return route.fulfill({
          status: 502,
          json: { detail: 'The mappings could not be loaded.' },
        });
      }
      return route.fulfill({ status: 200, json: ctrl.store });
    }
    if (path === '/api/erp-mappings' && request.method() === 'PUT') {
      const body = request.postDataJSON();
      ctrl.mappingPuts.push(body);
      if (ctrl.putFailNext) {
        const failure = ctrl.putFailNext;
        ctrl.putFailNext = null;
        return route.fulfill({ status: failure.status, json: { detail: failure.detail } });
      }
      if (ctrl.putHoldNext) {
        ctrl.putHoldNext = false;
        ctrl.heldPut = { route, body };
        return; // held: the test answers it
      }
      // The API's upsert: an existing (kind, source_code) updates its
      // target code instead of creating a duplicate. The match is the
      // DB's text-column comparison, so the numeric shape of a seeded
      // code (the site's 154) still matches the same logical code.
      const existing = ctrl.store.find(
        (row) => row.kind === body.kind && String(row.source_code) === String(body.source_code),
      );
      const row = existing
        ? { ...existing, target_code: body.target_code, updated_at: '2026-10-18T10:05:00+00:00' }
        : {
            id: ctrl.nextId++,
            kind: body.kind,
            target_system: body.target_system,
            source_code: body.source_code,
            target_code: body.target_code,
            created_at: '2026-10-18T10:00:00+00:00',
            updated_at: '2026-10-18T10:00:00+00:00',
          };
      const index = existing ? ctrl.store.indexOf(existing) : -1;
      if (index === -1) {
        ctrl.store.push(row);
      } else {
        ctrl.store[index] = row;
      }
      return route.fulfill({ status: 200, json: row });
    }
    const deleteMatch = /^\/api\/erp-mappings\/([^/]+)$/.exec(path);
    if (deleteMatch && request.method() === 'DELETE') {
      const id = Number(deleteMatch[1]);
      ctrl.mappingDeletes.push(id);
      const index = ctrl.store.findIndex((row) => row.id === id);
      if (index === -1) {
        return route.fulfill({ status: 404, json: { detail: 'Unknown mapping: ' + id } });
      }
      ctrl.store.splice(index, 1);
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      ctrl.listGets.push(path);
      const rows =
        path === '/api/drift' ? DRIFT_ROWS : path === '/api/excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 404, json: { detail: 'item site not found' } });
    }
    if (path === '/api/replenishment/actions/draft-po' && request.method() === 'POST') {
      const body = request.postDataJSON();
      ctrl.draftPoPosts.push(body);
      const next = ctrl.draftPoNext;
      ctrl.draftPoNext = null;
      if (next) {
        return route.fulfill({ status: next.status, json: next.body });
      }
      return route.fulfill({
        status: 200,
        json: {
          dry_run: !body.confirm,
          would_create: true,
          origin: 'AIERP/' + body.item_code + '/' + body.site_code,
          existing: null,
        },
      });
    }
    if (/^\/api\/(drift|excess|stockout)\/decisions$/.test(path)) {
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

