const EM_DASH = '\u2014';
const ARROW_DOWN = '\u25bc'; // ▼ the shortfall marker
const ARROW_UP = '\u25b2'; // ▲ the excess marker

function bucket(month, demand, supply, onHand, shortfall, demandValue, supplyValue) {
  return {
    month,
    projected_demand_units: demand,
    projected_supply_units: supply,
    projected_on_hand_units: onHand,
    projected_shortfall: shortfall,
    projected_demand_value: demandValue,
    projected_supply_value: supplyValue,
  };
}

// The one group the mock returns: the first bucket is the excess one
// (on-hand 300 is at least 3x the demand 100), the second the
// shortfall one (the server marks it; the rolled on-hand is below
// zero), the third a plain bucket that meets neither rule.
const GROUP_BUCKETS = [
  bucket('2026-11', 100, 0, 300, false, 500, 0),
  bucket('2026-12', 400, 0, -150, true, 2000, 0),
  bucket('2027-01', 800, 600, 250, false, 1600, 1200),
];

// The projection answer for any window: the single group, in order.
function projectionFor(months) {
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets: GROUP_BUCKETS,
      item_sites_without_unit_cost: 0,
    },
  ];
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can swap the config/me for the viewer
// pass and count the projection fetches.
async function mockAggregateApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    projectionGets: [],
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/projection') {
      const months = url.searchParams.get('months') || '6';
      ctrl.projectionGets.push({ months, url: request.url() });
      return route.fulfill({ status: 200, json: projectionFor(months) });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// The ::before content of the flagged cells, the token colours
// resolved through a probe element (the computed background of a box
// whose background is the token), and the flagged cells' backgrounds.
function readColoursAndMarkers() {
  const probe = document.createElement('div');
  probe.style.background = 'var(--color-risk-soft)';
  document.body.appendChild(probe);
  const riskSoft = getComputedStyle(probe).backgroundColor;
  probe.style.background = 'var(--color-accent-soft)';
  const accentSoft = getComputedStyle(probe).backgroundColor;
  probe.remove();
  const shortfallEl = document.querySelector('[data-testid="aggregate-shortfall"]');
  const excessEl = document.querySelector('[data-testid="aggregate-excess"]');
  return {
    riskSoft,
    accentSoft,
    shortfallBg: getComputedStyle(shortfallEl).backgroundColor,
    excessBg: getComputedStyle(excessEl).backgroundColor,
    shortfallText: shortfallEl.textContent,
    excessText: excessEl.textContent,
    shortfallBefore: getComputedStyle(shortfallEl, '::before').content,
    excessBefore: getComputedStyle(excessEl, '::before').content,
  };
}

// The computed ::before content of a generated string is a CSS string
// token (double-quoted in the computed value); strip the quotes so the
// marker character itself is compared.
function unquote(content) {
  return content && content.length >= 2 && content.startsWith('"') && content.endsWith('"')
    ? content.slice(1, -1)
    : content;
}

test('issue477 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in card, straight onto #/aggregate
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockAggregateApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
  });

  const monthsSelect = page.locator('[data-testid="aggregate-months"]');
  const unitToggle = page.locator('[data-testid="aggregate-unit-toggle"]');
  const grid = page.locator('[data-testid="aggregate-grid"]');
  const legend = page.locator('[data-testid="aggregate-legend"]');
  const shortfallCell = page.locator('[data-testid="aggregate-shortfall"]');
  const excessCell = page.locator('[data-testid="aggregate-excess"]');

  await page.goto('/#/aggregate');

  // No projection request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(0);
  // Before a load the grid has no groups: no legend yet.
  await expect(legend).toHaveCount(0);

  // Sign in through the development token card (the usual admin stub).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(page.url()).toContain('#/aggregate');
  await expect(grid).toBeVisible();
  await expect.poll(() => ctrl.projectionGets.length).toBe(1);
  expect(ctrl.projectionGets[0].months).toBe('6');
  expect(pageErrors).toEqual([]);

  // One group, three month columns, the three metric rows.
  await expect(grid.locator('[data-testid="aggregate-group"]')).toHaveCount(1);
  await expect(grid.locator('thead th')).toHaveText(['Month', '2026-11', '2026-12', '2027-01']);
  await expect(grid.locator('tbody th')).toHaveText([
    'Projected demand',
    'Projected supply',
    'Projected on-hand',
  ]);

  // --- the flags: colours from the tokens, two different hues --------
  await expect(shortfallCell).toHaveCount(1);
  await expect(excessCell).toHaveCount(1);

  const colours = await page.evaluate(readColoursAndMarkers);
  expect(colours.shortfallBg).not.toBe(colours.excessBg);
  expect(colours.shortfallBg).toBe(colours.riskSoft);
  expect(colours.excessBg).toBe(colours.accentSoft);

  // --- the non-colour cue: the leading markers, the text untouched ---
  expect(unquote(colours.shortfallBefore)).toBe(ARROW_DOWN);
  expect(unquote(colours.excessBefore)).toBe(ARROW_UP);
  expect(colours.shortfallText).toBe('-150');
  expect(colours.excessText).toBe('300');

  // --- the accessible names: aria-label and title, the figure -------
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(shortfallCell).toHaveAttribute('title', 'Projected shortfall: -150');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 300');
  await expect(excessCell).toHaveAttribute('title', 'Projected excess: 300');

  // --- the legend: below the controls, both labels, the cell tokens -
  await expect(legend).toBeVisible();
  await expect(legend).toHaveCount(1);
  await expect(legend.locator('.ag-legend-item')).toHaveCount(2);
  await expect(legend.locator('.ag-legend-item').nth(0)).toContainText(
    'Shortfall: projected on-hand below zero',
  );
  await expect(legend.locator('.ag-legend-item').nth(1)).toContainText(
    'Excess: on-hand at least 3\u00d7 the month\'s demand',
  );
  const legendLayout = await page.evaluate(() => {
    const controls = document.querySelector('[data-testid="aggregate-controls"]');
    const leg = document.querySelector('[data-testid="aggregate-legend"]');
    const swatches = Array.from(
      document.querySelectorAll('[data-testid="aggregate-legend"] .ag-legend-swatch'),
    ).map((el) => ({
      text: el.textContent,
      background: getComputedStyle(el).backgroundColor,
      color: getComputedStyle(el).color,
    }));
    return {
      belowControls: leg.getBoundingClientRect().top >= controls.getBoundingClientRect().bottom,
      swatches,
    };
  });
  expect(legendLayout.belowControls).toBe(true);
  expect(legendLayout.swatches).toHaveLength(2);
  expect(legendLayout.swatches[0].text).toBe(ARROW_DOWN);
  expect(legendLayout.swatches[0].background).toBe(colours.riskSoft);
  expect(legendLayout.swatches[1].text).toBe(ARROW_UP);
  expect(legendLayout.swatches[1].background).toBe(colours.accentSoft);

  // --- unflagged cells: no marker, no such label ---------------------
  const cells = await page.evaluate(() =>
    Array.from(document.querySelectorAll('.ag-table tbody td')).map((td) => ({
      flagged: !!td.getAttribute('data-testid'),
      before: getComputedStyle(td, '::before').content,
      ariaLabel: td.getAttribute('aria-label'),
      title: td.getAttribute('title'),
    })),
  );
  const unflagged = cells.filter((c) => !c.flagged);
  expect(unflagged.length).toBeGreaterThan(0);
  for (const c of unflagged) {
    expect(c.before).toBe('none');
    expect(c.ariaLabel).toBeNull();
    expect(c.title).toBeNull();
  }

  // --- dollars mode: the on-hand cell reads an em dash, but the flag's
  // --- name keeps the units figure -------------------------------------
  const fetchesBeforeToggle = ctrl.projectionGets.length;
  await unitToggle.selectOption('dollars');
  await expect(shortfallCell).toHaveText(EM_DASH);
  await expect(excessCell).toHaveText(EM_DASH);
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(shortfallCell).toHaveAttribute('title', 'Projected shortfall: -150');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 300');
  await expect(excessCell).toHaveAttribute('title', 'Projected excess: 300');
  const dollarState = await page.evaluate(readColoursAndMarkers);
  expect(unquote(dollarState.shortfallBefore)).toBe(ARROW_DOWN);
  expect(unquote(dollarState.excessBefore)).toBe(ARROW_UP);
  expect(dollarState.shortfallBg).toBe(colours.riskSoft);
  expect(dollarState.excessBg).toBe(colours.accentSoft);
  await expect(legend).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(fetchesBeforeToggle);

  await unitToggle.selectOption('units');
  await expect(shortfallCell).toHaveText('-150');
  await expect(excessCell).toHaveText('300');

  // --- 390x844: no horizontal page scroll -----------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(grid).toBeVisible();
  await expect(legend).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN (role 'user'), production boot, full
  // --- reload -----------------------------------------------------------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const meCountBeforeViewer = ctrl.meRequests.length;
  const projectionGetsBeforeViewer = ctrl.projectionGets.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and no projection fetch went out before Auth.bootstrap had
  // completed (the production boot lands on #/overview, the aggregate
  // view is not active and fetches nothing).
  expect(ctrl.projectionGets.length).toBe(projectionGetsBeforeViewer);

  // Activating the view for the viewer shows it read-only: the page
  // still renders, with the flags and the legend ...
  await page.click('.nav-btn[data-view="aggregate"]');
  expect(page.url()).toContain('#/aggregate');
  await expect(page.locator('#view-aggregate')).toBeVisible();
  await expect(grid).toBeVisible();
  await expect(grid.locator('[data-testid="aggregate-group"]')).toHaveCount(1);
  await expect(shortfallCell).toHaveText('-150');
  await expect(excessCell).toHaveText('300');
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 300');
  await expect(legend).toBeVisible();
  const viewerFlags = await page.evaluate(readColoursAndMarkers);
  expect(unquote(viewerFlags.shortfallBefore)).toBe(ARROW_DOWN);
  expect(unquote(viewerFlags.excessBefore)).toBe(ARROW_UP);
  expect(viewerFlags.shortfallBg).toBe(colours.riskSoft);
  expect(viewerFlags.excessBg).toBe(colours.accentSoft);

  // ... and no admin-only (indeed no mutating) control of any kind
  // exists on the screen — the read-only months and figure controls
  // are the only controls it carries, and they work for the viewer.
  await expect(page.locator('#aggregate-root [data-admin-only]')).toHaveCount(0);
  await expect(page.locator('#aggregate-root button')).toHaveCount(0);
  await expect(monthsSelect).toBeVisible();
  await expect(unitToggle).toBeVisible();
  const viewerFetches = ctrl.projectionGets.length;
  await unitToggle.selectOption('dollars');
  await expect(shortfallCell).toHaveText(EM_DASH);
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 300');
  expect(ctrl.projectionGets.length).toBe(viewerFetches);
  expect(pageErrors).toEqual([]);
});
