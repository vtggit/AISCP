// Proving spec for AIERP issue #477 — the on-hand flags of the
// Aggregate planning screen (#/aggregate): shortfall and excess are
// distinguished by more than colour, and named for screen readers.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900,
// with GET /api/aggregate/projection mocked to one group whose buckets
// include a shortfall bucket (projected_shortfall true) and an excess
// bucket (on-hand at least 3x the demand):
//   * the shortfall cell keeps the risk treatment (background the
//     computed value of --color-risk-soft) and the excess cell moves
//     to the accent treatment (background the computed value of
//     --color-accent-soft) — two different hues, tokens only;
//   * each flagged cell shows a leading marker drawn by CSS ::before —
//     "▼" for the shortfall, "▲" for the excess (read via
//     getComputedStyle(el, '::before').content) — while the cell's
//     textContent is still just the figure;
//   * each flagged cell carries the accessible name in aria-label and
//     the same text in title — "Projected shortfall: <figure>" /
//     "Projected excess: <figure>", the figure as displayed (the units
//     figure, so in dollars mode the on-hand cell reads as an em dash
//     yet the flag's name still carries the units figure);
//   * below the Months/Figures controls the legend
//     ([data-testid="aggregate-legend"]) shows a swatch and label for
//     each flag — "Shortfall: projected on-hand below zero" and
//     "Excess: on-hand at least 3× the month's demand" — in the same
//     tokens as the cells, and it is visible whenever the grid has
//     groups (absent before a load, with the empty note);
//   * an unflagged cell carries no marker and no such label;
//   * at 390x844 the page does not scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the Aggregate screen then
// renders read-only for the viewer — the flags and legend show, the
// months and figure controls work, and no admin-only (indeed no
// mutating) control of any kind exists on the screen.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue477 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

