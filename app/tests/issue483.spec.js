// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can swap the config/me for the viewer
// pass and steer the erp-mappings store.
async function mockApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    store: initialMappings(),
    mappingsGets: 0,
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      ctrl.mappingsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.store });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/recommendations/by-key') {
      return route.fulfill({ status: 404, json: { detail: 'item site not found' } });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue483 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in, straight onto #/settings -------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
  });

  const card = page.locator('[data-testid="erp-mappings"]');
  const form = page.locator('[data-testid="erp-mapping-form"]');
  const head = page.locator('[data-testid="erp-mapping-head"]');
  const rows = page.locator('[data-testid="erp-mapping-row"]');

  await page.goto('/#/settings');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  await expect(card).toBeVisible();
  await expect(rows).toHaveCount(3);
  await expect(head).toBeVisible();

  // --- wide (1440x900): the list reads as a labelled table -------------
  // Each row lays out horizontally ...
  const flexDirections = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => getComputedStyle(rowEl).flexDirection),
  );
  expect(flexDirections).toEqual(['row', 'row', 'row']);

  // ... and its Delete sits at the right end of the same line: the
  // button's vertical centre lies within the vertical extent of the
  // row's AIERP code cell.
  const deleteOnLine = await page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-testid="erp-mapping-row"]')).map((rowEl) => {
      const codeCell = rowEl.querySelector('.erp-mapping-code');
      const deleteButton = rowEl.querySelector('.erp-mapping-delete');
      if (!codeCell || !deleteButton) return false;
      const codeBox = codeCell.getBoundingClientRect();
      const deleteBox = deleteButton.getBoundingClientRect();
      const centre = deleteBox.top + deleteBox.height / 2;
      return centre >= codeBox.top && centre <= codeBox.bottom;
    }),
  );
  expect(deleteOnLine).toEqual([true, true, true]);

  // The rows are left-aligned with the card's content, and the header
  // (directly above the rows) lines up with them: every row's left
  // edge is within 1px of the header's ...
  const rowLefts = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => rowEl.getBoundingClientRect().left),
  );
  const headLeft = await head.evaluate((headEl) => headEl.getBoundingClientRect().left);
  const cardContentLeft = await card.evaluate((cardEl) => {
    const box = cardEl.getBoundingClientRect();
    const styles = getComputedStyle(cardEl);
    return box.left + parseFloat(styles.borderLeftWidth) + parseFloat(styles.paddingLeft);
  });
  for (const rowLeft of rowLefts) {
    expect(Math.abs(rowLeft - headLeft)).toBeLessThanOrEqual(1);
    expect(Math.abs(rowLeft - cardContentLeft)).toBeLessThanOrEqual(1);
  }

  // ... and it labels the four columns in the rows' own column
  // template: the "AIERP code" and "Odoo code" labels sit within 2px
  // of their values in the first row.
  const headLabels = await head.evaluate((headEl) =>
    Array.from(headEl.children).map((cellEl) => (cellEl.textContent || '').trim()),
  );
  expect(headLabels).toEqual(['Kind', 'AISCP code', 'Odoo code', 'Updated']);
  const labelAlignment = await page.evaluate(() => {
    const headEl = document.querySelector('[data-testid="erp-mapping-head"]');
    const firstRow = document.querySelector('[data-testid="erp-mapping-row"]');
    const headCells = Array.from(headEl.children).map((cellEl) =>
      cellEl.getBoundingClientRect().left,
    );
    return {
      aierpLabel: headCells[1],
      odooLabel: headCells[2],
      aierpCell: firstRow.querySelector('.erp-mapping-code').getBoundingClientRect().left,
      odooCell: firstRow.querySelector('.erp-mapping-target-code').getBoundingClientRect().left,
    };
  });
  expect(Math.abs(labelAlignment.aierpLabel - labelAlignment.aierpCell)).toBeLessThanOrEqual(2);
  expect(Math.abs(labelAlignment.odooLabel - labelAlignment.odooCell)).toBeLessThanOrEqual(2);

  // Each code cell is labelled for assistive tech, the value inserted
  // as text (never as HTML).
  const codeLabels = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => [
      rowEl.querySelector('.erp-mapping-code').getAttribute('aria-label'),
      rowEl.querySelector('.erp-mapping-target-code').getAttribute('aria-label'),
    ]),
  );
  expect(codeLabels).toEqual([
    ['AISCP code: DSAFIEX20S', 'Odoo code: DESK0005'],
    ['AISCP code: 154', 'Odoo code: WH'],
    ['AISCP code: GEMINI', 'Odoo code: SUP0001'],
  ]);
  expect(pageErrors).toEqual([]);

  // --- empty list: the header is absent or hidden -----------------------
  ctrl.store = [];
  await page.reload();
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // The empty note is the terminal state (while the list loads there
  // are no rows either, so it is what pins the check to the loaded
  // empty list).
  await expect(card.locator('.erp-mappings-empty')).toHaveText('No ERP code mappings yet.');
  await expect(rows).toHaveCount(0);
  const headCount = await head.count();
  expect(headCount).toBeLessThanOrEqual(1);
  if (headCount === 1) {
    expect(await head.isVisible()).toBe(false);
  }

  // --- narrow (390x844): the rows stack, the header hides ---------------
  ctrl.store = initialMappings();
  await page.reload();
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect(rows).toHaveCount(3);

  await page.setViewportSize({ width: 390, height: 844 });
  await expect(card).toBeVisible();
  // Each row stacks its values left-aligned ...
  const narrowAlignItems = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => getComputedStyle(rowEl).alignItems),
  );
  expect(narrowAlignItems).toEqual(['flex-start', 'flex-start', 'flex-start']);
  // ... with the Delete under the values ...
  const deleteBelow = await page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-testid="erp-mapping-row"]')).map((rowEl) => {
      const deleteButton = rowEl.querySelector('.erp-mapping-delete');
      const updatedCell = rowEl.querySelector('.erp-mapping-updated');
      if (!deleteButton || !updatedCell) return false;
      return (
        deleteButton.getBoundingClientRect().top >=
        updatedCell.getBoundingClientRect().bottom - 1
      );
    }),
  );
  expect(deleteBelow).toEqual([true, true, true]);
  // ... the header is hidden, and each code keeps its aria-label.
  expect(await head.isVisible()).toBe(false);
  const narrowCodeLabels = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => [
      rowEl.querySelector('.erp-mapping-code').getAttribute('aria-label'),
      rowEl.querySelector('.erp-mapping-target-code').getAttribute('aria-label'),
    ]),
  );
  expect(narrowCodeLabels).toEqual(codeLabels);
  // And the page does not scroll sideways.
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ------------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  ctrl.store = initialMappings();
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );

  // ... and the mappings card renders read-only: the admin-only
  // controls (the add form and the per-row Delete) are absent ...
  await page.click('.nav-btn[data-view="settings"]');
  await expect(card).toBeVisible();
  await expect(card).toContainText('Only an admin can change this.');
  await expect(form).toHaveCount(0);
  expect(await page.locator('button.erp-mapping-delete').count()).toBe(0);
  // ... while the stored mappings, the header's column labels and the
  // rest of the page still render.
  await expect(rows).toHaveCount(3);
  await expect(rows.nth(0)).toContainText('Item');
  await expect(rows.nth(0)).toContainText('DSAFIEX20S');
  await expect(rows.nth(0)).toContainText('DESK0005');
  await expect(rows.nth(1)).toContainText('Site');
  await expect(rows.nth(1)).toContainText('154');
  await expect(rows.nth(1)).toContainText('WH');
  await expect(rows.nth(2)).toContainText('Vendor');
  await expect(rows.nth(2)).toContainText('GEMINI');
  await expect(rows.nth(2)).toContainText('SUP0001');
  await expect(head).toBeVisible();
  const viewerHeadLabels = await head.evaluate((headEl) =>
    Array.from(headEl.children).map((cellEl) => (cellEl.textContent || '').trim()),
  );
  expect(viewerHeadLabels).toEqual(['Kind', 'AISCP code', 'Odoo code', 'Updated']);
  const viewerCodeLabels = await rows.evaluateAll((rowEls) =>
    rowEls.map((rowEl) => [
      rowEl.querySelector('.erp-mapping-code').getAttribute('aria-label'),
      rowEl.querySelector('.erp-mapping-target-code').getAttribute('aria-label'),
    ]),
  );
  expect(viewerCodeLabels).toEqual(codeLabels);
  await expect(page.locator('.settings-card[aria-label="System"]')).toBeVisible();
  await expect(page.locator('.settings-card[aria-label="Personal"]')).toBeVisible();
  expect(pageErrors).toEqual([]);
});
