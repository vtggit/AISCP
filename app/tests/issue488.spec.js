// The XSS payload a hostile site code may carry: it must reach the
// page as text — window.__pwned stays undefined.
const XSS_PAYLOAD = '<img src=x onerror=window.__pwned=1>';

const EM_DASH = '\u2014';

// One bucket of the S1 group: the existing projection fields, and the
// four planned fields when `planned` is given (the months=3 window
// omits them for its last bucket to prove the missing-fields case).
function bucket(month, demand, supply, onHand, shortfall, demandValue, supplyValue, planned) {
  const b = {
    month,
    projected_demand_units: demand,
    projected_supply_units: supply,
    projected_on_hand_units: onHand,
    projected_shortfall: shortfall,
    projected_demand_value: demandValue,
    projected_supply_value: supplyValue,
  };
  if (planned) {
    Object.assign(b, planned);
  }
  return b;
}

// Bucket 1: the as-is shortfall (projected_shortfall true, rolled
// on-hand below zero). The planned on-hand (50) is positive and below
// 3x the demand (300), and the server does not mark planned_shortfall
// — the bucket is unflagged in the planned view.
const B1 = bucket('2026-11', 100, 0, -150, true, 500, 0, {
  planned_receipts_units: 250,
  planned_receipts_value: 1250,
  planned_on_hand_units: 50,
  planned_shortfall: false,
});

// Bucket 2: plain as-is (on-hand 120 is far below 3x the demand 400),
// but the server marks planned_shortfall — the planned on-hand cell
// carries the shortfall flag.
const B2 = bucket('2026-12', 400, 0, 120, false, 2000, 0, {
  planned_receipts_units: 300,
  planned_receipts_value: 900,
  planned_on_hand_units: -80,
  planned_shortfall: true,
});

// Bucket 3: plain as-is (on-hand 250 is below 3x the demand 800), but
// the planned on-hand (2600) is at least 3x the demand (2400) — the
// planned on-hand cell carries the excess flag.
const B3 = bucket('2027-01', 800, 600, 250, false, 1600, 1200, {
  planned_receipts_units: 2400,
  planned_receipts_value: 9600,
  planned_on_hand_units: 2600,
  planned_shortfall: false,
});

// The same last bucket without its planned fields: the planned cells
// must read em dashes, and the bucket must be flagged by neither rule.
const B3_NO_PLANNED = bucket('2027-01', 800, 600, 250, false, 1600, 1200);

// The projection answer for a window: the single group, in order. The
// months=3 window drops the planned fields of its last bucket.
function projectionFor(months) {
  const n = parseInt(months, 10);
  const buckets = n === 3 ? [B1, B2, B3_NO_PLANNED] : [B1, B2, B3];
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets,
      item_sites_without_unit_cost: 0,
    },
  ];
}

// The hostile answer: the group's site code carries the XSS payload.
function xssProjectionFor(months) {
  const groups = projectionFor(months);
  groups[0].group.code = XSS_PAYLOAD;
  return groups;
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer one-shot answers
// (ctrl.projectionNext) and hold projection requests until it
// releases them (ctrl.projectionHoldNext / ctrl.heldProjections) to
// observe the controls while a fetch is out.
async function mockAggregateApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    projectionGets: [],
    projectionHoldNext: false,
    heldProjections: [],
    projectionNext: null,
    meRequests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/projection') {
      const months = url.searchParams.get('months') || '6';
      ctrl.projectionGets.push({ months, url: request.url() });
      if (ctrl.projectionHoldNext) {
        ctrl.projectionHoldNext = false;
        ctrl.heldProjections.push({ route, months });
        return; // held: the test answers it (the disabled-controls check)
      }
      if (ctrl.projectionNext) {
        const next = ctrl.projectionNext;
        ctrl.projectionNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: projectionFor(months) });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

test('issue488 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in card, straight onto #/aggregate
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = await mockAggregateApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  const monthsSelect = page.locator('[data-testid="aggregate-months"]');
  const unitToggle = page.locator('[data-testid="aggregate-unit-toggle"]');
  const planToggle = page.locator('[data-testid="aggregate-plan-toggle"]');
  const grid = page.locator('[data-testid="aggregate-grid"]');
  const groupTitle = grid.locator('.ag-group-title').first();
  const legend = page.locator('[data-testid="aggregate-legend"]');
  const planNote = page.locator('[data-testid="aggregate-plan-note"]');
  const shortfallCell = page.locator('[data-testid="aggregate-shortfall"]');
  const excessCell = page.locator('[data-testid="aggregate-excess"]');

  await page.goto('/#/aggregate');

  // No projection request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(0);

  // Sign in through the development token card (the usual admin stub).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(page.url()).toContain('#/aggregate');
  await expect(grid).toBeVisible();
  await expect.poll(() => ctrl.projectionGets.length).toBe(1);
  expect(ctrl.projectionGets[0].months).toBe('6');
  expect(pageErrors).toEqual([]);

  // --- the plan control: next to Months and Figures, labelled "Plan",
  // --- "As is" (as-is) the default, "With planned orders" (planned) ---
  await expect(planToggle).toBeVisible();
  await expect(planToggle).toBeEnabled();
  await expect(planToggle).toHaveValue('as-is');
  await expect(page.locator('label[for="ag-plan"]')).toHaveText('Plan');
  await expect(planToggle.locator('option')).toHaveCount(2);
  await expect(planToggle.locator('option').nth(0)).toHaveAttribute('value', 'as-is');
  await expect(planToggle.locator('option').nth(0)).toHaveText('As is');
  await expect(planToggle.locator('option').nth(1)).toHaveAttribute('value', 'planned');
  await expect(planToggle.locator('option').nth(1)).toHaveText('With planned orders');

  // --- the As is grid: exactly the three rows, bucket 1 the shortfall
  await expect(groupTitle).toHaveText('S1');
  await expect(grid.locator('thead th')).toHaveText(['Month', '2026-11', '2026-12', '2027-01']);
  await expect(grid.locator('tbody tr')).toHaveCount(3);
  await expect(grid.locator('tbody th')).toHaveText([
    'Projected demand',
    'Projected supply',
    'Projected on-hand',
  ]);
  await expect(grid.locator('tbody tr').nth(0).locator('td')).toHaveText(['100', '400', '800']);
  await expect(grid.locator('tbody tr').nth(2).locator('td')).toHaveText(['-150', '120', '250']);
  await expect(shortfallCell).toHaveCount(1);
  await expect(shortfallCell).toHaveText('-150');
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(grid.locator('tbody tr').nth(2).locator('td').nth(0)).toHaveAttribute(
    'data-testid',
    'aggregate-shortfall',
  );
  await expect(excessCell).toHaveCount(0);
  // The plan note does not show in As is.
  await expect(planNote).toHaveCount(0);

  // --- "With planned orders": re-rendered from the loaded answer, no
  // --- second projection request ----------------------------------------
  const fetchesBeforePlan = ctrl.projectionGets.length;
  await planToggle.selectOption('planned');

  // The four row labels, in order.
  await expect(grid.locator('tbody tr')).toHaveCount(4);
  await expect(grid.locator('tbody th')).toHaveText([
    'Projected demand',
    'Projected supply',
    'Planned receipts',
    'Planned on-hand',
  ]);
  // The re-render is up: only now is "no second projection request"
  // provable -- a request the change fired would already be recorded,
  // while asserting before the render could pass with one in flight.
  expect(ctrl.projectionGets.length).toBe(fetchesBeforePlan);

  // The unchanged rows keep the same figures ...
  await expect(grid.locator('tbody tr').nth(0).locator('td')).toHaveText(['100', '400', '800']);
  await expect(grid.locator('tbody tr').nth(1).locator('td')).toHaveText(['0', '0', '600']);
  // ... and the planned rows read whole units with thousands
  // separators.
  await expect(grid.locator('tbody tr').nth(2).locator('td')).toHaveText(['250', '300', '2,400']);
  await expect(grid.locator('tbody tr').nth(3).locator('td')).toHaveText(['50', '-80', '2,600']);

  // Bucket 1: the as-is shortfall is not flagged in this view, and
  // the planned on-hand (50) is below 3x the demand — unflagged.
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(0)).toHaveText('50');
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(0)).not.toHaveAttribute(
    'data-testid',
  );
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(0)).not.toHaveAttribute(
    'aria-label',
  );

  // Bucket 2: the planned shortfall, named for the planned figure.
  await expect(shortfallCell).toHaveCount(1);
  await expect(shortfallCell).toHaveText('-80');
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -80');
  await expect(shortfallCell).toHaveAttribute('title', 'Projected shortfall: -80');
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(1)).toHaveAttribute(
    'aria-label',
    'Projected shortfall: -80',
  );

  // Bucket 3: the planned on-hand is at least 3x the demand — excess.
  await expect(excessCell).toHaveCount(1);
  await expect(excessCell).toHaveText('2,600');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 2,600');
  await expect(excessCell).toHaveAttribute('title', 'Projected excess: 2,600');

  // The plan note: under the legend, explaining the planned orders.
  await expect(legend).toBeVisible();
  await expect(planNote).toBeVisible();
  await expect(planNote).toHaveText(
    "Planned orders: at each monthly review, an item-site whose stock position is below its reorder point plus that month's demand orders up to that level, arriving after its lead time.",
  );
  const noteLayout = await page.evaluate(() => {
    const legendEl = document.querySelector('[data-testid="aggregate-legend"]');
    const note = document.querySelector('[data-testid="aggregate-plan-note"]');
    return {
      belowLegend: note.getBoundingClientRect().top >= legendEl.getBoundingClientRect().bottom,
    };
  });
  expect(noteLayout.belowLegend).toBe(true);

  // --- dollars mode: whole dollars for the receipts, an em dash for
  // --- the planned on-hand; the flags keep the units figures ----------
  const fetchesBeforeDollars = ctrl.projectionGets.length;
  await unitToggle.selectOption('dollars');
  await expect(grid.locator('tbody tr').nth(2).locator('td')).toHaveText([
    '$1,250',
    '$900',
    '$9,600',
  ]);
  await expect(grid.locator('tbody tr').nth(3).locator('td')).toHaveText([
    EM_DASH,
    EM_DASH,
    EM_DASH,
  ]);
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -80');
  await expect(excessCell).toHaveAttribute('aria-label', 'Projected excess: 2,600');
  expect(ctrl.projectionGets.length).toBe(fetchesBeforeDollars);
  await unitToggle.selectOption('units');
  await expect(grid.locator('tbody tr').nth(3).locator('td')).toHaveText(['50', '-80', '2,600']);

  // --- 390x844 in the planned view: no horizontal page scroll ---------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(grid).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.setViewportSize({ width: 1440, height: 900 });

  // --- Months to 3: the re-fetch (held, so the controls show disabled)
  // --- keeps "With planned orders" selected ----------------------------
  const fetchesBeforeMonths3 = ctrl.projectionGets.length;
  ctrl.projectionHoldNext = true;
  await monthsSelect.selectOption('3');
  await expect.poll(() => ctrl.projectionGets.length).toBe(fetchesBeforeMonths3 + 1);
  expect(ctrl.projectionGets[ctrl.projectionGets.length - 1].months).toBe('3');
  // While the fetch is out: the skeleton shows and the controls —
  // including the plan select — are disabled.
  await expect(page.locator('[data-testid="aggregate-skeleton"]')).toHaveCount(1);
  await expect(grid).toHaveCount(0);
  await expect(monthsSelect).toBeDisabled();
  await expect(unitToggle).toBeDisabled();
  await expect(planToggle).toBeDisabled();

  // ... and the answer renders with the plan choice kept.
  ctrl.heldProjections[0].route.fulfill({ status: 200, json: projectionFor('3') });
  await expect(grid).toBeVisible();
  await expect(monthsSelect).toBeEnabled();
  await expect(unitToggle).toBeEnabled();
  await expect(planToggle).toBeEnabled();
  await expect(planToggle).toHaveValue('planned');
  await expect(grid.locator('tbody th')).toHaveText([
    'Projected demand',
    'Projected supply',
    'Planned receipts',
    'Planned on-hand',
  ]);
  await expect(planNote).toBeVisible();

  // The last bucket of the window carries no planned fields: its
  // planned cells read em dashes, and it is flagged by neither rule.
  await expect(grid.locator('tbody tr').nth(2).locator('td').nth(2)).toHaveText(EM_DASH);
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(2)).toHaveText(EM_DASH);
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(2)).not.toHaveAttribute(
    'data-testid',
  );
  await expect(grid.locator('tbody tr').nth(3).locator('td').nth(2)).not.toHaveAttribute(
    'aria-label',
  );
  // The flagged buckets of the window: the planned shortfall only.
  await expect(shortfallCell).toHaveCount(1);
  await expect(shortfallCell).toHaveText('-80');
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -80');
  await expect(excessCell).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- back to "As is": the three rows restored, the note hidden, no
  // --- request -----------------------------------------------------------
  const fetchesBeforeBack = ctrl.projectionGets.length;
  await planToggle.selectOption('as-is');
  await expect(grid.locator('tbody tr')).toHaveCount(3);
  await expect(grid.locator('tbody th')).toHaveText([
    'Projected demand',
    'Projected supply',
    'Projected on-hand',
  ]);
  await expect(planNote).toHaveCount(0);
  // The re-render is up: still no request (same proof as the switch
  // to planned, checked only after the render completes).
  expect(ctrl.projectionGets.length).toBe(fetchesBeforeBack);
  await expect(shortfallCell).toHaveCount(1);
  await expect(shortfallCell).toHaveText('-150');
  await expect(shortfallCell).toHaveAttribute('aria-label', 'Projected shortfall: -150');
  await expect(excessCell).toHaveCount(0);

  // --- a hostile site code reaches the page as text only ------------------
  ctrl.projectionNext = { status: 200, json: xssProjectionFor('6') };
  await monthsSelect.selectOption('6');
  await expect(grid).toBeVisible();
  await expect(groupTitle).toHaveText(XSS_PAYLOAD);
  expect(await grid.locator('img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // --- 390x844: no horizontal page scroll ---------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(grid).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);
});
