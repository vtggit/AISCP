// Proving spec for AIERP issue #488 — the "With planned orders" view of
// the Aggregate planning screen (#/aggregate): a plan control next to
// Months and Figures that re-renders the loaded projection without a
// new request, and a planned view of the same buckets.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900,
// with GET /api/aggregate/projection mocked to one group ("S1") whose
// three buckets carry the existing fields plus the four planned
// fields (planned_receipts_units, planned_receipts_value,
// planned_on_hand_units, planned_shortfall):
//   * the Plan control ([data-testid="aggregate-plan-toggle"],
//     labelled "Plan", next to Months and Figures) offers "As is"
//     (value as-is, the default) and "With planned orders" (value
//     planned), is visible with "As is" selected after the first
//     load, and is disabled while a fetch is out like the other
//     controls;
//   * the As is grid is exactly what it was: the three rows Projected
//     demand, Projected supply and Projected on-hand, and the bucket
//     the server marks projected_shortfall (bucket 1) is the only
//     flagged cell;
//   * choosing "With planned orders" re-renders from the loaded answer
//     with no second projection request: the four row labels in order
//     (Projected demand, Projected supply, Planned receipts, Planned
//     on-hand), the Planned receipts and Planned on-hand figures as
//     whole units with thousands separators, bucket 1 (planned
//     on-hand below 3x the demand, not marked planned_shortfall)
//     unflagged, bucket 2 (planned_shortfall true) flagged shortfall
//     with the accessible name "Projected shortfall: <planned figure>"
//     in aria-label and title, and bucket 3 (planned on-hand at least
//     3x its demand) flagged excess — the same classes, data-testids,
//     markers and colours as the as-is flags, and the as-is on-hand
//     flags gone;
//   * in dollars mode the Planned receipts row reads whole dollars and
//     the Planned on-hand row an em dash, while the flags' accessible
//     names keep the units figures;
//   * changing Months to 3 re-fetches (the fetch held to prove the
//     controls are disabled while it is out) and keeps "With planned
//     orders" selected; the answer for that window carries a bucket
//     with the planned fields missing, and that bucket's planned
//     cells read em dashes with no flag;
//   * switching back to "As is" restores the three rows and hides the
//     note, again without a request;
//   * in the planned view a note under the legend
//     ([data-testid="aggregate-plan-note"]) explains the planned
//     orders, and it does not show in As is;
//   * a hostile site code of <img src=x onerror=window.__pwned=1>
//     reaches the page as text with window.__pwned undefined;
//   * at 390x844 the page does not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue488 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

