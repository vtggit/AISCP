// Proving spec for AIERP issue #492 — the reworded plan note of the
// Aggregate planning screen (#/aggregate): the note under the legend
// ([data-testid="aggregate-plan-note"], shown in the "With planned
// orders" view only) now reads the monthly-review sentence, and
// nothing else about the note's place or timing changes.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900,
// with GET /api/aggregate/projection mocked to one group ("S1") whose
// two buckets carry the existing fields plus the planned fields
// (planned_receipts_units, planned_receipts_value,
// planned_on_hand_units, planned_shortfall):
//   * in the "As is" view (the default after the first load) the plan
//     note is absent;
//   * choosing "With planned orders" shows the note under the legend,
//     and its text is exactly:
//     "Planned orders: at each monthly review, an item-site whose
//     stock position is below its reorder point plus that month's
//     demand orders up to that level, arriving after its lead time.";
//   * switching back to "As is" hides the note again;
//   * at 390x844 the page does not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue492 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs several sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

const DEV_CONFIG = {
  authEnabled: true,
  authMode: 'development',
  issuer: 'http://idp.test/realms/r',
  clientId: 'aierp-app',
  audience: 'aierp-app',
  jwksUrl: 'http://idp.test/realms/r/protocol/openid-connect/certs',
  algorithms: ['RS256'],
};

const ADMIN_ME = {
  authenticated: true,
  user: { sub: 'u1', username: 'planner1', roles: ['admin'], groups: [] },
};

// The plan note, exactly as the planned view must read it.
const PLAN_NOTE_TEXT =
  "Planned orders: at each monthly review, an item-site whose stock position is below its reorder point plus that month's demand orders up to that level, arriving after its lead time.";

// Bucket 1: the as-is shortfall (projected_shortfall true, rolled
// on-hand below zero); the planned on-hand (50) is positive, so the
// planned view does not flag it.
const B1 = {
  month: '2026-11',
  projected_demand_units: 100,
  projected_supply_units: 0,
  projected_on_hand_units: -150,
  projected_shortfall: true,
  projected_demand_value: 500,
  projected_supply_value: 0,
  planned_receipts_units: 250,
  planned_receipts_value: 1250,
  planned_on_hand_units: 50,
  planned_shortfall: false,
};

// Bucket 2: plain as-is, but the server marks planned_shortfall — the
// planned on-hand cell carries the shortfall flag in the planned view.
const B2 = {
  month: '2026-12',
  projected_demand_units: 400,
  projected_supply_units: 0,
  projected_on_hand_units: 120,
  projected_shortfall: false,
  projected_demand_value: 2000,
  projected_supply_value: 0,
  planned_receipts_units: 300,
  planned_receipts_value: 900,
  planned_on_hand_units: -80,
  planned_shortfall: true,
};

// The projection answer: the single group, in order.
function projectionFor() {
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets: [B1, B2],
      item_sites_without_unit_cost: 0,
    },
  ];
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can count the projection fetches.
async function mockAggregateApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const ctrl = {
    config,
    me,
    projectionGets: [],
    meRequests: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/projection') {
      ctrl.projectionGets.push({ months: url.searchParams.get('months') || '6', url: request.url() });
      return route.fulfill({ status: 200, json: projectionFor() });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

test('issue492 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in card, straight onto #/aggregate
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = await mockAggregateApi(page, { config: DEV_CONFIG, me: ADMIN_ME });

  const planToggle = page.locator('[data-testid="aggregate-plan-toggle"]');
  const grid = page.locator('[data-testid="aggregate-grid"]');
  const legend = page.locator('[data-testid="aggregate-legend"]');
  const planNote = page.locator('[data-testid="aggregate-plan-note"]');

  await page.goto('/#/aggregate');

  // No projection request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(0);

  // Sign in through the development token card (the usual admin stub).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(page.url()).toContain('#/aggregate');
  await expect(grid).toBeVisible();
  await expect.poll(() => ctrl.projectionGets.length).toBe(1);
  expect(ctrl.projectionGets[0].months).toBe('6');
  expect(pageErrors).toEqual([]);

  // --- the "As is" view (the default): the plan note is absent -------
  await expect(planToggle).toBeVisible();
  await expect(planToggle).toHaveValue('as-is');
  await expect(legend).toBeVisible();
  await expect(planNote).toHaveCount(0);

  // --- "With planned orders": the note shows under the legend, and it
  // --- reads exactly the new sentence ---------------------------------
  await planToggle.selectOption('planned');
  await expect(grid).toBeVisible();
  await expect(legend).toBeVisible();
  await expect(planNote).toBeVisible();
  await expect(planNote).toHaveText(PLAN_NOTE_TEXT);
  const noteLayout = await page.evaluate(() => {
    const legendEl = document.querySelector('[data-testid="aggregate-legend"]');
    const note = document.querySelector('[data-testid="aggregate-plan-note"]');
    return {
      belowLegend: note.getBoundingClientRect().top >= legendEl.getBoundingClientRect().bottom,
    };
  });
  expect(noteLayout.belowLegend).toBe(true);

  // --- back to "As is": the note is hidden again ----------------------
  await planToggle.selectOption('as-is');
  await expect(planNote).toHaveCount(0);

  // --- 390x844: no horizontal page scroll ------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(grid).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);
});
