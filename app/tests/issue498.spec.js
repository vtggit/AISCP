// Proving spec for AIERP issue #498 — the Scenario control of the
// Aggregate planning screen (#/aggregate): the select
// ([data-testid="aggregate-scenario"], "Baseline" by default) next to
// Months, Figures and Plan offers one option per saved scenario, in
// the order GET /api/scenarios returns them — the id as value, the
// name as text (never HTML). Choosing a scenario re-fetches the
// projection with each of that scenario's levers that is not null
// after months (service_level, demand_multiplier, lead_time_multiplier);
// "Baseline" re-fetches with months only, the choice is kept when
// Months changes, Figures and Plan still switch without a request, and
// while a scenario is chosen a caption
// ([data-testid="aggregate-scenario-caption"]) under the controls
// names it and its levers.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) at 1440x900,
// with GET /api/scenarios answering two scenarios — "Peak +20%"
// (service_level 0.98, demand_multiplier 1.2, lead_time_multiplier
// null) and a name of "<img src=x onerror=window.__pwned=1>" (all
// levers null except lead_time_multiplier 1.5) — and GET
// /api/aggregate/projection echoing its query into the figures:
//   * the select shows "Baseline" first and both names as text, and
//     window.__pwned stays undefined;
//   * the first projection request carries months=6 and no lever
//     parameter;
//   * choosing "Peak +20%" requests months=6&service_level=0.98&
//     demand_multiplier=1.2 with no lead_time_multiplier, renders that
//     answer's figures, and shows the caption "Scenario: Peak +20% —
//     service level 98%, demand +20%";
//   * changing Months to 3 keeps the scenario selected and its levers
//     in the request;
//   * switching Plan to "With planned orders" makes no new request;
//   * choosing the second scenario shows a caption with "lead time
//     +50%" and its name as text;
//   * choosing "Baseline" requests months=3 only and hides the
//     caption;
//   * a 422 answer with a detail shows the inline error containing
//     that text, and Retry re-requests;
//   * with GET /api/scenarios answering 500 the select offers only
//     "Baseline" and the grid still loads;
//   * two quick scenario changes render only the latest answer;
//   * at 390x844 the page does not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue498 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// The freeform pass runs several sub-scenarios in one test; give slow CI
// runners room without weakening the assertions.
test.setTimeout(90000);

