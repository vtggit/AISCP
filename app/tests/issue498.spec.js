// The hostile saved-scenario name: it must reach the page as text
// (the option label and the caption), never as a live <img>.
const XSS_NAME = '<img src=x onerror=window.__pwned=1>';

// The two saved scenarios, in the order GET /api/scenarios returns
// them: newest created_at first, as the real endpoint orders them.
const SCENARIOS = [
  {
    id: 'sc-peak',
    name: 'Peak +20%',
    service_level: 0.98,
    demand_multiplier: 1.2,
    lead_time_multiplier: null,
    created_at: '2026-10-01T09:00:00Z',
    updated_at: '2026-10-01T09:00:00Z',
  },
  {
    id: 'sc-lead',
    name: XSS_NAME,
    service_level: null,
    demand_multiplier: null,
    lead_time_multiplier: 1.5,
    created_at: '2026-10-02T09:00:00Z',
    updated_at: '2026-10-02T09:00:00Z',
  },
];

// The projection answer for a request: the demand scales with the
// demand multiplier the request carries, so a scenario's answer reads
// differently from Baseline's (the lead-time scenario scales demand
// not at all and is told apart by its request, not its figures).
function projectionFor(params) {
  const factor = params.demand_multiplier ? Number(params.demand_multiplier) : 1;
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets: [
        {
          month: '2026-11',
          projected_demand_units: Math.round(100 * factor),
          projected_supply_units: 0,
          projected_on_hand_units: 250 - Math.round(100 * factor),
          projected_shortfall: false,
          projected_demand_value: Math.round(500 * factor),
          projected_supply_value: 0,
        },
        {
          month: '2026-12',
          projected_demand_units: Math.round(200 * factor),
          projected_supply_units: 0,
          projected_on_hand_units: 300 - Math.round(300 * factor),
          projected_shortfall: 300 - Math.round(300 * factor) < 0,
          projected_demand_value: Math.round(1000 * factor),
          projected_supply_value: 0,
        },
      ],
      item_sites_without_unit_cost: 0,
    },
  ];
}

// A one-bucket answer carrying a single distinctive figure, for the
// stale-fetch race: the stale and the latest answer are told apart by
// their figure alone.
function figuresPayload(demandUnits) {
  return [
    {
      group: { dimension: 'site', code: 'S1' },
      buckets: [
        {
          month: '2026-11',
          projected_demand_units: demandUnits,
          projected_supply_units: 0,
          projected_on_hand_units: demandUnits,
          projected_shortfall: false,
          projected_demand_value: demandUnits * 5,
          projected_supply_value: 0,
        },
      ],
      item_sites_without_unit_cost: 0,
    },
  ];
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the scenario list's answer and
// the projection's (counting every projection request URL as it goes).
async function mockAggregateApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    scenarios: SCENARIOS,
    scenariosStatus: 200,
    scenarioListGets: [],
    projectionGets: [],
    projectionNext: null,
    holdNext: false,
    held: [],
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/scenarios') {
      ctrl.scenarioListGets.push(request.url());
      if (ctrl.scenariosStatus === 500) {
        return route.fulfill({ status: 500, json: { detail: 'scenarios unavailable' } });
      }
      return route.fulfill({ status: 200, json: ctrl.scenarios });
    }
    if (path === '/api/aggregate/projection') {
      const params = {};
      for (const key of ['months', 'service_level', 'demand_multiplier', 'lead_time_multiplier']) {
        params[key] = url.searchParams.get(key);
      }
      ctrl.projectionGets.push({ url: request.url(), params });
      if (ctrl.projectionNext) {
        const next = ctrl.projectionNext;
        ctrl.projectionNext = null;
        return route.fulfill(next);
      }
      if (ctrl.holdNext) {
        ctrl.holdNext = false;
        ctrl.held.push({ route, params });
        return; // held: the test answers it (the stale-fetch race)
      }
      return route.fulfill({ status: 200, json: projectionFor(params) });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return ctrl;
}

test('issue498 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in card, straight onto #/aggregate
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = await mockAggregateApi(page);

  const scenarioSelect = page.locator('[data-testid="aggregate-scenario"]');
  const monthsSelect = page.locator('[data-testid="aggregate-months"]');
  const planToggle = page.locator('[data-testid="aggregate-plan-toggle"]');
  const grid = page.locator('[data-testid="aggregate-grid"]');
  const caption = page.locator('[data-testid="aggregate-scenario-caption"]');

  await page.goto('/#/aggregate');

  // No request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(0);
  expect(ctrl.scenarioListGets.length).toBe(0);

  // Sign in through the development token card (the usual admin stub).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(page.url()).toContain('#/aggregate');
  await expect(grid).toBeVisible();
  await expect.poll(() => ctrl.projectionGets.length).toBe(1);
  await expect.poll(() => ctrl.scenarioListGets.length).toBe(1);
  expect(pageErrors).toEqual([]);

  // --- the first projection request: months=6, no lever parameter ----
  const first = ctrl.projectionGets[0];
  expect(first.params.months).toBe('6');
  expect(first.params.service_level).toBeNull();
  expect(first.params.demand_multiplier).toBeNull();
  expect(first.params.lead_time_multiplier).toBeNull();

  // --- the Scenario control: Baseline first, both names as text ------
  // (Polled until the mocked list answer is processed: the request
  // going out does not mean the options are in the select yet.)
  await expect(scenarioSelect).toBeVisible();
  await expect(scenarioSelect).toHaveValue('');
  await expect.poll(async () => scenarioSelect.locator('option').allTextContents()).toEqual(
    ['Baseline', 'Peak +20%', XSS_NAME],
  );
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // --- "Peak +20%": its non-null levers join the request -------------
  const getsBeforePeak = ctrl.projectionGets.length;
  await scenarioSelect.selectOption('sc-peak');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBeforePeak + 1);
  const peak = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(peak.url).toContain(
    '/api/aggregate/projection?months=6&service_level=0.98&demand_multiplier=1.2',
  );
  expect(peak.params.months).toBe('6');
  expect(peak.params.service_level).toBe('0.98');
  expect(peak.params.demand_multiplier).toBe('1.2');
  expect(peak.params.lead_time_multiplier).toBeNull();

  // ... and that answer's figures render (demand scaled by 1.2).
  await expect(grid).toBeVisible();
  await expect(grid.locator('tbody tr').nth(0).locator('td')).toHaveText(['120', '240']);

  // ... and the caption names the scenario and its levers.
  await expect(caption).toBeVisible();
  await expect(caption).toHaveText('Scenario: Peak +20% \u2014 service level 98%, demand +20%');

  // --- Months to 3: the scenario stays chosen, levers in the request -
  const getsBeforeMonths = ctrl.projectionGets.length;
  await monthsSelect.selectOption('3');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBeforeMonths + 1);
  const months3 = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(months3.params.months).toBe('3');
  expect(months3.params.service_level).toBe('0.98');
  expect(months3.params.demand_multiplier).toBe('1.2');
  expect(months3.params.lead_time_multiplier).toBeNull();
  await expect(scenarioSelect).toHaveValue('sc-peak');
  await expect(caption).toHaveText('Scenario: Peak +20% \u2014 service level 98%, demand +20%');

  // --- Plan to "With planned orders": no new request ------------------
  const getsBeforePlan = ctrl.projectionGets.length;
  await planToggle.selectOption('planned');
  await expect(page.locator('[data-testid="aggregate-plan-note"]')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(getsBeforePlan);

  // --- the second scenario: its one lever, its name as text ----------
  const getsBeforeLead = ctrl.projectionGets.length;
  await scenarioSelect.selectOption('sc-lead');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBeforeLead + 1);
  const lead = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(lead.params.months).toBe('3');
  expect(lead.params.service_level).toBeNull();
  expect(lead.params.demand_multiplier).toBeNull();
  expect(lead.params.lead_time_multiplier).toBe('1.5');
  await expect(caption).toContainText('lead time +50%');
  await expect(caption).toContainText(XSS_NAME);
  expect(await page.locator('#aggregate-root img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // --- "Baseline": months only, the caption hides ---------------------
  const getsBeforeBaseline = ctrl.projectionGets.length;
  await scenarioSelect.selectOption('');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBeforeBaseline + 1);
  const baseline = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(baseline.params.months).toBe('3');
  expect(baseline.params.service_level).toBeNull();
  expect(baseline.params.demand_multiplier).toBeNull();
  expect(baseline.params.lead_time_multiplier).toBeNull();
  await expect(scenarioSelect).toHaveValue('');
  await expect(caption).toHaveCount(0);

  // --- a 422 from the projection: the inline error carries the detail -
  ctrl.projectionNext = {
    status: 422,
    json: { detail: 'item site X at S: the scaled inputs overflow the reorder formula' },
  };
  const getsBefore422 = ctrl.projectionGets.length;
  await scenarioSelect.selectOption('sc-peak');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBefore422 + 1);
  const errorMsg = page.locator('[data-testid="aggregate-error-msg"]');
  await expect(errorMsg).toBeVisible();
  await expect(errorMsg).toContainText(
    'item site X at S: the scaled inputs overflow the reorder formula',
  );

  // The choice survives the error: the caption still names the scenario.
  await expect(caption).toHaveText('Scenario: Peak +20% \u2014 service level 98%, demand +20%');

  // Retry re-requests the same scenario under the same months.
  const getsBeforeRetry = ctrl.projectionGets.length;
  await page.locator('[data-testid="aggregate-retry"]').click();
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBeforeRetry + 1);
  const retry = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(retry.params.months).toBe('3');
  expect(retry.params.service_level).toBe('0.98');
  expect(retry.params.demand_multiplier).toBe('1.2');
  expect(retry.params.lead_time_multiplier).toBeNull();
  await expect(grid).toBeVisible();

  // --- GET /api/scenarios 500: Baseline only, the grid still loads ----
  // Back to Baseline first, so the re-activation's projection is the
  // bare baseline whatever the list's fate.
  const getsBefore500 = ctrl.projectionGets.length;
  await scenarioSelect.selectOption('');
  await expect.poll(() => ctrl.projectionGets.length).toBe(getsBefore500 + 1);
  await expect(caption).toHaveCount(0);

  ctrl.scenariosStatus = 500;
  // Re-activating the view re-fetches the list (and the projection).
  await page.click('.nav-btn[data-view="scenario"]');
  await page.click('.nav-btn[data-view="aggregate"]');
  await expect(grid).toBeVisible();
  await expect.poll(async () => scenarioSelect.locator('option').allTextContents()).toEqual([
    'Baseline',
  ]);
  await expect(scenarioSelect).toHaveValue('');
  const reactivated = ctrl.projectionGets[ctrl.projectionGets.length - 1];
  expect(reactivated.params.months).toBe('3');
  expect(reactivated.params.service_level).toBeNull();
  expect(reactivated.params.demand_multiplier).toBeNull();
  expect(reactivated.params.lead_time_multiplier).toBeNull();
  expect(pageErrors).toEqual([]);

  // --- two quick scenario changes render only the latest --------------
  // The list loads again on the re-activation: restore it.
  ctrl.scenariosStatus = 200;
  await page.click('.nav-btn[data-view="scenario"]');
  await page.click('.nav-btn[data-view="aggregate"]');
  await expect.poll(() => scenarioSelect.locator('option').count()).toBe(3);

  // The first scenario change: its fetch is held.
  ctrl.holdNext = true;
  await scenarioSelect.selectOption('sc-peak');
  await expect.poll(() => ctrl.held.length).toBe(1);

  // The second: re-activating the view supersedes the first.
  ctrl.holdNext = true;
  await page.click('.nav-btn[data-view="scenario"]');
  await page.click('.nav-btn[data-view="aggregate"]');
  await expect.poll(() => ctrl.held.length).toBe(2);

  // The stale (first) answer now lands — it must be ignored.
  ctrl.held[0].route.fulfill({ status: 200, json: figuresPayload(1111) });
  await page.waitForTimeout(150);
  await expect(grid).toHaveCount(0);
  await expect(page.locator('[data-testid="aggregate-skeleton"]')).toHaveCount(1);

  // ... and the latest answer renders.
  ctrl.held[1].route.fulfill({ status: 200, json: figuresPayload(2222) });
  await expect(grid).toBeVisible();
  await expect(grid.locator('tbody tr').nth(0).locator('td').first()).toHaveText('2,222');
  expect(await grid.textContent()).not.toContain('1,111');
  expect(pageErrors).toEqual([]);

  // --- 390x844: no horizontal page scroll ------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(grid).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);
});
