  await expect(card).toBeVisible();
  await expect(card.locator('.settings-card-title')).toHaveText('Purchasing budget');
  // The card sits after the mappings card — under #settings-root,
  // after the .settings wrap (a sibling of it, not a child), so the
  // wrap the issue475 proof reads keeps exactly its three original
  // children and that proof passes unchanged ...
