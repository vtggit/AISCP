  expect(issue475Response.status()).toBe(200);
  const issue475Source = await issue475Response.text();
  expect(issue475Source).not.toContain('purchase-budget');
  expect(issue475Source).not.toContain('Purchasing budget');
  // The mappings card above it is untouched by the new card ...
  await expect(page.locator('[data-testid="erp-mappings"]')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mapping-row"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="erp-mapping-row"]')).toContainText('DSAFIEX20S');

  // --- one row per stored month, in the order served --------------------
  await expect(rows).toHaveCount(2);
  await expect(head).toBeVisible();
  const firstCells = await rows.nth(0).evaluate((rowEl) => [
    rowEl.querySelector('.purchase-budget-month').textContent,
    rowEl.querySelector('.purchase-budget-amount').textContent,
    rowEl.querySelector('.purchase-budget-updated').textContent,
  ]);
  expect(firstCells).toEqual(['Nov 2026', '$250,001', 'Updated 2026-10-17 by jason']);
