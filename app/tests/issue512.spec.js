// Proving spec for AIERP issue #512 — the "Purchasing budget" card of
// the Settings view, after the ERP code mappings card.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. Proves, signed in through the development
// token card as an admin (/api/auth/me roles ["admin"]) with GET
// /api/purchase-budgets returning 2026-11 (250000.5, updated by
// "jason") and 2026-12 (300000):
//   * at 1440x900 the card sits after the mappings card — under
//     #settings-root, after the .settings wrap, which keeps exactly
//     its three original children (System, Personal, erp-mappings),
//     so the issue475 proof that reads that list passes unchanged
//     and the served issue475 spec references this card nowhere —
//     one row per stored month in the order served, "Nov 2026"
//     "$250,001" and
//     "Dec 2026" "$300,000" — each row laid out horizontally (computed
//     flex-direction "row"), its Delete at the right end of the line
//     (the Delete's vertical centre within the row's amount cell), and
//     the header row labelling "Month", "Budget" and "Updated" in the
//     rows' own column template;
//   * the admin's set form (a labelled month input, a labelled amount
//     input, a Save) — saving 2027-01 with 123456.78 sends exactly one
//     PUT /api/purchase-budgets/2027-01 with body {"amount":123456.78}
//     and then re-requests the list; an empty amount, a negative
//     amount or an empty month sends nothing and shows its inline
//     message; a PUT answered 422 shows the server's detail inline and
//     keeps the inputs; a row's Delete sends DELETE
//     /api/purchase-budgets/{month} and reloads;
//   * a hostile updated_by (<img src=x onerror=...>) renders as text,
//     never as HTML;
//   * with an empty list the note "No purchasing budget set." shows
//     and the header is not rendered;
//   * a 500 on the list shows an inline error with a Retry, and Retry
//     re-requests;
//   * at 390x844 each row stacks left-aligned (computed align-items
//     "flex-start"), the header is hidden, and the page does not
//     scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, and the admin-only controls (the
// set form and the per-row Delete) are absent — with the "Only an admin
// can change this." note — while the stored budgets, the header labels
// and the rest of the page still render.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue512 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

