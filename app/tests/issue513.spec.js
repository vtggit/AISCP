// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the spend's answer (one-shot
// ctrl.spendNext, the null-budget variant, the hostile month) and
// hold spend requests until it answers them (ctrl.holdSpendNext /
// ctrl.heldSpend) for the stale-fetch scenario.
async function mockAggregateApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    scenarios: SCENARIOS,
    meRequests: [],
    projectionGets: [],
    spendGets: [],
    spendNext: null,
    spendAllNullBudgets: false,
    spendMonth: '2026-10',
    holdSpendNext: false,
    heldSpend: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/scenarios') {
      return route.fulfill({ status: 200, json: ctrl.scenarios });
    }
    if (path === '/api/aggregate/projection') {
      ctrl.projectionGets.push(request.url());
      return route.fulfill({ status: 200, json: PROJECTION });
    }
    if (path === '/api/aggregate/spend') {
      ctrl.spendGets.push(request.url());
      if (ctrl.spendNext) {
        const next = ctrl.spendNext;
        ctrl.spendNext = null;
        return route.fulfill(next);
      }
      if (ctrl.holdSpendNext) {
        ctrl.holdSpendNext = false;
        ctrl.heldSpend.push(route);
        return; // held: the test answers it (the stale-fetch race)
      }
      if (ctrl.spendAllNullBudgets) {
        return route.fulfill({ status: 200, json: spendPayloadAllNullBudgets() });
      }
      return route.fulfill({ status: 200, json: spendPayload(ctrl.spendMonth) });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// The computed ::before content of a generated string is a CSS string
// token (double-quoted in the computed value); strip the quotes so the
// marker character itself is compared.
function unquote(content) {
  return content && content.length >= 2 && content.startsWith('"') && content.endsWith('"')
    ? content.slice(1, -1)
    : content;
}

