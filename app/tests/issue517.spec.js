const SPEND_500 = { status: 500, json: { detail: 'spend unavailable' } };

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the spend's answer (one-shot
// ctrl.spendNext — a 500 for the failed loads — otherwise the valid
// spendPayload) and steer the sign-in (ctrl.config / ctrl.me) when
// the pass switches from the admin to the non-admin viewer.
async function mockAggregateApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    scenarios: [],
    meRequests: [],
    projectionGets: [],
    spendGets: [],
    spendNext: null,
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/scenarios') {
      return route.fulfill({ status: 200, json: ctrl.scenarios });
    }
    if (path === '/api/aggregate/projection') {
      ctrl.projectionGets.push(request.url());
      return route.fulfill({ status: 200, json: PROJECTION });
    }
    if (path === '/api/aggregate/spend') {
      ctrl.spendGets.push(request.url());
      if (ctrl.spendNext) {
        const next = ctrl.spendNext;
        ctrl.spendNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 200, json: spendPayload() });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue517 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // Every request URL the page makes, for the record.
  const allRequests = [];
  page.on('request', (request) => allRequests.push(request.url()));

  // --- admin pass: development sign-in card, straight onto #/aggregate
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockAggregateApi(page);

  const spend = page.locator('[data-testid="aggregate-spend"]');
  const spendError = page.locator('[data-testid="aggregate-spend-error-msg"]');
  const spendRetry = page.locator('[data-testid="aggregate-spend-retry"]');
  const monthsSelect = page.locator('[data-testid="aggregate-months"]');
  const grid = page.locator('[data-testid="aggregate-grid"]');

  // The spend's FIRST answer is a 500; every later answer is valid.
  ctrl.spendNext = SPEND_500;

  await page.goto('/#/aggregate');

  // No aggregate request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.projectionGets.length).toBe(0);
  expect(ctrl.spendGets.length).toBe(0);

  // Sign in through the development token card (the usual admin stub).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  expect(page.url()).toContain('#/aggregate');
  await expect(grid).toBeVisible();
  await expect.poll(() => ctrl.projectionGets.length).toBe(1);
  await expect.poll(() => ctrl.spendGets.length).toBe(1);
  expect(pageErrors).toEqual([]);

  // The failed spend: its own error and its own Retry, the grid
  // still rendering. The element is exactly what it was before the
  // keyboard behaviour: a span, not a button.
  await expect(spendError).toBeVisible();
  await expect(spendError).toHaveText('Spend could not be loaded.');
  await expect(spendRetry).toBeVisible();
  await expect(spendRetry).toHaveCount(1);
  const retryShape = await page.evaluate(() => {
    const el = document.querySelector('[data-testid="aggregate-spend-retry"]');
    return el
      ? {
          tag: el.tagName.toLowerCase(),
          cls: el.getAttribute('class'),
          role: el.getAttribute('role'),
          tabindex: el.getAttribute('tabindex'),
          testId: el.getAttribute('data-testid'),
          text: el.textContent,
        }
      : null;
  });
  expect(retryShape).toEqual({
    tag: 'span',
    cls: 'ag-spend-retry',
    role: 'button',
    tabindex: '0',
    testId: 'aggregate-spend-retry',
    text: 'Retry',
  });
  await expect(grid).toBeVisible();

  // --- Enter on the focused Retry: exactly one new spend request ---
  const beforeEnter = {
    projection: ctrl.projectionGets.length,
    spend: ctrl.spendGets.length,
  };
  await spendRetry.focus();
  expect(
    await page.evaluate(() =>
      document.activeElement ? document.activeElement.getAttribute('data-testid') : null,
    ),
  ).toBe('aggregate-spend-retry');
  await page.keyboard.press('Enter');
  await expect.poll(() => ctrl.spendGets.length).toBe(beforeEnter.spend + 1);
  // Exactly ONE new spend request: a moment of grace, then recount.
  await page.waitForTimeout(200);
  expect(ctrl.spendGets.length).toBe(beforeEnter.spend + 1);
  // The projection is not requested again.
  expect(ctrl.projectionGets.length).toBe(beforeEnter.projection);
  // The re-request carries the current query string, as the click does.
  const enterSpendSearch = new URL(ctrl.spendGets[ctrl.spendGets.length - 1]).search;
  expect(enterSpendSearch).toBe('?months=6');
  expect(enterSpendSearch).toBe(
    new URL(ctrl.projectionGets[ctrl.projectionGets.length - 1]).search,
  );
  // The spend table renders.
  await expect(spendError).toHaveCount(0);
  await expect(spend.locator('tbody tr')).toHaveCount(5);
  await expect(spend.locator('tbody th[scope="row"]')).toHaveText([
    'Committed',
    'Planned',
    'Total',
    'Budget',
    'Remaining',
  ]);
  await expect(spend.locator('tbody tr').nth(0).locator('td').first()).toHaveText(
    '$1,000',
  );
  expect(pageErrors).toEqual([]);

  // --- a fresh 500 (Months to 12), then Space: one request, no scroll
  ctrl.spendNext = SPEND_500;
  const beforeFresh500 = {
    projection: ctrl.projectionGets.length,
    spend: ctrl.spendGets.length,
  };
  await monthsSelect.selectOption('12');
  await expect.poll(() => ctrl.projectionGets.length).toBe(beforeFresh500.projection + 1);
  await expect.poll(() => ctrl.spendGets.length).toBe(beforeFresh500.spend + 1);
  await expect(spendError).toBeVisible();
  await expect(spendError).toHaveText('Spend could not be loaded.');
  await expect(grid).toBeVisible();

  // Make the document scrollable so Space's default action would be
  // visible, and centre the Retry in the viewport.
  await page.evaluate(() => {
    document.body.style.minHeight = '2000px';
  });
  expect(
    await page.evaluate(
      () => document.documentElement.scrollHeight > document.documentElement.clientHeight,
    ),
  ).toBe(true);
  await page.evaluate(() => {
    const el = document.querySelector('[data-testid="aggregate-spend-retry"]');
    el.scrollIntoView({ block: 'center' });
  });
  await spendRetry.focus();
  const scrollBefore = await page.evaluate(() => window.scrollY);
  const beforeSpace = {
    projection: ctrl.projectionGets.length,
    spend: ctrl.spendGets.length,
  };
  await page.keyboard.press('Space');
  await expect.poll(() => ctrl.spendGets.length).toBe(beforeSpace.spend + 1);
  await page.waitForTimeout(200);
  expect(ctrl.spendGets.length).toBe(beforeSpace.spend + 1);
  expect(ctrl.projectionGets.length).toBe(beforeSpace.projection);
  const spaceSpendSearch = new URL(ctrl.spendGets[ctrl.spendGets.length - 1]).search;
  expect(spaceSpendSearch).toBe('?months=12');
  expect(spaceSpendSearch).toBe(
    new URL(ctrl.projectionGets[ctrl.projectionGets.length - 1]).search,
  );
  await expect(spendError).toHaveCount(0);
  await expect(spend.locator('tbody tr')).toHaveCount(5);
  // The page did not scroll: Space's default was prevented.
  const scrollAfter = await page.evaluate(() => window.scrollY);
  expect(scrollAfter).toBe(scrollBefore);
  expect(pageErrors).toEqual([]);

  // --- the click still re-requests only the spend, as before -------
  ctrl.spendNext = SPEND_500;
  const beforeClick = {
    projection: ctrl.projectionGets.length,
    spend: ctrl.spendGets.length,
  };
  await monthsSelect.selectOption('3');
  await expect.poll(() => ctrl.projectionGets.length).toBe(beforeClick.projection + 1);
  await expect.poll(() => ctrl.spendGets.length).toBe(beforeClick.spend + 1);
  await expect(spendError).toBeVisible();
  await spendRetry.click();
  // +2, not +1: the Months change above already re-asked the spend
  // once; the click must add exactly one more request of its own.
  await expect.poll(() => ctrl.spendGets.length).toBe(beforeClick.spend + 2);
  await page.waitForTimeout(200);
  expect(ctrl.spendGets.length).toBe(beforeClick.spend + 2);
  // +1: the projection went out once, for the Months change; the
  // click re-asked the spend only.
  expect(ctrl.projectionGets.length).toBe(beforeClick.projection + 1);
  await expect(spend.locator('tbody tr')).toHaveCount(5);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ---------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const meCountBeforeViewer = ctrl.meRequests.length;
  const projectionGetsBeforeViewer = ctrl.projectionGets.length;
  const spendGetsBeforeViewer = ctrl.spendGets.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and no fetch went out before the view is activated.
  expect(ctrl.projectionGets.length).toBe(projectionGetsBeforeViewer);
  expect(ctrl.spendGets.length).toBe(spendGetsBeforeViewer);

  // Activating the view for the viewer: the page still renders, the
  // spend block included ...
  await page.click('.nav-btn[data-view="aggregate"]');
  expect(page.url()).toContain('#/aggregate');
  await expect(page.locator('#view-aggregate')).toBeVisible();
  await expect(grid).toBeVisible();
  await expect(spend).toBeVisible();
  await expect(spend.locator('tbody tr')).toHaveCount(5);
  await expect(spend.locator('tbody th[scope="row"]')).toHaveText([
    'Committed',
    'Planned',
    'Total',
    'Budget',
    'Remaining',
  ]);

  // ... with no admin-only (indeed no mutating) control of any kind
  // on the screen.
  await expect(page.locator('#aggregate-root [data-admin-only]')).toHaveCount(0);
  await expect(page.locator('#aggregate-root button')).toHaveCount(1);
  expect(pageErrors).toEqual([]);

  // Every /api/ request of the whole pass stays within the known set:
  // the auth/config, me, scenarios and the two aggregate endpoints the
  // screen owns, plus the Overview's own endpoints — the viewer's
  // production boot lands on #/overview before the nav click, and that
  // screen's regions request their lists (the mock answers 404; the
  // hidden view renders its per-region errors).
  const allowedApiPaths = new Set([
    '/api/auth/config',
    '/api/auth/me',
    '/api/feed/status',
    '/api/scenarios',
    '/api/aggregate/projection',
    '/api/aggregate/spend',
    '/api/aggregate/deferrals',
    '/api/decisions/summary',
    '/api/drift',
    '/api/excess',
    '/api/stockout',
    '/api/aggregate/releases',
    '/api/abc',
    '/api/exceptions',
    '/api/supply-plan/summary',
    '/api/stockout/proposals',
    '/api/excess/proposals',
    '/api/drift/decisions/acceptance',
    '/api/exceptions/proposals',
    '/api/forecast/overrides/proposals',
  ]);
  for (const url of allRequests) {
    if (url.indexOf('/api/') !== -1) {
      expect(allowedApiPaths.has(new URL(url).pathname)).toBe(true);
    }
  }
});
