// Proving spec for AIERP issue #518 — Space on the spend block's
// focused Retry ([data-testid="aggregate-spend-retry"]) on the
// Aggregate planning screen (#/aggregate) must re-request only the
// spend and must NOT scroll: the view (#view-aggregate) is the
// keyboard scroll box for the screen (the document never scrolls),
// and Space's default page scroll is the regression this proof
// guards. Nothing on the screen changes: the Retry stays a span,
// its click/Enter/Space activation from #517 is untouched, and the
// grid, the projection's own Retry and every other control behave
// as before.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (every request URL is recorded).
// Proves, signed in through the development token card as an admin
// (/api/auth/me roles ["admin"]) at 1440x900, with GET
// /api/aggregate/spend answering 500 on its first fetch:
//   * the view is made a real scroll box: a 2000px-tall spacer is
//     appended inside the active view (#view-aggregate) after its
//     content and the view's overflow-y becomes auto (the design
//     leaves it overflow: hidden, a box Chromium's keyboard
//     scrolling passes through rather than scrolls), so the view's
//     scrollHeight exceeds its clientHeight;
//   * with the Retry centred in the view, scrollTop + clientHeight
//     is still below scrollHeight — there is room to scroll down;
//     the centre scroll may still be animating when scrollIntoView
//     returns, so the position settles (three consecutive equal
//     readings, after a grace window) before the baseline is read;
//   * POSITIVE CONTROL: a plain focusable element (tabindex="0", no
//     key handling) inserted next to the Retry, focused and given a
//     Space, moves the view's scrollTop — expect.poll (up to 2 s)
//     waits for the increase because Chromium animates keyboard
//     scrolling, so an immediate read still sees the old position.
//     The time this run takes to observe the increase is recorded.
//     A Space default is therefore detectable in this setup; the
//     view's scrollTop is then restored (and settled);
//   * CHECK: the next spend request succeeds; the spend count is
//     shown to have settled (no request in flight) before the Retry
//     is focused, and the baseline is the last read before the
//     Space press, so a request that fires before the press cannot
//     satisfy the count; Space makes exactly one new spend request
//     (re-counted after a short grace and again after the full
//     scroll wait, so a late duplicate cannot slip in) and, after a
//     wait of at least 1 s — and at least 500 ms beyond the scroll
//     animation the positive control observed in this run — the
//     view's scrollTop and window.scrollY are both unchanged.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload:
// the token arrives in the URL hash as #access_token=...,
// /api/auth/config and /api/auth/me are mocked for that user, the
// IdP's auth and token endpoints carry the PKCE round-trip, no
// fetch goes out before the view is activated, and the screen then
// renders for the viewer — the spend block included — with no
// admin-only (indeed no mutating) control of any kind on it.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue518 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

