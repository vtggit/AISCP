// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer each answer by query string
// (ctrl.spendByQuery / ctrl.deferralsByQuery), throw one-shot faults
// (ctrl.spendNext / ctrl.deferralsNext), hold a deferrals request
// until it is answered (ctrl.holdDeferralsNext / ctrl.heldDeferrals)
// for the stale-fetch race, and steer the sign-in (ctrl.config /
// ctrl.me) when the pass switches from the admin to the non-admin
// viewer.
async function mockAggregateApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    scenarios: [],
    meRequests: [],
    projectionGets: [],
    spendGets: [],
    deferralsGets: [],
    spendByQuery: {},
    deferralsByQuery: {},
    spendNext: null,
    deferralsNext: null,
    holdDeferralsNext: false,
    heldDeferrals: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/scenarios') {
      return route.fulfill({ status: 200, json: ctrl.scenarios });
    }
    if (path === '/api/aggregate/projection') {
      ctrl.projectionGets.push(request.url());
      return route.fulfill({ status: 200, json: PROJECTION });
    }
    if (path === '/api/aggregate/spend') {
      ctrl.spendGets.push(request.url());
      if (ctrl.spendNext) {
        const next = ctrl.spendNext;
        ctrl.spendNext = null;
        return route.fulfill(next);
      }
      const pick = ctrl.spendByQuery[url.search] || spendOver;
      return route.fulfill({ status: 200, json: pick() });
    }
    if (path === '/api/aggregate/deferrals') {
      ctrl.deferralsGets.push(request.url());
      if (ctrl.holdDeferralsNext) {
        ctrl.holdDeferralsNext = false;
        ctrl.heldDeferrals.push(route);
        return; // held: the test answers it (the stale-fetch race)
      }
      if (ctrl.deferralsNext) {
        const next = ctrl.deferralsNext;
        ctrl.deferralsNext = null;
        return route.fulfill(next);
      }
      const pick = ctrl.deferralsByQuery[url.search] || deferralsBase;
      return route.fulfill({ status: 200, json: pick() });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

