// Proving spec for AIERP issue #529 — the "What to defer" block
// ([data-testid="aggregate-deferrals"]) of the Aggregate planning
// screen (#/aggregate): directly under the Spend vs budget block, only
// while the latest successful spend answer has at least one month over
// budget, it fetches GET /api/aggregate/deferrals with exactly the same
// query string as the spend and projection requests (and never
// otherwise), guards its answer with its own request sequence, and
// renders per over-budget month a heading, a summary, an optional
// following-month warning and the candidates table (suggested rows in
// the accent tokens, would-stock-out rows muted, cover at one decimal,
// an em dash without a figure). Its own skeleton, its own error ("
// Suggestions could not be loaded." with a real "Retry suggestions"
// button that re-fetches only the deferrals) never touch the spend
// block or the site grid; a failed spend re-fetch leaves the block's
// prior state and visibility to the latest successful spend answer.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (every request URL is recorded).
// Proves, signed in through the development token card as an admin
// (/api/auth/me roles ["admin"]) at 1440x900:
//   * with a spend answer in which no month is over budget the block
//     is absent and no deferrals request is ever made;
//   * with the 2026-10 month over budget, one deferrals request is
//     made with the same query string as the spend request, and the
//     answer (overrun 490715, suggested_value 513658, uncovered 0,
//     next_month 2026-11, next_month_over_after) renders the heading
//     "2026-10: over by $490,715", the summary "Defer $513,658 across
//     1 order to cover it.", the warning naming 2026-11 and the three
//     candidates in the answer's order (Suggested, empty, Would stock
//     out; covers 23.9 / 19.5 / -4.2);
//   * with uncovered 220 the summary ends "$220 cannot be covered
//     without a stockout.";
//   * changing Months re-requests spend and deferrals with the same
//     query string, while Figures and Plan re-request neither;
//   * a deferrals 500 shows "Suggestions could not be loaded." and a
//     real "Retry suggestions" button that re-fetches only the
//     deferrals, the spend block and the grid staying rendered;
//   * two quick Months changes render only the latest deferrals
//     answer (the stale one, released late, is ignored);
//   * a hostile item code renders as text (never HTML);
//   * a failed spend re-fetch leaves the block's last data and
//     shows no spend-related error of its own;
//   * at 390x844 the page does not scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=...,
// /api/auth/config and /api/auth/me are mocked for that user, the
// IdP's auth and token endpoints carry the PKCE round-trip, no
// fetch goes out before the view is activated, and the screen then
// renders for the viewer — the "What to defer" block included — with
// no admin-only (indeed no mutating) control of any kind on it.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue529 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

