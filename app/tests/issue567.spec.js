// Proving spec for AIERP issue #567 — the "Releases" screen
// (#/releases): a planner screen wired like the others — the
// "Releases" nav button (after "Aggregate", before "Decision log"),
// the #view-releases section with #releases-root, and the view
// registered in the shell (title "Releases", subtitle "Purchase
// orders released to the ERP, and where each one stands").
//
// The screen fetches GET /api/aggregate/releases through app/js/api.js
// when the view becomes active and when the Refresh button
// ([data-testid="releases-refresh"], a real <button>) is pressed. A
// request-sequence guard renders only the newest answer, and a
// skeleton shows while a fetch is out.
//
// Above the table a row of state chips ([data-testid="releases-
// filter"]) — "All", "Late", "Awaiting approval", "Partly received",
// "Open", "Received", "Cancelled" and "Missing" — each shows its
// number of orders (Late, Awaiting approval, Partly received and
// Received from the answer's counts, the rest counted from the
// orders); choosing a chip filters the table without a new request,
// and "All" is the default. The table
// ([data-testid="releases-table"]) scrolls within its own region,
// one row per order in the answer's order: Order, State (a badge —
// "Late" in the risk tokens with a leading ▼ marker, "Awaiting
// approval" in the accent tokens, the rest neutral), Vendor
// (vendor_code else supplier_code), Warehouse (warehouse_code else
// site_code), Released (the date part of released_at, then " by "
// and the actor), Value (whole dollars with separators, parsed from
// the decimal string), Promised (promised_on else an em dash) and
// Delay ("Late <n> d" when days_late is set, "Waiting <n> d" when
// days_waiting is set, else empty). A row is focusable; clicking it
// or pressing Enter expands a line table beneath it
// ([data-testid="releases-lines"]) — Item, Warehouse, Ordered,
// Received, Promised and Status ("Completed", "Cancelled" or empty)
// — and a second click collapses it. With no orders an empty note
// shows; a 502 or 503 shows the server's detail inline with a Retry,
// any other failure "Releases could not be loaded." with a Retry.
// Every API value is escaped; at 390x844 the page does not scroll
// sideways. When a new answer arrives (activation or Refresh) the
// selected chip filter is preserved and re-applied to the new
// orders, any expanded row collapses, and the "All" default applies
// only on first load.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route. The mocked releases answer has
// four orders — PO003072 (late, 3 days, ELEEASTCOM / WHOLESALE,
// "66931.41", promised 2026-11-05, one line AACOMPUT01 273/0
// promised 2026-11-07), PO003068 (awaiting_approval, 20 days
// waiting, "797380.24"), PO003070 (received) and PO003099
// (missing) — and counts {"awaiting_approval": 1, "late": 1,
// "partly_received": 0, "received": 1}.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, no releases fetch goes out before the view is
// activated, the screen then renders for the viewer, and the
// admin-only controls — the Settings view's mappings and budget
// forms — are absent where "Only an admin can change this." shows
// instead, the page rendering on.
//
// Two review regressions are proven explicitly: the toggle's
// re-render keeps the keyboard focus on the fresh row, so the second
// Enter on the same row collapses it; and a row's identity is its
// index in the answer's orders array, never its order_nbr, so two
// orders the server tagged with the same number expand and collapse
// independently.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue567 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

