// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the releases answers
// (ctrl.releasesAnswer) and the sign-in (ctrl.config / ctrl.me)
// when the pass switches from the planner to the non-admin viewer.
// Every releases request is counted in ctrl.releasesGets.
async function mockReleasesApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    releasesAnswer: null,
    releasesGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      const answer =
        typeof ctrl.releasesAnswer === 'function' ? ctrl.releasesAnswer() : ctrl.releasesAnswer;
      return route.fulfill({ status: 200, json: answer || releasesPayload17() });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue573 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in at 960x900 ------------------
  page.setViewportSize({ width: 960, height: 900 });
  const { ctrl, appOrigin, handler } = await mockReleasesApi(page);

  const chipsRow = page.locator('[data-testid="releases-filter"]');
  const chips = chipsRow.locator('button');
  const chipByState = (state) => chipsRow.locator('button[data-state="' + state + '"]');
  const table = page.locator('[data-testid="releases-table"]');
  const rows = page.locator('tr.rl-row');
  const refresh = page.locator('[data-testid="releases-refresh"]');
  const emptyNote = page.locator('[data-testid="releases-empty"]');

  await page.goto('/');

  // No releases request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.releasesGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // The releases view is not active yet (the default view is): no
  // releases request.
  await expect.poll(() => ctrl.releasesGets).toBe(1);
  expect(pageErrors).toEqual([]);

  await page.click('.nav-btn[data-view="releases"]');
  await expect(page).toHaveURL(/#\/releases$/);
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(2);
  await expect(table).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- review regression: the currency formatter must not throw at --
  // script load. A RangeError from Intl.NumberFormat (a maximum below
  // the currency's implicit minimum fraction digits) aborts
  // releases.js before it publishes window.Releases, so the view
  // never renders a row and the value cell never carries the
  // whole-dollar figure; both checks below fail if it returns.
  const scriptLoad = await page.evaluate(() => {
    const releases = window.Releases;
    return {
      loaded:
        releases !== null &&
        typeof releases === 'object' &&
        typeof releases.activate === 'function' &&
        typeof releases.reset === 'function',
    };
  });
  expect(scriptLoad.loaded).toBe(true);
  await expect(rows.nth(0).locator('.rl-cell-value')).toHaveText('$797,380');
  expect(pageErrors).toEqual([]);

  // --- the chips: the answer's counts --------------------------------
  await expect(chips).toHaveText([
    'All 17',
    'Late 0',
    'Awaiting approval 17',
    'Partly received 0',
    'Open 0',
    'Received 0',
    'Cancelled 0',
    'Missing 0',
  ]);

  // --- seventeen rows, in the answer's order -------------------------
  await expect(rows).toHaveCount(17);
  expect(await rows.locator('.rl-cell-order').allTextContents()).toEqual(
    Array.from({ length: 17 }, (_, i) => 'PO0030' + String(68 + i)),
  );
  // The first row's cells: the badge, the ten-character vendor, the
  // warehouse, the Released cell's flat text (date + " by jason"),
  // the whole-dollar value and the promised date.
  expect(await rows.nth(0).locator('td').allTextContents()).toEqual([
    'PO003068',
    'Awaiting approval',
    'CONGOODT00',
    'WHOLESALE',
    '2026-10-21 by jason',
    '$797,380',
    '2026-10-24',
    'Waiting 1 d',
  ]);
  expect(pageErrors).toEqual([]);

  // --- at 960x900 the eight columns fit: no horizontal scroll -------
  const regionDims = await page.evaluate(() => {
    const el = document.querySelector('.rl-table-region');
    return el ? { scrollWidth: el.scrollWidth, clientWidth: el.clientWidth } : null;
  });
  expect(regionDims).not.toBeNull();
  expect(regionDims.scrollWidth).toBeLessThanOrEqual(regionDims.clientWidth);
  // All eight columns render, in order.
  expect(await table.locator('thead th').allTextContents()).toEqual([
    'Order',
    'State',
    'Vendor',
    'Warehouse',
    'Released',
    'Value',
    'Promised',
    'Delay',
  ]);

  // --- dates and money never break inside the value ------------------
  // Each Released date, Value amount and Promised date sits on one
  // line: the element's height under 1.6 times its line height, or a
  // single client rect for the value's text node. Every date and the
  // value's amount live in their own inline element (the value's
  // figure span inside its cell), so the element's height IS the
  // number of lines the text occupies; the value's cell box itself
  // stretches to the row's height and could never witness it. The
  // rect probe only counts child nodes that are real text nodes
  // (nodeType 3) and expose their own getClientRects, so it can never
  // throw — the height check decides on its own if the probe yields
  // nothing.
  const oneLine = await page.evaluate(() => {
    const lineHeight = (el) => {
      const lh = parseFloat(getComputedStyle(el).lineHeight);
      return Number.isFinite(lh) && lh > 0 ? lh : parseFloat(getComputedStyle(el).fontSize) * 1.2;
    };
    const underOneLine = (el) => el.getBoundingClientRect().height < 1.6 * lineHeight(el);
    const textNodeRects = (el) => {
      let count = 0;
      try {
        let node = el.firstChild;
        while (node && typeof node === 'object') {
          if (node.nodeType === 3 && typeof node.getClientRects === 'function') {
            count += node.getClientRects().length;
          }
          node = node.nextSibling;
        }
      } catch (err) {
        count = 0; // a probe failure proves nothing about wrapping
      }
      return count;
    };
    const released = [];
    const value = [];
    const promised = [];
    document.querySelectorAll('tr.rl-row').forEach((row) => {
      const dateEl = row.querySelector('.rl-released-date');
      released.push(dateEl ? underOneLine(dateEl) : false);
      const valueCell = row.querySelector('.rl-cell-value');
      const valueEl = valueCell ? valueCell.querySelector('.rl-cell-value-fig') : null;
      value.push(valueEl ? underOneLine(valueEl) || textNodeRects(valueEl) === 1 : false);
      const promEl = row.querySelector('.rl-cell-date');
      promised.push(promEl ? underOneLine(promEl) || textNodeRects(promEl) === 1 : false);
    });
    return { rows: released.length, released, value, promised };
  });
  expect(oneLine.rows).toBe(17);
  expect(oneLine.released).toEqual(Array(17).fill(true));
  expect(oneLine.value).toEqual(Array(17).fill(true));
  expect(oneLine.promised).toEqual(Array(17).fill(true));

  // --- the Released cell: the date on one line, " by jason" on the --
  // next, in the secondary ink token.
  const releasedCell = await page.evaluate(() => {
    const rows = Array.from(document.querySelectorAll('tr.rl-row'));
    const first = rows[0];
    const dateEl = first && first.querySelector('.rl-released-date');
    const byEl = first && first.querySelector('.rl-released-by');
    if (!first || !dateEl || !byEl) {
      return {
        rows: rows.length,
        split: false,
        dateText: null,
        byText: null,
        colorMatchesToken: false,
      };
    }
    const split = rows.every((row) => {
      const d = row.querySelector('.rl-released-date');
      const b = row.querySelector('.rl-released-by');
      if (!d || !b) return false;
      const dr = d.getBoundingClientRect();
      const br = b.getBoundingClientRect();
      return br.top >= dr.bottom - 0.5 && Math.abs(br.left - dr.left) <= 1;
    });
    const token = getComputedStyle(document.documentElement)
      .getPropertyValue('--color-ink-3')
      .trim();
    let colorMatchesToken = false;
    const m = token.match(/^#([0-9a-fA-F]{6})$/);
    if (m) {
      const n = parseInt(m[1], 16);
      colorMatchesToken =
        getComputedStyle(byEl).color ===
        'rgb(' + ((n >> 16) & 255) + ', ' + ((n >> 8) & 255) + ', ' + (n & 255) + ')';
    }
    return {
      rows: rows.length,
      split,
      dateText: dateEl.textContent,
      byText: byEl.textContent,
      colorMatchesToken,
    };
  });
  expect(releasedCell.rows).toBe(17);
  expect(releasedCell.split).toBe(true);
  expect(releasedCell.dateText).toBe('2026-10-21');
  expect(releasedCell.byText.trim()).toBe('by jason');
  expect(releasedCell.colorMatchesToken).toBe(true);
  expect(pageErrors).toEqual([]);

  // --- an empty filter: the chip's own note, no table ----------------
  await chipByState('late').click();
  await expect(chipByState('late')).toHaveAttribute('aria-pressed', 'true');
  await expect(emptyNote).toHaveText('No orders are late.');
  // The note is not just present in the DOM: it is actually visible.
  await expect(emptyNote).toBeVisible();
  await expect(table).toHaveCount(0);
  await expect(rows).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // "All" brings every order back.
  await chipByState('all').click();
  await expect(emptyNote).toHaveCount(0);
  await expect(rows).toHaveCount(17);
  expect(pageErrors).toEqual([]);

  // --- an empty answer: the first-load note ---------------------------
  ctrl.releasesAnswer = releasesPayloadEmpty();
  await refresh.click();
  await expect(emptyNote).toHaveText('Nothing has been released to the ERP yet.');
  // The first-load note is visible, not just present in the DOM.
  await expect(emptyNote).toBeVisible();
  await expect(table).toHaveCount(0);
  ctrl.releasesAnswer = null;
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const releasesGetsBeforeViewer = ctrl.releasesGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and no releases fetch went out before the view is activated.
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 1);

  // Activating the view for the viewer: the screen renders ...
  await page.click('.nav-btn[data-view="releases"]');
  expect(page.url()).toContain('#/releases');
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 2);
  await expect(chips).toHaveText([
    'All 17',
    'Late 0',
    'Awaiting approval 17',
    'Partly received 0',
    'Open 0',
    'Received 0',
    'Cancelled 0',
    'Missing 0',
  ]);
  await expect(rows).toHaveCount(17);
  await expect(rows.nth(0).locator('.rl-cell-order')).toHaveText('PO003068');

  // ... and the admin-only controls are absent where the read-only
  // note shows instead: the Settings view's mappings and budget forms
  // do not render for the viewer, and the system setting is
  // read-only — while the page still renders.
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(0);
  await expect(
    page.locator('.settings-row-note', { hasText: 'Only an admin can change this.' }),
  ).toHaveCount(3);
  await expect(
    page.locator('.settings-row[data-key="decisions.require_action_choice"] button.settings-switch'),
  ).toBeDisabled();
  expect(pageErrors).toEqual([]);
});
