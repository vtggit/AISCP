// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the releases answer
// (ctrl.releasesAnswer / ctrl.releasesAnswerStatus) and the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the planner to
// the non-admin viewer. Every releases request is counted in
// ctrl.releasesGets and every request path recorded in ctrl.requests.
async function mockApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    releasesAnswer: null,
    releasesAnswerStatus: 200,
    releasesDetail: null,
    releasesGets: 0,
    requests: [],
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    ctrl.requests.push(path);
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      if (ctrl.releasesAnswerStatus !== 200) {
        return route.fulfill({
          status: ctrl.releasesAnswerStatus,
          json: { detail: ctrl.releasesDetail || 'Internal Server Error' },
        });
      }
      return route.fulfill({
        status: 200,
        json: ctrl.releasesAnswer === null ? releasesPayload() : ctrl.releasesAnswer,
      });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// Mark the figures stale and take the Overview off and on again: the
// next activation re-requests every region, releases included.
async function reactivateOverview(page) {
  await page.evaluate(() => {
    window.Overview.invalidate();
  });
  await page.evaluate(() => {
    window.location.hash = '#/queue';
  });
  await expect(page.locator('#view-queue')).toBeVisible();
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await expect(page.locator('#view-overview')).toBeVisible();
}

test('issue583 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  /* ---------------- planner pass: development sign-in ------------------ */
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockApi(page);
  const card = page.locator('[data-testid="ov-releases"]');
  const openLink = page.locator('[data-testid="ov-releases-open"]');

  await page.goto('/');

  // Sign in through the development token card, as the existing
  // Overview specs do. The Overview is the default view, so the
  // releases region loads the first time it becomes active.
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'issue583-dev-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  await expect.poll(() => ctrl.releasesGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // --- Case 1: card content ------------------------------------------
  await expect(card).toBeVisible();
  await expect(card.locator('.ov-releases-title')).toHaveText('Released orders');

  const figures = card.locator('.ov-releases-figures .ov-figure');
  await expect(figures).toHaveCount(4);
  await expect(figures.nth(0).locator('.ov-figure-label')).toHaveText('Late');
  // Late above 0: the leading ▼ marker, in the risk colour token.
  await expect(figures.nth(0).locator('.ov-figure-value')).toHaveText('\u25bc 1');
  const lateColor = await figures
    .nth(0)
    .locator('.ov-figure-value')
    .evaluate((el) => getComputedStyle(el).color);
  expect(lateColor).toBe('rgb(138, 59, 5)'); // --color-risk #8A3B05
  await expect(figures.nth(1).locator('.ov-figure-label')).toHaveText('Awaiting approval');
  await expect(figures.nth(1).locator('.ov-figure-value')).toHaveText('2');
  await expect(figures.nth(2).locator('.ov-figure-label')).toHaveText('Partly received');
  await expect(figures.nth(2).locator('.ov-figure-value')).toHaveText('0');
  await expect(figures.nth(3).locator('.ov-figure-label')).toHaveText('Received');
  await expect(figures.nth(3).locator('.ov-figure-value')).toHaveText('0');

  // The oldest waiting approval: the largest days_waiting (20,
  // PO003068), not the first awaiting order in the answer.
  await expect(card.locator('.ov-releases-note')).toHaveText('Oldest waiting 20 d (PO003068)');

  // "Open Releases" is a real link to #/releases, and it navigates.
  await expect(openLink).toHaveAttribute('href', '#/releases');
  await openLink.click();
  await expect(page).toHaveURL(/#\/releases$/);
  await expect(page.locator('#view-releases')).toBeVisible();
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await expect(page.locator('#view-overview')).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- Case 2: order ---------------------------------------------------
  const order = await page.evaluate(() => {
    const releases = document.getElementById('ov-region-releases');
    const lastCard = document.getElementById('ov-region-card-stockout');
    const attention = document.querySelector('.ov-attention');
    return {
      afterCards:
        lastCard.compareDocumentPosition(releases) & Node.DOCUMENT_POSITION_FOLLOWING,
      beforeAttention:
        releases.compareDocumentPosition(attention) & Node.DOCUMENT_POSITION_FOLLOWING,
    };
  });
  expect(order.afterCards).toBeTruthy();
  expect(order.beforeAttention).toBeTruthy();

  // --- Case 3: an empty answer -----------------------------------------
  const getsBeforeEmpty = ctrl.releasesGets;
  ctrl.releasesAnswer = releasesPayloadEmpty();
  await reactivateOverview(page);
  await expect.poll(() => ctrl.releasesGets).toBe(getsBeforeEmpty + 1);
  await expect(card.locator('.ov-releases-empty')).toHaveText(
    'Nothing has been released to the ERP yet.',
  );
  // No counts and no oldest-waiting line.
  await expect(card.locator('.ov-releases-figures')).toHaveCount(0);
  await expect(card.locator('.ov-releases-note')).toHaveCount(0);
  ctrl.releasesAnswer = null;
  expect(pageErrors).toEqual([]);

  // --- Case 4: failure isolation ---------------------------------------
  const getsBeforeFailure = ctrl.releasesGets;
  ctrl.releasesAnswerStatus = 503;
  ctrl.releasesDetail = 'Acumatica is unreachable';
  await reactivateOverview(page);
  await expect.poll(() => ctrl.releasesGets).toBe(getsBeforeFailure + 1);
  // The server's detail, inline, with a Retry ...
  await expect(card.locator('.ov-releases-error')).toBeVisible();
  await expect(card.locator('.ov-releases-error-msg')).toHaveText('Acumatica is unreachable');
  await expect(card.locator('.ov-retry')).toBeVisible();
  // ... while the other Overview regions are unaffected: the value
  // tiles still render, the attention region still shows its note.
  await expect(page.locator('#ov-region-tiles .ov-tile')).toHaveCount(3);
  await expect(page.locator('#ov-region-tiles .ov-tile').nth(0)).toContainText('$3,400');
  await expect(page.locator('#ov-attention-body')).toContainText(
    'Nothing needs a decision right now.',
  );

  // Retry re-requests only /api/aggregate/releases.
  ctrl.releasesAnswerStatus = 200;
  ctrl.releasesDetail = null;
  const requestsBeforeRetry = ctrl.requests.length;
  await card.locator('.ov-retry').click();
  await expect(card.locator('.ov-releases-figures')).toBeVisible();
  const retried = ctrl.requests.slice(requestsBeforeRetry);
  expect(retried).toEqual(['/api/aggregate/releases']);
  expect(pageErrors).toEqual([]);

  // --- Case 5: escaping -------------------------------------------------
  const getsBeforeEscape = ctrl.releasesGets;
  ctrl.releasesAnswer = releasesPayloadEscaped();
  await reactivateOverview(page);
  await expect.poll(() => ctrl.releasesGets).toBe(getsBeforeEscape + 1);
  // The hostile order_nbr renders as text in the oldest-waiting line.
  const noteText = (await card.locator('.ov-releases-note').textContent()).trim();
  expect(noteText).toBe('Oldest waiting 20 d (<img src=x onerror=window.__pwned=1>)');
  const pwned = await page.evaluate(() => window.__pwned);
  expect(pwned).toBeUndefined();
  ctrl.releasesAnswer = null;
  expect(pageErrors).toEqual([]);

  // --- Case 6: staleness ------------------------------------------------
  // Re-activation alone (no invalidation) does not re-request.
  const getsStable = ctrl.releasesGets;
  await page.evaluate(() => {
    window.location.hash = '#/queue';
  });
  await expect(page.locator('#view-queue')).toBeVisible();
  await page.evaluate(() => {
    window.location.hash = '#/overview';
  });
  await expect(page.locator('#view-overview')).toBeVisible();
  await page.waitForTimeout(300);
  expect(ctrl.releasesGets).toBe(getsStable);
  // ... but after Overview.invalidate(), re-activation does.
  const getsBeforeStale = ctrl.releasesGets;
  await reactivateOverview(page);
  await expect.poll(() => ctrl.releasesGets).toBe(getsBeforeStale + 1);
  expect(pageErrors).toEqual([]);

  /* ---------- viewer pass: NON-ADMIN, production boot, full reload ---- */
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  const getsBeforeViewer = ctrl.releasesGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');
  // ... and the releases region loaded for the viewer as well.
  await expect.poll(() => ctrl.releasesGets).toBe(getsBeforeViewer + 1);
  await expect(card).toBeVisible();
  await expect(card.locator('.ov-releases-title')).toHaveText('Released orders');
  await expect(card.locator('.ov-releases-figures')).toBeVisible();
  expect(pageErrors).toEqual([]);

  // The admin-only controls are absent while the page still renders:
  // nothing carries the admin-only marker, and the Settings view's
  // mappings and budget forms do not render for the viewer — the
  // read-only note shows instead, the system switch disabled.
  await expect(page.locator('[data-admin-only]')).toHaveCount(0);
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(0);
  await expect(
    page.locator('.settings-row-note', { hasText: 'Only an admin can change this.' }),
  ).toHaveCount(3);
  await expect(
    page.locator('.settings-row[data-key="decisions.require_action_choice"] button.settings-switch'),
  ).toBeDisabled();
  expect(pageErrors).toEqual([]);
});
