// Proving spec for AIERP issue #583 — the Overview's fifth load
// region, the "Released orders" card.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route — the same mocks and sign-in as the
// existing Overview specs (issue #229): /api/auth/config answers
// authMode development and the pass signs in through the development
// token card at 1440x900. The mocked releases answer has PO003077
// late (days_late 1), PO003068 awaiting_approval (days_waiting 20) and
// PO003070 awaiting_approval (days_waiting 3); counts are
// {"awaiting_approval": 2, "late": 1, "partly_received": 0,
// "received": 0}.
//
// The pass proves, in order:
//   * Card content: the card shows Late 1 with the leading ▼ marker in
//     the risk colour, Awaiting approval 2, Partly received 0,
//     Received 0, the line "Oldest waiting 20 d (PO003068)" (the
//     largest days_waiting among the awaiting orders), and "Open
//     Releases" — a real link to #/releases — which navigates there.
//   * Order: the card sits after the three list cards and before the
//     attention region.
//   * Empty answer: with no orders the card reads "Nothing has been
//     released to the ERP yet." and shows no counts.
//   * Failure isolation: a 503 {"detail": "Acumatica is unreachable"}
//     shows that detail inline with a Retry while the value tiles
//     still render; Retry re-requests only /api/aggregate/releases.
//   * Escaping: an order_nbr of "<img src=x onerror=window.__pwned=1>"
//     renders as text and window.__pwned stays undefined.
//   * Staleness: after Overview.invalidate(), re-activating the
//     Overview requests the releases aggregate again; without it,
//     re-activation alone does not.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, the shell renders for the
// viewer with the releases card loaded, and the admin-only controls —
// the Settings view's mappings and budget forms — are absent where
// "Only an admin can change this." shows instead.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue583 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

