// Proving spec for AIERP issue #605 — the "Suppliers" screen
// (#/suppliers): a planner screen wired like the others — the
// "Suppliers" nav button (after "Releases", before "Decision log"),
// the #view-suppliers section with #suppliers-root, and the view
// registered in the shell (title "Suppliers", subtitle "How
// reliably each supplier delivers by the promised date").
//
// The screen fetches GET /api/suppliers/performance?window_days=<n>
// through app/js/api.js when the view becomes active and again when
// the window select ([data-testid="suppliers-window"]) changes —
// "Last 90 days", "Last 180 days", "Last 365 days" (the default) and
// "Last 730 days". A request-sequence guard renders only the newest
// answer, and a skeleton shows while a fetch is out.
//
// The table ([data-testid="suppliers-table"]) scrolls within its own
// region, one row per supplier in the answer's order: Supplier
// (supplier_code), Receipts, On time (the rate as a whole percent
// with "(<on_time> of <with_promise>)" after it, "No promised dates"
// when the rate is null; below 80% a leading ▼ marker and the risk
// colour tokens), Late, Avg days late, Max days late (an em dash
// when null), Avg lead time (d, one decimal), P90 lead time (d) and
// Last receipt. With no suppliers the screen reads "No receipts in
// this window."; a 422 shows the server's detail inline with a
// Retry, any other failure "Supplier performance could not be
// loaded." with a Retry. Every API value is escaped; at 390x844 the
// page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route. The mocked performance answer has
// three suppliers — 4834 (5 receipts, 3 of 5 on time, 60%, 4.0/6
// days late, 12.4/18 lead time, last receipt 2026-06-25), 4861
// (2 receipts, no promised dates, lateness null) and 4883 (95% on
// time) — in that order.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, no suppliers fetch goes out before the view is
// activated, the screen then renders for the viewer, and the
// admin-only controls — the Settings view's mappings and budget
// forms — are absent where "Only an admin can change this." shows
// instead, the page rendering on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue605 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

