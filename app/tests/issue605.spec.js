// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the performance answers
// (ctrl.suppliersAnswer, the one-shot ctrl.suppliersNext), hold a
// request until it is answered (ctrl.holdSuppliersNext /
// ctrl.heldSuppliers) for the in-flight state, and steer the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the planner to
// the non-admin viewer. Every performance request is counted in
// ctrl.suppliersGets, and each request's window_days lands in
// ctrl.suppliersWindows.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    suppliersAnswer: null,
    suppliersNext: null,
    holdSuppliersNext: false,
    heldSuppliers: [],
    suppliersGets: 0,
    suppliersWindows: [],
    summaryGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.suppliersGets += 1;
      ctrl.suppliersWindows.push(url.searchParams.get('window_days'));
      if (ctrl.holdSuppliersNext) {
        ctrl.holdSuppliersNext = false;
        ctrl.heldSuppliers.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      if (ctrl.suppliersNext) {
        const next = ctrl.suppliersNext;
        ctrl.suppliersNext = null;
        return route.fulfill(next);
      }
      const answer =
        typeof ctrl.suppliersAnswer === 'function' ? ctrl.suppliersAnswer() : ctrl.suppliersAnswer;
      return route.fulfill({ status: 200, json: answer || suppliersPayloadBase() });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue605 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in ------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockSuppliersApi(page);

  const windowSelect = page.locator('[data-testid="suppliers-window"]');
  const table = page.locator('[data-testid="suppliers-table"]');
  const rows = page.locator('tr.sp-row');
  const skeleton = page.locator('[data-testid="suppliers-skeleton"]');
  const emptyNote = page.locator('[data-testid="suppliers-empty"]');
  const errorMsg = page.locator('[data-testid="suppliers-error-msg"]');
  const retry = page.locator('[data-testid="suppliers-retry"]');

  await page.goto('/');

  // No suppliers request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.suppliersGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // The suppliers view is not active yet (the default view is): no
  // suppliers request.
  expect(ctrl.suppliersGets).toBe(0);
  expect(pageErrors).toEqual([]);

  // The nav is wired like the other screens: the "Suppliers" button
  // after "Releases", before "Decision log", the view section with
  // #suppliers-root, and the hash #/suppliers on navigation.
  await expect(page.locator('.nav-btn[data-view="suppliers"]')).toHaveCount(1);
  await expect(page.locator('.nav-btn[data-view="suppliers"]')).toHaveText('Suppliers');
  const navViews = await page
    .locator('.nav .nav-btn')
    .evaluateAll((buttons) => buttons.map((b) => b.getAttribute('data-view')));
  expect(navViews).toEqual(NAV_VIEWS);
  await expect(page.locator('#view-suppliers.view[data-view="suppliers"]')).toHaveCount(1);
  await expect(page.locator('#view-suppliers > #suppliers-root')).toHaveCount(1);

  await page.click('.nav-btn[data-view="suppliers"]');
  await expect(page).toHaveURL(/#\/suppliers$/);
  await expect(page.locator('#view-suppliers')).toBeVisible();
  await expect(page.locator('.nav-btn[data-view="suppliers"]')).toHaveAttribute(
    'aria-current',
    'page',
  );
  await expect(page.locator('#page-title')).toHaveText('Suppliers');
  await expect(page.locator('#page-subtitle')).toHaveText(
    'How reliably each supplier delivers by the promised date',
  );

  // Activation fetches exactly once, and the answer renders.
  await expect.poll(() => ctrl.suppliersGets).toBe(1);
  expect(ctrl.suppliersWindows[ctrl.suppliersWindows.length - 1]).toBe('365');
  await expect(table).toBeVisible();
  expect(pageErrors).toEqual([]);

  // --- the window select: the four windows, 365 the default ----------
  const optionLabels = await windowSelect.locator('option').allTextContents();
  expect(optionLabels).toEqual([
    'Last 90 days',
    'Last 180 days',
    'Last 365 days',
    'Last 730 days',
  ]);
  await expect(windowSelect).toHaveValue('365');

  // --- the table: three suppliers, in the answer's order --------------
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('.sp-cell-supplier')).toHaveText(['4834', '4861', '4883']);

  // 4834: below 80% — the ▼ marker and the risk colour tokens, the
  // percent with its basis, the lateness and lead-time figures.
  expect(await rows.nth(0).locator('td').allTextContents()).toEqual([
    '4834',
    '5',
    '\u25bc 60% (3 of 5)',
    '2',
    '4.0',
    '6',
    '12.4',
    '18',
    '2026-06-25',
  ]);
  const riskyRate = rows.nth(0).locator('.sp-rate');
  await expect(riskyRate).toHaveText('\u25bc 60% (3 of 5)');
  await expect(riskyRate).toHaveClass(/sp-rate--risk/);

  // 4861: nothing promised — "No promised dates", em dashes for the
  // lateness figures.
  expect(await rows.nth(1).locator('td').allTextContents()).toEqual([
    '4861',
    '2',
    'No promised dates',
    '0',
    '\u2014',
    '\u2014',
    '8.0',
    '9',
    '2026-08-14',
  ]);
  await expect(rows.nth(1).locator('.sp-rate')).not.toHaveClass(/sp-rate--risk/);

  // 4883: 95% on time — no marker.
  expect(await rows.nth(2).locator('td').allTextContents()).toEqual([
    '4883',
    '40',
    '95% (38 of 40)',
    '2',
    '1.2',
    '3',
    '9.8',
    '14',
    '2026-07-02',
  ]);
  const healthyRate = rows.nth(2).locator('.sp-rate');
  await expect(healthyRate).toHaveText('95% (38 of 40)');
  await expect(healthyRate).not.toHaveClass(/sp-rate--risk/);
  expect(pageErrors).toEqual([]);

  // --- choosing a window re-fetches with it ---------------------------
  await windowSelect.selectOption({ label: 'Last 90 days' });
  await expect.poll(() => ctrl.suppliersGets).toBe(2);
  expect(ctrl.suppliersWindows[ctrl.suppliersWindows.length - 1]).toBe('90');
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('.sp-cell-supplier')).toHaveText(['4834', '4861', '4883']);
  expect(pageErrors).toEqual([]);

  // --- while a fetch is out: the skeleton, the select disabled --------
  ctrl.holdSuppliersNext = true;
  await windowSelect.selectOption({ label: 'Last 180 days' });
  await expect.poll(() => ctrl.suppliersGets).toBe(3);
  await expect(skeleton).toBeVisible();
  await expect(windowSelect).toBeDisabled();
  ctrl.heldSuppliers[0].fulfill({ status: 200, json: suppliersPayloadBase() });
  await expect(skeleton).toHaveCount(0);
  await expect(windowSelect).toBeEnabled();
  expect(ctrl.suppliersWindows[ctrl.suppliersWindows.length - 1]).toBe('180');
  await expect(rows).toHaveCount(3);
  expect(pageErrors).toEqual([]);

  // --- a 422: the server's detail inline, with a Retry ----------------
  ctrl.suppliersNext = {
    status: 422,
    json: { detail: 'window_days must be between 1 and 1825' },
  };
  await windowSelect.selectOption({ label: 'Last 365 days' });
  await expect(errorMsg).toHaveText('window_days must be between 1 and 1825');
  await expect(retry).toBeVisible();
  await expect(table).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- any other failure: the generic message, with a Retry -----------
  ctrl.suppliersNext = { status: 500, json: { detail: 'internal boom' } };
  await retry.click();
  await expect(errorMsg).toHaveText('Supplier performance could not be loaded.');
  await expect(retry).toBeVisible();

  // --- Retry recovers --------------------------------------------------
  await retry.click();
  await expect.poll(() => ctrl.suppliersGets).toBe(6);
  await expect(rows).toHaveCount(3);
  expect(pageErrors).toEqual([]);

  // --- an empty answer: the empty note --------------------------------
  ctrl.suppliersAnswer = suppliersPayloadEmpty;
  await windowSelect.selectOption({ label: 'Last 90 days' });
  await expect(emptyNote).toHaveText('No receipts in this window.');
  await expect(table).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- a hostile supplier code: text, never markup --------------------
  ctrl.suppliersAnswer = suppliersPayloadHostile;
  await windowSelect.selectOption({ label: 'Last 180 days' });
  const hostileCell = rows.nth(0).locator('td').first();
  await expect(hostileCell).toHaveText('<img src=x onerror=window.__pwned=1>');
  await expect(page.locator('#suppliers-root img')).toHaveCount(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  ctrl.suppliersAnswer = null;
  expect(pageErrors).toEqual([]);

  // --- 390x844: the page does not scroll sideways ---------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#view-suppliers')).toBeVisible();
  await expect(windowSelect).toBeVisible();
  const narrowScrollWidth = await page.evaluate(() => document.documentElement.scrollWidth);
  expect(narrowScrollWidth).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const suppliersGetsBeforeViewer = ctrl.suppliersGets;
  const summaryGetsBeforeViewer = ctrl.summaryGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and no suppliers fetch went out before the view is activated:
  // the Overview view (the default) loads on its own ...
  await expect.poll(() => ctrl.summaryGets).toBeGreaterThan(summaryGetsBeforeViewer);
  // ... and the suppliers screen has not asked for its data yet.
  expect(ctrl.suppliersGets).toBe(suppliersGetsBeforeViewer);

  // Activating the view for the viewer: the screen renders ...
  await page.click('.nav-btn[data-view="suppliers"]');
  expect(page.url()).toContain('#/suppliers');
  await expect(page.locator('#view-suppliers')).toBeVisible();
  await expect.poll(() => ctrl.suppliersGets).toBe(suppliersGetsBeforeViewer + 1);
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('.sp-cell-supplier')).toHaveText(['4834', '4861', '4883']);

  // ... and the admin-only controls are absent where the read-only
  // note shows instead: the Settings view's mappings and budget forms
  // do not render for the viewer, and the system setting is
  // read-only — while the page still renders.
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(0);
  await expect(
    page.locator('.settings-row-note', { hasText: 'Only an admin can change this.' }),
  ).toHaveCount(3);
  await expect(
    page.locator('.settings-row[data-key="decisions.require_action_choice"] button.settings-switch'),
  ).toBeDisabled();
  expect(pageErrors).toEqual([]);
});
