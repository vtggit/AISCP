// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the expedite answers
// (ctrl.expediteAnswer, the one-shot ctrl.expediteNext), hold a
// request until it is answered (ctrl.holdExpediteNext /
// ctrl.heldExpedite) for the in-flight state, and steer the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the planner to
// the non-admin viewer. Every expedite request is counted in
// ctrl.expediteGets.
async function mockExpediteApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    expediteAnswer: null,
    expediteNext: null,
    holdExpediteNext: false,
    heldExpedite: [],
    expediteGets: 0,
    summaryGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/expedite') {
      ctrl.expediteGets += 1;
      if (ctrl.holdExpediteNext) {
        ctrl.holdExpediteNext = false;
        // One held request per section: the previous section's route is
        // spent, so heldExpedite[0] is always this section's own request.
        ctrl.heldExpedite.length = 0;
        ctrl.heldExpedite.push(route);
        return; // held: the test answers it (the in-flight state)
      }
      if (ctrl.expediteNext) {
        const next = ctrl.expediteNext;
        ctrl.expediteNext = null;
        return route.fulfill(next);
      }
      const answer =
        typeof ctrl.expediteAnswer === 'function' ? ctrl.expediteAnswer() : ctrl.expediteAnswer;
      return route.fulfill({ status: 200, json: answer || expeditePayloadBase() });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

