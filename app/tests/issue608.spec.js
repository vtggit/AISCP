// Proving spec for AIERP issue #608 — the "Expedite" screen
// (#/expedite): a planner screen wired like the others — the
// "Expedite" nav button (after "Suppliers", before "Decision log"),
// the #view-expedite section with #expedite-root, and the view
// registered in the shell (title "Expedite", subtitle "Open
// purchase lines that are late or will arrive after the item runs
// out").
//
// The screen fetches GET /api/expedite through app/js/api.js when
// the view becomes active and when the Refresh button
// ([data-testid="expedite-refresh"], a real <button>) is pressed. A
// request-sequence guard renders only the newest answer, and a
// skeleton shows while a fetch is out.
//
// Above the table a row of reason chips
// ([data-testid="expedite-filter"]) — "All", "Late" and "After
// stockout" — each shows its number of lines, counted from the
// answer's reasons; choosing a chip filters the table without a new
// request, and "All" is the default. The table
// ([data-testid="expedite-table"]) scrolls within its own region,
// one row per line in the answer's order: Order (order_nbr " / "
// line_nbr), Item, Site, Supplier (the code, followed by "· <n>% on
// time" when the answer carries a supplier_on_time_rate — below 80%
// that part gets the risk colour tokens), Promised, Late ("<n> d"
// when days_late is set, else empty), Open units and Value (whole
// dollars with separators, an em dash when the value is null), Cover
// ("<n> d", else an em dash), Stockout on (the date, else an em
// dash — when "after_stockout" is in the reasons it gets a leading
// ▼ marker and the risk colour tokens) and Why (a "Late" and/or an
// "After stockout" badge per reason). Below the table, when the
// answer's stale_excluded is above 0, a note reads "<n> line(s)
// promised more than 90 days ago are not shown."
//
// With no lines the screen reads "Nothing to chase today."; a 422
// shows the server's detail inline with a Retry, any other failure
// "The expedite list could not be loaded." with a Retry. Every API
// value is escaped; at 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route. The mocked expedite answer has
// three lines and stale_excluded 2 — PO003077 / 1 (late, 2 days,
// 647 units, 1941.0, 2.0 days of cover, stockout 2026-10-25,
// supplier 4883 at 95%), PO003090 / 1 (after stockout, stockout
// 2026-10-26, supplier 4834 at 60%) and PO003091 / 2 (late and
// after stockout, no open value) — in that order.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, no expedite fetch goes out before the view is
// activated, the screen then renders for the viewer, and the
// admin-only controls — the Settings view's mappings and budget
// forms — are absent where "Only an admin can change this." shows
// instead, the page rendering on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue608 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

