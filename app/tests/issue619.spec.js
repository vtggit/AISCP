// screens that show a supplier or vendor identity: Suppliers
// (#/suppliers), Expedite (#/expedite) and Releases (#/releases).
//
// Each of the three cells now leads with supplier_name: Suppliers
// shows supplier_name with vendor_code beneath it in the secondary
// ink token, the vendor code alone without a name, and the supplier
// code as today without either; Expedite follows the same rule with
// the existing "· <n>% on time" note after the identity; Releases
// shows supplier_name with vendor_code beneath it, the vendor code
// (else the supplier code) without a name, as today. A missing or
// empty supplier_name falls back to the existing code, never a
// blank. Every value is still inserted as text, never as markup,
// the colours come only from the design tokens, and at 390x844 the
// page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// the Releases spec (issue #567), plus the suppliers-performance
// and expedite answers. The mocked performance answer has three
