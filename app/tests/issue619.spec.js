// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the sign-in (ctrl.config /
// ctrl.me) when the pass switches from the planner to the non-admin
// viewer. Every request to the three screens under test is counted
// (ctrl.suppliersGets, ctrl.expediteGets, ctrl.releasesGets) and
// every /api/auth/me request lands in ctrl.meRequests.
async function mockScreensApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    suppliersGets: 0,
    expediteGets: 0,
    releasesGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.suppliersGets += 1;
      return route.fulfill({ status: 200, json: suppliersPayloadBase() });
    }
    if (path === '/api/expedite') {
      ctrl.expediteGets += 1;
      return route.fulfill({ status: 200, json: expeditePayloadBase() });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      return route.fulfill({ status: 200, json: releasesPayloadBase() });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// True when the first two-line identity cell on the screen shows the
// name line above the code line, both starting at the same x.
function assertNameAboveCode(page, rowSelector, nameSelector, codeSelector) {
  return page
    .evaluate(
      ([rowSelector, nameSelector, codeSelector]) => {
        const row = document.querySelector(rowSelector);
        const name = row ? row.querySelector(nameSelector) : null;
        const code = row ? row.querySelector(codeSelector) : null;
        if (!name || !code) {
          return false;
        }
        const nameRect = name.getBoundingClientRect();
        const codeRect = code.getBoundingClientRect();
        return (
          codeRect.top >= nameRect.bottom - 0.5 &&
          Math.abs(codeRect.left - nameRect.left) <= 1
        );
      },
      [rowSelector, nameSelector, codeSelector],
    )
    .then((above) => {
      expect(above).toBe(true);
    });
}

