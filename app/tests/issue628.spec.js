// Expedite and Releases screens: the Item cell shows the
// item_description, with the item_code beneath it in the secondary
// ink token, or just the code when there is no description.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as the
// Releases spec (issue #567): the planner signs in through the
// development token card at 1440x900, and the pass ends as a
// NON-ADMIN (role 'user') after a full reload: the token arrives in
// the URL hash as #access_token=..., /api/auth/config and
// /api/auth/me are mocked for that user, the IdP's auth and token
// endpoints carry the PKCE round-trip, the screens then render for
// the viewer, and the admin-only controls — the Settings view's
// mappings and budget forms — are absent where "Only an admin can
// change this." shows instead, the page rendering on.
//
// Checked, in order:
//
//   * Expedite: the line with item_code "CONPAPERST" and
//     item_description "Letter Paper Ream Standard" shows both, the
//     description first, and a line with a null description shows
//     only the code;
//   * Releases: expanding an order shows a line's description above
//     its code (and a null-description line shows only the code);
//   * a 120-character description wraps inside its cell — checked
//     on both screens — and the table region's scrollWidth stays
//     within its clientWidth;
//   * an item_description of "<img src=x onerror=window.__pwned=1>"
//     renders as text, and window.__pwned stays undefined;
//   * at 390x844 the page does not scroll sideways.
//
// Every value is inserted as text, and the colours come only from
// the design tokens in tokens.css (the secondary ink token for the
// code beneath the description).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue628 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

