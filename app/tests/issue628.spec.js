  const viewerItem = page.locator('tr.ex-row').nth(0).locator('.ex-cell-item');
  await expect(viewerItem.locator('.ex-item-desc')).toHaveText('Letter Paper Ream Standard');
  await expect(viewerItem.locator('.ex-item-code')).toHaveText('CONPAPERST');

