// Mock every /api/* call the queue (and the shell around it) makes —
// the same shape as the mocks in issue251.spec.js.
async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const meRequests = [];
  const appOrigin = { value: null };
  const api = { posted: [], historyGets: [], listGets: [] };

  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      api.listGets.push({ kind: path.slice('/api/'.length), query: url.search });
      const rows =
        path === '/api/drift' ? DRIFT_ROWS : path === '/api/excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      if (request.method() === 'POST') {
        api.posted.push({ kind: decisions[1], body: request.postDataJSON() });
        return route.fulfill({ status: 201, json: request.postDataJSON() });
      }
      api.historyGets.push({
        item: url.searchParams.get('item_code'),
        site: url.searchParams.get('site_code'),
      });
      return route.fulfill({ status: 200, json: [] });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests, appOrigin, api };
}

