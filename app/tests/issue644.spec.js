// Proving spec for AIERP issue #644 — the Releases table says when a
// promise is the ERP default. In the Promised cell
// (td.rl-cell-promised), when an order's promise_is_default is exactly
// true (never a truthy lookalike) and expected_on is a non-empty
// string, the cell gains a <span class="rl-cell-expected"> reading
// "expected <expected_on>" (for example "expected 2026-11-04") after
// the existing .rl-cell-date span, on its own line, in the
// --color-ink-2 token at 12px, with the title "The promised date is
// the ERP default; expected from the supplier's average lead time".
// Otherwise nothing new: promise_is_default not exactly true, or
// expected_on missing or empty, renders the cell exactly as before.
// The .rl-cell-date span and its text, the header list, every other
// cell and the expanded line rows are unchanged. The note's value is
// inserted escaped; colours come only from the tokens; at 390x844 the
// page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route — the same mocks and sign-in as
// app/tests/issue567.spec.js: the pass runs as a PLANNER (role
// 'user') signed in through the development token card at 1440x900,
// straight onto #/releases, and it ends as a NON-ADMIN (role 'user')
// after a full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer, and the
// admin-only controls — the Settings view's mappings and budget forms
// — are absent where "Only an admin can change this." shows instead,
// the page rendering on.
//
// The mocked releases answer has three orders — PO004001 (open, the
// ERP default promise: promised 2026-10-21, expected 2026-11-04,
// promise_is_default true), PO004002 (late, promise_is_default false
// with an expected_on) and PO004003 (received, neither field) — and
// counts {"awaiting_approval": 0, "late": 1, "partly_received": 0,
// "received": 1}.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue644 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

