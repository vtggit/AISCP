// Mock every /api/* call the app makes (the same surface as
// issue567.spec.js). The handler reads ctrl on every request, so the
// test can steer the releases answers (ctrl.releasesAnswer, the
// one-shot ctrl.releasesNext) and the sign-in (ctrl.config /
// ctrl.me) when the pass switches from the planner to the non-admin
// viewer. Every releases request is counted in ctrl.releasesGets.
async function mockReleasesApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    releasesAnswer: null,
    releasesNext: null,
    releasesGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/aggregate/releases') {
      ctrl.releasesGets += 1;
      if (ctrl.releasesNext) {
        const next = ctrl.releasesNext;
        ctrl.releasesNext = null;
        return route.fulfill(next);
      }
      const answer =
        typeof ctrl.releasesAnswer === 'function' ? ctrl.releasesAnswer() : ctrl.releasesAnswer;
      return route.fulfill({ status: 200, json: answer || releasesPayloadBase() });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue644 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- planner pass: development sign-in, straight onto #/releases --
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockReleasesApi(page);

  const chips = page.locator('[data-testid="releases-filter"] button');
  const table = page.locator('[data-testid="releases-table"]');
  const rows = page.locator('tr.rl-row');
  const refresh = page.locator('[data-testid="releases-refresh"]');

  await page.goto('/');

  // No releases request before the sign-in (Auth.bootstrap) completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.releasesGets).toBe(0);

  // Sign in through the development token card as the planner.
  await page.fill('#token-input', 'dev-planner-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
  // The Overview's released-orders card is the only releases request
  // until the Releases view is activated.
  await expect.poll(() => ctrl.releasesGets).toBe(1);
  expect(pageErrors).toEqual([]);

  await page.click('.nav-btn[data-view="releases"]');
  await expect(page).toHaveURL(/#\/releases$/);
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(2);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('.rl-cell-order')).toHaveText([
    'PO004001',
    'PO004002',
    'PO004003',
  ]);
  expect(pageErrors).toEqual([]);

  // The header list is unchanged.
  expect(
    await page.evaluate(() =>
      Array.from(document.querySelectorAll('[data-testid="releases-table"] thead th')).map(
        (th) => th.textContent,
      ),
    ),
  ).toEqual(['Order', 'State', 'Vendor', 'Warehouse', 'Released', 'Value', 'Promised', 'Delay']);

  // --- a default promise: the expected note --------------------------
  // PO004001: promise_is_default exactly true with a non-empty
  // expected_on — the note renders, after the untouched date span.
  const promised0 = rows.nth(0).locator('td.rl-cell-promised');
  await expect(promised0.locator('.rl-cell-date')).toHaveText('2026-10-21');
  const note0 = promised0.locator('.rl-cell-expected');
  await expect(note0).toHaveCount(1);
  await expect(note0).toHaveText('expected 2026-11-04');
  await expect(note0).toHaveAttribute(
    'title',
    "The promised date is the ERP default; expected from the supplier's average lead time",
  );
  // The cell's children are exactly the date span, then the note; the
  // note is a block on its own line beneath the date, in the
  // --color-ink-2 token (#33414E) at 12px.
  expect(
    await page.evaluate(() => {
      const cell = document.querySelector('tr.rl-row td.rl-cell-promised');
      const date = cell.querySelector('.rl-cell-date');
      const note = cell.querySelector('.rl-cell-expected');
      if (!cell || !date || !note) return null;
      const d = date.getBoundingClientRect();
      const n = note.getBoundingClientRect();
      const style = getComputedStyle(note);
      return {
        children: Array.from(cell.children).map((el) => el.getAttribute('class')),
        dateOnOneLine: d.height > 0 && n.top >= d.top + d.height / 2,
        sameLeft: n.left === d.left,
        display: style.display,
        fontSize: style.fontSize,
        color: style.color,
      };
    }),
  ).toEqual({
    children: ['rl-cell-date', 'rl-cell-expected'],
    dateOnOneLine: true,
    sameLeft: true,
    display: 'block',
    fontSize: '12px',
    color: 'rgb(51, 65, 78)',
  });

  // --- no note otherwise ----------------------------------------------
  // PO004002: promise_is_default false with an expected_on — no note,
  // the date span exactly as before.
  const promised1 = rows.nth(1).locator('td.rl-cell-promised');
  await expect(promised1.locator('.rl-cell-expected')).toHaveCount(0);
  await expect(promised1.locator('.rl-cell-date')).toHaveText('2026-10-18');
  // PO004003: neither field — no note either.
  const promised2 = rows.nth(2).locator('td.rl-cell-promised');
  await expect(promised2.locator('.rl-cell-expected')).toHaveCount(0);
  await expect(promised2.locator('.rl-cell-date')).toHaveText('2026-10-12');
  // Every non-default cell is exactly as before: only the date span.
  expect(
    await page.evaluate(() =>
      Array.from(document.querySelectorAll('tr.rl-row td.rl-cell-promised')).map((cell) =>
        Array.from(cell.children).map((el) => el.getAttribute('class')),
      ),
    ),
  ).toEqual([
    ['rl-cell-date', 'rl-cell-expected'],
    ['rl-cell-date'],
    ['rl-cell-date'],
  ]);
  expect(pageErrors).toEqual([]);

  // --- escaping: a hostile expected_on stays text ---------------------
  ctrl.releasesAnswer = releasesPayloadHostile();
  await refresh.click();
  await expect(rows).toHaveCount(3);
  const hostileNote = rows.nth(0).locator('td.rl-cell-promised .rl-cell-expected');
  await expect(hostileNote).toHaveText('expected <img src=x onerror=window.__pwned=1>');
  await expect(hostileNote).toHaveAttribute(
    'title',
    "The promised date is the ERP default; expected from the supplier's average lead time",
  );
  await expect(page.locator('#releases-root img')).toHaveCount(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  ctrl.releasesAnswer = null;
  expect(pageErrors).toEqual([]);

  // --- 390x844: the page does not scroll sideways ---------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect(refresh).toBeVisible();
  const narrowScrollWidth = await page.evaluate(() => document.documentElement.scrollWidth);
  expect(narrowScrollWidth).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload ----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const releasesGetsBeforeViewer = ctrl.releasesGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and the Overview's released-orders card is the only releases
  // fetch before the Releases view is activated.
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 1);

  // Activating the view for the viewer: the screen renders, the note
  // still there for the default-promise order ...
  await page.click('.nav-btn[data-view="releases"]');
  expect(page.url()).toContain('#/releases');
  await expect(page.locator('#view-releases')).toBeVisible();
  await expect.poll(() => ctrl.releasesGets).toBe(releasesGetsBeforeViewer + 2);
  await expect(chips).toHaveText([
    'All 3',
    'Late 1',
    'Awaiting approval 0',
    'Partly received 0',
    'Open 1',
    'Received 1',
    'Cancelled 0',
    'Missing 0',
  ]);
  await expect(rows).toHaveCount(3);
  await expect(rows.locator('.rl-cell-order')).toHaveText([
    'PO004001',
    'PO004002',
    'PO004003',
  ]);
  await expect(rows.nth(0).locator('td.rl-cell-promised .rl-cell-date')).toHaveText(
    '2026-10-21',
  );
  await expect(rows.nth(0).locator('td.rl-cell-promised .rl-cell-expected')).toHaveText(
    'expected 2026-11-04',
  );
  await expect(rows.nth(1).locator('td.rl-cell-promised .rl-cell-expected')).toHaveCount(0);
  await expect(rows.nth(2).locator('td.rl-cell-promised .rl-cell-expected')).toHaveCount(0);

  // ... and the admin-only controls are absent where the read-only
  // notes show instead: the Settings view's mappings and budget forms
  // do not render for the viewer, and the system setting is
  // read-only — while the page still renders.
  await page.click('.nav-btn[data-view="settings"]');
  await expect(page.locator('#view-settings')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(0);
  await expect(
    page.locator('.settings-row-note', { hasText: 'Only an admin can change this.' }),
  ).toHaveCount(3);
  await expect(
    page.locator('.settings-row[data-key="decisions.require_action_choice"] button.settings-switch'),
  ).toBeDisabled();
  expect(pageErrors).toEqual([]);
});
