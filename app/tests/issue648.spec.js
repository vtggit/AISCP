// Mock every /api/* call the queue (and the shell around it) makes —
// the same mocks as issue251.spec.js, with one recording added: every
// GET /api/recommendations/by-key is counted in api.byKeyGets so the
// proof can show the Order quantity section never requests one (a
// non-admin's queue has no draft-PO prefill to make that call).
async function mockQueueApi(page, { config = DEV_CONFIG, me = ADMIN_ME } = {}) {
  const meRequests = [];
  const appOrigin = { value: null };
  const api = {
    posted: [],
    historyGets: [],
    listGets: [],
    byKeyGets: [],
    store: {
      'B|S1': [
        {
          id: 'dec-b1',
          item_code: 'B',
          site_code: 'S1',
          decision: 'snoozed',
          action: null,
          reason: null,
          snooze_until: '2026-10-01',
          as_of: '2026-09-18',
          recommended_reorder_point_units: 210,
          current_reorder_point: 300,
          money_at_stake: 12150.5,
          decided_by: 'planner1',
          decided_at: '2026-09-18T09:00:00+00:00',
        },
      ],
    },
  };
  const rowByKey = {};
  for (const [kind, rows] of [
    ['drift', DRIFT_ROWS],
    ['excess', EXCESS_ROWS],
    ['stockout', STOCKOUT_ROWS],
  ]) {
    for (const row of rows) {
      rowByKey[kind + '|' + row.item_code + '|' + row.site_code] = row;
    }
  }

  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      api.listGets.push({ kind: path.slice('/api/'.length), query: url.search });
      const rows =
        path === '/api/drift' ? DRIFT_ROWS : path === '/api/excess' ? EXCESS_ROWS : STOCKOUT_ROWS;
      return route.fulfill({ status: 200, json: rows });
    }
    if (path === '/api/decisions/summary') {
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/recommendations/by-key') {
      api.byKeyGets.push({ query: url.search });
      return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
    }
    const decisions = /^\/api\/(drift|excess|stockout)\/decisions$/.exec(path);
    if (decisions) {
      const kind = decisions[1];
      if (request.method() === 'POST') {
        const body = request.postDataJSON();
        api.posted.push({ kind, path, body });
        if (kind === 'drift' && body.item_code === 'E' && body.site_code === 'S2') {
          return route.fulfill({ status: 422, json: { detail: E_DETAIL } });
        }
        const source = rowByKey[kind + '|' + body.item_code + '|' + body.site_code] || {};
        const stored = {
          id: 'dec-posted-' + api.posted.length,
          item_code: body.item_code,
          site_code: body.site_code,
          decision: body.decision,
          action: body.action || null,
          reason: body.reason || null,
          snooze_until: body.snooze_until || null,
          as_of: '2026-10-09',
          recommended_reorder_point_units:
            source.reorder_point_units != null
              ? source.reorder_point_units
              : source.excess_units != null
                ? source.excess_units
                : null,
          current_reorder_point:
            source.current_reorder_point != null ? source.current_reorder_point : null,
          money_at_stake:
            source.money_at_stake != null
              ? source.money_at_stake
              : source.money_tied_up != null
                ? source.money_tied_up
                : source.money_at_risk != null
                  ? source.money_at_risk
                  : null,
          decided_by: 'planner1',
          decided_at: '2026-10-09T07:30:00+00:00',
        };
        const key = body.item_code + '|' + body.site_code;
        api.store[key] = [stored].concat(api.store[key] || []);
        return route.fulfill({ status: 201, json: stored });
      }
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.historyGets.push({ item, site });
      return route.fulfill({
        status: 200,
        json: api.store[(item || '') + '|' + (site || '')] || [],
      });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { meRequests, appOrigin, api };
}

// The four dt/dd pairs of the Order quantity facts, in order.
async function oqFacts(page) {
  return page.locator('.q-orderqty .q-oq-fact').evaluateAll((els) =>
    els.map((el) => ({
      dt: el.querySelector('dt').textContent,
      dd: el.querySelector('dd').textContent,
    })),
  );
}

