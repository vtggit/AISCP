const SYS_KEY = 'decisions.require_action_choice';
const USR_KEY = 'queue.default_filter';
const NUM_KEY = 'replenishment.service_level';
const SET_SOURCE = 'Set by planner1 on 2026-10-09';
const REJECT_MESSAGE = 'Enter a number between 0.5 and 0.9999.';
const RANGE_TEXT = 'Between 0.5 and 0.9999';
const DESCRIPTION = 'The service level the replenishment model targets.';
const HOSTILE_DESCRIPTION = '<img src=x onerror=window.__pwned=1>';
const ADMIN_NOTE = 'Only an admin can change this.';

// The boolean and enum rows, exactly issue301's entries: the boolean on
// its default (no Reset) and the enum on its default.
function booleanEntry() {
  return {
    key: SYS_KEY,
    scope: 'system',
    type: 'boolean',
    allowed: null,
    default: true,
    description:
      'Accept on an excess or stockout row stays disabled until an action is chosen.',
    value: true,
    source: 'default',
    editable: true,
    updated_by: null,
    updated_by_name: null,
    updated_at: null,
  };
}

function enumEntry() {
  return {
    key: USR_KEY,
    scope: 'user',
    type: 'enum',
    allowed: ['open', 'decided', 'all'],
    default: 'open',
    description: 'The filter the Work queue opens with.',
    value: 'open',
    source: 'default',
    editable: true,
    updated_by: null,
    updated_by_name: null,
    updated_at: null,
  };
}

// The number row: system scope, on its default, editable by default.
function numberEntry(overrides) {
  const entry = {
    key: NUM_KEY,
    scope: 'system',
    type: 'number',
    allowed: null,
    default: 0.95,
    min: 0.5,
    max: 0.9999,
    description: DESCRIPTION,
    value: 0.95,
    source: 'default',
    editable: true,
    updated_by: null,
    updated_by_name: null,
    updated_at: null,
  };
  return Object.assign(entry, overrides || {});
}

// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user. The settings mock is an echo like
// the real API (and issue301's): a PUT stores the body's value (the
// source becomes the scope, planner1 is the changer) and a DELETE
// restores the default — both answering with the updated entry.
async function mockSettingsApi(page, { config, me, entries }) {
  const api = {
    settingsGets: 0,
    calls: [], // { method, key, body, contentType } for PUT/DELETE
    meRequests: [],
    current: entries,
    appOrigin: { value: null },
  };
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (api.appOrigin.value === null) {
      api.appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      api.meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    const match = /^\/api\/settings\/([^/]+)$/.exec(path);
    if (match && (request.method() === 'PUT' || request.method() === 'DELETE')) {
      const key = decodeURIComponent(match[1]);
      const entry = api.current.find((e) => e.key === key);
      if (!entry) {
        return route.fulfill({ status: 404, json: { detail: 'Unknown setting: ' + key } });
      }
      const body = request.method() === 'PUT' ? request.postDataJSON() : null;
      api.calls.push({
        method: request.method(),
        key,
        body,
        contentType: request.headers()['content-type'] || null,
      });
      if (request.method() === 'PUT') {
        entry.value = body.value;
        entry.source = entry.scope;
        entry.updated_by = 'planner1';
        entry.updated_at = '2026-10-09T07:30:00+00:00';
      } else {
        entry.value = entry.default;
        entry.source = 'default';
        entry.updated_by = null;
        entry.updated_at = null;
      }
      return route.fulfill({ status: 200, json: entry });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

// The production boot's PKCE round-trip, mocked the way the other
// proofs' viewer passes do it: the IdP's auth endpoint answers with a
// page that bounces straight back to the app with a code and the same
// state, and the token endpoint answers with the viewer's token.
async function mockPkceRoundTrip(page, appOrigin) {
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
}

test('issue654 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const api = await mockSettingsApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    entries: [booleanEntry(), enumEntry(), numberEntry()],
  });

  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // Open the settings view by hash change and wait for the rows.
  await page.click('.nav-btn[data-view="settings"]');
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/settings');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);

  const row = page.locator('.settings-row[data-key="' + NUM_KEY + '"]');
  const input = row.locator('.settings-number-input');
  const save = row.locator('.settings-number-save');
  const range = row.locator('.settings-number-range');
  const rowError = row.locator('.settings-row-error');

  // --- the control ----------------------------------------------------
  await expect(input).toHaveValue('0.95');
  await expect(input).toHaveAttribute('min', '0.5');
  await expect(input).toHaveAttribute('max', '0.9999');
  await expect(input).toHaveAttribute('step', 'any');
  await expect(input).toHaveAttribute('aria-label', DESCRIPTION);
  await expect(input).toBeEnabled();
  await expect(save).toHaveText('Save');
  await expect(save).toBeEnabled();
  await expect(range).toHaveText(RANGE_TEXT);
  await expect(rowError).toHaveCount(0);
  await expect(row.locator('.settings-reset')).toHaveCount(0);
  // The admin-only controls of the settings view are present for the
  // admin: the mappings and the budgets add forms.
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(1);

  // --- a valid save: one PUT with {"value":0.98}, the row updates -----
  await input.fill('0.98');
  await save.click();
  await expect.poll(() => api.calls.length).toBe(1);
  expect(api.calls[0]).toEqual({
    method: 'PUT',
    key: NUM_KEY,
    body: { value: 0.98 },
    contentType: 'application/json',
  });
  await expect(row.locator('.settings-source')).toHaveText(SET_SOURCE);
  await expect(row.locator('.settings-reset')).toBeVisible();
  await expect(row.locator('.settings-reset')).toHaveText('Reset to default');
  await expect(input).toHaveValue('0.98');
  await expect(rowError).toHaveCount(0);
  // The form sits in the row's controls, before the Reset button.
  expect(
    await row.locator('.settings-row-controls').evaluate((controls) =>
      Array.from(controls.children).map((child) => child.className),
    ),
  ).toEqual(['settings-number', 'btn btn-secondary settings-reset']);

  // --- local refusals: out of range, then blank — no request, error ---
  await input.fill('1.5');
  await save.click();
  expect(api.calls.length).toBe(1);
  await expect(rowError).toHaveText(REJECT_MESSAGE);

  await input.fill('');
  await save.click();
  expect(api.calls.length).toBe(1);
  await expect(rowError).toHaveText(REJECT_MESSAGE);

  // --- at 390x844 nothing scrolls sideways ------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);

  // --- back to the contract's 1440x900 for the non-admin pass ----------
  // The phone check above is the only place this proof narrows the page;
  // the second pass runs at the contract's 1440x900 and must not inherit
  // the phone viewport from the check.
  await page.setViewportSize({ width: 1440, height: 900 });
  expect(
    await page.evaluate(() => [window.innerWidth, window.innerHeight]),
  ).toEqual([1440, 900]);

  // --- the non-admin pass: full reload, the production boot ------------
  // The session from the admin pass is a different user's: a fresh
  // viewer starts with an empty session, and the token in the URL hash
  // is the production way in (the PKCE round-trip completes the boot).
  const viewerApi = await mockSettingsApi(page, {
    config: PROD_CONFIG,
    me: VIEWER_ME,
    entries: [
      booleanEntry(),
      enumEntry(),
      numberEntry({ editable: false, description: HOSTILE_DESCRIPTION }),
    ],
  });
  await mockPkceRoundTrip(page, viewerApi.appOrigin);
  await page.evaluate(() => window.sessionStorage.clear());
  // The admin pass left the document on /#/settings, and a goto that
  // changes only the fragment is a same-document navigation: the
  // signed-in shell would stay in memory and the production boot would
  // never run. Leave the document first so the viewer's boot is a full
  // document load.
  await page.goto('about:blank');
  await page.goto('/#access_token=viewer-token-abc');

  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect.poll(() => viewerApi.meRequests.length).toBeGreaterThan(0);
  expect(viewerApi.meRequests[0].headers()['authorization']).toBe('Bearer pkce-viewer-token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  expect(page.url()).not.toContain('access_token');

  await page.evaluate(() => {
    window.location.hash = '#/settings';
  });
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => viewerApi.settingsGets).toBeGreaterThanOrEqual(1);

  const vRow = page.locator('.settings-row[data-key="' + NUM_KEY + '"]');
  const vInput = vRow.locator('.settings-number-input');
  const vSave = vRow.locator('.settings-number-save');

  // --- not editable: the input and the Save button are disabled --------
  await expect(vInput).toHaveValue('0.95');
  await expect(vInput).toHaveAttribute('min', '0.5');
  await expect(vInput).toHaveAttribute('max', '0.9999');
  await expect(vInput).toBeDisabled();
  await expect(vSave).toBeDisabled();
  await expect(vRow.locator('.settings-number-range')).toHaveText(RANGE_TEXT);
  // The admin note for a non-editable entry, and no Reset: the value
  // is still on its default.
  await expect(vRow.locator('.settings-row-note')).toHaveText(ADMIN_NOTE);
  await expect(vRow.locator('.settings-reset')).toHaveCount(0);

  // --- escaping: the hostile description renders as text ---------------
  await expect(vRow.locator('.settings-desc')).toHaveText(HOSTILE_DESCRIPTION);
  expect(await page.evaluate(() => window.__pwned === undefined)).toBe(true);

  // --- the admin-only controls are absent, the page still renders ------
  await expect(page.locator('[data-testid="erp-mapping-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="purchase-budget-form"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="erp-mappings"]')).toBeVisible();
  await expect(page.locator('[data-testid="purchase-budgets"]')).toBeVisible();
  await expect(page.locator('[data-testid="erp-mappings"] .settings-row-note')).toHaveText([
    'No ERP code mappings yet.',
    ADMIN_NOTE,
  ]);
  await expect(page.locator('[data-testid="purchase-budgets"] .settings-row-note')).toHaveText([
    'No purchasing budget set.',
    ADMIN_NOTE,
  ]);
  // The settings rows still render for the non-admin.
  await expect(page.locator('.settings-row[data-key="' + SYS_KEY + '"]')).toBeVisible();
  await expect(page.locator('.settings-row[data-key="' + USR_KEY + '"]')).toBeVisible();
  // Nothing was sent for the whole viewer run.
  expect(viewerApi.calls.length).toBe(0);
});
