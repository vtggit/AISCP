// Proving spec for AIERP issue #665 — the service level line of the
// Work queue's detail pane (the planner's page, #/queue).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route (the same mocks and sign-in as
// app/tests/issue648.spec.js — here its production pass: the token in
// the URL hash as #access_token=..., /api/auth/config and /api/auth/me
// mocked for a NON-ADMIN (role "user") and the PKCE round-trip mocked
// to carry the viewer through it). A non-admin run is the only pass
// the line can be proven in: an admin's queue prefills the draft-PO
// section from GET /api/recommendations/by-key for every selected
// Reorder point row, so a by-key-free run means the queue renders
// read-only for a "user" role — the admin-only decision buttons and
// the draft-PO section asserted absent while the queue, the service
// level line included, still renders. Proves, at 1440x900 on #/queue:
//   * a Reorder points row whose service_level is 0.98 and whose
//     service_level_source is {"abc_class": "A", "source": "class"}
//     renders <p class="q-service-level"> reading exactly
//     "Service level 98% · class A level", directly after the existing
//     section.q-why and before the .q-orderqty of the same pane;
//   * a row with 0.95 and {"abc_class": "C", "source": "single"}
//     reads "Service level 95% · class C, single level", a row with
//     0.9999 and {"abc_class": null, "source": "single"} reads
//     "Service level 99.99%", and 0.975 renders "97.5%";
//   * a row whose service_level is null renders no .q-service-level at
//     all, and neither do the Excess and Stockout risk tabs;
//   * the line is set in the --color-ink-3 token colour and its values
//     reach the page escaped: the queue makes no request of its own —
//     the mock records no request beyond the ones issue648 already
//     expects, in particular none to /api/recommendations/by-key;
//   * at 1440x900 the document does not scroll and at 390x844 nothing
//     scrolls sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue665 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

