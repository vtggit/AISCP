//
// The pass proves, in order:
//   * Card content: the card follows the Released orders card, its
//     header row reads Class / Item-sites / Annual value / Share and
//     its rows read exactly A 2 "$800" "80%", B 1 "$100" "10%",
//     C 1 "$100" "10%"; the note reads "3 item-sites have no class
