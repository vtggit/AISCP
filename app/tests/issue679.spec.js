// The per-class mapping a 98 / 95 / 90 input set sends: each
// percentage/100, the float artefacts of the division rounded away.
const CLASS_ECHO = { A: 0.98, B: 0.95, C: 0.9 };

// A small, internally consistent simulation answer.
// service_level_by_class is null unless the lever was given — the
// note renders only for an object echo.
function buildResponse(options) {
  const opts = options || {};
  const prefix = opts.prefix || 'I';
  const rows = [];
  for (let i = 0; i < 6; i += 1) {
    const baseline = 500 + i * 37;
    const delta = i % 2 === 0 ? 15 : -10;
    rows.push({
      item_code: prefix + String(i + 1).padStart(3, '0'),
      site_code: i % 2 === 0 ? 'S1' : 'S2',
      baseline: {
        reorder_point: baseline - 0.4,
        reorder_point_units: baseline,
        safety_stock: 90 + i,
        safety_stock_units: 90 + i,
      },
      scenario: {
        reorder_point: baseline + delta - 0.4,
        reorder_point_units: baseline + delta,
        safety_stock: 90 + i + 8,
        safety_stock_units: 90 + i + 8,
      },
      reorder_point_units_delta: delta,
      safety_stock_units_delta: 8,
    });
  }
  const total = (key) => rows.reduce((acc, row) => acc + row[key], 0);
  return {
    summary: {
      item_sites: rows.length,
      reorder_point_units_delta_total: total('reorder_point_units_delta'),
      safety_stock_units_delta_total: total('safety_stock_units_delta'),
      reorder_point_up: rows.filter((r) => r.reorder_point_units_delta > 0).length,
      reorder_point_down: rows.filter((r) => r.reorder_point_units_delta < 0).length,
      reorder_point_unchanged: rows.filter((r) => r.reorder_point_units_delta === 0).length,
      dollar_impact: -1234.56,
      item_sites_without_unit_cost: 0,
      levers: { service_level: null, demand_multiplier: null, lead_time_multiplier: null },
      service_level_by_class: opts.classLevels !== undefined ? opts.classLevels : null,
    },
    item_sites: rows,
  };
}

const RESPONSE_CLASS = buildResponse({ prefix: 'I', classLevels: CLASS_ECHO });
const RESPONSE_BLANK = buildResponse({ prefix: 'J' });
const RESPONSE_VIEWER = buildResponse({ prefix: 'V', classLevels: CLASS_ECHO });

