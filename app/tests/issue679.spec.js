// The mocked API, the same shape as issue430.spec.js: every
// POST /api/scenarios/simulate is held — pushed onto ctrl.runs with
// its route — and the test answers it, in the order it chooses. The
// saved-scenario list answers immediately, and every
// POST /api/scenarios is held on ctrl.saves the same way.
async function mockScenarioApi(page, ctrl) {
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (url.pathname === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (url.pathname === '/api/scenarios/simulate' && request.method() === 'POST') {
      ctrl.runs.push({ body: request.postDataJSON(), route });
      return; // held: the test answers it, in the order it chooses
    }
    if (url.pathname === '/api/scenarios' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: ctrl.savedList });
    }
    if (url.pathname === '/api/scenarios' && request.method() === 'POST') {
      ctrl.saves.push({ body: request.postDataJSON(), route });
      return; // held: the test answers it
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
}

async function signIn(page) {
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');
}

// The uncaught exceptions of the page so far.
function collectPageErrors(page) {
  const errors = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  return errors;
}

test('issue679 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    runs: [],
    saves: [],
    meRequests: [],
    savedList: [SAVED_ROW],
  };
  await mockScenarioApi(page, ctrl);
  const pageErrors = collectPageErrors(page);

  await page.goto('/');
  await signIn(page);

  // --- the scenario view ---------------------------------------------
  await page.click('.nav-btn[data-view="scenario"]');
  await expect(page.locator('#view-scenario')).toHaveClass(/is-active/);
  await expect(page.locator('#view-scenario')).toBeVisible();
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/scenario');
  await expect(page.locator('[data-testid="scenario-levers"]')).toBeVisible();
  // The activation loaded the saved list: the placeholder plus the
  // one stored scenario.
  await expect(page.locator('[data-testid="scenario-saved-select"] option')).toHaveCount(2);

  // --- the class-levels fieldset -------------------------------------
  // Between the levers form and the saved-scenarios control, with the
  // legend and the three blank number inputs.
  const fieldset = page.locator('[data-testid="scenario-class-levels"]');
  await expect(fieldset).toBeVisible();
  await expect(fieldset.locator('legend')).toHaveText('Service level by class (%)');
  for (const field of CLASS_FIELDS) {
    const input = page.locator('[data-testid="' + field.testId + '"]');
    await expect(input).toBeVisible();
    expect(await input.getAttribute('type')).toBe('number');
    expect(await input.getAttribute('id')).toBe(field.id);
    expect(await input.getAttribute('min')).toBe('50');
    expect(await input.getAttribute('max')).toBe('99.9');
    expect(await input.getAttribute('step')).toBe('0.1');
    await expect(input).toHaveValue('');
    expect(await input.getAttribute('placeholder')).toBe(field.placeholder);
    const label = page.locator('label[for="' + field.id + '"]');
    await expect(label).toBeVisible();
    await expect(label).toHaveText(field.label);
  }

  // --- all three filled: the mapping travels, the note renders --------
  await page.fill('[data-testid="scenario-class-level-a"]', '98');
  await page.fill('[data-testid="scenario-class-level-b"]', '95');
  await page.fill('[data-testid="scenario-class-level-c"]', '90');
  await page.click('[data-testid="scenario-run"]');
  await expect.poll(() => ctrl.runs.length).toBe(1);
  // Exactly one run, and the body is the three null levers (the
  // levers are at their defaults: service level blank, the changes 0)
  // plus the per-class mapping, each percentage/100.
  expect(ctrl.runs[0].body).toEqual({
    service_level: null,
    demand_multiplier: null,
    lead_time_multiplier: null,
    service_level_by_class: { A: 0.98, B: 0.95, C: 0.9 },
  });
  ctrl.runs[0].route.fulfill({ status: 200, json: RESPONSE_CLASS });
  // The answer echoes the mapping: the note reads the echoed values as
  // percents, trailing zeros dropped.
  await expect(page.locator('[data-testid="scenario-class-note"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="scenario-class-note"]')).toHaveText(
    'Class levels: A 98% \u00B7 B 95% \u00B7 C 90%',
  );

  // --- all three blank: today's body, no note -------------------------
  for (const field of CLASS_FIELDS) {
    await page.fill('[data-testid="' + field.testId + '"]', '');
  }
  await page.click('[data-testid="scenario-run"]');
  await expect.poll(() => ctrl.runs.length).toBe(2);
  // Exactly the three-key body — no service_level_by_class key at all.
  expect(ctrl.runs[1].body).toEqual({
    service_level: null,
    demand_multiplier: null,
    lead_time_multiplier: null,
  });
  ctrl.runs[1].route.fulfill({ status: 200, json: RESPONSE_BLANK });
  // The echo is null: no class note.
  await expect(page.locator('[data-testid="scenario-class-note"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="scenario-summary"]')).toBeVisible();

  // --- one filled: the run is refused, no request ---------------------
  await page.fill('[data-testid="scenario-class-level-a"]', '98');
  await page.click('[data-testid="scenario-run"]');
  // No request went out; the status line says the set must be filled
  // together or left all blank.
  await expect(page.locator('[data-testid="scenario-class-gate"]')).toHaveText(
    'Fill in all three class levels, or leave them all blank.',
  );
  await expect(page.locator('[data-testid="scenario-status"]')).toContainText(
    'Fill in all three class levels, or leave them all blank.',
  );
  expect(ctrl.runs.length).toBe(2);
  // A keystroke in the set addresses the line: it clears, and the
  // previous answer is back on screen.
  await page.fill('[data-testid="scenario-class-level-a"]', '');
  await expect(page.locator('[data-testid="scenario-class-gate"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="scenario-summary"]')).toBeVisible();
  await expect(page.locator('[data-testid="scenario-class-note"]')).toHaveCount(0);

  // --- Save posts the three existing levers only ----------------------
  // Even with the class inputs filled: the save body is the name plus
  // the three levers, and no service_level_by_class.
  await page.fill('[data-testid="scenario-service-level"]', '98');
  await page.fill('[data-testid="scenario-demand-change"]', '20');
  await page.fill('[data-testid="scenario-class-level-a"]', '98');
  await page.fill('[data-testid="scenario-class-level-b"]', '95');
  await page.fill('[data-testid="scenario-class-level-c"]', '90');
  await page.fill('[data-testid="scenario-name"]', 'Peak');
  await page.click('[data-testid="scenario-save"]');
  await expect.poll(() => ctrl.saves.length).toBe(1);
  expect(ctrl.saves[0].body).toEqual({
    name: 'Peak',
    service_level: 0.98,
    demand_multiplier: 1.2,
    lead_time_multiplier: null,
  });
  ctrl.saves[0].route.fulfill({ status: 201, json: CREATED_ROW });
  await expect(page.locator('[data-testid="scenario-save-msg"]')).toHaveText('Saved');

  // --- selecting a saved scenario clears the class inputs -------------
  // The stored row persists only the three levers, so the class inputs
  // go back to blank and a later run cannot carry class levels the
  // saved scenario never stored.
  await page.selectOption('[data-testid="scenario-saved-select"]', 'saved-1');
  await expect(page.locator('[data-testid="scenario-service-level"]')).toHaveValue('97');
  await expect(page.locator('[data-testid="scenario-demand-change"]')).toHaveValue('10');
  await expect(page.locator('[data-testid="scenario-lead-time-change"]')).toHaveValue('0');
  for (const field of CLASS_FIELDS) {
    await expect(page.locator('[data-testid="' + field.testId + '"]')).toHaveValue('');
  }

  // --- and no horizontal page scroll at 390x844 ------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('[data-testid="scenario-levers"]')).toBeVisible();
  await expect(fieldset).toBeVisible();
  const narrow = await page.evaluate(() => ({
    docWidth: document.documentElement.scrollWidth,
    viewportW: window.innerWidth,
  }));
  expect(narrow.docWidth).toBeLessThanOrEqual(narrow.viewportW);

  // --- viewer pass: NON-ADMIN, production boot, full reload ------------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  const allRequests = [];
  page.on('request', (request) => allRequests.push(request));
  let viewerAppOrigin = null;
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (viewerAppOrigin === null) {
      viewerAppOrigin = url.origin;
    }
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: PROD_CONFIG });
    }
    if (url.pathname === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: VIEWER_ME });
    }
    if (url.pathname === '/api/scenarios/simulate' && request.method() === 'POST') {
      ctrl.runs.push({ body: request.postDataJSON(), route });
      return;
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      viewerAppOrigin + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#sidebar')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  // ... the session is the token the IdP issued, not the fragment's ...
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(0);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');
  expect(page.url()).not.toContain('access_token');
  // ... and the fragment's token was never sent anywhere.
  const offenders = allRequests.filter(
    (request) => request.headers()['authorization'] === 'Bearer viewer-token-abc',
  );
  expect(offenders).toEqual([]);

  // The scenario screen renders for the viewer, with the class-levels
  // fieldset present and its inputs blank ...
  await page.click('.nav-btn[data-view="scenario"]');
  await expect(page.locator('#view-scenario')).toHaveClass(/is-active/);
  await expect(page.locator('[data-testid="scenario-levers"]')).toBeVisible();
  await expect(fieldset).toBeVisible();
  for (const field of CLASS_FIELDS) {
    await expect(page.locator('[data-testid="' + field.testId + '"]')).toHaveValue('');
  }
  // ... with no admin-only control present in the view.
  expect(await page.locator('#view-scenario [data-admin-only]').count()).toBe(0);
  // ... and the viewer can still run a class-level scenario end to
  // end.
  await page.fill('[data-testid="scenario-class-level-a"]', '98');
  await page.fill('[data-testid="scenario-class-level-b"]', '95');
  await page.fill('[data-testid="scenario-class-level-c"]', '90');
  const viewerRunIndex = ctrl.runs.length;
  await page.click('[data-testid="scenario-run"]');
  await expect.poll(() => ctrl.runs.length).toBe(viewerRunIndex + 1);
  expect(ctrl.runs[viewerRunIndex].body).toEqual({
    service_level: null,
    demand_multiplier: null,
    lead_time_multiplier: null,
    service_level_by_class: { A: 0.98, B: 0.95, C: 0.9 },
  });
  ctrl.runs[viewerRunIndex].route.fulfill({ status: 200, json: RESPONSE_VIEWER });
  await expect(page.locator('[data-testid="scenario-class-note"]')).toHaveText(
    'Class levels: A 98% \u00B7 B 95% \u00B7 C 90%',
  );

  // The production-boot shell fills exactly the viewport: no page
  // scroll at 1440x900.
  const viewerLayout = await page.evaluate(() => ({
    docHeight: document.documentElement.scrollHeight,
    viewport: window.innerHeight,
  }));
  expect(viewerLayout.docHeight).toBe(viewerLayout.viewport);
  expect(pageErrors).toEqual([]);
});
