// Mock every /api/* call; records the list, the by-key, the accuracy
// and the recommendations by-key requests so the spec can inspect
// them. The auth pair is read from the mutable auth object, so the
// viewer pass can switch it to the production config and the viewer.
async function mockDemandApi(page) {
  const auth = { config: DEV_CONFIG, me: ADMIN_ME };
  const meRequests = [];
  const api = {
    listGets: 0,
    byKeyGets: [],
    accuracyGets: [],
    empiricalGets: [],
    empirical404InFlight: [],
    empirical404Delivered: [],
  };
  const empiricalStore = { 'L|S1': LUMPY_RECOMMENDATION };
  await page.route('**/api/**', async (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/auth/config') {
      return route.fulfill({ status: 200, json: auth.config });
    }
    if (url.pathname === '/api/auth/me') {
      meRequests.push(route.request());
      return route.fulfill({ status: 200, json: auth.me });
    }
    if (url.pathname === '/api/forecast') {
      api.listGets += 1;
      return route.fulfill({ status: 200, json: ROWS });
    }
    if (url.pathname === '/api/forecast/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.byKeyGets.push({ item, site });
      const detail = DETAILS[item + '|' + site];
      if (!detail) {
        return route.fulfill({ status: 404, json: { detail: 'forecast not found' } });
      }
      return route.fulfill({ status: 200, json: detail });
    }
    if (url.pathname === '/api/forecast/overrides') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (url.pathname === '/api/forecast/accuracy') {
      api.accuracyGets.push({ bucketIndex: url.searchParams.get('bucket_index') });
      const isAhead = url.searchParams.get('bucket_index') === '1';
      return route.fulfill({ status: 200, json: isAhead ? ACCURACY_AHEAD : ACCURACY_ALL });
    }
    if (url.pathname === '/api/recommendations/by-key') {
      const item = url.searchParams.get('item_code');
      const site = url.searchParams.get('site_code');
      api.empiricalGets.push({ item, site, query: url.search });
      const payload = empiricalStore[item + '|' + site];
      if (!payload) {
        // The 404 answer goes out late: the spec proves the pane
        // shows nothing while the answer is in flight and proves it
        // again, strictly, after the 404 has been delivered.
        api.empirical404InFlight.push({ item, site });
        await new Promise((resolve) => setTimeout(resolve, 500));
        api.empirical404Delivered.push({ item, site });
        return route.fulfill({ status: 404, json: { detail: 'item site not found' } });
      }
      return route.fulfill({ status: 200, json: payload });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return { api, auth, meRequests };
}

