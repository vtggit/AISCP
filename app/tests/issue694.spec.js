// Proving spec for AIERP issue #694 — the CSV download buttons in the
// Work queue (the planner's page, #/queue).
//
// The tab bar (.q-bar) gains, after the existing tabs and chips, a
// .q-downloads group with two buttons:
//   * "Download CSV" ([data-testid="queue-download"]) — downloads the
//     active tab's export: drift → /api/drift/export.csv as drift.csv,
//     excess → /api/excess/export.csv as excess.csv, stockout →
//     /api/stockout/export.csv as stockout.csv;
//   * "Planning sheet (CSV)" ([data-testid="queue-download-plan"]) —
//     downloads /api/recommendations/export.csv as
//     planning-parameters.csv.
// Both go through Api.download (app/js/api.js): the same
// Authorization: Bearer <token> header as Api.request, the same 401
// handling (token cleared, unauthorized handler, rejection with
// `unauthorized` set), a rejection with `status` for any other non-ok
// response, and — on success — the body as a Blob saved through a
// temporary <a download> click.
// While a download runs its button is disabled; a failed download shows
// a [data-testid="queue-download-msg"] status region reading
// "Download failed. <message>", cleared by the next click; and nothing
// is requested until a button is clicked.
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route, using the same mocks and the same
// development token-card sign-in as issue638.spec.js, at 1440x900 on
// #/queue. Each CSV route is mocked with a small text/csv body and
// records the request's Authorization header:
//   * on load, none of the four CSV paths is requested;
//   * on the drift tab, clicking queue-download fires a Playwright
//     download event whose suggestedFilename() is drift.csv, after a
//     request to /api/drift/export.csv that carried the Bearer token;
//   * after switching tabs, the same click downloads excess.csv and
//     stockout.csv from their own paths;
//   * clicking queue-download-plan downloads planning-parameters.csv
//     from /api/recommendations/export.csv;
//   * while a download runs its button is disabled (and the other one
//     stays enabled);
//   * with the drift export mocked to answer 500, the click shows
//     queue-download-msg starting with "Download failed." and fires no
//     download event; the message is cleared by the next click;
//   * at 390x844 the buttons wrap and the page does not scroll
//     sideways.
//
// The "(viewer)" pass boots the production way (token in the URL hash)
// as a NON-ADMIN (role "user") and asserts the admin-only decision
// controls are absent while the queue still renders — and the download
// buttons still work, carrying the PKCE token.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue694 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

