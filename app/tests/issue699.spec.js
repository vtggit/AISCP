// Proving spec for AIERP issue #699 — the "Intermittent and lumpy
// items" card on the Settings view (#/settings).
//
// After every existing card, the screen appends the card
// [data-testid="intermittent-impact"], fetched separately from
// GET /api/recommendations/intermittent-impact. The gate serves the
// static app with no backend, so every /api/* call is mocked with
// page.route (the same mocks and sign-in as
// app/tests/issue654.spec.js: the development token card as an admin,
// the production URL-hash token as a non-admin), at 1440x900 on
// #/settings. The impact route is mocked with three rows — a
// -$23,942.25 loss, a +$120.00 gain and a row with a null dollar
// change — and the summary carries item_sites 3, current_value
// 39903.75, empirical_value 16081.5, dollar_delta -23822.25,
// item_sites_without_unit_cost 1 and switch_on false. Proves:
//   * the summary line ([data-testid="intermittent-impact-summary"])
//     reads exactly "3 item-sites. Reorder-point value at unit cost:
//     $39,903.75 now, $16,081.50 with the empirical reorder points
//     (−$23,822.25)." — dollars with two decimals and thousands
//     separators, the change signed before the "$" with U+2212;
//   * the switch line ([data-testid="intermittent-impact-switch"])
//     reads exactly "The switch is off: these are shown for review
//     only." — and, with the mock's switch_on true and the view
//     re-activated, reads "The switch is on.";
//   * the table ([data-testid="intermittent-impact-table"]) orders its
//     rows by the absolute dollar change, largest first, the null
//     change last: −$23,942.25, then +$120.00, then the row showing
//     "—" — the ERP and empirical reorder points as plain whole
//     numbers with thousands separators;
//   * the no-cost line ([data-testid="intermittent-impact-nocost"])
//     reads exactly "1 item-sites have no unit cost and are not in the
//     dollar figures.";
//   * with the impact route answering 500, there is no card and no
//     error message, and every other card is still present;
//   * an item_code of <img src=x onerror=alert(1)> renders as text,
//     with no img in the card;
//   * at 390x844 the page does not scroll sideways (the table scrolls
//     inside its own container).
// The second pass, in the same test after a full reload, runs as a
// NON-ADMIN (role "user"): it boots the production way (the token in
// the URL hash, /api/auth/config and /api/auth/me mocked for that
// user, the PKCE round-trip mocked) and asserts the admin-only
// controls (the mappings and the budgets add forms) are absent while
// the settings rows and the read-only cards — the impact card among
// them — still render.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue699 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

