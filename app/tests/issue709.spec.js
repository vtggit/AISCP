// The mocked body of GET /api/recommendations/intermittent-impact,
// built from the mock's adoption store, the way the API reports the
// stored adoptions per item-site.
function impactBody(adopted) {
  return {
    summary: {
      item_sites: 2,
      current_value: 50,
      empirical_value: 44,
      dollar_delta: -6,
      item_sites_without_unit_cost: 0,
      switch_on: false,
    },
    item_sites: [
      Object.assign({}, ROW_A, { adopted: adopted[ROW_A.item_code] }),
      Object.assign({}, ROW_B, { adopted: adopted[ROW_B.item_code] }),
    ],
  };
}

const SUMMARY_TEXT =
  '2 item-sites. Reorder-point value at unit cost: $50.00 now, ' +
  '$44.00 with the empirical reorder points (\u2212$6.00).';
const SWITCH_OFF_TEXT = 'The switch is off: these are shown for review only.';

// The table's cells, row by row: the six existing columns' text plus
// the Adopted column's "Yes"/"No" and, for an admin, the action
// button's text.
function readCells(page) {
  return page.evaluate(() =>
    Array.from(
      document.querySelectorAll('[data-testid="intermittent-impact-table"] tbody tr'),
    ).map((tr) => Array.from(tr.querySelectorAll('td')).map((td) => td.textContent)),
  );
}

function readHeaders(page) {
  return page.evaluate(() =>
    Array.from(
      document.querySelectorAll(
        '[data-testid="intermittent-impact-table"] thead th',
      ),
    ).map((th) => th.textContent),
  );
}

