// Proving spec for AIERP issue #709 — the per-row adoption on the
// "Intermittent and lumpy items" card on the Settings view
// (#/settings).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route (the same mocks and sign-in as
// app/tests/issue699.spec.js: the development token card as an admin,
// the production URL-hash token as a non-admin), at 1440x900 on
// #/settings. The impact route is mocked with two rows — A, not
// adopted, and B, adopted — and the mock keeps the adoptions' store,
// flipping a pair on a successful PUT or DELETE the way the API does,
// so the card's re-fetch after a save shows the updated rows. Proves:
//   * the status column: the card's table gains a last "Adopted"
//     column — "No" for A, "Yes" for B — the existing columns and
//     their text unchanged;
//   * the action column (admin only): A shows an "Adopt" button
//     (class ii-adopt,
//     [data-testid="intermittent-impact-adopt"]) and B a "Withdraw"
//     button (class ii-withdraw,
//     [data-testid="intermittent-impact-withdraw"]); the action
//     column's th carries no text;
//   * adopting: clicking A's Adopt sends exactly one PUT
//     /api/empirical-adoptions whose body is
//     {"item_code": "ITM-A", "site_code": "SA"}; the buttons stay
//     disabled while the request is out; on success the impact route
//     is requested again and A's row reads "Yes" with "Withdraw";
//   * withdrawing: clicking B's Withdraw sends exactly one DELETE to
//     /api/empirical-adoptions with B's item_code and site_code as
//     query parameters, and the re-fetch shows B "No" with "Adopt";
//   * a failure: with the PUT answering 500, the card shows
//     [data-testid="intermittent-impact-msg"] reading "Could not
//     save: " followed by the error's message, and the table is
//     unchanged;
//   * at 390x844 the page does not scroll sideways (the table
//     scrolls inside its own container).
// The second pass, in the same test after a full reload, runs as a
// NON-ADMIN (role "user"): it boots the production way (the token in
// the URL hash, /api/auth/config and /api/auth/me mocked for that
// user, the PKCE round-trip mocked) and asserts the admin-only
// controls — no Adopt or Withdraw button — are absent while the
// Adopted column still shows and the settings rows and the read-only
// cards — the impact card among them — still render.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue709 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#750: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

