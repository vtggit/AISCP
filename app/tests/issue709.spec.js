// Mock every /api/* call the settings view (and the shell around it)
// makes, signed in as the given user: issue699's settings mocks plus
// the impact route, built from the mock's adoption store, and the
// adoption writes — the PUT stores (or holds, for the in-flight check)
// and the DELETE withdraws, flipping the store on a successful answer
// the way the API does.
async function mockSettingsApi(page, { config, me, entries, adopted }) {
  const api = {
    settingsGets: 0,
    impactGets: 0,
    meRequests: [],
    puts: [], // the bodies of the PUT /api/empirical-adoptions requests
    deletes: [], // the query pairs of the DELETE requests
    putStatus: 200, // the answer a non-held PUT receives
    holdPut: false, // hold the next PUT: the test answers it
    heldPut: null, // { route, body } of the held PUT
    current: entries,
    adopted, // { item_code: boolean } — the mock's adoption store
    appOrigin: { value: null },
  };
  const putFulfillment = (body, status) => {
    const answer = status === undefined ? api.putStatus : status;
    if (answer === 200) {
      api.adopted[body.item_code] = true;
      return {
        status: 200,
        json: {
          item_code: body.item_code,
          site_code: body.site_code,
          adopted_by: me.user.sub,
          adopted_by_name: me.user.username,
          adopted_at: '2026-10-28T10:00:00+00:00',
          note: null,
        },
      };
    }
    return { status: answer, json: { detail: 'the adoption store is down' } };
  };
  // The held PUT, answered by the test: it fulfils with 200, the way
  // a successful store of the adoption answers.
  api.releasePut = () => {
    const held = api.heldPut;
    api.heldPut = null;
    held.route.fulfill(putFulfillment(held.body, 200));
  };
  await page.route('**/api/**', async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (api.appOrigin.value === null) {
      api.appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: config });
    }
    if (path === '/api/auth/me') {
      api.meRequests.push(request);
      return route.fulfill({ status: 200, json: me });
    }
    if (path === '/api/settings' && request.method() === 'GET') {
      api.settingsGets += 1;
      return route.fulfill({ status: 200, json: api.current });
    }
    if (path === '/api/erp-mappings' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/purchase-budgets' && request.method() === 'GET') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (
      path === '/api/recommendations/intermittent-impact' &&
      request.method() === 'GET'
    ) {
      api.impactGets += 1;
      return route.fulfill({ status: 200, json: impactBody(api.adopted) });
    }
    if (path === '/api/empirical-adoptions' && request.method() === 'PUT') {
      const body = await request.postDataJSON();
      api.puts.push(body);
      if (api.holdPut) {
        api.holdPut = false;
        api.heldPut = { route, body };
        return; // held: the test answers it
      }
      return route.fulfill(putFulfillment(body));
    }
    if (path === '/api/empirical-adoptions' && request.method() === 'DELETE') {
      const itemCode = url.searchParams.get('item_code');
      const siteCode = url.searchParams.get('site_code');
      api.deletes.push({ item_code: itemCode, site_code: siteCode });
      if (itemCode !== null) {
        api.adopted[itemCode] = false;
      }
      return route.fulfill({ status: 204 });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  });
  return api;
}

// The production boot's PKCE round-trip, mocked the way the other
// proofs' viewer passes do it: the IdP's auth endpoint answers with a
// page that bounces straight back to the app with a code and the same
// state, and the token endpoint answers with the viewer's token.
async function mockPkceRoundTrip(page, appOrigin) {
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });
}

test('issue709 freeform', async ({ page }) => {
  page.setViewportSize({ width: 1440, height: 900 });
  const api = await mockSettingsApi(page, {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    entries: [booleanEntry(), enumEntry(), numberEntry()],
    adopted: { 'ITM-A': false, 'ITM-B': true },
  });

  await page.goto('/');
  await expect(page.locator('#signin-form')).toBeVisible();
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('planner1');

  // Open the settings view by hash change; the impact read starts with
  // the activation, the way the settings, mappings and budgets reads
  // do.
  await page.click('.nav-btn[data-view="settings"]');
  await expect.poll(() => page.evaluate(() => window.location.hash)).toBe('#/settings');
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => api.settingsGets).toBeGreaterThanOrEqual(1);
  await expect.poll(() => api.impactGets).toBeGreaterThanOrEqual(1);

  const card = page.locator('[data-testid="intermittent-impact"]');
  await expect(card).toBeVisible();
  await expect(card.locator('h2')).toHaveText('Intermittent and lumpy items');

  // --- the summary and switch lines, unchanged -----------------------
  await expect(
    page.locator('[data-testid="intermittent-impact-summary"]'),
  ).toHaveText(SUMMARY_TEXT);
  await expect(
    page.locator('[data-testid="intermittent-impact-switch"]'),
  ).toHaveText(SWITCH_OFF_TEXT);

  // --- the columns: the Adopted column and the admin action column ---
  // The existing six columns and their text are unchanged; the table
  // gains the "Adopted" column and, for this admin, a final action
  // column whose header carries no text.
  await expect.poll(async () => readHeaders(page)).toEqual([
    'Item',
    'Site',
    'Class',
    'ERP reorder point',
    'Empirical reorder point',
    'Change ($)',
    'Adopted',
    '',
  ]);
  // A is not adopted ("No", an "Adopt" button); B is adopted ("Yes", a
  // "Withdraw" button). The row order is the largest absolute change
  // first: A (−$30.00), then B (+$24.00).
  await expect.poll(async () => readCells(page)).toEqual([
    ['ITM-A', 'SA', 'intermittent', '5', '2', '\u2212$30.00', 'No', 'Adopt'],
    ['ITM-B', 'SB', 'lumpy', '0', '6', '+$24.00', 'Yes', 'Withdraw'],
  ]);
  const adoptA = card.locator('button[data-testid="intermittent-impact-adopt"]');
  const withdrawB = card
    .locator('tbody tr')
    .nth(1)
    .locator('button[data-testid="intermittent-impact-withdraw"]');
  await expect(adoptA).toHaveCount(1);
  await expect(adoptA).toHaveText('Adopt');
  await expect(withdrawB).toHaveCount(1);
  await expect(withdrawB).toHaveText('Withdraw');

  // --- adopting: A's Adopt PUTs the row's pair exactly once ----------
  // Hold the PUT so the in-flight state is observable: the buttons are
  // disabled while the request is out, and the answer comes when the
  // test releases it.
  api.holdPut = true;
  await adoptA.click();
  await expect.poll(() => api.heldPut !== null).toBe(true);
  expect(api.puts).toHaveLength(1);
  expect(api.puts[0]).toEqual({ item_code: 'ITM-A', site_code: 'SA' });
  await expect(adoptA).toBeDisabled();
  await expect(
    card.locator('button[data-testid="intermittent-impact-withdraw"]'),
  ).toBeDisabled();
  api.releasePut();

  // The success re-fetches the impact read; the mock now answers with
  // A adopted, and A's row reads "Yes" with "Withdraw".
  await expect.poll(() => api.impactGets).toBeGreaterThanOrEqual(2);
  await expect.poll(async () => readCells(page)).toEqual([
    ['ITM-A', 'SA', 'intermittent', '5', '2', '\u2212$30.00', 'Yes', 'Withdraw'],
    ['ITM-B', 'SB', 'lumpy', '0', '6', '+$24.00', 'Yes', 'Withdraw'],
  ]);
  expect(api.puts).toHaveLength(1);
  await expect(card.locator('button[data-testid="intermittent-impact-adopt"]')).toHaveCount(0);
  await expect(
    card.locator('button[data-testid="intermittent-impact-withdraw"]'),
  ).toHaveCount(2);
  await expect(withdrawB).toBeEnabled();

  // --- withdrawing: B's Withdraw DELETEs the pair exactly once -------
  // B is the second row (the largest absolute change first).
  await card
    .locator('tbody tr')
    .nth(1)
    .locator('button[data-testid="intermittent-impact-withdraw"]')
    .click();
  await expect.poll(() => api.deletes.length).toBe(1);
  expect(api.deletes[0]).toEqual({ item_code: 'ITM-B', site_code: 'SB' });
  // The success re-fetches again; the mock now answers with B not
  // adopted.
  await expect.poll(() => api.impactGets).toBeGreaterThanOrEqual(3);
  await expect.poll(async () => readCells(page)).toEqual([
    ['ITM-A', 'SA', 'intermittent', '5', '2', '\u2212$30.00', 'Yes', 'Withdraw'],
    ['ITM-B', 'SB', 'lumpy', '0', '6', '+$24.00', 'No', 'Adopt'],
  ]);
  expect(api.deletes).toHaveLength(1);

  // --- a failure: the PUT answers 500 --------------------------------
  // The card shows "Could not save: " plus the error's message in its
  // status line, and the table is unchanged: B is still not adopted,
  // its Adopt button back.
  api.putStatus = 500;
  const adoptB = card.locator('button[data-testid="intermittent-impact-adopt"]');
  await adoptB.click();
  await expect
    .poll(() => api.puts.length)
    .toBe(2);
  expect(api.puts[1]).toEqual({ item_code: 'ITM-B', site_code: 'SB' });
  const message = card.locator('[data-testid="intermittent-impact-msg"]');
  await expect(message).toHaveText(/^Could not save: /);
  await expect.poll(async () => readCells(page)).toEqual([
    ['ITM-A', 'SA', 'intermittent', '5', '2', '\u2212$30.00', 'Yes', 'Withdraw'],
    ['ITM-B', 'SB', 'lumpy', '0', '6', '+$24.00', 'No', 'Adopt'],
  ]);
  await expect(adoptB).toBeEnabled();

  // --- at 390x844 nothing scrolls sideways -----------------------------
  // The table scrolls inside its own container; the page does not.
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(
    390,
  );

  // --- back to the contract's 1440x900 for the viewer pass ------------
  await page.setViewportSize({ width: 1440, height: 900 });
  expect(
    await page.evaluate(() => [window.innerWidth, window.innerHeight]),
  ).toEqual([1440, 900]);

  // --- the non-admin pass: full reload, the production boot ------------
  // The session from the admin pass is a different user's: a fresh
  // viewer starts with an empty session, and the token in the URL hash
  // is the production way in (the PKCE round-trip completes the boot).
  const viewerApi = await mockSettingsApi(page, {
    config: PROD_CONFIG,
    me: VIEWER_ME,
    entries: [booleanEntry(), enumEntry(), numberEntry({ editable: false })],
    adopted: { 'ITM-A': false, 'ITM-B': true },
  });
  await mockPkceRoundTrip(page, viewerApi.appOrigin);
  await page.evaluate(() => window.sessionStorage.clear());
  // The admin pass left the document on /#/settings, and a goto that
  // changes only the fragment is a same-document navigation: the
  // signed-in shell would stay in memory and the production boot would
  // never run. Leave the document first so the viewer's boot is a full
  // document load.
  await page.goto('about:blank');
  await page.goto('/#access_token=viewer-token-abc');

  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  await expect.poll(() => viewerApi.meRequests.length).toBeGreaterThan(0);
  expect(viewerApi.meRequests[0].headers()['authorization']).toBe(
    'Bearer pkce-viewer-token',
  );
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  expect(page.url()).not.toContain('access_token');

  await page.evaluate(() => {
    window.location.hash = '#/settings';
  });
  await expect(page.locator('#view-settings')).toHaveClass(/is-active/);
  await expect.poll(() => viewerApi.impactGets).toBeGreaterThanOrEqual(1);

  // --- the read-only impact card still renders for the non-admin ------
  // The Adopted column still shows; no Adopt or Withdraw button exists
  // and the action column's header is absent.
  await expect(page.locator('[data-testid="intermittent-impact"]')).toBeVisible();
  await expect(
    page.locator('[data-testid="intermittent-impact-summary"]'),
  ).toHaveText(SUMMARY_TEXT);
  await expect(
    page.locator('[data-testid="intermittent-impact-switch"]'),
  ).toHaveText(SWITCH_OFF_TEXT);
  await expect.poll(async () => readHeaders(page)).toEqual([
    'Item',
    'Site',
    'Class',
    'ERP reorder point',
    'Empirical reorder point',
    'Change ($)',
    'Adopted',
  ]);
  await expect.poll(async () => readCells(page)).toEqual([
    ['ITM-A', 'SA', 'intermittent', '5', '2', '\u2212$30.00', 'No'],
    ['ITM-B', 'SB', 'lumpy', '0', '6', '+$24.00', 'Yes'],
  ]);
  await expect(page.locator('button[data-testid="intermittent-impact-adopt"]')).toHaveCount(0);
  await expect(
    page.locator('button[data-testid="intermittent-impact-withdraw"]'),
  ).toHaveCount(0);
  // The page still renders: the other read-only cards and the
  // settings rows, not editable.
  await expect(page.locator('[data-testid="erp-mappings"]')).toBeVisible();
  await expect(page.locator('[data-testid="purchase-budgets"]')).toBeVisible();
  await expect(page.locator('.settings-row[data-key="' + SYS_KEY + '"]')).toBeVisible();
  await expect(page.locator('.settings-row[data-key="' + USR_KEY + '"]')).toBeVisible();
  const vRow = page.locator('.settings-row[data-key="' + NUM_KEY + '"]');
  await expect(vRow.locator('.settings-number-input')).toBeDisabled();
  await expect(vRow.locator('.settings-number-save')).toBeDisabled();
});
