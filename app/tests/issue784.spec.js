// Buffers screen (#/buffers), below the existing table and unsized
// list, each independent of the others and fetched through
// app/js/api.js on activation and on Refresh alongside the existing
// plan and zones fetches:
//
//   * "Suggested buffers" ([data-testid="buffers-candidates"]) — GET
//     /api/ddmrp/candidates: one row per candidate, in the answer's
//     order, showing item / site, class, annual value (whole dollars),
//     lead time ("<n> d") and the reason; for an admin a "Designate"
//     button ([data-testid="buffers-designate"]) per row that sends
//     PUT /api/ddmrp/buffers with the pair and then refetches
//     everything.
//   * "Planned adjustments" ([data-testid="buffers-adjustments"]) —
//     GET /api/ddmrp/adjustments: one line per adjustment showing the
//     scope ("All buffers" or item / site), the window
//     ("<start> – <end>"), "×<factor>" and the note; for an admin an
//     add form ([data-testid="buffers-adjust-add"]) with optional item
//     and site, start and end dates, factor and note, that sends POST
//     /api/ddmrp/adjustments, and a Delete per line
//     ([data-testid="buffers-adjust-delete"]) that asks "Delete this
//     adjustment?" inline, then sends the DELETE. A 409, 422 or 404
//     shows the server's detail inline (the six-field draft survives);
//     any other failure shows "The change could not be saved.".
//   * "Buffer performance (last 90 days)"
//     ([data-testid="buffers-performance"]) — GET
//     /api/ddmrp/performance: one row per buffer showing item / site,
//     days observed, a stacked bar whose red, yellow, green and over
//     segments are proportional to the four percentages (the zone
//     colour tokens; the over segment the neutral token) and
//     "<n>% stocked out".
//
// A section whose fetch fails shows its own one-line note ("Suggestions
// could not be loaded." / "Adjustments could not be loaded." /
// "Performance could not be loaded."), never blocks or replaces the
// main table, and never leaves a loading placeholder; when every new
// endpoint answers 404 the screen renders exactly as today plus those
// three notes. A buffer row whose zone row carries an
// adjustment_factor other than 1 badges its zone bar with
// "×<factor>". Non-admins get no Designate, no add form and no
// Delete. Every API value is rendered as text; at 390x844 the page
// does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route, the same mocks and the same admin
