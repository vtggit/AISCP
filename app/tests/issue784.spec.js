// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the plan, the zones and the
// three new section answers (either a payload or a { status, json }
// failure, a one-shot via the *Next keys), steer the designation
// (ctrl.putNext), the adjustment add (ctrl.postNext) and the
// adjustment delete (ctrl.deleteAdjustNext), and steer the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the admin to
// the non-admin viewer. Every request is counted, every PUT/POST body
// is recorded and every DELETE call is kept.
async function mockBuffersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    planAnswer: null,
    planNext: null,
    zonesAnswer: null,
    zonesNext: null,
    candidatesAnswer: null,
    candidatesNext: null,
    adjustmentsAnswer: null,
    adjustmentsNext: null,
    performanceAnswer: null,
    performanceNext: null,
    putNext: null,
    deleteNext: null,
    postNext: null,
    deleteAdjustNext: null,
    planGets: 0,
    zonesGets: 0,
    candidatesGets: 0,
    adjustmentsGets: 0,
    performanceGets: 0,
    putBodies: [],
    postBodies: [],
    deleteCalls: [],
    deleteAdjustCalls: [],
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/ddmrp/plan') {
      ctrl.planGets += 1;
      if (ctrl.planNext) {
        const next = ctrl.planNext;
        ctrl.planNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.planAnswer, planPayloadBase());
    }
    if (path === '/api/ddmrp/zones') {
      ctrl.zonesGets += 1;
      if (ctrl.zonesNext) {
        const next = ctrl.zonesNext;
        ctrl.zonesNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.zonesAnswer, zonesPayloadBase());
    }
    if (path === '/api/ddmrp/candidates') {
      ctrl.candidatesGets += 1;
      if (ctrl.candidatesNext) {
        const next = ctrl.candidatesNext;
        ctrl.candidatesNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.candidatesAnswer, candidatesPayloadBase());
    }
    if (path === '/api/ddmrp/adjustments') {
      if (request.method() === 'POST') {
        let body = null;
        try {
          body = request.postDataJSON();
        } catch (error) {
          // An unparsable body: the recorded null is the failure's proof.
        }
        ctrl.postBodies.push(body);
        if (ctrl.postNext) {
          const next = ctrl.postNext;
          ctrl.postNext = null;
          return route.fulfill(next);
        }
        return route.fulfill({
          status: 201,
          json: {
            id: 'adj-new',
            item_code: body && body.item_code !== undefined ? body.item_code : null,
            site_code: body && body.site_code !== undefined ? body.site_code : null,
            start_on: body ? body.start_on : null,
            end_on: body ? body.end_on : null,
            factor: body ? body.factor : null,
            note: body && body.note !== undefined ? body.note : null,
            created_by: 'u-admin',
            created_by_name: 'Admin User',
            created_at: '2026-10-29T10:05:00Z',
          },
        });
      }
      ctrl.adjustmentsGets += 1;
      if (ctrl.adjustmentsNext) {
        const next = ctrl.adjustmentsNext;
        ctrl.adjustmentsNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.adjustmentsAnswer, adjustmentsPayloadBase());
    }
    if (path.indexOf('/api/ddmrp/adjustments/') === 0 && request.method() === 'DELETE') {
      ctrl.deleteAdjustCalls.push(path.split('/')[4]);
      if (ctrl.deleteAdjustNext) {
        const next = ctrl.deleteAdjustNext;
        ctrl.deleteAdjustNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/ddmrp/performance') {
      ctrl.performanceGets += 1;
      if (ctrl.performanceNext) {
        const next = ctrl.performanceNext;
        ctrl.performanceNext = null;
        return route.fulfill(next);
      }
      return answerOrFulfill(route, ctrl.performanceAnswer, performancePayloadBase());
    }
    if (path === '/api/ddmrp/buffers' && request.method() === 'PUT') {
      let body = null;
      try {
        body = request.postDataJSON();
      } catch (error) {
        // An unparsable body: the recorded null is the failure's proof.
      }
      ctrl.putBodies.push(body);
      if (ctrl.putNext) {
        const next = ctrl.putNext;
        ctrl.putNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({
        status: 200,
        json: {
          item_code: body ? body.item_code : null,
          site_code: body ? body.site_code : null,
          designated_by: 'u-admin',
          designated_by_name: 'Admin User',
          designated_at: '2026-10-29T10:00:00Z',
          note: null,
        },
      });
    }
    if (path === '/api/ddmrp/buffers' && request.method() === 'DELETE') {
      ctrl.deleteCalls.push({
        item_code: url.searchParams.get('item_code'),
        site_code: url.searchParams.get('site_code'),
      });
      if (ctrl.deleteNext) {
        const next = ctrl.deleteNext;
        ctrl.deleteNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

