// Proving spec for AIERP issue #800 — the "Exceptions" screen
// (#/exceptions): the triage list of what needs attention today,
// across every planning signal — the "Exceptions" nav button (directly
// after "Overview"), the #view-exceptions section with
// #exceptions-root, and the view registered in the shell (title
// "Exceptions", subtitle "What needs attention today, across every
// planning signal").
//
// The screen fetches GET /api/exceptions through app/js/api.js on
// activation and on the Refresh button
// ([data-testid="exceptions-refresh"]); the "Show snoozed" checkbox
// ([data-testid="exceptions-show-snoozed"]) refetches with
// include_snoozed=true when ticked. A request-sequence guard renders
// only the newest answers, and a skeleton shows while a fetch is out.
// Whether the viewer is an admin is read from GET /api/auth/me's
// roles, exactly as the Push to ERP view does; an unknown or failed
// read fails closed.
//
// The summary ([data-testid="exceptions-summary"]) reads
// "<high> high · <medium> medium · <acknowledged> acknowledged" from
// the answer's counts. A non-empty sources_failed raises the note
// ([data-testid="exceptions-sources-failed"]) "Some signals could not
// be read: …" while the rows that did load still render.
//
// The table ([data-testid="exceptions-table"]) has one row per
// exception ([data-testid="exceptions-row"]) in the answer's order:
// Severity ("High"/"Medium", raw on data-severity), Signal (the
// kind's label), Item and Site ("item / site", an em dash when both
// are null), Detail, Detected, Status ("New", or "Acknowledged by
// <name>" / "Acknowledged", gaining " · snoozed until <date>"), and
// Open — a link whose href is the row's view, only when the view
// starts with "#/". The admin-only Actions column has "Acknowledge"
// ([data-testid="exceptions-ack"], one PUT /api/exceptions/ack with
// exactly {"key": <key>}), "Snooze 7 days"
// ([data-testid="exceptions-snooze"], the same PUT with snooze_until
// = the answer's as_of plus 7 days) and "Clear"
// ([data-testid="exceptions-clear"], one DELETE whose key query
// parameter is the row key); each success refetches the list. A 403
// shows "Only an admin can acknowledge exceptions.", any other
// failure "The change could not be saved.", inline in
// [data-testid="exceptions-action-error"]. A non-admin sees no
// Actions column and the note "Only an admin can acknowledge
// exceptions."
//
// With no rows the table is replaced by "No exceptions today."; a
// failed fetch shows "Exceptions could not be loaded." without a
// page error. Every API value is rendered as text, never as markup;
// at 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route. The mocked answer has one high
// buffer_stocked_out row, one medium expedite_late row (site null)
// and one acknowledged, snoozed medium row; as_of is 2026-10-29, so
// "Snooze 7 days" must send 2026-11-05.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, no exceptions fetch goes out before the view is
// activated, the screen then renders for the viewer, and the
// admin-only controls — the Actions column and its buttons — are
// absent while the page renders on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue800 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

