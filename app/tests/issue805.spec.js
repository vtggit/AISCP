//   * Partial: a non-empty sources_failed shows "Some signals could
//     not be read.".
//   * On failure: with /api/exceptions answering 500, and again
//     answering {}, the card is removed — no error text, no Retry, no
//     new [role="alert"].
//   * Escaping: a detail of "<img src=x onerror=window.__pwned=1>"
//     renders as text and window.__pwned stays undefined.
//   * Phone width: at 390x844 the page does not scroll sideways.
//
// The pass ends as a NON-ADMIN (role 'user') after a full reload: the
// token arrives in the URL hash as #access_token=..., /api/auth/config
// and /api/auth/me are mocked for that user, the IdP's auth and token
