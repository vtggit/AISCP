// viewer with the Exceptions today card loaded, and the admin-only
// controls — the Exceptions view's Actions column and its buttons —
// are absent where "Only an admin can acknowledge exceptions." shows
// instead.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue805 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the
