// order: one high stockout_likely (unacknowledged), one medium
// expedite_late with both codes null (unacknowledged), one medium
// acknowledged, and two more medium unacknowledged.
//
// The pass proves, in order:
//   * Placement and counts: the card follows the "Value by class"
//     card, and the counts line reads "1 high · 3 medium · 1
//     acknowledged".
//   * The list: exactly three items — the first and second
//     unacknowledged rows, then the third, skipping the acknowledged
//     one — the null-code row without its " — " part.
//   * The link: "Open the inbox" is a real link to #/exceptions that
//     shows the Exceptions view.
//   * Nothing waiting: an answer whose rows are all acknowledged
