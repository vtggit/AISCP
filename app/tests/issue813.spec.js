// Proving spec for AIERP issue #813 — the "New today" features on the
// Exceptions screen (#/exceptions) and the Overview's "Exceptions
// today" card:
//
//   * The badge: a row whose `new` is true shows the "New" badge
//     ([data-testid="exceptions-new"], class exc-new) in its Signal
//     cell, after the label; a row whose `new` is false or missing
//     shows none.
//   * The filter: the "New only" checkbox
//     ([data-testid="exceptions-new-only"]) next to "Show snoozed".
//     Ticked, the table shows only the rows whose `new` is true,
//     client-side on the current answer — it makes no request; with
//     nothing new the table is replaced by "Nothing new today.";
//     unticking restores the full list; a refetch keeps the tick.
//   * The screen's count: when the answer's counts.new is a number
//     above 0, a line ([data-testid="exceptions-new-count"]) reads
//     "<n> new today" directly after the summary; otherwise there is
//     no such element. The summary text is unchanged.
//   * The Overview card: when counts.new is a number above 0, the
//     "Exceptions today" card shows <p class="ov-exceptions-new">
//     reading "<n> new today" directly after .ov-exceptions-counts;
//     otherwise no such element.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// app/tests/issue800.spec.js: the mocked /api/exceptions answer has
// four rows, two of them `new` true, and counts high 1, medium 3,
// acknowledged 0, new 2.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer, and the
// admin-only controls — the Actions column and its buttons — are
// absent while the page renders on (the badge, the count line and
// the "New only" filter are not admin-only and serve the viewer as
// well).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue813 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

