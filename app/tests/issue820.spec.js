// Proving spec for AIERP issue #820 — the "Forecast bias" label and
// the "Signal" kind filter on the Exceptions screen (#/exceptions):
//
//   * The label: the kind-label map gains forecast_bias → "Forecast
//     bias"; every other label is unchanged, and an unknown kind
//     still shows its raw text.
//   * The filter: a <select data-testid="exceptions-kind-filter"
//     aria-label="Signal"> next to the "New only" checkbox. Its first
//     option is "All signals" (value empty); it then has one option
//     per distinct kind in the current answer, labelled by the
//     kind-label map, in the order the kinds first appear. Choosing a
//     kind shows only that kind's rows, client-side — it makes no
//     request; the choice combines with "New only" (a row shows only
//     when it passes both), and a combination that leaves no row
//     replaces the table with "No exceptions match these filters.";
//     "All signals" chosen, "New only" alone keeps today's "Nothing
//     new today." and the list restores. A refetch keeps the choice
//     while the answer still carries the kind, and returns to "All
//     signals" otherwise.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// app/tests/issue813.spec.js: the mocked /api/exceptions answer has
// five rows in order — a stockout_likely, two forecast_bias (one
// `new` true), an expedite_late and a second stockout_likely (`new`
// true) — and counts high 2, medium 3, acknowledged 0, new 2.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer, and the
// admin-only controls — the Actions column and its buttons — are
// absent while the page renders on (the Signal filter is not
// admin-only and serves the viewer as well).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue820 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

