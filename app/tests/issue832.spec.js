// Proving spec for AIERP issue #832 — one shared navigation list.
//
// The shell's thirteen views (the .nav .nav-btn buttons in
// app/index.html) used to be pinned by every proving spec that cared:
// each one restated all 13 view ids (or the 13 labels) as a literal
// array, so a re-ordered or re-labelled nav failed ten copies of the
// same truth. Issue #832 gathers that truth into one CommonJS helper,
// app/tests/nav_order.js (NAV_VIEWS and NAV_LABELS), and the ten
// specs import it instead of restating the list.
//
// This spec is now the ONE place that pins the page's navigation to
// the shared lists:
//   * the page — after the same development token card sign-in as
//     issue #800, the .nav .nav-btn elements' data-view attributes
//     equal NAV_VIEWS and their texts equal NAV_LABELS;
//   * no full list left behind — for each of the ten files
//     (issue276, issue320, issue430, issue463, issue567, issue605,
//     issue608, issue728, issue744, issue800) the file's text has no
//     line carrying all three of the quoted ids — the "overview" id,
//     the "exceptions" id and the "settings" id — and it imports the
//     helper with require('./nav_order').
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route, exactly as
// app/tests/issue800.spec.js mocks them.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the shell renders for the viewer with the nav still
// pinned to NAV_VIEWS / NAV_LABELS, and the admin-only controls — the
// Exceptions Actions column and its buttons — are absent while the
// page renders on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue832 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

