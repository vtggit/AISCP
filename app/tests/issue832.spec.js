// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the exceptions answer (ctrl.exceptionsAnswer,
// either a payload or a { status, json } failure) and the actions
// (ctrl.putNext / ctrl.deleteNext, one-shot failures), and steer the
// sign-in (ctrl.config / ctrl.me) when the pass switches from the
// admin to the non-admin viewer. Every list request is counted
// (ctrl.exceptionsGets) with its include_snoozed query recorded in
// ctrl.exceptionsQueries, every PUT body in ctrl.putBodies and every
// DELETE key in ctrl.deleteCalls.
async function mockExceptionsApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    exceptionsAnswer: null,
    putNext: null,
    deleteNext: null,
    exceptionsGets: 0,
    exceptionsQueries: [],
    putBodies: [],
    deleteCalls: [],
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/exceptions') {
      ctrl.exceptionsGets += 1;
      ctrl.exceptionsQueries.push(url.searchParams.get('include_snoozed'));
      return answerOrFulfill(route, ctrl.exceptionsAnswer, exceptionsBase());
    }
    if (path === '/api/exceptions/ack' && request.method() === 'PUT') {
      let body = null;
      try {
        body = request.postDataJSON();
      } catch (error) {
        // An unparsable body: the recorded null is the failure's proof.
      }
      ctrl.putBodies.push(body);
      if (ctrl.putNext) {
        const next = ctrl.putNext;
        ctrl.putNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({
        status: 200,
        json: {
          key: body ? body.key : null,
          acknowledged_by: 'u-admin',
          acknowledged_by_name: 'Admin User',
          acknowledged_at: '2026-10-29T10:00:00Z',
          snooze_until: body && body.snooze_until ? body.snooze_until : null,
          note: null,
        },
      });
    }
    if (path === '/api/exceptions/ack' && request.method() === 'DELETE') {
      ctrl.deleteCalls.push({ key: url.searchParams.get('key') });
      if (ctrl.deleteNext) {
        const next = ctrl.deleteNext;
        ctrl.deleteNext = null;
        return route.fulfill(next);
      }
      return route.fulfill({ status: 204 });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

