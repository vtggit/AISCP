// A line of the old shape: one line carrying all three of the quoted
// view ids (the ids on their own lines of a multi-line literal are
// not a full list, only this single-line shape is).
function fullListLines(text) {
  return text
    .split('\n')
    .filter(
      (line) =>
        line.includes("'overview'") &&
        line.includes("'exceptions'") &&
        line.includes("'settings'"),
    );
}

test('issue832 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- no full list left behind: the helper is the single source -----
  for (const file of SUPERSEDED_SPECS) {
    const text = fs.readFileSync(path.join(__dirname, file), 'utf8');
    expect(fullListLines(text)).toEqual([]);
    expect(text.includes("require('./nav_order')")).toBe(true);
  }

  // --- the page: the nav is pinned to the shared lists ----------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockExceptionsApi(page);

  const navButtons = page.locator('.nav .nav-btn');

  await page.goto('/');

  // No exceptions request before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.exceptionsGets).toBe(0);

  // Sign in through the development token card as the admin (the same
  // sign-in as issue #800).
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');

  // All thirteen buttons, in the shared order, with the shared
  // labels.
  await expect(navButtons).toHaveCount(NAV_VIEWS.length);
  const navViews = await navButtons.evaluateAll((buttons) =>
    buttons.map((b) => b.getAttribute('data-view')),
  );
  expect(navViews).toEqual(NAV_VIEWS);
  const navTexts = await navButtons.evaluateAll((buttons) =>
    buttons.map((b) => (b.textContent || '').trim()),
  );
  expect(navTexts).toEqual(NAV_LABELS);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload -----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const meCountBeforeViewer = ctrl.meRequests.length;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-abc');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me.
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // The nav renders for the non-admin too, still pinned to the shared
  // lists ...
  const viewerNavViews = await navButtons.evaluateAll((buttons) =>
    buttons.map((b) => b.getAttribute('data-view')),
  );
  expect(viewerNavViews).toEqual(NAV_VIEWS);
  const viewerNavTexts = await navButtons.evaluateAll((buttons) =>
    buttons.map((b) => (b.textContent || '').trim()),
  );
  expect(viewerNavTexts).toEqual(NAV_LABELS);

  // ... and the admin-only controls are absent while the page renders
  // on: open the Exceptions screen (one of the thirteen views) for
  // the viewer — no Actions column and none of its buttons, the note
  // shows, and the rows still render.
  await page.click('.nav-btn[data-view="exceptions"]');
  expect(page.url()).toContain('#/exceptions');
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect(page.locator('[data-testid="exceptions-table"]')).toBeVisible();
  await expect(page.locator('[data-testid="exceptions-row"]')).toHaveCount(3);
  await expect(page.locator('#exceptions-root th')).toHaveText([
    'Severity',
    'Signal',
    'Item and Site',
    'Detail',
    'Detected',
    'Status',
    'Open',
  ]);
  await expect(page.locator('[data-testid="exceptions-ack"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="exceptions-snooze"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="exceptions-clear"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="exceptions-admin-note"]')).toHaveText(
    'Only an admin can acknowledge exceptions.',
  );
  expect(pageErrors).toEqual([]);
});
