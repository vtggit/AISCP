// The summary ([data-testid="orders-summary"]) reads "<line_count>
// lines · <total_value as whole dollars> across <n> suppliers" (n
// counts the groups with a non-null supplier_code). One block per
// supplier group ([data-testid="orders-supplier"]), in the answer's
