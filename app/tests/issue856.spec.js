// Proving spec for AIERP issue #856 — the "Transfer suggestions"
// section of the Order plan screen (#/orders).
//
// Below the last supplier block of #orders-root, a section
// ([data-testid="orders-transfers"]) headed "Transfer suggestions"
// holding the "Show transfer suggestions" button
// ([data-testid="orders-transfers-show"]), for every signed-in user,
// admin or not. The section sends GET /api/supply-plan/transfers
// through app/js/api.js only when that button is clicked, and again
// only on a later click of it: activating the view, the Refresh
// button and the horizon select send no transfers request. Once an
// answer has landed the button reads "Refresh transfer suggestions".
//
// The answer: a summary
// ([data-testid="orders-transfers-summary"]) reading "<count>
// transfers · <total_value as whole dollars>", and a table
// ([data-testid="orders-transfers-lines"]) with one row per
// suggestion in the answer's order and the columns Item, From, To,
// Quantity, Value and Why — Value shows whole dollars, an em dash
// when null; the route's decimal strings ("65714.45") are read as
// numbers, the way the release groups' value already is. Why shows
// the arithmetic as text, never as markup. With no suggestions the
// section reads "No transfers suggested: no site holds surplus
// another site needs."; a failed request shows "Transfer suggestions
// could not be loaded." in [data-testid="orders-transfers-error"],
// without a page error and the supplier blocks unchanged. The
// section's answer, error and pending flag live in module state and
// survive a full re-render of #orders-root; sign-out clears them,
// and an answer arriving after sign-out is discarded.
//
// One day, singular: in the supplier blocks, the Due column reads
// "in 1 day" when due_in_days is 1 ("Now" for 0, "in <n> days"
// otherwise). Every API value is rendered as text; at 390x844 the
// page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #841 spec, plus the /api/supply-plan/transfers answer, which
// the mock counts — ctrl.transfersGets). The mocked answer carries
// two suggestions, one with a null value, with value and total_value
// given as decimal strings exactly as the route sends them.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
