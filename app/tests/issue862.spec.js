// Proving spec for AIERP issue #862 — the transfer marks on the
// Order plan screen (#/orders) plan lines.
//
// The match: once a transfer answer has landed (the transfers
// section's button was clicked), every order-plan line whose
// item_code and site_code equal a suggestion's item_code and to_site
// is marked. The row ([data-testid="orders-lines"] tr) gains
// data-transfer="true" and, in its Quantity cell, a note
// ([data-testid="orders-line-transfer"]). The note reads "transfer
// of <quantity> from site <from_site> could cover this" when the
// suggestions to that item-site total at least the line's quantity,
// else "transfer of <quantity> from site <from_site> covers part of
// this"; a total exactly equal to the line's quantity covers. With
// several suggestions to one item-site the note lists each as
// "transfer of <quantity> from site <from_site>", joined by "; ",
// then the covering tail once, comparing their total with the line's
// quantity — e.g. "transfer of 30 from site 159; transfer of 80 from
// site 160 could cover this".
//
// Before any transfer answer: no row is marked and no transfer
// request is sent. The marks appear without a new request, from the
// answer already in module state: a horizon change or a Refresh
// re-renders the plan and the marks are re-applied from the same
// transfer answer, with no new transfer request. A later transfer
// answer replaces them, and an empty or a failed answer leaves no
// row marked. While a transfer refresh is in flight (the section
// showing its loading state) no order-plan row is marked; the marks
// re-appear when the new transfer answer lands.
//
// The release panel is unchanged: the marks are notes only, and no
// quantity, total or request body changes. Every API value is
// rendered as text; at 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #856 spec, plus a release preview answer whose request body
// the mock records — ctrl.releaseBodies). The plan mock holds item A
// at site 154 with quantity 100, item B at site 159 with quantity
// 50 and item C at site 160 (no suggestion ever receives there); the
// transfers mock — values as decimal strings, as the route sends
// them — suggests 120 of A from site 159 to site 154 and 20 of B
// from site 154 to site 159, which the mock counts (ctrl.transfersGets).
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer with the marks
// on it once its own transfer answer lands, and no admin-only
// control of any kind is on it while the page renders on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue862 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

