// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the exceptions answer
// (ctrl.exceptionsAnswer, either a payload or null for the base) and
// the sign-in (ctrl.config / ctrl.me) when the pass switches from the
// admin to the non-admin viewer. Every list request is counted
// (ctrl.exceptionsGets).
async function mockApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    abcAnswer: abcPayload(),
    exceptionsAnswer: null,
    exceptionsGets: 0,
    exceptionsQueries: [],
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/exceptions') {
      ctrl.exceptionsGets += 1;
      ctrl.exceptionsQueries.push(url.searchParams.get('include_snoozed'));
      return route.fulfill({ status: 200, json: ctrl.exceptionsAnswer || exceptionsPayload() });
    }
    if (path === '/api/abc') {
      return route.fulfill({ status: 200, json: ctrl.abcAnswer });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

test('issue867 freeform', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));

  // --- admin pass: development sign-in --------------------------------
  page.setViewportSize({ width: 1440, height: 900 });
  const { ctrl, appOrigin, handler } = await mockApi(page);

  const summary = page.locator('[data-testid="exceptions-summary"]');
  const kindFilter = page.locator('[data-testid="exceptions-kind-filter"]');
  const table = page.locator('[data-testid="exceptions-table"]');
  const rows = page.locator('[data-testid="exceptions-row"]');
  const adminNote = page.locator('[data-testid="exceptions-admin-note"]');

  await page.goto('/');

  // No exceptions request before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.exceptionsGets).toBe(0);

  // Sign in through the development token card as the admin.
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  // The Overview (the default view) has loaded its Exceptions today
  // card once; the inbox view is not active yet.
  await expect.poll(() => ctrl.exceptionsGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // Into the inbox: one more fetch, and the answer renders.
  await page.click('.nav-btn[data-view="exceptions"]');
  await expect(page).toHaveURL(/#\/exceptions$/);
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect.poll(() => ctrl.exceptionsGets).toBe(2);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(summary).toHaveText('1 high \u00b7 1 medium \u00b7 0 acknowledged');
  expect(pageErrors).toEqual([]);

  // --- the label: whichever order the screen shows them in ------------
  // The first node of each Signal cell is the kind's label; map each
  // row by its Detail so the order the screen chose never matters.
  const labelByDetail = await page.evaluate(() => {
    const rowEls = Array.from(
      document.querySelectorAll('[data-testid="exceptions-row"]'),
    );
    const byDetail = {};
    for (const row of rowEls) {
      const detailCell = row.querySelector('.ex-detail');
      const signalCell = row.querySelector('.ex-signal');
      const first = signalCell ? signalCell.firstChild : null;
      byDetail[detailCell ? detailCell.textContent : ''] =
        first && first.nodeType === Node.TEXT_NODE ? first.textContent : null;
    }
    return byDetail;
  });
  expect(Object.keys(labelByDetail)).toHaveLength(2);
  expect(
    labelByDetail['PO003068 to V-1 awaiting approval in the ERP for 10 days'],
  ).toBe('Awaiting ERP approval');
  expect(labelByDetail['release to V-2 failed']).toBe('Release failed');
  expect(pageErrors).toEqual([]);

  // --- the filter: an option reading "Awaiting ERP approval" ----------
  await expect(kindFilter).toHaveCount(1);
  await expect(kindFilter).toHaveAttribute('aria-label', 'Signal');
  const optionTexts = await kindFilter.locator('option').allTextContents();
  expect(optionTexts).toEqual([
    'All signals',
    'Awaiting ERP approval',
    'Release failed',
  ]);
  expect(await kindFilter.evaluate((select) => select.value)).toBe('');
  expect(pageErrors).toEqual([]);

  // Choosing it leaves only that row — client-side, no request.
  const getsBeforeFilter = ctrl.exceptionsGets;
  await kindFilter.selectOption({ label: 'Awaiting ERP approval' });
  await expect(rows).toHaveCount(1);
  await expect(rows.nth(0).locator('.ex-signal')).toHaveText('Awaiting ERP approval');
  await expect(rows.nth(0).locator('.ex-detail')).toHaveText(
    'PO003068 to V-1 awaiting approval in the ERP for 10 days',
  );
  expect(ctrl.exceptionsGets).toBe(getsBeforeFilter);
  expect(pageErrors).toEqual([]);

  // "All signals" chosen again: both rows return, still without a
  // request.
  await kindFilter.selectOption({ value: '' });
  await expect(rows).toHaveCount(2);
  expect(ctrl.exceptionsGets).toBe(getsBeforeFilter);
  expect(pageErrors).toEqual([]);

  // --- no raw name in the view's visible text --------------------------
  const rawInView = await page.evaluate((needle) => {
    const view = document.getElementById('view-exceptions');
    const text = view ? view.textContent : '';
    return text.indexOf(needle) !== -1;
  }, 'release_awaiting_approval');
  expect(rawInView).toBe(false);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload -----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => {
    window.sessionStorage.clear();
  });
  const getsBeforeViewer = ctrl.exceptionsGets;
  const meCountBeforeViewer = ctrl.meRequests.length;
  ctrl.exceptionsAnswer = null;
  await page.unroute('**/api/**');
  ctrl.config = PROD_CONFIG;
  ctrl.me = VIEWER_ME;
  await page.route('**/api/**', handler);
  await page.route(/protocol\/openid-connect\/token/, (route) => {
    return route.fulfill({
      status: 200,
      json: { access_token: 'pkce-viewer-token', token_type: 'Bearer' },
    });
  });
  await page.route(/protocol\/openid-connect\/auth/, (route) => {
    const state = new URL(route.request().url()).searchParams.get('state') || '';
    const backToApp =
      appOrigin.value + '/?code=fake-pkce-code&state=' + encodeURIComponent(state);
    return route.fulfill({
      status: 200,
      contentType: 'text/html',
      body:
        '<!doctype html><html><body><script>window.location.replace(' +
        JSON.stringify(backToApp) +
        ');</script></body></html>',
    });
  });

  // A full reload through a distinct path carrying the token hash, as
  // the identity requirement calls for.
  await page.goto('/index.html#access_token=viewer-token-867');

  // The PKCE round-trip completes and the shell renders for the
  // non-admin user, signed in through /api/auth/me ...
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('viewer1');
  expect(page.url()).not.toContain('access_token');
  expect(await page.evaluate(() => window.sessionStorage.getItem('aierp_token'))).toBe(
    'pkce-viewer-token',
  );
  await expect.poll(() => ctrl.meRequests.length).toBeGreaterThan(meCountBeforeViewer);
  const viewerMe = ctrl.meRequests[ctrl.meRequests.length - 1];
  expect(viewerMe.headers()['authorization']).toBe('Bearer pkce-viewer-token');

  // ... and the Overview (the default view) loads its Exceptions today
  // card for the viewer too.
  await expect.poll(() => ctrl.exceptionsGets).toBe(getsBeforeViewer + 1);
  expect(pageErrors).toEqual([]);

  // Activating the view for the viewer: the screen renders ...
  await page.click('.nav-btn[data-view="exceptions"]');
  expect(page.url()).toContain('#/exceptions');
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect.poll(() => ctrl.exceptionsGets).toBe(getsBeforeViewer + 2);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(summary).toHaveText('1 high \u00b7 1 medium \u00b7 0 acknowledged');

  // ... and the admin-only controls are absent — no Actions column and
  // none of its buttons — while the page renders on.
  await expect(page.locator('#exceptions-root th')).toHaveText([
    'Severity',
    'Signal',
    'Item and Site',
    'Detail',
    'Detected',
    'Status',
    'Open',
  ]);
  await expect(page.locator('[data-testid="exceptions-ack"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="exceptions-snooze"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="exceptions-clear"]')).toHaveCount(0);
  await expect(adminNote).toHaveText('Only an admin can acknowledge exceptions.');

  // The labels hold for the viewer too, whichever order the screen
  // shows them in.
  const viewerLabelByDetail = await page.evaluate(() => {
    const rowEls = Array.from(
      document.querySelectorAll('[data-testid="exceptions-row"]'),
    );
    const byDetail = {};
    for (const row of rowEls) {
      const detailCell = row.querySelector('.ex-detail');
      const signalCell = row.querySelector('.ex-signal');
      const first = signalCell ? signalCell.firstChild : null;
      byDetail[detailCell ? detailCell.textContent : ''] =
        first && first.nodeType === Node.TEXT_NODE ? first.textContent : null;
    }
    return byDetail;
  });
  expect(
    viewerLabelByDetail['PO003068 to V-1 awaiting approval in the ERP for 10 days'],
  ).toBe('Awaiting ERP approval');
  expect(viewerLabelByDetail['release to V-2 failed']).toBe('Release failed');

  // The Signal filter is not admin-only: the viewer gets it as well,
  // and the filtering is client-side.
  const viewerOptionTexts = await kindFilter.locator('option').allTextContents();
  expect(viewerOptionTexts).toEqual([
    'All signals',
    'Awaiting ERP approval',
    'Release failed',
  ]);
  const getsBeforeViewerFilter = ctrl.exceptionsGets;
  await kindFilter.selectOption({ label: 'Awaiting ERP approval' });
  await expect(rows).toHaveCount(1);
  expect(ctrl.exceptionsGets).toBe(getsBeforeViewerFilter);
  await kindFilter.selectOption({ value: '' });
  await expect(rows).toHaveCount(2);
  expect(ctrl.exceptionsGets).toBe(getsBeforeViewerFilter);

  // ... and the raw name is nowhere in the view's visible text for the
  // viewer either.
  const viewerRawInView = await page.evaluate((needle) => {
    const view = document.getElementById('view-exceptions');
    const text = view ? view.textContent : '';
    return text.indexOf(needle) !== -1;
  }, 'release_awaiting_approval');
  expect(viewerRawInView).toBe(false);
  expect(pageErrors).toEqual([]);
});
