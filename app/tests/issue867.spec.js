// Proving spec for AIERP issue #867 — the "Awaiting ERP approval" label
// for the release_awaiting_approval kind on the Exceptions screen
// (#/exceptions), the label the #865 rows arrive with:
//
//   * The label: the kind-label map gains
//     release_awaiting_approval → "Awaiting ERP approval"; a row of
//     that kind reads "Awaiting ERP approval" in the Signal column,
//     and the Signal filter's option for it reads the same. Every
//     other label is unchanged — the release_failed row beside it
//     still reads "Release failed".
//   * The filter: the Signal filter lists an option reading "Awaiting
//     ERP approval"; choosing it leaves only that row, client-side —
//     it makes no request.
//   * No raw name: the text "release_awaiting_approval" appears
//     nowhere in the view's visible text.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// app/tests/issue820.spec.js: the mocked /api/exceptions answer has
// two rows — one release_awaiting_approval (severity "medium", detail
// "PO003068 to V-1 awaiting approval in the ERP for 10 days", view
// "#/releases") and one release_failed — and counts high 1, medium
// 1, acknowledged 0, new 0.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer, and the
// admin-only controls — the Actions column and its buttons — are
// absent while the page renders on (the Signal filter is not
// admin-only and serves the viewer as well).
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue867 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


