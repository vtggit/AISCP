// Proving spec for AIERP issue #869 — the "Supplier terms" section on
// the Suppliers screen (#/suppliers), below the performance table.
//
// The section ([data-testid="suppliers-terms"]) is headed "Supplier
// terms" and holds a select
// ([data-testid="suppliers-terms-supplier"]) — first "Choose a
// supplier" (an empty value), then one option per row of the current
// performance answer that has a non-empty supplier_code, in the
// table's order, labelled with the supplier name, else the vendor
// code, else the supplier code, valued by the supplier_code — and a
// "Show terms" button ([data-testid="suppliers-terms-show"]). With
// no such rows the section is not shown.
//
// The terms are fetched on demand only: the screen sends GET
// /api/supplier-terms?supplier_code=<the chosen code, URL-encoded>
// through app/js/api.js only when "Show terms" is clicked with a
// supplier chosen. Activating the view and changing the window send
// no terms request; a click with no supplier chosen sends nothing.
// The answer renders as a table
// ([data-testid="suppliers-terms-table"]) with one row per terms row
// in the answer's order — columns Item, Minimum, Lot size, Maximum,
// Lead time (d) and Default — a null number as an em dash, numbers
// without trailing zeros, "Yes" where is_default is true, and a
// caption "<n> items for <the option's text>"; the terms rows never
// carry the performance table's sp-row class. An empty answer reads
// "No ordering terms are stored for this supplier."; a failed
// request shows "Supplier terms could not be loaded." in
// [data-testid="suppliers-terms-error"] and leaves the performance
// table unchanged. The chosen supplier, the answer, the error and a
// pending flag live in module state and survive a re-render (a
// window change); sign-out clears them, and an answer arriving after
// sign-out or after a newer click is discarded. Every API value is
// escaped or set as text; at 390x844 the page does not scroll
// sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route — the same mocks and sign-in as
// app/tests/issue605.spec.js, plus a mock for /api/supplier-terms
// that records each request's supplier_code. The performance mock
// answers two suppliers: "4850" (named "Net Jenn Toy Development")
// and "4861" (no name, vendor code "CONGOODTOL"). The terms mock
// answers two rows for "4850": one with minimum 300, lot size 25,
// maximum null, lead time 15 and is_default true, and one with every
// number null.
//
// The pass runs as a PLANNER (role 'user') signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, no suppliers or terms fetch goes out before the
// view is activated, the screen then renders for the viewer, and the
// admin-only controls — the Settings view's mappings and budget
// forms — are absent where "Only an admin can change this." shows
// instead, the page rendering on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue869 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

