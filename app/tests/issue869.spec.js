// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the terms answers
// (ctrl.termsAnswer, the one-shot ctrl.termsNext) and the sign-in
// (ctrl.config / ctrl.me) when the pass switches from the planner to
// the non-admin viewer. Every performance request is counted in
// ctrl.suppliersGets, every terms request in ctrl.termsGets, and
// each terms request's supplier_code lands in ctrl.termsCodes.
async function mockSuppliersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: PLANNER_ME,
    suppliersAnswer: null,
    termsAnswer: TERMS_4850,
    termsNext: null,
    suppliersGets: 0,
    suppliersWindows: [],
    termsGets: 0,
    termsCodes: [],
    summaryGets: 0,
    meRequests: [],
  };
  const appOrigin = { value: null };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/suppliers/performance') {
      ctrl.suppliersGets += 1;
      ctrl.suppliersWindows.push(url.searchParams.get('window_days'));
      const answer =
        typeof ctrl.suppliersAnswer === 'function'
          ? ctrl.suppliersAnswer()
          : ctrl.suppliersAnswer;
      return route.fulfill({ status: 200, json: answer || suppliersPayload() });
    }
    if (path === '/api/supplier-terms') {
      ctrl.termsGets += 1;
      ctrl.termsCodes.push(url.searchParams.get('supplier_code'));
      if (ctrl.termsNext) {
        const next = ctrl.termsNext;
        ctrl.termsNext = null;
        return route.fulfill(next);
      }
      const answer =
        typeof ctrl.termsAnswer === 'function' ? ctrl.termsAnswer() : ctrl.termsAnswer;
      return route.fulfill({ status: 200, json: answer || [] });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    if (path === '/api/erp-mappings') {
      return route.fulfill({ status: 200, json: MAPPINGS });
    }
    if (path === '/api/purchase-budgets') {
      return route.fulfill({ status: 200, json: BUDGETS });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

