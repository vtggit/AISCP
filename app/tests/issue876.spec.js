// A small RFC-4180 reader for the proof: rows end with CRLF (a
// bare CR or LF is accepted too), fields separate on commas, a
// double-quoted field carries doubled inner quotes. The parser
// returns the rows' fields as plain strings.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
        } else {
          inQuotes = false;
          i += 1;
        }
        continue;
      }
      field += ch;
      i += 1;
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (ch === ',') {
      row.push(field);
      field = '';
      i += 1;
      continue;
    }
    if (ch === '\r' || ch === '\n') {
      if (ch === '\r' && text[i + 1] === '\n') {
        i += 2;
      } else {
        i += 1;
      }
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
      continue;
    }
    field += ch;
    i += 1;
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the supply-plan answer
// (ctrl.supplyAnswer, either a payload or a { status, json } failure)
// and the sign-in (ctrl.config / ctrl.me) when the pass switches
// from the admin to the non-admin viewer. Every supply-plan request
// is counted (ctrl.supplyGets) with its horizon_days query recorded
// in ctrl.supplyQueries, the answer can be held back
// (ctrl.supplyDelayMs, in milliseconds) so the in-flight state is
// observable, and every API request of any kind is counted
// (ctrl.apiGets) so "the click sends no request" is provable.
async function mockOrdersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    supplyAnswer: null,
    supplyGets: 0,
    supplyQueries: [],
    supplyDelayMs: 0,
    apiGets: 0,
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    ctrl.apiGets += 1;
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/supply-plan') {
      ctrl.supplyGets += 1;
      ctrl.supplyQueries.push(url.searchParams.get('horizon_days'));
      const answer = ctrl.supplyAnswer;
      const respond = () => answerOrFulfill(route, answer, supplyBase());
      if (ctrl.supplyDelayMs > 0) {
        return new Promise((resolve) => {
          setTimeout(() => resolve(respond()), ctrl.supplyDelayMs);
        });
      }
      return respond();
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

