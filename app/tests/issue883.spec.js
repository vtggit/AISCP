// Proving spec for AIERP issue #883 — the release control per
// transfer suggestion of the Order plan screen (#/orders).
//
// Admin only, decided from the screen's existing role exactly as the
// supplier "Release to Acumatica" control decides it — the shared
// Auth identity's, read off the screen's zero-size [data-admin-only]
// probe, failing closed (no control at all for a non-admin or an
// unresolved identity). For a resolved admin, the transfers table
// always gains a last column headed "Release", whatever the rows:
// every row whose suggestion source_system is "acumatica" carries a
// "Release" button ([data-testid="orders-transfer-release"]) in that
// cell, every other row's cell is empty; a non-admin sees no such
// column, and every other column and cell reads as before.
//
// Preview first: the button POSTs /api/supply-plan/transfers/release
// with exactly {"transfers": [{"item_code", "from_site", "to_site"}]}
// for that row — no quantity, no confirm — and the answer's panel
// ([data-testid="orders-transfer-panel"], below the table) lists each
// returned group's "<from_site> → <to_site>", its line count and each
// line's item and quantity, each unreleasable entry's item and
// reason, and the "Confirm transfer"
// ([data-testid="orders-transfer-confirm"]) and "Cancel"
// ([data-testid="orders-transfer-cancel"]) buttons. With no groups it
// reads "Nothing to release for this suggestion." and has no Confirm.
// Only one panel is open at a time, and a newer preview replaces it.
//
// Confirm: Confirm sends the same body with "confirm": true and the
// panel then shows each group's outcome
// ([data-testid="orders-transfer-outcome"]): "created" reads
// "Transfer <reference_nbr> created on hold", "exists" "Already
// released as <reference_nbr>", "error" "Failed: <error>". Both
// buttons are disabled while a request is out, so a double click
// sends one request. A 403 shows "Only an admin can release
// transfers.", a 409 or 503 the server's detail, any other failure
// "The transfer could not be released." — each in
// [data-testid="orders-transfer-error"], and none changes the plan
// or the transfers table, which the release never refetches. Cancel
// closes the panel and sends nothing.
//
// The panel's state lives in module state and survives a full
// re-render of #orders-root; sign-out clears it, and an answer
// arriving after sign-out is discarded. Every API value is inserted
// as text, never as markup; at 390x844 the page does not scroll
// sideways.
//
