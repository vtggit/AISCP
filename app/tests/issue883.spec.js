// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the supply-plan answer
// (ctrl.supplyAnswer, either a payload or a { status, json } failure),
// the transfers answer (ctrl.transfersAnswer, the same shape) and the
// transfer release answer (ctrl.transferReleaseAnswer, the same two
// shapes) plus its delay (ctrl.transferReleaseDelay ms) and the
// sign-in (ctrl.config / ctrl.me) when the pass switches from the
// admin to the non-admin viewer. Every supply-plan GET is counted
// (ctrl.supplyGets), every transfers GET (ctrl.transfersGets) and
// every transfer release POST is recorded (ctrl.transferReleasePosts,
// raw body plus the parsed body).
async function mockOrdersApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    supplyAnswer: null,
    supplyGets: 0,
    supplyQueries: [],
    transfersAnswer: null,
    transfersGets: 0,
    transferReleaseAnswer: null,
    transferReleaseDelay: 0,
    transferReleasePosts: [],
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/supply-plan') {
      ctrl.supplyGets += 1;
      ctrl.supplyQueries.push(url.searchParams.get('horizon_days'));
      return answerOrFulfill(route, ctrl.supplyAnswer, supplyBase());
    }
    if (path === '/api/supply-plan/transfers') {
      ctrl.transfersGets += 1;
      return answerOrFulfill(route, ctrl.transfersAnswer, transfersBase());
    }
    if (path === '/api/supply-plan/transfers/release') {
      const raw = request.postData();
      let parsed = null;
      try {
        parsed = JSON.parse(raw);
      } catch (error) {
        parsed = raw;
      }
      ctrl.transferReleasePosts.push({ method: request.method(), raw, body: parsed });
      const delay = ctrl.transferReleaseDelay;
      if (delay > 0) {
        setTimeout(() => answerOrFulfill(route, ctrl.transferReleaseAnswer, transferReleaseBase()), delay);
        return;
      }
      return answerOrFulfill(route, ctrl.transferReleaseAnswer, transferReleaseBase());
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

// Two real mouse clicks at the element's centre, with no
// actionability wait in between: the first click's handler disables
// the button before the second one lands, so a screen that honours
// "disabled while a request is out" sends exactly one request. The
// target is first scrolled into the visible part of the screen's
// own scrolling body — the transfers table (and the panel below it)
// sit below the fold at the pass's 1440x900 viewport, and a raw
// click at unscrolled coordinates lands on the clipped area beyond
// the scrollport, on nothing — so the scroll goes first.
async function doubleClick(page, locator) {
  await locator.scrollIntoViewIfNeeded();
  const box = await locator.boundingBox();
  const x = box.x + box.width / 2;
  const y = box.y + box.height / 2;
  await page.mouse.click(x, y);
  await page.mouse.click(x, y);
}

