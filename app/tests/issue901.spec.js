// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the supply-plan answer
// (ctrl.supplyAnswer, either a payload or a { status, json }
// failure), the release answer (ctrl.releaseAnswer), the transfers
// answer (ctrl.transfersAnswer), the transfer release answer
// (ctrl.transferReleaseAnswer) and the exceptions answer
// (ctrl.exceptionsAnswer), and the sign-in (ctrl.config / ctrl.me)
// when the pass switches from the admin to the non-admin viewer.
// Every supply-plan GET is counted (ctrl.supplyGets), every
// release POST is recorded (ctrl.releasePosts, raw body plus the
// parsed body), every transfers GET is counted (ctrl.transfersGets),
// every transfer release POST is recorded
// (ctrl.transferReleasePosts) and every exceptions GET is counted
// (ctrl.exceptionsGets).
async function mockApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    supplyAnswer: null,
    supplyGets: 0,
    supplyQueries: [],
    releaseAnswer: null,
    releasePosts: [],
    transfersAnswer: null,
    transfersGets: 0,
    transferReleaseAnswer: null,
    transferReleasePosts: [],
    exceptionsAnswer: null,
    exceptionsGets: 0,
    meRequests: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      return route.fulfill({ status: 200, json: ctrl.me });
    }
    if (path === '/api/supply-plan') {
      ctrl.supplyGets += 1;
      ctrl.supplyQueries.push(url.searchParams.get('horizon_days'));
      return answerOrFulfill(route, ctrl.supplyAnswer, supplyBase());
    }
    if (path === '/api/supply-plan/release') {
      const raw = request.postData();
      let parsed = null;
      try {
        parsed = JSON.parse(raw);
      } catch (error) {
        parsed = raw;
      }
      ctrl.releasePosts.push({ method: request.method(), raw, body: parsed });
      return answerOrFulfill(route, ctrl.releaseAnswer, releaseBase());
    }
    if (path === '/api/supply-plan/transfers') {
      ctrl.transfersGets += 1;
      return answerOrFulfill(route, ctrl.transfersAnswer, transfersBase());
    }
    if (path === '/api/supply-plan/transfers/release') {
      const raw = request.postData();
      let parsed = null;
      try {
        parsed = JSON.parse(raw);
      } catch (error) {
        parsed = raw;
      }
      ctrl.transferReleasePosts.push({ method: request.method(), raw, body: parsed });
      return answerOrFulfill(route, ctrl.transferReleaseAnswer, transferReleaseBase());
    }
    if (path === '/api/exceptions') {
      ctrl.exceptionsGets += 1;
      return route.fulfill({ status: 200, json: ctrl.exceptionsAnswer || exceptionsBase() });
    }
    if (path === '/api/abc') {
      return route.fulfill({ status: 200, json: abcPayload() });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

