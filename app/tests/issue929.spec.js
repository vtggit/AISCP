// forecast accuracy yet", and the overrides line
// ([data-testid="sop-forecast-overrides"]) appears only when
// overridden_buckets is above 0 and value_added is not null.
//
// The month table ([data-testid="sop-table"]) has one column per
// entry of months in the answer's order, headed by the month, with
// the Demand / Supply / Money rows; units carry thousands
// separators, values and money are whole dollars, the shortage cells
// join the site lists with commas (an em dash when empty) and carry
// the class sop-flag when non-empty, and the budget status reads
// "Over budget" (flagged), "No budget" or "Within budget". The
// missing-cost note ([data-testid="sop-no-cost"]) is singular at
// exactly 1 and absent at 0, and [data-testid="sop-links"] holds
// "Open Demand" (#/demand), "Open Aggregate" (#/aggregate), "Open
