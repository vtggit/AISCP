// Mock every /api/* call the app makes. The handler reads ctrl on
// every request, so the test can steer the review answer
// (ctrl.sopAnswer, either a payload or a { status, json } failure),
// the sign-in (ctrl.config / ctrl.me — roles ["admin"] unless a check
// says otherwise, a { status, json } failure, or a stalled answer)
// and the sign-off POSTs (ctrl.signoffResponse / ctrl.signoffStall)
// as the pass switches scenarios. Every review request is counted
// (ctrl.sopGets) with its months query recorded in ctrl.sopQueries;
// every role read is recorded in ctrl.meRequests; every POST
// /api/sop/signoffs body is recorded in ctrl.signoffPosts. While a
// stall flag is true the matching requests queue in the stalled list
// unfulfilled, so the test can hold an answer out.
async function mockSopApi(page) {
  const ctrl = {
    config: DEV_CONFIG,
    me: ADMIN_ME,
    sopAnswer: null,
    sopGets: 0,
    sopQueries: [],
    sopStall: false,
    sopStalled: [],
    meRequests: [],
    meStall: false,
    meStalled: [],
    signoffPosts: [],
    signoffResponse: null,
    signoffStall: false,
    signoffStalled: [],
    summaryGets: 0,
  };
  const appOrigin = { value: null };

  const answerOrFulfill = (route, answer, fallback) => {
    if (answer && typeof answer === 'object' && !Array.isArray(answer) && 'status' in answer) {
      return route.fulfill({ status: answer.status, json: answer.json });
    }
    return route.fulfill({ status: 200, json: answer || fallback });
  };

  const handler = (route) => {
    const request = route.request();
    const url = new URL(request.url());
    if (appOrigin.value === null) {
      appOrigin.value = url.origin;
    }
    const path = url.pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, json: ctrl.config });
    }
    if (path === '/api/auth/me') {
      ctrl.meRequests.push(request);
      if (ctrl.meStall) {
        ctrl.meStalled.push(route);
        return;
      }
      return answerOrFulfill(route, ctrl.me, ADMIN_ME);
    }
    if (path === '/api/sop/review') {
      ctrl.sopGets += 1;
      ctrl.sopQueries.push(url.searchParams.get('months'));
      if (ctrl.sopStall) {
        ctrl.sopStalled.push(route);
        return;
      }
      return answerOrFulfill(route, ctrl.sopAnswer, sopBase());
    }
    if (path === '/api/sop/signoffs') {
      if (request.method() !== 'POST') {
        return route.fulfill({ status: 405, json: { detail: 'Method Not Allowed' } });
      }
      ctrl.signoffPosts.push(JSON.parse(request.postData() || '{}'));
      if (ctrl.signoffStall) {
        ctrl.signoffStalled.push(route);
        return;
      }
      return answerOrFulfill(route, ctrl.signoffResponse, { recorded: true });
    }
    if (path === '/api/aggregate/releases') {
      return route.fulfill({ status: 200, json: RELEASES_EMPTY });
    }
    if (path === '/api/decisions/summary') {
      ctrl.summaryGets += 1;
      return route.fulfill({ status: 200, json: SUMMARY });
    }
    if (path === '/api/drift' || path === '/api/excess' || path === '/api/stockout') {
      return route.fulfill({ status: 200, json: [] });
    }
    if (path === '/api/settings') {
      return route.fulfill({ status: 200, json: SETTINGS_ENTRIES });
    }
    return route.fulfill({ status: 404, json: { detail: 'Not Found' } });
  };

  await page.route('**/api/**', handler);
  return { ctrl, appOrigin, handler };
}

