// Proving spec for AIERP issue #931 — the sign-off control on the
// S&OP review screen (#/sop): the view sends GET /api/auth/me once
// per activation, and a viewer whose roles include "admin" (the way
// the Aggregate view reads it) gets, once a review answer is
// loaded, the [data-testid="sop-signoff-open"] button reading
// "Sign off <review_month>" (or "Sign off <review_month> again"
// when latest_signoff is not null); a viewer who is not an admin, or
// whose role read failed or is still out, sees no control at all,
// and the button is not shown while the review failed to load.
//
// Clicking it opens [data-testid="sop-signoff-panel"] with the
// sentence "This records that <review_month> was reviewed and stores
// today's figures. It changes nothing in the plan or the ERP.", the
// note field [data-testid="sop-signoff-text"] (labelled "Note
// (optional)", limited to 500 characters) and
// [data-testid="sop-signoff-confirm"] / [data-testid="sop-signoff-cancel"].
// Opening the panel sends no request; Cancel closes the panel and
// sends nothing. Confirming sends one POST /api/sop/signoffs through
// app/js/api.js with {"month": <review_month>, "months": <the chosen
// horizon>} and the trimmed note when it is not empty — the month
// and horizon come from what is loaded at that moment — and the
// confirm button is disabled while the request is out, so a double
// click sends one request. On success the panel closes and clears
// and the view fetches the review once more through its usual path,
// so the status line reads the server's answer; on failure the panel
// stays open with the note kept and the message shows in
// [data-testid="sop-signoff-error"] — a 403 reads "Only an admin can
// sign off.", a 422 shows the server's detail (how a month that has
// rolled over is reported), anything else reads "The sign-off could
// not be recorded.". A review refresh or a horizon change does not
// close an open panel or lose its note.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #929 spec): /api/auth/me answers roles ["admin"] unless a
// check says otherwise, /api/sop/review answers review_month 2026-11
// with latest_signoff null, and every POST /api/sop/signoffs body is
// recorded. The pass runs as an ADMIN signed in through the
// development token card at 1440x900, and it ends as a NON-ADMIN
// (role 'user') after a full reload: the token arrives in the URL
// hash as #access_token=..., /api/auth/config and /api/auth/me are
// mocked for that user, the IdP's auth and token endpoints carry the
// PKCE round-trip, the screen renders for the viewer, and no
// sign-off control of any kind is on it. At 390x844 with the panel
// open the page does not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue931 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

