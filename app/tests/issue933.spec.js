// Proving spec for AIERP issue #933 — the Sign-offs section of the
// "S&OP review" screen (#/sop): the stored sign-offs and the figures
// each one froze when it was recorded.
//
// Below the links, the section ([data-testid="sop-history"]) is
// headed "Sign-offs", visible to every signed-in user whether or not
// the review has loaded, with a "Show sign-offs" button
// ([data-testid="sop-history-show"]). The button is the only trigger
// of GET /api/sop/signoffs?limit=50 through app/js/api.js — opening
// the view sends no sign-offs request — and after an answer has
// landed the button reads "Refresh sign-offs". A sign-off recorded on
// the screen while a list answer is showing fetches the list once
// more, so the new row appears. The list
// ([data-testid="sop-history-table"]) has one row per answer row in
// the answer's order — Month, Signed by (actor_name, else actor),
// Date (the date of created_at), Note (an em dash when null) and a
// "View figures" button ([data-testid="sop-history-view"]); an empty
// answer reads "No sign-offs yet.", and a failed list fetch shows
// "Sign-offs could not be loaded." in
// [data-testid="sop-history-error"] with the review above unchanged.
//
// "View figures" sends GET /api/sop/signoffs/{id} once and shows the
// frozen figures ([data-testid="sop-history-figures"]) headed
// "Figures as signed on <the date of created_at> by <the signer>",
// holding the same forecast sentence and the same month table the
// review shows — the row's stored figures fed to the same rendering
// code, so the two cannot drift apart. "Close"
// ([data-testid="sop-history-close"]) hides the block; choosing
// another row replaces it, a request-sequence guard renders only the
// newest choice, and a failure shows "These figures could not be
// loaded." inside the block. The block is read-only (no sign-off
// control), never changes the review above, its status line or its
// chosen horizon, and a review refresh never changes the block; a
// stored figure missing a field the renderer reads shows an em dash,
// never a page error. The list, its error, the chosen row and its
// answer live in module state and survive a re-render; sign-out
// clears them, and an answer arriving after sign-out is discarded.
// Every API value is rendered as text, never as markup; both tables
// scroll inside their own regions, and at 390x844 the page does not
// scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #929 spec, plus the sign-offs answers). The list answer has
// two rows: 2026-11 by "Pat Admin" with the note "Agreed", and
// 2026-10 by "admin1" (no display name, no note). The figures answer
// of id 1 has one month (2026-10) with total_spend 111111 and budget
// 222222, while the live review's first month carries total_spend
// 999999.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, then as a PLANNER (roles ["planner"]) after a
// reload — the section and its figures work and the frozen block
// holds no sign-off control — and it ends as a NON-ADMIN (role
// 'user') after a full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer with the
// section visible and no admin-only control of any kind on it while
// the page renders on.
//
// The test is TOP-LEVEL and its title is the full proof name
