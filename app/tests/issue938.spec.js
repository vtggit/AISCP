// Proving spec for AIERP issue #938 — the "Since the last sign-off"
// block of the "S&OP review" screen (#/sop): the drift of this
// review against the newest stored sign-off, read from the review
// answer the screen already loaded.
//
// The block ([data-testid="sop-since"]) lives directly above the
// month table, headed "Since the last sign-off". It shows only when
// the loaded answer's since_signoff is not null — with since_signoff
// null, or absent from the answer, there is no block and no empty
// placeholder. Its sentence ([data-testid="sop-since-base"]) reads
// "Compared with the sign-off of <signed_month> by <signed_by> on
// <the date of signed_at>". The table
// ([data-testid="sop-since-table"]) has one column per entry of
// since_signoff.months in the answer's order, headed by the month,
// and these rows in this order: "Demand units", "Demand value",
// "Open supply value", "Planned receipts value", "Total spend" and
// "Budget", from demand_units_delta, demand_value_delta,
// supply_value_delta, planned_receipts_value_delta,
// total_spend_delta and budget_delta. A positive delta reads with a
// leading "+" and a negative one with a leading "-": units carry
// thousands separators and values are whole dollars, as in "+1,234"
// and "-$5,678"; a delta that rounds to zero reads "No change", and
// a null or missing delta reads an em dash. With an empty months the
// sentence shows and, in place of the table, the block reads "No
// months in common with that sign-off.". The block belongs to the
// live review only: a past sign-off's frozen figures, even carrying
// since_signoff, hold no such block.
//
// The block reads only the review answer already loaded and sends no
// request of its own: opening the view sends exactly one review
// request (GET /api/sop/review through app/js/api.js) and the block
// sends none. Every API value is set as text — a hostile signed_by
// renders as words — and a delta is never marked good or bad by
// colour, because a rise can be either; the table scrolls inside its
// own region, and at 390x844 the page does not scroll sideways.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #929 spec, plus the sign-offs list and one row's frozen
// figures, which carry since_signoff). The mocked review answer has
// review month 2026-11, as of 2026-11-02, no sign-off of the review
// month, two months, and since_signoff of the 2026-10 sign-off by
// "Pat Admin" on 2026-10-05 with two months: 2026-11 with
// demand_units_delta 1234, demand_value_delta -5678.4,
// supply_value_delta 0, planned_receipts_value_delta 0.3,
// total_spend_delta 1000 and budget_delta null, and 2026-12 with
// every delta 0.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, no review fetch goes out before the view is activated,
// the screen then renders for the viewer — the block included — and
// no admin-only control of any kind is on it while the page renders
// on.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue938 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

