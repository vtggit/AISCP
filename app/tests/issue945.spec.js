// Proving spec for AIERP issue #945 — the Scenarios section of the
// S&OP review screen (#/sop): directly above the Sign-offs section,
// [data-testid="sop-scenarios"] headed "Scenarios", visible to every
// signed-in user whether or not the review has loaded, with the
// "Compare saved scenarios" button
// ([data-testid="sop-scenarios-show"]).
//
// The screen sends GET /api/sop/scenarios?months=<the chosen horizon>
// through app/js/api.js only when that button is clicked — opening
// the view and changing the horizon send no such request — and again
// on a later click. Once an answer has landed, the button reads
// "Refresh the comparison"; while a request is out it is disabled and
// reads "Comparing…", and two clicks send one request. A
// request-sequence guard renders only the newest answer, and after
// the horizon changes an answer already showing stays and its
// heading says which horizon it covers:
// [data-testid="sop-scenarios-heading"] reads "Over
// <horizon_months> months, compared with the plan". The table
// ([data-testid="sop-scenarios-table"]) has a first row "Plan" from
// the baseline, then one row per scenario in the answer's order:
// "Scenario" (the name, its set levers below it in
// [data-testid="sop-scenarios-levers"] — "Service level 95.0%",
// "Demand × 1.50", "Lead time × 1.20", "Same as the plan" without a
// lever set), "Demand value", "Change", "Total spend", "Change",
// "Months over budget" and "Months short with plan" — whole dollars,
// a change signed with a leading "+" or "-" ("No change" when it
// rounds to zero), the Plan row's change cells an em dash. A
// scenario whose error is not null shows its name and reads "Could
// not be compared: <error>" across the figure cells; when
// scenarios_total is above the number of rows,
// [data-testid="sop-scenarios-more"] reads "Showing the newest <n>
// of <scenarios_total> saved scenarios."; with no scenarios,
// [data-testid="sop-scenarios-empty"] reads "No saved scenarios
// yet. Save one on the Scenario screen." (the "Scenario screen"
// linking #/scenario) and the Plan row is not shown. A failed fetch
// shows "The comparison could not be loaded." in
// [data-testid="sop-scenarios-error"] and leaves the review and any
// earlier comparison unchanged. The answer, the error and the
// pending flag live in module state and survive a re-render;
// sign-out clears them, and an answer arriving after sign-out is
// discarded. Every API value is rendered as text, the table scrolls
// inside its own region, and at 390x844 the page does not scroll
// sideways.
//
// The open button hides while the panel is open: with the sign-off
// panel open, [data-testid="sop-signoff-open"] is not shown, and it
// returns when the panel closes by Cancel or after a sign-off —
// everything else about the control unchanged.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #929 spec, plus the sop scenarios answer, which counts
// requests and answers horizon_months 3, scenarios_total 7, a
// baseline of 1,000,000 demand value / 500,000 total spend / 1 month
// over budget / 0 months short with plan, and two scenarios: "Busy
// Q4" with demand_multiplier 1.5 and figures 1,500,000 / 450,000 /
// 0 / 2 (deltas +500,000 / -50,000), and "Broken" with error
// "lever out of range" and null figures).
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked
