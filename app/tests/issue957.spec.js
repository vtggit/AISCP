  const rows = page.locator('[data-testid="exceptions-row"]');
  const badges = page.locator('[data-testid="exceptions-new"]');
  const adminNote = page.locator('[data-testid="exceptions-admin-note"]');
  const card = page.locator('.ov-exceptions');

  await page.goto('/');

  // No exceptions request before the sign-in (Auth.bootstrap)
  // completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.exceptionsGets).toBe(0);

  // Sign in through the development token card as the admin.
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  // The Overview (the default view) has loaded its Exceptions today
  // card once; the inbox view is not active yet.
  await expect.poll(() => ctrl.exceptionsGets).toBe(1);
  expect(pageErrors).toEqual([]);

  // Into the inbox: one more fetch, and the answer renders.
  await page.click('.nav-btn[data-view="exceptions"]');
  await expect(page).toHaveURL(/#\/exceptions$/);
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect.poll(() => ctrl.exceptionsGets).toBe(2);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(summary).toHaveText('1 high \u00b7 1 medium \u00b7 0 acknowledged');
  // Nothing is new: no count line, no badge.
  await expect(newCount).toHaveCount(0);
  await expect(badges).toHaveCount(0);
  // The admin gets the Actions column.
  expect(await page.locator('#exceptions-root th').allTextContents()).toEqual([
    'Severity',
    'Signal',
    'Item and Site',
    'Detail',
    'Detected',
    'Status',
    'Open',
    'Actions',
  ]);
  expect(pageErrors).toEqual([]);

  // --- the label: the Signal column, whichever order the screen ------
  // shows the two rows in — addressed by their Signal text.
  const signalLabels = await page.evaluate(() => {
    const rowEls = Array.from(document.querySelectorAll('[data-testid="exceptions-row"]'));
    return rowEls.map((row) => {
      const cell = row.querySelector('.ex-signal');
      return cell ? cell.textContent.trim() : null;
    });
  });
  expect([...signalLabels].sort()).toEqual(['ERP push failed', 'S&OP sign-off due']);

  // The sign-off row: "S&OP sign-off due" in the Signal cell, an em
  // dash for its null item and site, its detail, and the link to its
  // view, "#/sop".
  expect(await rowBySignal(page, 'S&OP sign-off due')).toEqual({
    severity: 'Medium',
    signal: 'S&OP sign-off due',
    pair: '\u2014',
    detail:
      '2026-11 has not been signed off. The last sign-off was for 2026-10 on 2026-10-05.',
    detected: '2026-11-10',
    status: 'New',
    href: '#/sop',
  });
  // The other row: "ERP push failed", unchanged.
  expect(await rowBySignal(page, 'ERP push failed')).toEqual({
    severity: 'High',
    signal: 'ERP push failed',
    pair: '\u2014',
    detail: 'push to acumatica failed',
    detected: '2026-11-01',
    status: 'New',
    href: '#/writeback',
  });
  expect(pageErrors).toEqual([]);

  // --- the filter: an option reading "S&OP sign-off due" -------------
  await expect(kindFilter).toHaveCount(1);
  await expect(kindFilter).toHaveAttribute('aria-label', 'Signal');
  const optionTexts = await kindFilter.locator('option').allTextContents();
  expect(optionTexts).toEqual([
    'All signals',
    'ERP push failed',
    'S&OP sign-off due',
  ]);
  const firstOptionValue = await kindFilter
    .locator('option')
    .first()
    .getAttribute('value');
  expect(firstOptionValue).toBe('');
  expect(await kindFilter.evaluate((select) => select.value)).toBe('');

  // Choosing the option leaves only its row — client-side, no new
  // request.
  const getsBeforeFilter = ctrl.exceptionsGets;
  await kindFilter.selectOption({ label: 'S&OP sign-off due' });
  await expect(rows).toHaveCount(1);
  await expect(rows.nth(0).locator('.ex-signal')).toHaveText('S&OP sign-off due');
  expect(await kindFilter.evaluate((select) => select.value)).toBe('sop_signoff_due');
  expect(ctrl.exceptionsGets).toBe(getsBeforeFilter);
  expect(pageErrors).toEqual([]);

  // "All signals" restores both rows, still without a request.
  await kindFilter.selectOption({ value: '' });
  await expect(rows).toHaveCount(2);
  expect(ctrl.exceptionsGets).toBe(getsBeforeFilter);
  expect(pageErrors).toEqual([]);

  // --- no raw name in the view's visible text -------------------------
  await assertNoRawKind(page);

  // --- phone width: no sideways scroll --------------------------------
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect(table).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(pageErrors).toEqual([]);

  // --- viewer pass: NON-ADMIN, production boot, full reload -----------
  // The token arrives in the URL hash the way the identity requirement
  // describes; since the hash is no longer a token delivery path the
  // production boot completes through the PKCE round-trip, so the IdP's
  // auth and token endpoints carry the viewer through it.
