  await expect.poll(() => ctrl.exceptionsGets).toBe(getsBeforeViewer + 1);
  await expect(card).toBeVisible();
  await expect(card.locator('.ov-exceptions-counts')).toHaveText(
    '1 high \u00b7 1 medium \u00b7 0 acknowledged',
  );
  await expect(card.locator('.ov-exceptions-new')).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // Activating the view for the viewer: the screen renders ...
  await page.click('.nav-btn[data-view="exceptions"]');
  expect(page.url()).toContain('#/exceptions');
  await expect(page.locator('#view-exceptions')).toBeVisible();
  await expect.poll(() => ctrl.exceptionsGets).toBe(getsBeforeViewer + 2);
  await expect(table).toBeVisible();
  await expect(rows).toHaveCount(2);
  await expect(summary).toHaveText('1 high \u00b7 1 medium \u00b7 0 acknowledged');
  await expect(newCount).toHaveCount(0);
