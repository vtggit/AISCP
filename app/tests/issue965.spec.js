// Proving spec for AIERP issue #965 — the demand signals in the
// Demand view (#/demand).
//
// The gate serves the static app with no backend, so every /api/* call
// is mocked with page.route. The by-key detail carries one forecast
// period whose signal_quantity is above 0 (quantity 100,
// signal_quantity 300, override_days 0, effective_quantity 400) and
// one period with signal_quantity 0. The /api/demand-signals GET mock
// counts its requests, records the item and site, and answers one
// signal (id 7, kind "promotion", 2026-12-01 to 2026-12-30, quantity
// 300, reason "Holiday promotion", created_by_name "Pat Admin"); the
// POST mocks record their bodies.
//
// Proves, signed in through the development token card as an admin
// (/api/auth/me roles ["admin"]), at 1440x900:
//   * the periods: the first period shows 400 in the effective column
//     and "+300 from signals" in its coverage, with 100 still shown
//     as statistical; the second period (signal_quantity 0) reads
//     exactly as it does with no signal;
//   * on demand: opening a detail sends no signals request; one click
//     sends exactly one, with the item and site; the row reads
//     "Promotion", "2026-12-01", "2026-12-30", "300", "Holiday
//     promotion" and "Pat Admin"; the button then reads "Refresh
//     signals";
//   * empty and failure: an empty answer reads "No demand signals for
//     this item-site."; a 503 shows "Signals could not be loaded."
//     with the rest of the detail still shown, the button still
//     reading "Refresh signals" and the error visible across a
//     re-render;
//   * another item-site: choosing another row clears the section back
//     to "Show signals", and a late answer for the first item-site
//     doesn't appear;
//   * adding: Save is disabled until the form is complete — blank
//     reason, an end before the start and units that are not a number
//     above 0 all refuse — a save sends the stated body with the
//     reason trimmed, closes the form, and sends one more signals
//     request and one more by-key request; a double click sends one
//     POST;
//   * refusals: a 422 with a detail keeps the form open with the typed
//     values and shows that detail; a 403 shows "Only an admin can
//     change demand signals."; a 500 shows "The signal could not be
//     saved.";
//   * withdrawing: Confirm sends one POST to
//     /api/demand-signals/7/withdraw with the trimmed reason, then
//     reloads the signals and the detail;
//   * as a planner: with roles ["planner"] the list shows, with no
//     add or withdraw controls;
//   * hostile text: a reason of "<img src=x
//     onerror=window.__pwned=1>" renders as text, with
//     window.__pwned undefined;
//   * phone width: at 390x844 with the form open, the page does not
//     scroll sideways.
//
// The "(viewer)" pass boots the production way as a NON-ADMIN
// (role 'user'): the token arrives in the URL hash as
// #access_token=..., /api/auth/config answers production and
// /api/auth/me answers for the viewer — the signals list loads
// read-only, with no "Add signal" or "Withdraw" control.
//
// The delays live in the mocked routes (gates the spec resolves),
// never as fixed waits in the page.
//
// The tests are TOP-LEVEL and each title is the full proof name
// ("issue965 freeform"): the merge gate builds its junit nodeids from
// the Playwright test title, and a describe() block would join the
// titles with a "›" the contract nodeid does not carry, so the proof
// would read as "not collected".

