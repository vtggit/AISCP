  await expect(signoffLine).toHaveText('Not signed off yet');
  await expect(sinceSentence).toHaveText(
    'Compared with the sign-off of 2026-10 by Pat Admin on 2026-10-05',
  );
  await expect(sopRow('From demand signals').locator('td').nth(0)).toHaveText('1,500');
  await expect(sopRow('From demand signals').locator('td').nth(1)).toHaveText('\u2014');
  await expect(sinceRow('From demand signals').locator('td').nth(0)).toHaveText('+1,500');

  // ... and the screen's admin-only control (the sign-off button) is
