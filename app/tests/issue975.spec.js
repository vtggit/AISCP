// Proving spec for AIERP issue #975 — the S&OP review screen's
// demand-signal rows (#/sop): the month table's "From demand signals"
// row, directly after "Demand value", reads each month's
// signal_units with thousands separators — an em dash when the
// figure is 0, rounds to 0, or is absent (a frozen row of an older
// answer) — and the "Since the last sign-off" table's "From demand
// signals" row, directly after its "Demand units" row, reads
// signal_units_delta by the existing delta rules (a positive delta
// with a leading "+", a rounded zero "No change", a null or missing
// delta an em dash). The frozen figures of a past sign-off render
// through the same month-table code, so they gain the row too, and
// an older stored answer without signal_units renders an em dash
// without a page error.
//
// The gate serves the static app with no backend, so every /api/*
// call is mocked with page.route (the same mocks and sign-in as the
// issue #929 spec, plus the sign-offs list and frozen-figures
// answers of the issue #938 spec). The mocked review answer has
// review_month 2026-11, as_of 2026-11-02, two months — 2026-11 with
// signal_units 1500 and 2026-12 with signal_units 0 — and a
// since_signoff of the 2026-10 sign-off by "Pat Admin" whose
// signal_units_delta is 1500 in the first (only) common month.
//
// The pass runs as an ADMIN signed in through the development token
// card at 1440x900, and it ends as a NON-ADMIN (role 'user') after a
// full reload: the token arrives in the URL hash as
// #access_token=..., /api/auth/config and /api/auth/me are mocked for
// that user, the IdP's auth and token endpoints carry the PKCE
// round-trip, the screen then renders for the viewer — the new rows
// included — and the screen's admin-only control (the sign-off
// button) is absent while the page renders on. At 390x844 the page
// does not scroll sideways.
//
// The test is TOP-LEVEL and its title is the full proof name
// ("issue975 freeform"): the merge gate builds its junit nodeids
// from the Playwright test title, and a describe() block would join
// the titles with a "›" the contract nodeid does not carry, so the
// proof would read as "not collected".

