  const historyShow = page.locator('[data-testid="sop-history-show"]');
  const historyTable = page.locator('[data-testid="sop-history-table"]');
  const historyView = page.locator('[data-testid="sop-history-view"]');
  const historyFigures = page.locator('[data-testid="sop-history-figures"]');

  await page.goto('/');

  // No review or signals request before the sign-in completes.
  await expect(page.locator('#signin-form')).toBeVisible();
  expect(ctrl.sopGets).toBe(0);
  expect(ctrl.signalsGets).toBe(0);

  // Sign in through the development token card as the admin.
  await page.fill('#token-input', 'dev-admin-token');
  await page.click('#signin-button');
  await expect(page.locator('#app')).toBeVisible();
  await expect(page.locator('#user-name')).toHaveText('admin1');
  expect(pageErrors).toEqual([]);

  await page.click('.nav-btn[data-view="sop"]');
  await expect(page).toHaveURL(/#\/sop$/);
  await expect(page.locator('#view-sop')).toBeVisible();

  // --- Better: the line reads the signals' effect on the error --------
  // Activation loads the review once — and the signals request once
  // with it, under its own guard.
  await expect.poll(() => [ctrl.sopGets, ctrl.signalsGets].join(':')).toBe('1:1');
  await expect(forecastLine).toHaveText(FORECAST_TEXT);
  await expect(signalsLine).toHaveText(
    'Demand signals changed the error by +16.0 points on 1,200 periods',
  );
  // Inside the forecast card, directly after the overrides line's
  // place: the base answer has no overrides line, so the card's
  // paragraphs are the forecast line and the signals line, in order.
  await expect(forecastCard.locator('[data-testid="sop-forecast-signals"]')).toHaveCount(1);
  await expect(forecastCard.locator('p')).toHaveText([
    FORECAST_TEXT,
    'Demand signals changed the error by +16.0 points on 1,200 periods',
  ]);
  expect(pageErrors).toEqual([]);

  // One request per load of the review: a Refresh loads the review
  // once more and exactly one signals request goes with it.
  await refresh.click();
  await expect.poll(() => [ctrl.sopGets, ctrl.signalsGets].join(':')).toBe('2:2');
  await expect(signalsLine).toHaveText(
    'Demand signals changed the error by +16.0 points on 1,200 periods',
  );
  expect(pageErrors).toEqual([]);

  // --- Worse: a negative value_added reads with a leading "-" --------
  ctrl.signalsAnswer = Object.assign({}, SIGNALS_BETTER, { value_added: -0.3 });
  await refresh.click();
  await expect.poll(() => [ctrl.sopGets, ctrl.signalsGets].join(':')).toBe('3:3');
  await expect(signalsLine).toHaveText(
    'Demand signals changed the error by -30.0 points on 1,200 periods',
  );
  await expect(forecastLine).toHaveText(FORECAST_TEXT);
  expect(pageErrors).toEqual([]);

  // --- Nothing to say: the paragraph stays out of the page ------------
  // compared_buckets 0: no line, the rest of the review reads as before.
  ctrl.signalsAnswer = Object.assign({}, SIGNALS_BETTER, { compared_buckets: 0 });
  await refresh.click();
  await expect.poll(() => [ctrl.sopGets, ctrl.signalsGets].join(':')).toBe('4:4');
  await expect(signalsLine).toHaveCount(0);
  await expect(forecastLine).toHaveText(FORECAST_TEXT);
  await expect(table).toHaveCount(1);
  await expect(errorNote).toHaveCount(0);
