  await expect(page.locator('[data-testid="sop-forecast-signals"]')).toHaveCount(1);
  expect(pageErrors).toEqual([]);
  await page.locator('[data-testid="sop-history-close"]').click();
  await expect(historyFigures).toHaveCount(0);
  expect(pageErrors).toEqual([]);

  // --- 390x844: the page does not scroll sideways ----------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#view-sop')).toBeVisible();
  await expect(refresh).toBeVisible();
