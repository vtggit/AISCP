  const getsBeforeViewerFilter = ctrl.exceptionsGets;
  await kindFilter.selectOption({ label: 'Same codes in two ERPs' });
  await expect(rows).toHaveCount(1);
  await expect(rows.nth(0).locator('.ex-signal')).toHaveText('Same codes in two ERPs');
  expect(ctrl.exceptionsGets).toBe(getsBeforeViewerFilter);
  await kindFilter.selectOption({ value: '' });
  await expect(rows).toHaveCount(1);
  expect(ctrl.exceptionsGets).toBe(getsBeforeViewerFilter);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  expect(pageErrors).toEqual([]);

  // And the raw name never reaches the viewer's visible text either.
