"""Issue #1174 proof: the generated reference docs.

``scripts/generate_reference_docs.py`` writes ``docs/reference/SETTINGS.md``
from the settings registry and ``docs/reference/API.md`` from
``backend/openapi.json`` (read, never written).  The script is loaded by
file path and checked like this: the settings table holds exactly one row
per registered setting, in key order, with the default as JSON and the
allowed values or the repr'd bounds in the range column; the API table
holds exactly one row per schema operation, ordered by path and then by
GET, POST, PUT, PATCH, DELETE; a pipe and a newline inside a value are
written ``\\|`` and as a space; two writes into fresh directories are
byte-identical; ``check_references`` finds nothing against a copy of the
committed files, and names ``docs/reference/API.md`` once a line is
appended to that copy; and the committed files still match the live
registry and schema, so a later change that adds a setting or a route
without regenerating the references fails here.
"""

import importlib.util
import json
import re
from pathlib import Path

from app.settings import registry

REPO_ROOT = Path(__file__).resolve().parents[2]
BACKEND_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "generate_reference_docs.py"
EN_DASH = "\u2013"
EM_DASH = "\u2014"
SETTINGS_HEADER = "| key | scope | type | default | allowed or range | description |"
API_HEADER = "| method | path | summary |"
_METHOD_ORDER = {"GET": 0, "POST": 1, "PUT": 2, "PATCH": 3, "DELETE": 4}
SETTINGS_BANNER = "Generated by `scripts/generate_reference_docs.py` from the settings registry (`backend/app/settings/registry.py`). Do not edit by hand."
API_BANNER = "Generated by `scripts/generate_reference_docs.py` from `backend/openapi.json`. Do not edit by hand."

_spec = importlib.util.spec_from_file_location("generate_reference_docs", SCRIPT)
generate_reference_docs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(generate_reference_docs)


def _table_rows(text, header):
    lines = text.splitlines()
    rows = []
    for line in lines[lines.index(header) + 1 :]:
        if not line.startswith("|"):
            break
        rows.append(line)
    return rows


def _cells(row):
    parts = re.split(r"(?<!\\)\|", row)
    assert parts[0] == "" and parts[-1] == ""
    return [part.strip() for part in parts[1:-1]]


def _row_for(rows, prefix):
    for row in rows:
        if row.startswith(prefix):
            return row
    raise AssertionError(f"no row starting with {prefix!r}")


def _expected_summary(operation):
    summary = operation.get("summary")
    if isinstance(summary, str) and summary.strip():
        return summary
    description = operation.get("description")
    if isinstance(description, str):
        for line in description.splitlines():
            if line.strip():
                return line
    return EM_DASH


def _method_rank(method):
    return _METHOD_ORDER.get(method.upper(), len(_METHOD_ORDER))


def test_issue1174_freeform(tmp_path):
    settings = registry.all_settings()
    spec = json.loads((BACKEND_ROOT / "openapi.json").read_text(encoding="utf-8"))

    # --- The settings table ---------------------------------------------------
    settings_text = generate_reference_docs.settings_markdown(settings)
    settings_lines = settings_text.splitlines()
    assert settings_lines[0] == "# Settings reference"
    assert SETTINGS_BANNER in settings_lines
    assert settings_text.endswith("\n") and not settings_text.endswith("\n\n")

    rows = _table_rows(settings_text, SETTINGS_HEADER)
    assert [_cells(row)[0] for row in rows] == [setting.key for setting in settings]

    top_up = registry.get_setting("supply_plan.top_up_lookahead_days")
    expected_top_up = f"| supply_plan.top_up_lookahead_days | system | number | 30 | 1{EN_DASH}90 | {top_up.description} |"
    assert _row_for(rows, "| supply_plan.top_up_lookahead_days |") == expected_top_up
    prefer = _cells(_row_for(rows, "| supply_plan.prefer_lower_risk_supplier |"))
    assert prefer[3] == "true"
    assert prefer[4] == EM_DASH

    for setting in settings:
        if setting.type == "enum":
            cells = _cells(_row_for(rows, f"| {setting.key} |"))
            assert cells[4] == ", ".join(setting.allowed)
    currency = _cells(_row_for(rows, "| erp.reporting_currency |"))
    assert currency[3] == '"USD"'
    assert currency[4] == "USD, EUR, GBP, CAD, AUD, JPY, CHF, MXN"

    # --- The API table ---------------------------------------------------------
    api_text = generate_reference_docs.api_markdown(spec)
    api_lines = api_text.splitlines()
    assert api_lines[0] == "# API reference"
    assert API_BANNER in api_lines
    assert api_text.endswith("\n") and not api_text.endswith("\n\n")

    api_rows = _table_rows(api_text, API_HEADER)
    expected = []
    for path in sorted(spec["paths"]):
        item = spec["paths"][path]
        for method in sorted(item, key=_method_rank):
            operation = item[method]
            if not isinstance(operation, dict):
                continue
            expected.append(
                f"| {method.upper()} | {path} | {_expected_summary(operation)} |"
            )
    assert len(api_rows) == len(expected)
    assert api_rows == expected
    assert any(row.startswith("| GET | /api/supply-plan/top-ups |") for row in api_rows)

    # --- Escaping ----------------------------------------------------------------
    nasty = registry.Setting(
        key="z.nasty",
        scope="system",
        type="boolean",
        default=False,
        description="a|b\nc",
    )
    nasty_rows = _table_rows(
        generate_reference_docs.settings_markdown(settings + [nasty]),
        SETTINGS_HEADER,
    )
    nasty_row = _row_for(nasty_rows, "| z.nasty |")
    assert _cells(nasty_row)[5] == "a\\|b c"
    assert "\n" not in nasty_row

    escaped_api = generate_reference_docs.api_markdown(
        {"paths": {"/api/nasty": {"get": {"summary": "a|b"}}}}
    )
    escaped_rows = _table_rows(escaped_api, API_HEADER)
    assert _cells(_row_for(escaped_rows, "| GET | /api/nasty |"))[2] == "a\\|b"

    # --- Determinism ---------------------------------------------------------------
    written = generate_reference_docs.write_references(tmp_path / "first")
    assert written == ["docs/reference/SETTINGS.md", "docs/reference/API.md"]
    generate_reference_docs.write_references(tmp_path / "second")
    for name in ("SETTINGS.md", "API.md"):
        first_bytes = (tmp_path / "first" / "docs" / "reference" / name).read_bytes()
        second_bytes = (tmp_path / "second" / "docs" / "reference" / name).read_bytes()
        assert first_bytes == second_bytes

    # --- Check mode ------------------------------------------------------------------
    check_copy = tmp_path / "check"
    for name in ("SETTINGS.md", "API.md"):
        source = REPO_ROOT / "docs" / "reference" / name
        target = check_copy / "docs" / "reference" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(source.read_bytes())
    assert generate_reference_docs.check_references(check_copy) == []
    api_copy = check_copy / "docs" / "reference" / "API.md"
    original = api_copy.read_text(encoding="utf-8")
    api_copy.write_text(original + "a trailing line\n", encoding="utf-8")
    assert generate_reference_docs.check_references(check_copy) == [
        "docs/reference/API.md",
    ]

    # --- The committed files match this repository ------------------------------------
    assert generate_reference_docs.check_references(REPO_ROOT) == []
