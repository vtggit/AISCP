"""Issue #1397 proof: the "basis" source of the exceptions inbox.

AC-1 — the two system settings of type number, registered like
``exceptions.forecast_bias_threshold`` and placed before
``exceptions.forecast_bias_min_periods``, answer their defaults,
bounds and descriptions through ``get_setting``:
``exceptions.basis_switch_margin`` (default 5, min 0.5, max 50,
"How many points nearer what sold, one period ahead, the demand
basis not in use must have been before the exceptions inbox
proposes switching to it.") and
``exceptions.basis_switch_min_periods`` (default 60, min 1, max
100000, "The fewest periods, one period ahead, the demand basis
measure must compare before the exceptions inbox proposes switching
the basis.").  ``docs/reference/SETTINGS.md`` is regenerated by
``scripts/generate_reference_docs.py``.

AC-2 — the new source "basis" of ``GET /api/exceptions``, read once
per call: it calls the module's own ``basis_accuracy`` name with
``bucket_index=1`` (the demand basis one period ahead, the horizon
the reorder points compare) and takes the effective
``replenishment.demand_basis`` value and the two settings from the
stored system settings the exceptions list already reads once — the
two settings through ``setting_value`` (a missing or out-of-range
stored value falling back to the registry default, as the other
settings do), the basis the way the reorder point reads it, never
through ``setting_value`` and never stored by the route: no second
settings read, no other accuracy call.  One row, kind
"demand_basis_switch" (medium), the key
"demand_basis_switch:<the proposed basis>", ``item_code`` and
``site_code`` null, title "Demand basis to review", the detail
"One period ahead over <N> periods, the <proposed basis> was <Z>
points nearer what sold than the <basis in use>, which reorder
points use. An admin may switch the demand basis to the <proposed
basis> in Settings." (N the measure's compared buckets, with
thousands separators, Z the absolute ``value_added`` times 100, to
one decimal), view "#/settings" and ``detected_on`` the measure's
``as_of``, only when the measure's ``compared_buckets`` is at least
the fewest periods and either the in-use basis is ``history`` with
``value_added`` times 100 at least the margin (proposing
``forecast``) or the in-use basis is ``forecast`` with minus
``value_added`` times 100 at least the margin (proposing
``history``) — no row otherwise, and none with a null
``value_added``.  In the kind order it stands directly after
"standing_grant_run", as the last kind.  A source that raises is
listed "basis" in ``sources_failed`` and the other sources still
answer, with status 200.  Every other source of the route module is
replaced with a fake answering no row, the way
``tests/test_issue955_freeform.py`` stands them in.

AC-4 — proved in one test, the module's ``basis_accuracy`` and
``_stored_system_settings`` stood in, the other sources answering
no row:

  * the default settings (the stored settings empty) with the
    FORECAST_NEARER measure (``compared_buckets`` 120,
    ``history_wape`` 0.3, ``forecast_wape`` 0.2, ``value_added``
    0.1) give one "demand_basis_switch" row: severity "medium",
    title "Demand basis to review", ``item_code`` and ``site_code``
    null, key "demand_basis_switch:forecast", the detail "One
    period ahead over 120 periods, the forecast was 10.0 points
    nearer what sold than the history, which reorder points use. An
    admin may switch the demand basis to the forecast in Settings.",
    and ``basis_accuracy`` was called exactly once, with
    ``bucket_index=1``;
  * no row with FORECAST_NEARER when ``replenishment.demand_basis``
    is stored as ``forecast``, when ``exceptions.basis_switch_margin``
    is stored as 15 or ``exceptions.basis_switch_min_periods`` as
    121 — and no row with the NOTHING measure (``compared_buckets``
    0, ``value_added`` null);
  * the mirror — the HISTORY_NEARER measure (``compared_buckets``
    120, ``history_wape`` 0.2, ``forecast_wape`` 0.3,
    ``value_added`` -0.1) with the basis stored as ``forecast``
    gives the row with the key "demand_basis_switch:history" and
    the detail with "the history" and "the forecast" swapped, while
    the basis on its default ``history`` gives no row;
  * a failed read — ``basis_accuracy`` raising — answers 200 with
    "basis" in ``sources_failed`` and no "demand_basis_switch" row;
  * the settings — the two settings answer their defaults, bounds
    and descriptions through ``get_setting``;
  * the row's position — a "demand_basis_switch" row comes after
    the rows of every other kind, as the kind order gives it the
    last place;
  * the viewer — the role "user" sees the same row as the admin,
    and no token is a 401.

Identity — the proof also runs as a NON-ADMIN (role "user"): a
second pass in the same test after a full reload, with the page
booted the production way (the token it would take from the URL
hash as ``#access_token=...`` — the development token, role "user"
— sent as its Bearer token), ``GET /api/auth/config`` answering
publicly and ``GET /api/auth/me`` resolving the viewer — sees the
list page still render (200 with the same body the admin sees, the
route open to any signed-in user, no admin-only control on it)
while the admin-only control is absent for that caller (the
acknowledgement route answers the viewer 403) and no token is still
a 401.
"""

