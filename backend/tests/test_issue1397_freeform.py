class FakeBasisAccuracy:
    """The fake for the route module's ``basis_accuracy``: answers
    the scenario's measure and records every call — the source's one
    read per call, with its keyword arguments."""

    calls: list = []
    answer: dict = {}
    raise_on_call = False

    def __call__(self, **kwargs):
        FakeBasisAccuracy.calls.append(kwargs)
        if FakeBasisAccuracy.raise_on_call:
            raise RuntimeError("the basis accuracy read is down")
        return dict(FakeBasisAccuracy.answer)


