def _basis_row(nearer: str, in_use: str) -> dict:
    """The expected demand_basis_switch row: the detail names the
    proposed basis twice and the in-use basis once."""
    return {
        "kind": "demand_basis_switch",
        "severity": "medium",
        "key": f"demand_basis_switch:{nearer}",
        "item_code": None,
        "site_code": None,
        "title": "Demand basis to review",
        "detail": (
            f"One period ahead over 120 periods, the {nearer} was "
            f"10.0 points nearer what sold than the {in_use}, which "
            f"reorder points use. An admin may switch the demand "
            f"basis to the {nearer} in Settings."
        ),
        "view": "#/settings",
        "detected_on": MEASURE_AS_OF,
    }


def _assert_response(body, expected_rows, sources_failed):
    """The full expected triage list: the rows the scenario yields,
    in order, nothing else — the stood-in sources answer no row."""
    assert set(body) == {"as_of", "counts", "rows", "sources_failed"}
    assert body["as_of"] is None, "the stood-in sources report no as-of"
    assert body["sources_failed"] == sources_failed
    assert [
        {
            "kind": row["kind"],
            "severity": row["severity"],
            "key": row["key"],
            "item_code": row["item_code"],
            "site_code": row["site_code"],
            "title": row["title"],
            "detail": row["detail"],
            "view": row["view"],
            "detected_on": row["detected_on"],
            "acknowledged": row["acknowledged"],
            "acknowledged_by_name": row["acknowledged_by_name"],
            "acknowledged_at": row["acknowledged_at"],
            "snooze_until": row["snooze_until"],
            "first_seen_on": row["first_seen_on"],
            "new": row["new"],
        }
        for row in body["rows"]
    ] == [
        dict(
            row,
            acknowledged=False,
            acknowledged_by_name=None,
            acknowledged_at=None,
            snooze_until=None,
            first_seen_on=None,
            new=False,
        )
        for row in expected_rows
    ]
    assert body["counts"] == {
        "high": sum(1 for row in expected_rows if row["severity"] == "high"),
        "medium": sum(1 for row in expected_rows if row["severity"] == "medium"),
        "acknowledged": 0,
        "new": 0,
    }


def test_issue1397_freeform(monkeypatch, client, admin_token):
    # Every other source of the route module is replaced with a fake
    # answering no row, the way the issue 955 proof does it, the
    # basis accuracy and the stored system settings stood in for the
    # scenario.  The fakes record the reads they must stay one of.
    FakeBasisAccuracy.calls = []
    FakeBasisAccuracy.answer = dict(FORECAST_NEARER)
    FakeBasisAccuracy.raise_on_call = False
    monkeypatch.setattr(exceptions, "basis_accuracy", FakeBasisAccuracy())
    monkeypatch.setattr(exceptions, "_ddmrp_source", FakeDdmrpSource())
    monkeypatch.setattr(exceptions, "stockout_ranked", FakeStockoutSource())
    monkeypatch.setattr(exceptions, "expedite_list", FakeExpediteSource())
    monkeypatch.setattr(exceptions, "_plan_releases_repo", FakePlanReleasesRepo())
    monkeypatch.setattr(exceptions, "_open_purchase_lines_repo", FakeOpenPurchaseRepo())
    monkeypatch.setattr(
        exceptions, "_transfer_releases_repo", FakeTransferReleasesRepo()
    )
    monkeypatch.setattr(
        exceptions, "_parameter_writebacks_repo", FakeParameterWritebacksRepo()
    )
    monkeypatch.setattr(exceptions, "realised_accuracy", FakeRealisedAccuracy())
    monkeypatch.setattr(exceptions, "_sop_signoffs_repo", FakeSopSignoffsRepo())
    monkeypatch.setattr(exceptions, "_erp_code_clashes_repo", FakeErpCodeClashesRepo())
    monkeypatch.setattr(
        exceptions, "_erp_source_currencies_repo", FakeErpSourceCurrenciesRepo()
    )
    monkeypatch.setattr(
        exceptions, "_erp_code_mappings_repo", FakeErpCodeMappingsRepo()
    )
    monkeypatch.setattr(exceptions, "supplier_risk", FakeSupplierRisk())
    monkeypatch.setattr(exceptions, "second_sources", FakeSecondSources())
    monkeypatch.setattr(
        exceptions, "_supplier_order_minimum_repo", FakeSupplierOrderMinimumsRepo()
    )
    monkeypatch.setattr(exceptions, "_standing_grants_repo", FakeStandingGrantsRepo())
    monkeypatch.setattr(
        exceptions, "_standing_grant_runs_repo", FakeStandingGrantRunsRepo()
    )
    # The window anchor: the route's "current UTC time".
    monkeypatch.setattr(exceptions, "_utcnow", lambda: NOW)

    # No ERP call: the client classes fail if constructed.
    def _no_client(self, *args, **kwargs):
        raise AssertionError("the exceptions route must not call an ERP")

    monkeypatch.setattr(acumatica_client_module.AcumaticaClient, "__init__", _no_client)
    monkeypatch.setattr(odoo_client_module.OdooClient, "__init__", _no_client)

    # The stored system settings: the scenario's dict, read once per
    # call and counted, so the source adds no read of its own.
    stored = {"settings": {}}
    settings_reads = {"count": 0}

    def counting_stored_settings():
        settings_reads["count"] += 1
        return dict(stored["settings"])

    monkeypatch.setattr(exceptions, "_stored_system_settings", counting_stored_settings)

    admin = TestClient(app, headers={"Authorization": f"Bearer {admin_token}"})

    def _get(caller):
        """One GET of the triage list: one basis-accuracy call, with
        bucket_index=1, and one stored-settings read."""
        before_accuracy = len(FakeBasisAccuracy.calls)
        before_settings = settings_reads["count"]
        response = caller.get(URL)
        assert response.status_code == 200, response.text
        assert len(FakeBasisAccuracy.calls) == before_accuracy + 1
        assert FakeBasisAccuracy.calls[-1] == {"bucket_index": 1}
        assert settings_reads["count"] == before_settings + 1
        return response.json()

    # --- The settings: defaults, bounds and descriptions --------------
    margin = get_setting(MARGIN_KEY)
    assert margin is not None
    assert margin.scope == "system"
    assert margin.type == "number"
    assert margin.default == 5
    assert margin.min == 0.5
    assert margin.max == 50
    assert margin.description == (
        "How many points nearer what sold, one period ahead, the "
        "demand basis not in use must have been before the "
        "exceptions inbox proposes switching to it."
    )
    min_periods = get_setting(MIN_PERIODS_KEY)
    assert min_periods is not None
    assert min_periods.scope == "system"
    assert min_periods.type == "number"
    assert min_periods.default == 60
    assert min_periods.min == 1
    assert min_periods.max == 100000
    assert min_periods.description == (
        "The fewest periods, one period ahead, the demand basis "
        "measure must compare before the exceptions inbox proposes "
        "switching the basis."
    )
    # Registered before the forecast-bias settings, like them.
    assert get_setting("exceptions.forecast_bias_min_periods") is not None

    # --- The default settings, FORECAST_NEARER: one row ---------------
    stored["settings"] = {}
    FakeBasisAccuracy.answer = dict(FORECAST_NEARER)
    body = _get(admin)
    expected = [_basis_row("forecast", "history")]
    _assert_response(body, expected, [])
    assert [row["kind"] for row in body["rows"]] == ["demand_basis_switch"]
    row = body["rows"][0]
    assert row["key"] == "demand_basis_switch:forecast"
    assert row["detail"] == (
        "One period ahead over 120 periods, the forecast was 10.0 "
        "points nearer what sold than the history, which reorder "
        "points use. An admin may switch the demand basis to the "
        "forecast in Settings."
    )
    # The source made exactly one basis-accuracy call of the call,
    # with bucket_index=1, and no settings read of its own.
    assert FakeBasisAccuracy.calls == [{"bucket_index": 1}]
    assert settings_reads["count"] == 1
    # The row's position: the kind order gives it the last place —
    # after the rows of every other kind — and it stands there.
    assert exceptions._KIND_ORDER["demand_basis_switch"] == 20
    assert exceptions._TITLES["demand_basis_switch"] == "Demand basis to review"
    assert all(
        order < exceptions._KIND_ORDER["demand_basis_switch"]
        for kind, order in exceptions._KIND_ORDER.items()
        if kind != "demand_basis_switch"
    )
    assert body["rows"][-1]["kind"] == "demand_basis_switch"

    # --- No row: the basis already stored as forecast -----------------
    stored["settings"] = {DEMAND_BASIS_KEY: "forecast"}
    body = _get(admin)
    _assert_response(body, [], [])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])

    # --- No row: the margin stored at 15 (10.0 < 15) ------------------
    stored["settings"] = {MARGIN_KEY: 15}
    body = _get(admin)
    _assert_response(body, [], [])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])

    # --- No row: the fewest periods stored at 121 (120 < 121) --------
    stored["settings"] = {MIN_PERIODS_KEY: 121}
    body = _get(admin)
    _assert_response(body, [], [])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])

    # --- No row: the NOTHING measure (0 periods, no value added) -----
    stored["settings"] = {}
    FakeBasisAccuracy.answer = dict(NOTHING)
    body = _get(admin)
    _assert_response(body, [], [])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])

    # --- The mirror: HISTORY_NEARER, the basis stored as forecast ----
    stored["settings"] = {DEMAND_BASIS_KEY: "forecast"}
    FakeBasisAccuracy.answer = dict(HISTORY_NEARER)
    body = _get(admin)
    expected = [_basis_row("history", "forecast")]
    _assert_response(body, expected, [])
    assert body["rows"][0]["key"] == "demand_basis_switch:history"
    assert body["rows"][0]["detail"] == (
        "One period ahead over 120 periods, the history was 10.0 "
        "points nearer what sold than the forecast, which reorder "
        "points use. An admin may switch the demand basis to the "
        "history in Settings."
    )
    # The basis on its default, history: the same measure proposes
    # nothing.
    stored["settings"] = {}
    body = _get(admin)
    _assert_response(body, [], [])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])

    # --- A failed read: "basis" in sources_failed, the others answer -
    FakeBasisAccuracy.answer = dict(FORECAST_NEARER)
    stored["settings"] = {}
    FakeBasisAccuracy.raise_on_call = True
    body = _get(admin)
    _assert_response(body, [], ["basis"])
    assert not any(row["kind"] == "demand_basis_switch" for row in body["rows"])
    FakeBasisAccuracy.raise_on_call = False
    body = _get(admin)
    _assert_response(body, [_basis_row("forecast", "history")], [])

    # --- The viewer: the role "user" sees the same row ---------------
    # The fixture client carries the development token, role "user".
    user_body = _get(client)
    admin_body = _get(admin)
    assert user_body == admin_body
    assert user_body["rows"][0]["key"] == "demand_basis_switch:forecast"
    # No token: the route's gate answers 401.
    assert TestClient(app).get(URL).status_code == 401

    # --- Identity: a second pass after a full reload, as the
    #     NON-ADMIN (role "user").  The page is booted the production
    #     way: the token it would take from the URL hash as
    #     #access_token=... is the development token (role "user")
    #     sent as its Bearer token; GET /api/auth/config answers
    #     publicly and GET /api/auth/me resolves the viewer.
    viewer = TestClient(app, headers={"Authorization": f"Bearer {VIEWER_TOKEN}"})
    anon_reloaded = TestClient(app)
    assert anon_reloaded.get("/api/auth/config").status_code == 200
    me = viewer.get("/api/auth/me")
    assert me.status_code == 200
    assert me.json()["authenticated"] is True
    assert "user" in me.json()["user"]["roles"]
    assert "admin" not in me.json()["user"]["roles"]

    # The list page still renders for the viewer — the route is open
    # to any signed-in user, so no admin-only control stands on it —
    # with the same body the admin sees.
    viewer_body = _get(viewer)
    admin_body = _get(admin)
    assert viewer_body == admin_body
    assert viewer_body["rows"][0]["key"] == "demand_basis_switch:forecast"
    # The admin-only control: the acknowledgement route answers the
    # viewer 403 while the page renders.
    ack = viewer.put(ACK_URL, json={"key": "demand_basis_switch:forecast"})
    assert ack.status_code == 403, ack.text
    # No token: still a 401.
    assert anon_reloaded.get(URL).status_code == 401
