"""Issue #1540 proof: the DDMRP buffer's order signal plans its lines.

AC-1 — ``supply_plan.plan_buffers_by_signal`` is a registered system
setting (boolean, default true): proven here against the registry,
and listed in ``tests/test_issue274_freeform.py`` and
``tests/test_issue502_freeform.py``, which list every registered
setting.

AC-2 — the plan: with the setting on (the stored value, else the
default), ``app.api.supply_plan.build_supply_plan`` reads the DDMRP
plan once per call through the module's ``_buffer_rows`` —
``app.api.ddmrp.ddmrp_zone_rows`` with the plan's as-of, then
``app.ddmrp.plan.plan_ddmrp`` with the as-of the zone rows answer and
those rows, keyed by (item_code, site_code) — and a raised read
builds the plan exactly as with the setting off, the way a raised
risk read does.  A designated item-site (one in those rows) whose
recommendation has status "ok" is planned by its buffer, not its
reorder point: with the row's ``order_signal`` true, one line —
``due_in_days`` 0 and ``order_by`` the as-of date, ``raw_quantity``
the row's ``suggested_order_units`` fitted to the supplier's terms
exactly as every line's raw quantity is, ``position_units`` the
row's ``net_flow`` rounded down to whole units,
``reorder_point_units`` the row's ``top_of_yellow``, and the
arithmetic's label "buffer signal: top of green <top of green> minus
net flow <net flow>, rounded up", the net flow rounded to one
decimal place the way ``_format_number`` writes numbers; with the
``order_signal`` false, no line, whatever the reorder point says.
Every other item-site is planned exactly as today.  Every line's
``source`` reads ``"buffer"`` for a line from a buffer's signal and
``"reorder_point"`` for every other line, the supplier groups' lines
carrying it too; with the setting off every line is exactly as today
and ``_buffer_rows`` is never called.

AC-3 — the reference docs: ``docs/reference/SETTINGS.md`` carries the
setting's row, generated by ``scripts/generate_reference_docs.py``.

AC-4 — the pins: the setting-key lists of
``tests/test_issue274_freeform.py`` and
``tests/test_issue502_freeform.py`` gain the key, and the expected
plan lines of ``tests/test_issue1191_freeform.py`` and
``tests/test_issue1225_freeform.py`` gain ``"source":
"reorder_point"``.

AC-5 — this proof: three item-sites, each with a status "ok"
recommendation — on hand 5, on order 0, reorder point 20, order
quantity 25 and daily demand 2, so the reorder point makes each due
now — B1 and B2 with buffer rows (B1's signal on: net flow 12.6, top
of yellow 30, top of green 49, suggested 37; B2's off: net flow 35,
suggested 0), R1 without; one supplier with a lot size of 10 covers
all three.  ``recommendations_for_all`` and ``_buffer_rows`` in
``app.api.supply_plan`` are stood in, the way
``tests/test_issue1076_freeform.py`` stands in for the risk read; the
supplier terms and the supplier are rows inserted and deleted.
Proven through ``GET /api/supply-plan?horizon_days=7`` for a
signed-in user:

  * ON (the default): B1's line has ``source`` "buffer",
    ``due_in_days`` 0, ``raw_quantity`` 37, ``quantity`` 40,
    ``position_units`` 12 and ``reorder_point_units`` 30, its
    ``arithmetic`` "raw 37 (buffer signal: top of green 49 minus net
    flow 12.6, rounded up) → rounded to lot 10: 40", the daily
    demand, terms, lead time, arrival, unit cost and value those of
    any line; B2 has no line; R1's line has ``source``
    "reorder_point" and is identical to its line with the setting
    off — and the DDMRP plan is read once per call.
  * Identity: a second pass after a full reload, as the NON-ADMIN
    (role "user") — the page booted the production way, the token it
    would take from the URL hash as #access_token=... sent as its
    Bearer token, ``GET /api/auth/config`` answering publicly and
    ``GET /api/auth/me`` resolving the viewer — with the admin-only
    control absent (the route is open to any signed-in user) and the
    same body; no token still a 401.
  * OFF (stored false): all three have lines from their reorder
    points, each with ``source`` "reorder_point", and
    ``_buffer_rows`` was not called.
  * Read fails: ``_buffer_rows`` raises, so the answer is OFF's.
  * The setting: registered with system scope, boolean, default
    true.
"""

import json
import os

from fastapi.testclient import TestClient

import app.api.supply_plan as supply_plan
from app.db.connection import get_connection
from app.main import app
from app.settings.registry import get_setting

URL = "/api/supply-plan"
ADMIN_TOKEN = "dev-secret-token:admin"
VIEWER_TOKEN = os.environ.get("AUTH_DEV_TOKEN", "dev-secret-token")

SETTING_KEY = "supply_plan.plan_buffers_by_signal"

SITE = "159"
SOURCE_SYSTEM = "test"
ITEM_B1 = "B-1540-1"
ITEM_B2 = "B-1540-2"
ITEM_R1 = "R-1540-1"
ITEMS = (ITEM_B1, ITEM_B2, ITEM_R1)
SUPPLIER = "S-1540"
SUPPLIER_NAME = "Buffer Stock Co."
VENDOR_CODE = "V-1540"

# The buffer rows of the DDMRP plan the stand-in answers: B1's
# order signal is on (net flow 12.6, top of yellow 30, top of green
# 49, suggested 37); B2's is off (net flow 35, suggested 0).  R1 has
# no buffer row.
BUFFER_B1 = {
    "item_code": ITEM_B1,
    "site_code": SITE,
    "status": "ok",
    "order_signal": True,
    "net_flow": 12.6,
    "top_of_red": 10,
    "top_of_yellow": 30,
    "top_of_green": 49,
    "suggested_order_units": 37,
}
BUFFER_B2 = {
    "item_code": ITEM_B2,
    "site_code": SITE,
    "status": "ok",
    "order_signal": False,
    "net_flow": 35.0,
    "top_of_red": 10,
    "top_of_yellow": 30,
    "top_of_green": 49,
    "suggested_order_units": 0,
}
ON_BUFFER_ROWS = {
    (ITEM_B1, SITE): BUFFER_B1,
    (ITEM_B2, SITE): BUFFER_B2,
}

# B1's line: the raw 37 fitted to the lot of 10, the position the
# net flow 12.6 rounded down, the reorder point the top of yellow.
B1_ARITHMETIC = (
    "raw 37 (buffer signal: top of green 49 minus net flow 12.6, "
    "rounded up) → rounded to lot 10: 40"
)
R1_ARITHMETIC = "raw 25 (EOQ) → rounded to lot 10: 30"

ITEM_SITE_SQL = (
    "INSERT INTO item_sites (id, item_code, site_code, unit_cost, "
    "reorder_point, safety_stock, max_qty, order_qty, source_system) "
    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)"
)
TERMS_SQL = (
    "INSERT INTO supplier_terms (id, business_key, source_system, "
    "item_code, supplier_code, min_order_qty, max_order_qty, lot_size, "
    "lead_time_days, is_default) "
    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
)
SUPPLIER_SQL = (
    "INSERT INTO suppliers (id, supplier_code, vendor_code, name, status, "
    "source_system) VALUES (%s, %s, %s, %s, %s, %s)"
)
SETTING_SQL = (
    "INSERT INTO settings (scope, owner, key, value, updated_by) "
    "VALUES ('system', '', %s, %s::jsonb, 'test')"
)


def _recommendation(item_code):
    """One status "ok" recommendation: on hand 5, on order 0,
    reorder point 20, order quantity 25 and daily demand 2 — the
    position below the reorder point makes the item-site due now."""
    return {
        "item_code": item_code,
        "site_code": SITE,
        "status": "ok",
        "on_hand_units": 5,
        "on_order_units": 0,
        "reorder_point_units": 20,
        "order_quantity": {"basis": "eoq", "order_quantity_units": 25},
        "suggested_order_quantity": None,
        "inputs": {"d": 2.0, "lt": 5.0},
        "unit_cost": 10.0,
    }


class _Recommendations:
    """The stand-in for ``recommendations_for_all`` in
    ``app.api.supply_plan``: every call is counted, the three fixed
    recommendations are handed back unchanged."""

    calls = 0

    def __call__(self, as_of):
        _Recommendations.calls += 1
        return [_recommendation(item_code) for item_code in ITEMS]


class _Buffers:
    """The stand-in for ``_buffer_rows`` in ``app.api.supply_plan``:
    every call is counted, the fixed buffer rows are handed back
    unchanged (or the error raised)."""

    calls = 0

    def __init__(self, rows=None, error=None):
        self._rows = rows
        self._error = error

    def __call__(self, as_of):
        _Buffers.calls += 1
        if self._error is not None:
            raise self._error
        return self._rows


def _seed(cur) -> None:
    """The three item-sites of the source system, the one supplier
    and its terms row per item — one supplier with a lot size of 10
    covering all three."""
    for item_code in ITEMS:
        cur.execute(
            ITEM_SITE_SQL,
            (
                f"id-is-1540-{item_code}",
                item_code,
                SITE,
                10.0,
                20.0,
                0.0,
                None,
                None,
                SOURCE_SYSTEM,
            ),
        )
        cur.execute(
            TERMS_SQL,
            (
                f"id-st-1540-{item_code}",
                f"{item_code}:terms-1540",
                SOURCE_SYSTEM,
                item_code,
                SUPPLIER,
                None,
                None,
                10,
                None,
                True,
            ),
        )
    cur.execute(
        SUPPLIER_SQL,
        ("id-sp-1540", SUPPLIER, VENDOR_CODE, SUPPLIER_NAME, "active", SOURCE_SYSTEM),
    )


def _store_setting(value) -> None:
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("DELETE FROM settings WHERE key = %s", (SETTING_KEY,))
            cur.execute(SETTING_SQL, (SETTING_KEY, json.dumps(value)))
        conn.commit()
    finally:
        conn.close()


def _delete_setting() -> None:
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("DELETE FROM settings WHERE key = %s", (SETTING_KEY,))
        conn.commit()
    finally:
        conn.close()


def _lines_by_item(body):
    """The plan's lines keyed by item_code, across every group."""
    return {
        line["item_code"]: line
        for group in body["suppliers"]
        for line in group["lines"]
    }


def test_issue1540_freeform(client, monkeypatch) -> None:
    # The setting: registered with system scope, boolean, default
    # true.
    setting = get_setting(SETTING_KEY)
    assert setting is not None, "supply_plan.plan_buffers_by_signal is registered"
    assert setting.scope == "system"
    assert setting.type == "boolean"
    assert setting.default is True

    conn = get_connection()
    try:
        with conn.cursor() as cur:
            _seed(cur)
        conn.commit()
    finally:
        conn.close()

    admin = TestClient(app, headers={"Authorization": f"Bearer {ADMIN_TOKEN}"})

    try:
        # --- ON (the default): B1 by its buffer's signal, B2 no
        #     line, R1 exactly as today. ------------------------------
        monkeypatch.setattr(supply_plan, "recommendations_for_all", _Recommendations())
        monkeypatch.setattr(supply_plan, "_buffer_rows", _Buffers(rows=ON_BUFFER_ROWS))
        _Recommendations.calls = 0
        _Buffers.calls = 0
        response = admin.get(URL, params={"horizon_days": 7})
        assert response.status_code == 200, response.text
        on_body = response.json()
        lines = _lines_by_item(on_body)
        assert set(lines) == {
            ITEM_B1,
            ITEM_R1,
        }, "B2 has no line, whatever its reorder point says"

        as_of_str = on_body["as_of"]
        b1 = lines[ITEM_B1]
        assert b1["source"] == "buffer"
        assert b1["due_in_days"] == 0
        assert b1["order_by"] == as_of_str
        assert b1["raw_quantity"] == 37
        assert b1["quantity"] == 40
        assert b1["position_units"] == 12
        assert b1["reorder_point_units"] == 30
        assert b1["arithmetic"] == B1_ARITHMETIC
        # The daily demand, supplier choice, terms, lead time,
        # arrival, unit cost and value are those of any line.
        assert b1["daily_demand"] == 2.0
        assert b1["terms"] == {
            "min_order_qty": None,
            "lot_size": 10.0,
            "max_order_qty": None,
        }
        assert b1["unit_cost"] == 10.0
        assert b1["value"] == "400.00"
        assert b1["lead_time_days"] == 5.0

        r1 = lines[ITEM_R1]
        assert r1["source"] == "reorder_point"
        assert r1["arithmetic"] == R1_ARITHMETIC

        # The supplier group's lines carry the source too, under the
        # one supplier with the lot of 10.
        group = next(g for g in on_body["suppliers"] if g["supplier_code"] == SUPPLIER)
        assert group["vendor_code"] == VENDOR_CODE
        assert {line["item_code"] for line in group["lines"]} == {ITEM_B1, ITEM_R1}
        assert {line["item_code"]: line["source"] for line in group["lines"]} == {
            ITEM_B1: "buffer",
            ITEM_R1: "reorder_point",
        }

        assert _Recommendations.calls == 1
        assert _Buffers.calls == 1, "the DDMRP plan is read once per call"

        # --- Identity: a second pass after a full reload, as the
        #     NON-ADMIN (role "user").  The page is booted the
        #     production way: the token it would take from the URL
        #     hash as #access_token=... is the development token
        #     (role "user") sent as its Bearer token; GET
        #     /api/auth/config answers publicly and GET /api/auth/me
        #     resolves the viewer.
        viewer = TestClient(app, headers={"Authorization": f"Bearer {VIEWER_TOKEN}"})
        anon_reloaded = TestClient(app)
        assert anon_reloaded.get("/api/auth/config").status_code == 200
        me = viewer.get("/api/auth/me")
        assert me.status_code == 200, me.text
        assert me.json()["authenticated"] is True
        assert "user" in me.json()["user"]["roles"]
        assert "admin" not in me.json()["user"]["roles"]

        # The plan page still renders for the viewer — the route is
        # open to any signed-in user, so no admin-only control stands
        # on it — with the same body, and no token is still a 401.
        viewer_response = viewer.get(URL, params={"horizon_days": 7})
        assert viewer_response.status_code == 200, viewer_response.text
        assert viewer_response.json() == on_body
        assert anon_reloaded.get(URL).status_code == 401

        # --- OFF (stored false): all three from their reorder
        #     points, and _buffer_rows is never called. --------------
        _store_setting(False)
        monkeypatch.setattr(supply_plan, "_buffer_rows", _Buffers(rows=ON_BUFFER_ROWS))
        _Buffers.calls = 0
        response = admin.get(URL, params={"horizon_days": 7})
        assert response.status_code == 200, response.text
        off_body = response.json()
        off_lines = _lines_by_item(off_body)
        assert set(off_lines) == set(ITEMS)
        for item_code in ITEMS:
            line = off_lines[item_code]
            assert line["source"] == "reorder_point"
            assert line["raw_quantity"] == 25
            assert line["quantity"] == 30
            assert line["position_units"] == 5
            assert line["reorder_point_units"] == 20
            assert line["due_in_days"] == 0
            assert line["arithmetic"] == R1_ARITHMETIC
        assert _Buffers.calls == 0, "_buffer_rows is never called with the setting off"
        # R1's line is identical to its line with the setting on.
        assert off_lines[ITEM_R1] == r1
        _delete_setting()

        # --- Read fails: _buffer_rows raises — the answer is
        #     OFF's, the route answers 200. ---------------------------
        monkeypatch.setattr(
            supply_plan,
            "_buffer_rows",
            _Buffers(error=RuntimeError("the buffer read failed")),
        )
        _Buffers.calls = 0
        response = admin.get(URL, params={"horizon_days": 7})
        assert response.status_code == 200, response.text
        assert response.json() == off_body
        assert _Buffers.calls == 1, "the buffer read is still made once per call"
    finally:
        conn = get_connection()
        try:
            with conn.cursor() as cur:
                cur.execute(
                    "DELETE FROM item_sites WHERE site_code = %s "
                    "AND item_code = ANY(%s)",
                    (SITE, list(ITEMS)),
                )
                cur.execute(
                    "DELETE FROM supplier_terms WHERE supplier_code = %s", (SUPPLIER,)
                )
                cur.execute(
                    "DELETE FROM suppliers WHERE supplier_code = %s", (SUPPLIER,)
                )
                cur.execute("DELETE FROM settings WHERE key = %s", (SETTING_KEY,))
            conn.commit()
        finally:
            conn.close()
