#!/usr/bin/env python3
"""Generate the committed reference docs from the live sources.

Usage:
    python scripts/generate_reference_docs.py           # write both files
    python scripts/generate_reference_docs.py --check   # verify, write nothing

Writes docs/reference/SETTINGS.md from the settings registry
(backend/app/settings/registry.py) and docs/reference/API.md from the
committed OpenAPI schema (backend/openapi.json, which is only read).
Both files carry a "do not edit by hand" banner; regenerate them whenever
a setting is registered or a route changes.  With --check the script
prints the repository-relative path of each file that differs from what
it would write and exits 1 if any differ, 0 when both match.  The script
reads no database and makes no network call: the settings come from the
imported registry and the operations from the committed schema file.
"""

import argparse
import json
import sys
from pathlib import Path

# Ensure the backend package is importable regardless of working directory,
# the way scripts/export_openapi.py does it.
REPO_ROOT = Path(__file__).resolve().parent.parent
backend_dir = REPO_ROOT / "backend"
sys.path.insert(0, str(backend_dir))

from app.settings.registry import Setting, all_settings  # noqa: E402

EN_DASH = "\u2013"  # 1–90
EM_DASH = "\u2014"  # a missing value

_SETTINGS_BANNER = (
    "Generated by `scripts/generate_reference_docs.py` from the settings "
    "registry (`backend/app/settings/registry.py`). Do not edit by hand."
)
_API_BANNER = (
    "Generated by `scripts/generate_reference_docs.py` from "
    "`backend/openapi.json`. Do not edit by hand."
)

_METHOD_ORDER = {"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4}


def _cell(value: object) -> str:
    """One table cell: pipes escaped, newlines flattened to spaces."""
    return (
        str(value)
        .replace("\r\n", " ")
        .replace("\n", " ")
        .replace("\r", " ")
        .replace("|", "\\|")
    )


def _range_cell(setting: Setting) -> str:
    """The 'allowed or range' column for one setting."""
    if setting.type == "enum":
        return ", ".join(setting.allowed or ())
    if setting.type == "number":
        if setting.min is None or setting.max is None:
            return EM_DASH
        return f"{setting.min!r}{EN_DASH}{setting.max!r}"
    return EM_DASH


def settings_markdown(settings: list[Setting]) -> str:
    """The full text of docs/reference/SETTINGS.md for *settings*."""
    lines = [
        "# Settings reference",
        "",
        _SETTINGS_BANNER,
        "",
        "| key | scope | type | default | allowed or range | description |",
    ]
    for setting in sorted(settings, key=lambda s: s.key):
        lines.append(
            "| "
            + " | ".join(
                (
                    _cell(setting.key),
                    _cell(setting.scope),
                    _cell(setting.type),
                    _cell(json.dumps(setting.default)),
                    _cell(_range_cell(setting)),
                    _cell(setting.description),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def _summary_cell(operation: dict) -> str:
    """The summary of one operation, or the em dash when it has none."""
    summary = operation.get("summary")
    if isinstance(summary, str) and summary.strip():
        return _cell(summary)
    description = operation.get("description")
    if isinstance(description, str):
        for line in description.splitlines():
            if line.strip():
                return _cell(line)
    return EM_DASH


def api_markdown(spec: dict) -> str:
    """The full text of docs/reference/API.md for one OpenAPI *spec*."""
    lines = [
        "# API reference",
        "",
        _API_BANNER,
        "",
        "| method | path | summary |",
    ]
    for path in sorted(spec.get("paths", {})):
        item = spec["paths"][path]
        methods = sorted(
            item, key=lambda m: (_METHOD_ORDER.get(m, len(_METHOD_ORDER)), m)
        )
        for method in methods:
            operation = item[method]
            if not isinstance(operation, dict):
                continue
            lines.append(
                "| "
                + " | ".join(
                    (
                        _cell(method.upper()),
                        _cell(path),
                        _summary_cell(operation),
                    )
                )
                + " |"
            )
    return "\n".join(lines) + "\n"


def _load_spec() -> dict:
    return json.loads((backend_dir / "openapi.json").read_text(encoding="utf-8"))


def _documents() -> list[tuple[str, str]]:
    """Both reference files as (repository-relative path, text) pairs."""
    return [
        ("docs/reference/SETTINGS.md", settings_markdown(all_settings())),
        ("docs/reference/API.md", api_markdown(_load_spec())),
    ]


def write_references(root: Path | str) -> list[str]:
    """Write both reference files under *root*; return their relative paths."""
    root = Path(root)
    written = []
    for rel_path, text in _documents():
        path = root / rel_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(rel_path)
    return written


def check_references(root: Path | str) -> list[str]:
    """The relative paths that differ from what write_references would write."""
    root = Path(root)
    differing = []
    for rel_path, text in _documents():
        path = root / rel_path
        try:
            existing = path.read_text(encoding="utf-8")
        except OSError:
            differing.append(rel_path)
            continue
        if existing != text:
            differing.append(rel_path)
    return differing


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate docs/reference/SETTINGS.md and docs/reference/API.md."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; print each file that differs and exit 1",
    )
    args = parser.parse_args(argv)
    if args.check:
        differing = check_references(REPO_ROOT)
        for rel_path in differing:
            print(rel_path)
        return 1 if differing else 0
    for rel_path in write_references(REPO_ROOT):
        print(f"Wrote {REPO_ROOT / rel_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
